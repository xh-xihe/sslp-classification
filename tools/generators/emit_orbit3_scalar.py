#!/usr/bin/env python3
"""Emit all six orbit-3 rational scalar duals as kernel certificates.

The output proves the consequences for the displayed scalar system. The
projector-to-category averaging and label-sensitive row identities are not
assumed to have been proved merely by generating this finite module.
"""
from __future__ import annotations
import argparse
from fractions import Fraction as F
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def rat(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f'({x.numerator}/{x.denominator})'


def vector(x):
    return '![' + ', '.join(map(rat, x)) + ']'


def matrix(rows):
    return '![' + ',\n  '.join(vector(row) for row in rows) + ']'


def generate(source, output):
    path = ROOT / 'tools/certificates/orbit3_scalar_certificate.py'
    spec = importlib.util.spec_from_file_location('scalar', path)
    v = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(v)
    raw = source.read_bytes()
    reports = json.loads(raw)['proved_class3_linear_consequences']
    columns = [c for c in v.categories() if c[2] % 2 == 0]
    unit = lambda label: [F(c == label) for c in columns]
    eq, rhs, keys = [unit((0, 0, 0))], [F(1)], [('norm', None)]
    positive, pkeys = [], []
    for error in v.categories():
        transform = [v.fourier_kernel(error, c) for c in columns]
        spin = [x * (-1)**sum(c) for x, c in zip(transform, columns)]
        positive += [transform, spin]
        pkeys += [('B', error), ('shadow', error)]
        a, j, k = error
        if k % 2 == 0:
            complement = (a, 5-j-k, k)
            eq.append([x - F(int(c == error) + int(c == complement), v.orbit_size(error))
                       for x, c in zip(transform, columns)])
            rhs.append(F(0)); keys.append(('diag', error))
        if sum(error) <= 2:
            eq.append([x - F(c == error, v.orbit_size(error)) for x, c in zip(transform, columns)])
            rhs.append(F(0)); keys.append(('KL', error))
        if k % 2 and sum(error) % 2:
            eq.append(spin); rhs.append(F(0)); keys.append(('shadowzero', error))
    targets = [(0, 1, 0), (0, 0, 2), (0, 1, 2), (1, 2, 0), (0, 3, 0), None]
    objectives, ems, pms, remainders, bounds = [], [], [], [], []
    for report, target in zip(reports, targets):
        objective = [F(sum(c) in (1, 2, 3)) for c in columns] if target is None else [-x for x in unit(target)]
        em, pm, rem = [F(0)] * len(eq), [F(0)] * len(positive), [F(0)] * 24
        for kind, label, coefficient in report['equality_terms']:
            em[keys.index((kind, tuple(label) if label is not None else None))] += F(coefficient)
        for kind, label, coefficient in report['inequality_terms']:
            pm[pkeys.index((kind, tuple(label)))] -= F(coefficient)
        for entry in report['nonnegative_variable_remainder']:
            rem[columns.index(tuple(entry['category']))] = F(entry['coefficient'])
        objectives.append(objective); ems.append(em); pms.append(pm); remainders.append(rem)
        bounds.append(F(report['proved_lower_bound']))
    text = f'''-- Generated by tools/generators/emit_orbit3_scalar.py.
-- Input SHA-256: {hashlib.sha256(raw).hexdigest()}
import MainTheory.RationalLinearCertificate

/-! Six exact duals for the scalar category system. Actual-encoder realization
of this system remains a separate semantic obligation. -/
namespace SixQubit.Generated.Orbit3Scalar

set_option maxHeartbeats 8000000
set_option maxRecDepth 200000

def categories : Fin 24 → ℕ × ℕ × ℕ := ![{', '.join(f'({a}, {j}, {k})' for a,j,k in columns)}]

-- Equality row labels: {keys}
def equalities : Fin {len(eq)} → Fin 24 → ℚ := {matrix(eq)}
def rhs : Fin {len(eq)} → ℚ := {vector(rhs)}
-- Positive row labels: {pkeys}
def positive : Fin {len(positive)} → Fin 24 → ℚ := {matrix(positive)}
def objective : Fin 6 → Fin 24 → ℚ := {matrix(objectives)}
def lowerBound : Fin 6 → ℚ := {vector(bounds)}
def equalityMultiplier : Fin 6 → Fin {len(eq)} → ℚ := {matrix(ems)}
def positiveMultiplier : Fin 6 → Fin {len(positive)} → ℚ := {matrix(pms)}
def remainder : Fin 6 → Fin 24 → ℚ := {matrix(remainders)}

theorem coefficients : ∀ c j, objective c j =
    (∑ i, equalityMultiplier c i * equalities i j) +
    (∑ i, positiveMultiplier c i * positive i j) + remainder c j := by
  decide +kernel

theorem constant : ∀ c, lowerBound c = ∑ i, equalityMultiplier c i * rhs i := by
  decide +kernel

theorem positiveMultiplier_nonneg : ∀ c i, 0 ≤ positiveMultiplier c i := by decide +kernel
theorem remainder_nonneg : ∀ c j, 0 ≤ remainder c j := by decide +kernel

def certificate (c : Fin 6) :
    MainTheory.RationalLinearCertificate.Certificate (objective c) (lowerBound c)
      equalities rhs positive where
  equalityMultiplier := equalityMultiplier c
  positiveMultiplier := positiveMultiplier c
  remainder := remainder c
  coefficients := coefficients c
  constant := constant c
  positiveMultiplier_nonneg := positiveMultiplier_nonneg c
  remainder_nonneg := remainder_nonneg c

open MainTheory.RationalLinearCertificate

theorem lower_bounds (y : Fin 24 → ℝ)
    (heq : ∀ i, evaluate (equalities i) y = (rhs i : ℝ))
    (hpos : ∀ i, 0 ≤ evaluate (positive i) y)
    (hy : ∀ j, 0 ≤ y j) (c : Fin 6) :
    (lowerBound c : ℝ) ≤ evaluate (objective c) y :=
  (certificate c).bound y heq hpos hy

def zeroIndex : Fin 5 → Fin 24 := ![1, 6, 7, 14, 3]

def zeroCertificate (c : Fin 5) : Fin 6 := ⟨c.val, lt_trans c.isLt (by decide)⟩

theorem zero_objective : ∀ c : Fin 5, ∀ j : Fin 24,
    objective (zeroCertificate c) j = if j = zeroIndex c then -1 else 0 := by
  decide +kernel

theorem zero_bound : ∀ c : Fin 5, lowerBound (zeroCertificate c) = 0 := by decide +kernel

theorem zero_categories (y : Fin 24 → ℝ)
    (heq : ∀ i, evaluate (equalities i) y = (rhs i : ℝ))
    (hpos : ∀ i, 0 ≤ evaluate (positive i) y)
    (hy : ∀ j, 0 ≤ y j) (c : Fin 5) : y (zeroIndex c) = 0 := by
  have h := lower_bounds y heq hpos hy (zeroCertificate c)
  rw [zero_bound] at h
  norm_num only [Rat.cast_zero] at h
  have heval : evaluate (objective (zeroCertificate c)) y = -y (zeroIndex c) := by
    unfold evaluate
    simp only [zero_objective, apply_ite, Rat.cast_neg, Rat.cast_one,
      Rat.cast_zero, ite_mul, neg_one_mul, zero_mul]
    simp
  rw [heval] at h
  have := hy (zeroIndex c)
  linarith

theorem plane_objective : ∀ j : Fin 24,
    objective 5 j = if (categories j).1 + (categories j).2.1 + (categories j).2.2 ∈
      ([1, 2, 3] : List ℕ) then 1 else 0 := by decide +kernel

theorem low_mass_bound (y : Fin 24 → ℝ)
    (heq : ∀ i, evaluate (equalities i) y = (rhs i : ℝ))
    (hpos : ∀ i, 0 ≤ evaluate (positive i) y)
    (hy : ∀ j, 0 ≤ y j) :
    1 ≤ ∑ j : Fin 24,
      if (categories j).1 + (categories j).2.1 + (categories j).2.2 ∈
        ([1, 2, 3] : List ℕ) then y j else 0 := by
  have h := lower_bounds y heq hpos hy 5
  have hb : lowerBound 5 = 1 := by decide
  rw [hb] at h
  unfold evaluate at h
  simp_rw [plane_objective] at h
  simpa only [apply_ite, Rat.cast_one, Rat.cast_zero, ite_mul, one_mul, zero_mul] using h

end SixQubit.Generated.Orbit3Scalar
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')
    print(f'Generated 6 scalar kernel certificates: {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT/'results/orbit3-kernel/scalar-certificate.json')
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3Scalar.lean')
    args = parser.parse_args()
    generate(args.input, args.output)
