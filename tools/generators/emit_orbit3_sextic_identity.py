#!/usr/bin/env python3
"""Emit the exact reduced orbit-3 coefficient identity as a kernel proof.

This consumes rebuilt reduced coefficients, not encoder assumptions. The
connection of the 269 coordinates to positive actual encoder moments remains a
separate theorem; these declarations do not assert the full orbit converse.
"""
from __future__ import annotations
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def rat(value):
    value = Fraction(value)
    return str(value.numerator) if value.denominator == 1 else f"({value.numerator}/{value.denominator})"


def vector(values):
    return "![" + ", ".join(map(rat, values)) + "]"


def generate(source, output):
    raw = source.read_bytes()
    data = json.loads(raw)
    if len(data['target']) != 269 or len(data['rows']) != 211:
        raise ValueError('Incorrect certificate dimensions')
    if any(len(row) != 269 for row in data['rows']):
        raise ValueError('Incorrect row dimensions')
    columns = []
    for j in range(269):
        columns.append("[" + ", ".join(
            f"({i}, {rat(row[j])})" for i, row in enumerate(data['rows']) if row[j]) + "]")
    sparse_columns = "![" + ",\n  ".join(columns) + "]"
    text = f'''-- Generated by tools/generators/emit_orbit3_sextic_identity.py.
-- Input SHA-256: {hashlib.sha256(raw).hexdigest()}.
import Mathlib

/-!
# Exact orbit-3 identity in the 269 reduced moment coordinates

The finite identity is kernel checked. Its realization by actual positive
encoder moments, and vanishing of its rows on those encoders, are separate
semantic obligations. The conditional conclusion below does not discharge them.
-/

namespace SixQubit.Generated.Orbit3SexticIdentity

set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

def target : Fin 269 → ℚ := {vector(data['target'])}
def square : Fin 269 → ℚ := {vector(data['square'])}
def multiplier : Fin 211 → ℚ := {vector(data['multipliers'])}
def columns : Fin 269 → List (Fin 211 × ℚ) :=
  {sparse_columns}

def scatter (l : List (Fin 211 × ℚ)) (i : Fin 211) : ℚ :=
  (l.map fun e => if i = e.1 then e.2 else 0).sum

def rows (i : Fin 211) (j : Fin 269) : ℚ := scatter (columns j) i

theorem weighted_scatter (l : List (Fin 211 × ℚ)) :
    (∑ i, multiplier i * scatter l i) =
      (l.map fun e => multiplier e.1 * e.2).sum := by
  induction l with
  | nil => simp [scatter]
  | cons e l ih =>
    simp only [scatter, List.map_cons, List.sum_cons, mul_add,
      Finset.sum_add_distrib] at *
    rw [ih]
    congr 1
    simp

theorem sparse_coefficients : ∀ j : Fin 269,
    3 * target j + 1280 * square j =
      80 * ((columns j).map fun e => multiplier e.1 * e.2).sum := by
  decide +kernel

theorem coefficients (j : Fin 269) :
    3 * target j + 1280 * square j = 80 * ∑ i, multiplier i * rows i j := by
  rw [show (∑ i, multiplier i * rows i j) =
      ((columns j).map fun e => multiplier e.1 * e.2).sum from weighted_scatter (columns j)]
  exact sparse_coefficients j

noncomputable def evaluate (r : Fin 269 → ℚ) (y : Fin 269 → ℝ) : ℝ :=
  ∑ j, (r j : ℝ) * y j

theorem identity_on_moments (y : Fin 269 → ℝ) :
    3 * evaluate target y + 1280 * evaluate square y =
      80 * ∑ i, (multiplier i : ℝ) * evaluate (rows i) y := by
  have h (j : Fin 269) :
      3 * (target j : ℝ) + 1280 * (square j : ℝ) =
        80 * ∑ i, (multiplier i : ℝ) * (rows i j : ℝ) := by
    exact_mod_cast coefficients j
  unfold evaluate
  calc
    _ = ∑ j, (3 * (target j : ℝ) + 1280 * (square j : ℝ)) * y j := by
      simp only [add_mul, Finset.sum_add_distrib, mul_assoc, ← Finset.mul_sum]
    _ = ∑ j, (80 * ∑ i, (multiplier i : ℝ) * (rows i j : ℝ)) * y j := by
      simp_rw [h]
    _ = _ := by
      simp only [Finset.sum_mul, Finset.mul_sum, mul_assoc]
      rw [Finset.sum_comm]

/-- The final scalar implication once an actual-encoder moment bridge is supplied. -/
theorem target_zero_of_constraints (y : Fin 269 → ℝ)
    (hz : ∀ i, evaluate (rows i) y = 0)
    (ht : 0 ≤ evaluate target y) (hv : 0 ≤ evaluate square y) :
    evaluate target y = 0 := by
  have h := identity_on_moments y
  simp only [hz, mul_zero, Finset.sum_const_zero] at h
  linarith

end SixQubit.Generated.Orbit3SexticIdentity
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')
    print(f'Generated {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT/'results/orbit3-kernel/reduced-coefficients.json')
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3SexticIdentity.lean')
    args = parser.parse_args()
    generate(args.input, args.output)
