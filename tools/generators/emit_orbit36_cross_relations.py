"""Export every pair and star relation from actual distance-three KL rows."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
edge={(0,1):6,(0,2):7,(0,3):8,(1,2):9,(1,3):10,(2,3):11}
def edge_index(i,j): return edge[tuple(sorted((i,j)))]
def U(i,j): return f'star (c y{edge_index(i,j)}) * d z{j+2}'
def V(i,j): return f'star (c y{j+2}) * d z{edge_index(i,j)}'
pair_results=[f'{U(i,j)} = {V(i,j)}' for i in range(4) for j in range(4) if i!=j]
star_results=[' + '.join(U(i,j) for j in range(4) if i!=j)+' = 0' for i in range(4)]
source='''-- Generated by tools/generators/emit_orbit36_cross_relations.py.
import SixQubit.CodeOrbit36
import MainTheory.Orbit36AlgebraDisplays

set_option autoImplicit false
set_option maxHeartbeats 1600000

namespace MainTheory.Orbit36CrossRelations
open SixQubit.Orbit36

theorem all_pair_and_star_relations (c d : SS.BitString 6 → ℂ)
    (hc : ∀ x, x ∉ S0 → c x = 0) (hd : ∀ x, x ∉ S1 → d x = 0)
    (hdist : SS.HasDistance ![c,d] 3) :
'''
source+='    '+' ∧\n    '.join(pair_results+star_results)+' := by\n'
source+='  obtain ⟨'+','.join('h'+str(i) for i in range(22))+'⟩ := SixQubit.Orbit36.klRows c d hc hd hdist\n'
pair_names=[]
for i in range(4):
    neighbors=[j for j in range(4) if i!=j]
    for k,j in enumerate([None]+neighbors):
        source+=f'  rw [ex_ex{i+1}_w{0 if j is None else j+1}] at h{4*i+k}\n'
    names=[f'p{i}{j}' for j in neighbors]
    pair_names+=names
    source+='  obtain ⟨'+','.join(names+[f's{i}'])+'⟩ :=\n'
    source+='    SixQubit.K4Kernel.starSum_of_dressings\n'
    for k,j in enumerate(neighbors,1):
        e=edge_index(i,j)
        source+=f'      (c{k} := c y{e}) (r{k} := c y{j+2}) (R{k} := d z{j+2}) (C{k} := d z{e})\n'
    source+='      '+' '.join(f'(by linear_combination h{4*i+k})' for k in range(4))+'\n'
source+='  exact ⟨'+','.join(pair_names+[f's{i}' for i in range(4)])+'⟩\n\n'
source+='end MainTheory.Orbit36CrossRelations\n'
path=ROOT/'MainTheory/Orbit36CrossRelations.lean'
path.write_text(source,encoding='utf-8')
print(path.relative_to(ROOT))
