#!/usr/bin/env python3
"""Pure bit-arithmetic caches, each entry checked against physical bitstrings."""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def tree(values):
    if len(values) == 1:
        return f'(.leaf {values[0]})'
    mid = len(values)//2
    return f'(.node {mid} {tree(values[:mid])} {tree(values[mid:])})'


def generate(output):
    text = '''-- Generated by tools/generators/emit_orbit3_bit_arithmetic.py.
import MainTheory.Orbit3PauliMomentInterpretation
import MainTheory.BalancedFiniteTable

namespace SixQubit.Generated.Orbit3BitArithmetic

open MainTheory.Orbit3PauliMomentInterpretation MainTheory.BalancedFiniteTable
set_option maxHeartbeats 16000000
set_option maxRecDepth 100000

'''
    for name, typ, rows in (
            ('xor', 'Fin 64', [[a ^ b for b in range(64)] for a in range(64)]),
            ('sign', 'ℤ', [[-1 if (a & b).bit_count() % 2 else 1 for b in range(64)] for a in range(64)])):
        text += f'def {name}Table : MainTheory.BalancedFiniteTable.Tree (MainTheory.BalancedFiniteTable.Tree ({typ})) :=\n  '+tree([tree(row) for row in rows])+'\n\n'
        text += f'def {name}Value (a b : Fin 64) : {typ} :=\n  lookup (lookup {name}Table a.val) b.val\n\n'
        expr = ('bitLabel (SS.bxor (SixQubit.Realize.nbit a.val) (SixQubit.Realize.nbit b.val))'
                if name == 'xor' else
                'sign (SS.bdot (SixQubit.Realize.nbit a.val) (SixQubit.Realize.nbit b.val))')
        for a in range(64):
            fixed = expr.replace('a.val', str(a))
            text += f'theorem {name}_row_{a:02d} : ∀ b : Fin 64, {name}Value {a} b = {fixed} := by\n  decide +kernel\n\n'
        text += f'theorem {name}_correct (a b : Fin 64) : {name}Value a b = {expr} := by\n  fin_cases a\n'
        for a in range(64):
            text += f'  · exact {name}_row_{a:02d} b\n'
        text += '\n'
    text += 'end SixQubit.Generated.Orbit3BitArithmetic\n'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3BitArithmetic.lean')
    generate(parser.parse_args().output)
