#!/usr/bin/env python3
"""Emit the *index skeleton* for the future binary beta certificates.

This generator intentionally does not compute determinants and does not emit a
theorem claiming ``BetaExact 6 9``.  It only partitions the 1716 canonical
top-three-row pattern indices into small Lean modules.  The Lean definitions
refer to ``BinaryDetCircuit.patternAt``; therefore the Python copy of the
pattern tuple is diagnostic metadata, not trusted proof data.

The eventual certificate for an index ``i`` should quantify over one
``BitVec 18`` tail and prove the signed bound for
``indexedDetCircuit (R := BitVec 16) i tail``.  A separate, ordinary-kernel
bridge must relate that signed bit-vector value to the integer determinant
before those shards can establish ``BetaBound 6 9``.

This file is deliberately lightweight: running ``--check`` performs only the
``combinations_with_replacement(range(8), 6)`` index construction.  It does
not invoke Lean, Lake, ``bv_decide``, or any external solver.
"""

from __future__ import annotations

import argparse
import json
from itertools import combinations_with_replacement
from pathlib import Path


PATTERN_COUNT = 1716
# Keep future `bv_decide` proofs isolated: one pattern theorem per module avoids
# retaining several SAT certificates in the same Lean worker.
DEFAULT_SHARD_SIZE = 1


def canonical_patterns() -> list[tuple[int, ...]]:
    """Diagnostic mirror of ``weakAngles6 8`` in lexicographic order."""

    patterns = list(combinations_with_replacement(range(8), 6))
    if len(patterns) != PATTERN_COUNT:
        raise RuntimeError(
            f"internal pattern count is {len(patterns)}, expected {PATTERN_COUNT}"
        )
    return patterns


def write_if_changed(path: Path, text: str) -> None:
    """Avoid invalidating Lean build artifacts when generated bytes agree."""

    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def shard_module_name(shard_no: int) -> str:
    return f"BinaryBetaIndexShard{shard_no:03d}"


def lean_index(index: int) -> str:
    return f"⟨{index}, by decide⟩"


def emit_shard(output_dir: Path, shard_no: int, indices: range) -> str:
    """Emit definitions only; no numerical determinant theorem is asserted."""

    module = shard_module_name(shard_no)
    rendered = ",\n    ".join(lean_index(index) for index in indices)
    text = f"""-- Generated by tools/generators/gen_binary_beta.py.
-- Index partition only: this file is not a determinant certificate.
import MainTheory.BinaryDetCircuit

namespace MainTheory.Generated.{module}

open MainTheory.BinaryDetCircuit

def indices : List PatternIndex :=
  [ {rendered} ]

/-- Patterns are read from Lean's authoritative enumeration, not trusted
Python literals. -/
def patterns := indices.map patternAt

/-
Future certificate shape (intentionally not emitted yet):

  theorem det_bound_INDEX (tail : BitVec 18) :
      signedAbs (indexedDetCircuit (R := BitVec 16) INDEX tail) ≤ 9 := by
    bv_decide

Such a theorem is useful only after the ordinary-kernel BitVec/Int bridge is
present.  Do not replace this comment by an axiom or an unchecked constant.
-/

end MainTheory.Generated.{module}
"""
    write_if_changed(output_dir / f"{module}.lean", text)
    return module


def emit_aggregate(output_dir: Path, modules: list[str]) -> None:
    imports = "\n".join(f"import MainTheory.Generated.{name}" for name in modules)
    qualified = " ++\n    ".join(
        f"MainTheory.Generated.{name}.indices" for name in modules
    )
    text = f"""-- Generated by tools/generators/gen_binary_beta.py.
-- Aggregate of index definitions only; no beta theorem is claimed here.
{imports}

namespace MainTheory.Generated.BinaryBetaIndex

open MainTheory.BinaryDetCircuit

def indices : List PatternIndex :=
  {qualified}

end MainTheory.Generated.BinaryBetaIndex
"""
    write_if_changed(output_dir / "BinaryBetaIndex.lean", text)


def emit_manifest(
    manifest_path: Path,
    patterns: list[tuple[int, ...]],
    shard_size: int,
) -> None:
    payload = {
        "status": "index-plan-only",
        "trusted_for_proof": False,
        "pattern_count": len(patterns),
        "shard_size": shard_size,
        "patterns": [
            {
                "index": index,
                "pattern": list(pattern),
                "shard": index // shard_size,
            }
            for index, pattern in enumerate(patterns)
        ],
    }
    write_if_changed(
        manifest_path,
        json.dumps(payload, indent=2, sort_keys=True) + "\n",
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="check the lightweight 1716-index construction without writing files",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("MainTheory/Generated"),
        help="directory for index-only Lean shards",
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("formalization/data/binary_beta_index.json"),
        help="diagnostic, explicitly untrusted JSON index manifest",
    )
    parser.add_argument(
        "--shard-size",
        type=int,
        default=DEFAULT_SHARD_SIZE,
        help="number of canonical pattern indices per Lean module",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.shard_size <= 0:
        raise SystemExit("--shard-size must be positive")

    patterns = canonical_patterns()
    if args.check:
        print(f"binary beta index: {len(patterns)} patterns (no files written)")
        return

    modules: list[str] = []
    for start in range(0, len(patterns), args.shard_size):
        stop = min(start + args.shard_size, len(patterns))
        modules.append(
            emit_shard(
                args.output_dir,
                start // args.shard_size,
                range(start, stop),
            )
        )
    emit_aggregate(args.output_dir, modules)
    emit_manifest(args.manifest, patterns, args.shard_size)
    print(
        f"emitted {len(modules)} index-only shards for {len(patterns)} patterns; "
        "no determinant certificate was generated"
    )


if __name__ == "__main__":
    main()
