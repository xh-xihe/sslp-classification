#!/usr/bin/env python3
"""Kernel-check the Pauli invariance/parity data and primitive-row divisors."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(source: Path, output: Path):
    raw = source.read_bytes()
    terms = json.loads(raw)['terms']
    if len(terms) != 211:
        raise ValueError('Expected the complete 211-row certificate')
    divisors = [term['row_divisor'] for term in terms]
    if any(not isinstance(d, int) or d == 0 for d in divisors):
        raise ValueError('Invalid primitive row divisor')
    values = ', '.join(map(str, divisors))
    text = f'''-- Generated by tools/generators/emit_orbit3_row_metadata.py.
-- Input SHA-256: {hashlib.sha256(raw).hexdigest()}
import SixQubit.Generated.Orbit3PauliConstraints

namespace SixQubit.Generated.Orbit3RowMetadata

open MainTheory.Orbit3PauliZeros
set_option maxHeartbeats 16000000
set_option maxRecDepth 100000

def rowDivisor : Fin 211 → ℤ := ![{values}]

def pauli (i : Fin 211) (k : Fin 3) : SS.PauliString 6 :=
  decode (Orbit3PauliConstraints.labels i k)

theorem xor_zero_x : ∀ i : Fin 211, ∀ j : Fin 6,
    SS.bxor (pauli i 0).x (pauli i 1).x j = (pauli i 2).x j := by
  decide +kernel

theorem xor_zero_z : ∀ i : Fin 211, ∀ j : Fin 6,
    SS.bxor (pauli i 0).z (pauli i 1).z j = (pauli i 2).z j := by
  decide +kernel

theorem conjugation_even : ∀ i : Fin 211,
    ((pauli i 0).numY + (pauli i 1).numY + (pauli i 2).numY) % 2 = 0 := by
  decide +kernel

theorem divisor_nonzero : ∀ i : Fin 211, rowDivisor i ≠ 0 := by
  decide +kernel

end SixQubit.Generated.Orbit3RowMetadata
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT/'results/orbit3-kernel/certificate.json')
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3RowMetadata.lean')
    args = parser.parse_args()
    generate(args.input, args.output)


if __name__ == '__main__':
    main()
