#!/usr/bin/env python3
"""Discover 24 projective spectator Cliffords; emit exact kernel identities.

All discovery arithmetic is rational in r and i, with r^2=1/2 and i^2=-1.
The output proves unitarity and generator closure in actual complex matrices.
"""
from __future__ import annotations
import argparse
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def val(a=0, b=0, c=0, d=0):
    return tuple(map(Q, (a, b, c, d)))


def add(a, b):
    return tuple(x+y for x, y in zip(a, b))


def rr(a, b):
    return a[0]*b[0]+a[1]*b[1]/2, a[0]*b[1]+a[1]*b[0]


def mul(a, b):
    ac, bd, ad, bc = rr(a[:2], b[:2]), rr(a[2:], b[2:]), rr(a[:2], b[2:]), rr(a[2:], b[:2])
    return ac[0]-bd[0], ac[1]-bd[1], ad[0]+bc[0], ad[1]+bc[1]


ONE, ZERO, IM, R = val(1), val(), val(c=1), val(b=1)
PHASES = [ONE, val(b=1,d=1), IM, val(b=-1,d=1), val(-1),
          val(b=-1,d=-1), val(c=-1), val(b=1,d=-1)]
H = (R, R, R, val(b=-1))
S = (ONE, ZERO, ZERO, IM)
IDENTITY = (ONE, ZERO, ZERO, ONE)


def mm(a, b):
    return tuple(add(mul(a[2*i], b[j]), mul(a[2*i+1], b[2+j]))
                 for i in range(2) for j in range(2))


def sm(c, m):
    return tuple(mul(c, x) for x in m)


def canonical(m):
    return min((sm(c, m), k) for k, c in enumerate(PHASES))


def rat(q):
    return str(q.numerator) if q.denominator == 1 else f'({q.numerator}/{q.denominator})'


def scalar(x):
    pieces = []
    for q, basis in zip(x, ('', 'root', 'Complex.I', '(root * Complex.I)')):
        if not q:
            continue
        pieces.append(rat(q) if not basis else basis if q == 1 else f'{rat(q)} * {basis}')
    return '('+' + '.join(pieces)+')' if pieces else '0'


def matrix(m):
    return '!!['+', '.join(scalar(x) for x in m[:2])+'; '+', '.join(scalar(x) for x in m[2:])+']'


def vector(xs):
    return '!['+', '.join(map(str, xs))+']'


def generate(output):
    first, _ = canonical(IDENTITY)
    reps = [first]
    lookup = {first: 0}
    for m in reps:
        for generator in (H, S):
            new, _ = canonical(mm(generator, m))
            if new not in lookup:
                lookup[new] = len(reps)
                reps.append(new)
    if len(reps) != 24:
        raise ValueError('Expected exactly 24 projective Cliffords')
    code = ['''-- Generated by tools/generators/emit_spectator_clifford.py.
import MainTheory.PauliTransferTwo

namespace SixQubit.Generated.SpectatorClifford

open MainTheory.ClassificationLevels MainTheory.PauliTransferTwo

noncomputable section
set_option maxHeartbeats 4000000
-- One common proof template covers entries with and without real-root terms.
-- These options affect boilerplate linting only; every equality is kernel checked.
set_option linter.unusedSimpArgs false
set_option linter.unreachableTactic false
set_option linter.unnecessarySeqFocus false
set_option linter.unusedTactic false

def root : ℂ := (Real.sqrt 2 : ℂ) / 2

theorem root_star : star root = root := by simp [root]

theorem root_sq : root ^ 2 = (1/2 : ℂ) := by
  have hr : ((Real.sqrt 2 : ℝ) : ℂ) ^ 2 = 2 := by
    exact_mod_cast Real.sq_sqrt (show (0 : ℝ) ≤ 2 by norm_num)
  rw [root, div_pow, hr]
  norm_num
''']
    for k, c in enumerate(PHASES):
        code.append(f'def phase{k:02d} : ℂ := {scalar(c)}\n')
    code.append('def phase : Fin 8 → ℂ := '+vector(f'phase{k:02d}' for k in range(8))+'\n')
    for i, m in enumerate(reps):
        code.append(f'def C{i:02d} : Mat2 := {matrix(m)}\n')
        code.append(f'''theorem unit{i:02d} : IsOneQubitUnitary C{i:02d} := by
  constructor <;> ext a b <;> fin_cases a <;> fin_cases b <;>
    simp [C{i:02d}, Matrix.mul_apply, Fin.sum_univ_two, Matrix.star_apply, root_star, map_ofNat] <;>
    ring_nf <;> norm_num [root_sq, map_ofNat] <;> ring
''')
    code.append('def clifford : Fin 24 → Mat2 := '+vector(f'C{i:02d}' for i in range(24))+'\n')
    code.append('def hadamard : Mat2 := '+matrix(H)+'\n')
    code.append('def phaseGate : Mat2 := '+matrix(S)+'\n')
    for name, m in [('H', H), ('S', S)]:
        target, phases = [], []
        matrix_name = dict(H='hadamard', S='phaseGate')[name]
        for i, rep in enumerate(reps):
            result, p = canonical(mm(m, rep))
            j, p = lookup[result], (-p) % 8
            if mm(m, rep) != sm(PHASES[p], reps[j]):
                raise ValueError('Internal closure phase mismatch')
            target.append(j)
            phases.append(p)
            code.append(f'''theorem closure{name}{i:02d} :
    {matrix_name} * C{i:02d} = phase{p:02d} • C{j:02d} := by
  ext a b
  fin_cases a <;> fin_cases b <;>
    simp [{matrix_name}, C{i:02d}, C{j:02d}, phase{p:02d}, Matrix.mul_apply, Fin.sum_univ_two] <;>
    ring_nf <;> norm_num [root_sq] <;> ring
''')
        code.append(f'def next{name} : Fin 24 → Fin 24 := {vector(target)}\n')
        code.append(f'def phase{name} : Fin 24 → Fin 8 := {vector(phases)}\n')
        choices = '\n    '.join(f'| exact closure{name}{i:02d}' for i in range(24))
        code.append(f'''theorem closure{name} (g : Fin 24) :
    {matrix_name} * clifford g = phase (phase{name} g) • clifford (next{name} g) := by
  fin_cases g <;> first
    {choices}

theorem next{name}_injective : Function.Injective next{name} := by decide +kernel
theorem next{name}_bijective : Function.Bijective next{name} :=
  ⟨next{name}_injective, Finite.surjective_of_injective next{name}_injective⟩
''')
    choices = '\n    '.join(f'| exact unit{i:02d}' for i in range(24))
    code.append(f'''theorem clifford_unitary (g : Fin 24) : IsOneQubitUnitary (clifford g) := by
  fin_cases g <;> first
    {choices}

theorem phase_unit (p : Fin 8) : star (phase p) * phase p = 1 := by
  fin_cases p <;>
    simp [phase, {', '.join(f'phase{k:02d}' for k in range(8))}, root_star, map_ofNat] <;>
    ring_nf <;> norm_num [root_sq, map_ofNat] <;> ring

end
end SixQubit.Generated.SpectatorClifford
''')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(code), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/SpectatorClifford.lean')
    generate(parser.parse_args().output)
