#!/usr/bin/env python3
"""Kernel-bind the 715 ordinary XOR-zero cubic triples and all 4096 pairs."""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def vector(values):
    return '![' + ', '.join(map(str, values)) + ']'


def tree(values):
    if len(values) == 1:
        return f'(.leaf {values[0]})'
    split = len(values) // 2
    return f'(.node {split} {tree(values[:split])} {tree(values[split:])})'


def generate(output: Path):
    triples = sorted({tuple(sorted((a, b, a ^ b))) for a in range(64) for b in range(64)})
    if len(triples) != 715:
        raise ValueError('Wrong cubic basis dimension')
    lookup = {t: i for i, t in enumerate(triples)}
    pairs = [[lookup[tuple(sorted((a, b, a ^ b)))] for b in range(64)] for a in range(64)]
    values = [f'({a}, {b}, {c})' for a, b, c in triples]
    pair_tree = tree([tree(row) for row in pairs])
    canonical_rows = '\n'.join(
        f'theorem canonical_row_{a:02d} : ∀ b : Fin 64, triples (pairIndex {a} b) = canonicalPair {a} b := by\n'
        '  decide +kernel\n' for a in range(64))
    canonical_cases = '\n'.join(f'  · exact canonical_row_{a:02d} b' for a in range(64))
    text = f'''-- Generated by tools/generators/emit_orbit3_cubic_triples.py.
import MainTheory.CubicTripleCanonical
import MainTheory.BalancedFiniteTable

namespace SixQubit.Generated.Orbit3CubicTriples

open MainTheory.CubicTripleCanonical
open MainTheory.BalancedFiniteTable
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

def tripleTable : MainTheory.BalancedFiniteTable.Tree (Fin 64 × Fin 64 × Fin 64) := {tree(values)}
def triples (i : Fin 715) : Fin 64 × Fin 64 × Fin 64 :=
  MainTheory.BalancedFiniteTable.lookup tripleTable i.val
def pairTable : MainTheory.BalancedFiniteTable.Tree
    (MainTheory.BalancedFiniteTable.Tree (Fin 715)) := {pair_tree}
def pairIndex (a b : Fin 64) : Fin 715 :=
  MainTheory.BalancedFiniteTable.lookup (MainTheory.BalancedFiniteTable.lookup pairTable a.val) b.val

-- Independent fixed-row proofs cover every input pair.
{canonical_rows}
theorem canonical_pair (a b : Fin 64) : triples (pairIndex a b) = canonicalPair a b := by
  fin_cases a
{canonical_cases}

theorem pair_return : ∀ i : Fin 715, pairIndex (triples i).1 (triples i).2.1 = i := by
  decide +kernel

theorem xor_correct : ∀ i : Fin 715, xor64 (triples i).1 (triples i).2.1 = (triples i).2.2 := by
  decide +kernel

theorem ordered : ∀ i : Fin 715, (triples i).1 ≤ (triples i).2.1 ∧
    (triples i).2.1 ≤ (triples i).2.2 := by
  decide +kernel

theorem triples_injective : Function.Injective triples := by
  intro i j h
  have hp := congrArg (fun t : Fin 64 × Fin 64 × Fin 64 => pairIndex t.1 t.2.1) h
  change pairIndex (triples i).1 (triples i).2.1 = pairIndex (triples j).1 (triples j).2.1 at hp
  rw [pair_return, pair_return] at hp
  exact hp

theorem pairIndex_surjective : Function.Surjective (fun ab : Fin 64 × Fin 64 => pairIndex ab.1 ab.2) := by
  intro i
  exact ⟨((triples i).1, (triples i).2.1), pair_return i⟩

def physical (i : Fin 715) : SS.BitString 6 × SS.BitString 6 × SS.BitString 6 :=
  (SixQubit.Realize.nbit (triples i).1.val,
    SixQubit.Realize.nbit (triples i).2.1.val, SixQubit.Realize.nbit (triples i).2.2.val)

theorem physical_xor (i : Fin 715) :
    SS.bxor (physical i).1 (physical i).2.1 = (physical i).2.2 := by
  have h := congrArg (fun a : Fin 64 => SixQubit.Realize.nbit a.val) (xor_correct i)
  change SixQubit.Realize.nbit (xor64 (triples i).1 (triples i).2.1).val =
    SixQubit.Realize.nbit (triples i).2.2.val at h
  rw [nbit_xor64] at h
  exact h

theorem actual_cubic_pair (w : SS.State 6 ℂ) (a b : Fin 64) :
    monomial w (physical (pairIndex a b)) =
      w (SixQubit.Realize.nbit a.val) * w (SixQubit.Realize.nbit b.val) *
        w (SS.bxor (SixQubit.Realize.nbit a.val) (SixQubit.Realize.nbit b.val)) := by
  change monomial (fun i : Fin 64 => w (SixQubit.Realize.nbit i.val)) (triples (pairIndex a b)) = _
  rw [canonical_pair, canonicalPair, monomial_sort3]
  simp only [monomial, nbit_xor64]

end SixQubit.Generated.Orbit3CubicTriples
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3CubicTriples.lean')
    args = parser.parse_args()
    generate(args.output)


if __name__ == '__main__':
    main()
