"""Emit the enumerator of the exhibited code, for orbits with no fiber-wide mask.

Orbits 7, 8 and 9 each carry a modulus-one Pauli of weight at most two:

    orbit 7   Z on qubits {0,2}   lambda = -1   weight 2
    orbit 8   Z on qubit  {4}     lambda = -1   weight 1
    orbit 9   Z on qubits {1,2}   lambda = +1   weight 2

The sign is the parity of the mask's overlap with the support, which is uniform
across it: even fixes the state, odd negates it.  Either way the projector trace
has modulus two, so `SixQubit/Pin.lean` pins the whole enumerator.

WHAT THIS IS NOT.  For orbits 10, 11, 16, 22 and 23 the mask has even overlap
with the entire fiber, so the conclusion is about every code in the orbit.  Here
it is not: none of these three masks has uniform parity on the full fiber -- a
brute-force search over all sixty-three nonzero masks finds none for any of the
three -- so what is certified is the enumerator of the *exhibited* code, which is
attainment of one point, not uniqueness.  The manuscript gets uniqueness for
orbit 9 and an interval for orbits 7 and 8 through a support reduction this
module does not attempt.

    python tools/run.py generators/genattain.py
    python tools/run.py generators/genattain.py --check
"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
import genreal as G                                          # noqa: E402

OUT = os.path.join(REPO, 'SixQubit')
NL = chr(10)

# orbit -> (mask bits, lambda, expected weight)
JOBS = {7: ((0, 2), -1, 2), 8: ((4,), -1, 1), 9: ((1, 2), +1, 2)}
VALUES = {1: (4, 0, 0, 60, 60, 0), 2: (0, 4, 0, 44, 64, 12)}
NAMES = {1: '(1, 1, 0, 0, 15, 15, 0)', 2: '(1, 0, 1, 0, 11, 16, 3)'}


def emit(oid, rec, bits, sgn, wt, w0, w1):
    zm = tuple(1 if j in bits else 0 for j in range(6))
    a1, a2, a3, a4, a5, a6 = VALUES[wt]
    lit = ', '.join('true' if b else 'false' for b in zm)
    par = 'false' if sgn > 0 else 'true'
    parity = 'even' if sgn > 0 else 'odd'
    acts = 'fixes' if sgn > 0 else 'negates'
    lemma = 'zstring_fixes' if sgn > 0 else 'zstring_negates'
    thm = 'enumerator_of_forced' if sgn > 0 else 'enumerator_of_forced_neg'
    rhs = '' if sgn > 0 else '-'
    branch = '.1' if wt == 1 else '.2'
    return '''import Mathlib
import SS.HilbertKL
import SixQubit.Pin
import SixQubit.Orbit{oid}Real

/-!
# Orbit {oid}: the enumerator of the exhibited code

The code of `SixQubit/Orbit{oid}Real.lean` carries the `Z`-string on qubits
`{bitsdoc}`, whose overlap with every word of both supports is {parity}, so it
{acts} both logical words.  Its Pauli weight is {wt}, so `SixQubit/Pin.lean`
pins the enumerator to

    {name}

**Scope.**  This is attainment of one point, not uniqueness.  For orbits 10, 11,
16, 22 and 23 the analogous mask has even overlap with the whole *fiber*, so
their `enumerator_unique` is about every code in the orbit.  No mask does that
here: a search over all sixty-three nonzero masks finds none with uniform parity
on orbit {oid}'s fibers.  The manuscript reaches its orbit-{oid} claim through a
support reduction that is not attempted in this development.

Generated by `tools/generators/genattain.py`.
-/

namespace SixQubit.Orbit{oid}Attain

open SS.MacWilliams SixQubit.Pin SixQubit.Orbit{oid}Real

/-- The `Z`-string on qubits `{bitsdoc}`. -/
def zmask : SS.BitString 6 := ![{lit}]

/-- Its overlap with every bottom word is {parity}. -/
theorem zmask_L0 : ∀ s ∈ L0, SS.bdot zmask s = {par} := by decide

/-- Its overlap with every top word is {parity}. -/
theorem zmask_L1 : ∀ s ∈ L1, SS.bdot zmask s = {par} := by decide

/-- Its Pauli weight. -/
theorem zmask_wt :
    (⟨fun _ => false, zmask⟩ : SS.PauliString 6).wt = {wt} := by decide

/-- **The exhibited orbit-{oid} code has enumerator `{name}`.** -/
theorem enumerator :
    Aco ![w0, w1] 1 = {a1} ∧ Aco ![w0, w1] 2 = {a2} ∧ Aco ![w0, w1] 3 = {a3}
      ∧ Aco ![w0, w1] 4 = {a4} ∧ Aco ![w0, w1] 5 = {a5}
      ∧ Aco ![w0, w1] 6 = {a6} := by
  have hnorm : ∀ k, SS.innerC ((![w0, w1] : Fin 2 → SS.State 6 ℂ) k)
      ((![w0, w1] : Fin 2 → SS.State 6 ℂ) k) = 1 := by
    intro k
    fin_cases k
    · exact w0_normalized
    · exact w1_normalized
  have hG : ∀ k, SS.pauliAct (⟨fun _ => false, zmask⟩ : SS.PauliString 6)
      ((![w0, w1] : Fin 2 → SS.State 6 ℂ) k)
        = {rhs}((![w0, w1] : Fin 2 → SS.State 6 ℂ) k) := by
    intro k
    fin_cases k
    · exact {lemma} w0 L0 w0_vanishes zmask zmask_L0
    · exact {lemma} w1 L1 w1_vanishes zmask zmask_L1
  exact ({thm} ![w0, w1] is_code (Aco_zero _ hnorm) hnorm _ hG){branch} zmask_wt

end SixQubit.Orbit{oid}Attain
'''.format(oid=oid, bitsdoc=''.join(str(b) for b in zm), parity=parity,
           acts=acts, wt=wt, name=NAMES[wt], lit=lit, par=par, lemma=lemma,
           thm=thm, rhs=rhs, branch=branch,
           a1=a1, a2=a2, a3=a3, a4=a4, a5=a5, a6=a6)


def main(argv):
    check_only = '--check' in argv
    want = [int(a) for a in argv if a.isdigit()] or sorted(JOBS)
    real, cplx, jobs = G.load_doc()
    print('%-6s %-8s %-8s %-5s %-9s %s'
          % ('orbit', 'mask', 'lambda', 'wt', 'parity', 'status'))
    written, bad = 0, False
    for oid in want:
        bits, sgn, wt = JOBS[oid]
        rec = jobs[oid]
        w0 = G.build_word(real, cplx, rec['base'], 0, rec['perm'], rec['t'])
        w1 = G.build_word(real, cplx, rec['base'], 1, rec['perm'], rec['t'])
        if rec['swap']:
            w0, w1 = w1, w0
        zm = tuple(1 if j in bits else 0 for j in range(6))
        par = set(sum(zi * xi for zi, xi in zip(zm, x)) % 2
                  for x in list(w0) + list(w1))
        want_par = {0} if sgn > 0 else {1}
        ok = (par == want_par and sum(zm) == wt)
        bad |= not ok
        print('%-6d %-8s %-8s %-5d %-9s %s'
              % (oid, 'Z' + ''.join(map(str, bits)), '%+d' % sgn, sum(zm),
                 'even' if par == {0} else 'odd' if par == {1} else 'MIXED',
                 'ok' if ok else 'FAIL'))
        if ok and not check_only:
            io.open(os.path.join(OUT, 'Orbit%dAttain.lean' % oid), 'w',
                    encoding='utf-8', newline=NL).write(
                        emit(oid, rec, bits, sgn, wt, w0, w1))
            written += 1
    print()
    print('modules written: %d' % written)
    return 1 if bad else 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
