#!/usr/bin/env python3
"""Candidate coefficient trees; their raw Pauli provenance is kernel checked.

The input supplies expected coefficients only. It cannot supply the semantic
proof: that proof compares each tree with collection of all actual bit pairs.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def tree(values):
    if not any(values):
        return f'(MainTheory.DyadicCoefficientTree.zero {(len(values)).bit_length()-1})'
    if len(values) == 1:
        return f'(.leaf ({values[0]}))'
    mid = len(values)//2
    return f'(.node {tree(values[:mid])} {tree(values[mid:])})'


def generate(output: Path):
    certificate = ROOT/'results/orbit3-kernel/certificate.json'
    reduced = ROOT/'results/orbit3-kernel/reduced-coefficients.json'
    terms = json.loads(certificate.read_text(encoding='utf-8'))['terms']
    rows = json.loads(reduced.read_text(encoding='utf-8'))['rows']
    if len(terms) != 211 or len(rows) != 211:
        raise ValueError('Expected 211 complete rows')
    header = ('-- Generated by tools/generators/emit_orbit3_collected_rows.py.\n'
              f'-- Certificate SHA-256: {hashlib.sha256(certificate.read_bytes()).hexdigest()}\n'
              f'-- Reduced SHA-256: {hashlib.sha256(reduced.read_bytes()).hexdigest()}\n'
              'import MainTheory.DyadicCoefficientTree\n'
              'import MainTheory.BalancedFiniteTable\n\n'
              'namespace SixQubit.Generated.Orbit3CollectedRows.Data\n\n')
    values = []
    for i, (term, row) in enumerate(zip(terms, rows)):
        if len(row) != 269 or any(not isinstance(v, int) for v in row):
            raise ValueError('Expected integral primitive rows')
        coefficients = [v*term['row_divisor'] for v in row]+[0]*243
        header += f'def row{i:03d} : MainTheory.DyadicCoefficientTree.Tree 9 :=\n  {tree(coefficients)}\n\n'
        values.append(f'row{i:03d}')

    def table(v):
        if len(v) == 1:
            return f'(.leaf {v[0]})'
        mid = len(v)//2
        return f'(.node {mid} {table(v[:mid])} {table(v[mid:])})'

    header += ('def rowTable : MainTheory.BalancedFiniteTable.Tree '
               '(MainTheory.DyadicCoefficientTree.Tree 9) :=\n  '+table(values)+'\n\n'
               'def row (i : Fin 211) : MainTheory.DyadicCoefficientTree.Tree 9 :=\n'
               '  MainTheory.BalancedFiniteTable.lookup rowTable i.val\n\n'
               'end SixQubit.Generated.Orbit3CollectedRows.Data\n')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path,
                        default=ROOT/'SixQubit/Generated/Orbit3CollectedRows/Data.lean')
    generate(parser.parse_args().output)
