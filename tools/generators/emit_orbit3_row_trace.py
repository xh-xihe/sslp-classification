#!/usr/bin/env python3
"""Candidate cumulative row states; every transition requires a kernel proof."""
from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path
from functools import lru_cache

from emit_orbit3_collected_rows import tree

ROOT = Path(__file__).resolve().parents[2]


@lru_cache(maxsize=1)
def inputs():
    spec = importlib.util.spec_from_file_location('sextic_trace', ROOT/'tools/certificates/orbit3_exact_sextic_certificate.py')
    v = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(v)
    terms = json.loads((ROOT/'results/orbit3-kernel/certificate.json').read_text(encoding='utf-8'))['terms']
    rows = json.loads((ROOT/'results/orbit3-kernel/reduced-coefficients.json').read_text(encoding='utf-8'))['rows']
    return terms, rows, v.coordinate_tables()


def generate(row, output, proof_output=None, certified_output=None):
    all_terms, rows, tables = inputs()
    term = all_terms[row]
    if term['kind'] != 'kl':
        raise ValueError('Pauli trace generator expects a KL row')
    _, _, entries, pairs, _ = tables
    labels = term['paulis']
    x = [r & 63 for r in labels]
    z = [r >> 6 for r in labels]
    iphase = sum((xx & zz).bit_count() for xx, zz in zip(x, z)) % 4
    if iphase % 2 or labels[0] ^ labels[1] ^ labels[2]:
        raise ValueError('Invalid physical Pauli triple')
    prefix = [0]*512
    states = [prefix.copy()]
    for a in range(64):
        for b in range(64):
            coord = entries[pairs[a][b]][pairs[a ^ x[0]][b ^ x[1]]]
            if coord >= 0:
                parity = sum((t & zz).bit_count() for t, zz in zip((a, b, a ^ b), z)) % 2
                prefix[coord] += 1 if (parity + iphase//2) % 2 == 0 else -1
        states.append(prefix.copy())
    expected = rows[row]
    if prefix[:269] != [c*term['row_divisor'] for c in expected]:
        raise ArithmeticError('Candidate final state disagrees with expected coefficients')
    namespace = f'SixQubit.Generated.Orbit3CollectedRows.Trace{row:03d}'
    text = f'''-- Generated by tools/generators/emit_orbit3_row_trace.py.
-- Candidate cumulative data; transitions are checked in separate proof modules.
import MainTheory.DyadicCoefficientTree
import MainTheory.BalancedFiniteTable

namespace {namespace}

'''
    for i, state in enumerate(states):
        text += f'def state{i:02d} : MainTheory.DyadicCoefficientTree.Tree 9 :=\n  {tree(state)}\n\n'

    def table(values):
        if len(values) == 1:
            return f'(.leaf {values[0]})'
        mid = len(values)//2
        return f'(.node {mid} {table(values[:mid])} {table(values[mid:])})'

    text += ('def stateTable : MainTheory.BalancedFiniteTable.Tree (MainTheory.DyadicCoefficientTree.Tree 9) :=\n  '
             +table([f'state{i:02d}' for i in range(65)])+'\n\n'
             'def states (n : ℕ) : MainTheory.DyadicCoefficientTree.Tree 9 :=\n'
             '  MainTheory.BalancedFiniteTable.lookup stateTable n\n\n'
             f'end {namespace}\n')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')
    if proof_output is not None:
        proof = f'''-- Generated by tools/generators/emit_orbit3_row_trace.py.
import {namespace}
import SixQubit.Generated.Orbit3RowMetadata
import SixQubit.Generated.Orbit3CollectedRows.Data
import MainTheory.Orbit3CoefficientTrace

namespace {namespace}.Checks

set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

'''
        for a in range(64):
            proof += (f'theorem step{a:02d} : MainTheory.DyadicCoefficientTree.accumulate state{a:02d}\n'
                      f'    (MainTheory.Orbit3CoefficientTrace.rowTerms (Orbit3RowMetadata.pauli {row}) {a}) = state{a+1:02d} := by\n'
                      '  decide +kernel\n\n')
        proof += (f'theorem steps : ∀ a : Fin 64, MainTheory.DyadicCoefficientTree.accumulate (states a.val)\n'
                  f'    (MainTheory.Orbit3CoefficientTrace.rowTerms (Orbit3RowMetadata.pauli {row}) a) = states (a.val + 1) := by\n'
                  '  intro a\n  fin_cases a\n')
        for a in range(64):
            proof += f'  · exact step{a:02d}\n'
        proof += ('\ntheorem initial : states 0 = MainTheory.DyadicCoefficientTree.zero 9 := by decide +kernel\n\n'
                  f'theorem final : states 64 = SixQubit.Generated.Orbit3CollectedRows.Data.row{row:03d} := by decide +kernel\n\n'
                  f'end {namespace}.Checks\n')
        proof_output.parent.mkdir(parents=True, exist_ok=True)
        proof_output.write_text(proof, encoding='utf-8', newline='\n')
    if certified_output is not None:
        certified = f'''-- Generated by tools/generators/emit_orbit3_row_trace.py.
import {namespace}Checks
import MainTheory.Orbit3CollectedPauliRow

namespace {namespace}.Certified

set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

theorem primitive_coefficients : ∀ j : Fin 269,
    (MainTheory.DyadicCoefficientTree.lookup SixQubit.Generated.Orbit3CollectedRows.Data.row{row:03d} j.val : ℚ) =
      (SixQubit.Generated.Orbit3RowMetadata.rowDivisor {row} : ℚ) *
        SixQubit.Generated.Orbit3SexticIdentity.rows {row} j := by decide +kernel

theorem primitive_row_zero (W : MainTheory.Orbit3ScalarCategoryRealization.Encoder) :
    SixQubit.Generated.Orbit3SexticIdentity.evaluate (SixQubit.Generated.Orbit3SexticIdentity.rows {row})
      (MainTheory.Orbit3CoordinateRealization.coordinates W) = 0 :=
  MainTheory.Orbit3CollectedPauliRow.primitive_row_zero W {row} (by decide +kernel)
    states Checks.initial Checks.steps Checks.final primitive_coefficients

end {namespace}.Certified
'''
        certified_output.parent.mkdir(parents=True, exist_ok=True)
        certified_output.write_text(certified, encoding='utf-8', newline='\n')


def generate_all(directory=None, aggregate_output=None):
    terms, _, _ = inputs()
    directory = directory or ROOT/'SixQubit/Generated/Orbit3CollectedRows'
    aggregate_output = aggregate_output or ROOT/'SixQubit/Generated/Orbit3CollectedKLRows.lean'
    rows = [i for i, t in enumerate(terms) if t['kind'] == 'kl']
    for row in rows:
        if row == 0:
            continue
        generate(row, directory/f'Trace{row:03d}.lean', directory/f'Trace{row:03d}Checks.lean',
                 directory/f'Trace{row:03d}Certified.lean')
    text = ('-- Generated by tools/generators/emit_orbit3_row_trace.py.\n'
            'import MainTheory.Orbit3FirstCollectedRow\n')
    for row in rows:
        if row:
            text += f'import SixQubit.Generated.Orbit3CollectedRows.Trace{row:03d}Certified\n'
    text += '''
namespace SixQubit.Generated.Orbit3CollectedKLRows

set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

theorem all_kl_primitive_rows_zero (W : MainTheory.Orbit3ScalarCategoryRealization.Encoder)
    (i : Fin 211) (hi : Orbit3PauliConstraints.kind i = 0) :
    Orbit3SexticIdentity.evaluate (Orbit3SexticIdentity.rows i)
      (MainTheory.Orbit3CoordinateRealization.coordinates W) = 0 := by
  fin_cases i
'''
    for i, term in enumerate(terms):
        if term['kind'] != 'kl':
            text += f'  · exact False.elim ((by decide +kernel : Orbit3PauliConstraints.kind {i} ≠ 0) hi)\n'
        elif not i:
            text += '  · exact MainTheory.Orbit3FirstCollectedRow.primitive_row_zero W\n'
        else:
            text += f'  · exact Orbit3CollectedRows.Trace{i:03d}.Certified.primitive_row_zero W\n'
    text += '\nend SixQubit.Generated.Orbit3CollectedKLRows\n'
    aggregate_output.write_text(text, encoding='utf-8', newline='\n')
    print(f'Generated {len(rows)-1} additional complete KL row traces and their semantic bindings; candidates require kernel checks.')


def generate_step_probe(row, step, output):
    namespace = f'SixQubit.Generated.Orbit3CollectedRows.Trace{row:03d}'
    text = f'''import {namespace}
import SixQubit.Generated.Orbit3RowMetadata
import MainTheory.Orbit3CoefficientTrace

namespace {namespace}

set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

theorem step{step:02d} : MainTheory.DyadicCoefficientTree.accumulate state{step:02d}
    (MainTheory.Orbit3CoefficientTrace.rowTerms (Orbit3RowMetadata.pauli {row}) {step}) = state{step+1:02d} := by
  decide +kernel

end {namespace}
'''
    output.write_text(text, encoding='utf8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--row', type=int)
    parser.add_argument('--all-kl', action='store_true')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--proof-output', type=Path)
    parser.add_argument('--certified-output', type=Path)
    args = parser.parse_args()
    if args.all_kl:
        generate_all()
    elif args.row is not None:
        generate(args.row, args.output or ROOT/f'SixQubit/Generated/Orbit3CollectedRows/Trace{args.row:03d}.lean',
                 args.proof_output, args.certified_output)
    else:
        parser.error('Specify --row or --all-kl')
