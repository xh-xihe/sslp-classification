#!/usr/bin/env python3
"""Enumerate, per coarse-directory row, that a right-rejected row's pair is one
of the 422 certified in `Generated.ExtraMomentData`.

That is the one hypothesis `CoarseFilterSound.keepAt_of_s0_of_feasible` still
carries.  It is decidable and purely combinatorial -- true by construction,
since the 422 were read off the directory's own generated source -- but it
ranges over all 11,422 rows, so it is discharged in chunks: a single `decide`
over the whole table would exceed the kernel's patience, while 500 rows at a
time costs about half a minute.

Emitted:

  Generated/CoarseRightRows/ChunkNN.lean   500 rows each, 23 chunks
  Generated/CoarseRightRowsData.lean       the assembled statement

Usage:  python tools/generators/emit_coarse_right_rows.py [--chunk N]
"""
import io
import os
import sys

ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'MainTheory', 'Generated', 'CoarseRightRows')
TOP = os.path.join(ROOT, 'MainTheory', 'Generated', 'CoarseRightRowsData.lean')
ROWS = 11422
CHUNK = 500
NL = chr(10)

HEAD = ['-- Generated by tools/generators/emit_coarse_right_rows.py.',
        '-- Do not edit by hand; regenerate it instead.', '']


def chunk(idx, base, length):
    return NL.join(HEAD + [
        'import MainTheory.CoarseFilterSound',
        '',
        'namespace MainTheory.Generated.CoarseRightRows.Chunk%02d' % idx,
        '',
        'open MainTheory.CoarseFilterSound',
        'open MainTheory.Generated.FiniteCoarseDirectory',
        'open MainTheory.Generated.FinitePairMappingBase',
        '',
        'set_option maxRecDepth 4000000',
        'set_option maxHeartbeats 4000000',
        '',
        '/-- Rows %d to %d: a right-rejected row carries one of the certified'
        % (base, base + length - 1),
        'pairs. -/',
        'theorem covered : ∀ k, ∀ h : k < %d,' % length,
        '    isRejectRight (directory.decisionAt ⟨%d + k, by omega⟩) = true →'
        % base,
        '    directory.inputAt ⟨%d + k, by omega⟩ ∈' % base,
        '      MainTheory.Generated.ExtraMoment.rejectRightPairs := by decide',
        '',
        'end MainTheory.Generated.CoarseRightRows.Chunk%02d' % idx,
        '',
    ])


def top(bounds):
    n = len(bounds)
    lines = list(HEAD)
    lines += ['import MainTheory.Generated.CoarseRightRows.Chunk%02d' % i
              for i in range(n)]
    lines += [
        '',
        '/-!',
        '# Every right-rejected coarse row is one of the certified 422',
        '',
        'This discharges the last hypothesis of',
        '`CoarseFilterSound.keepAt_of_s0_of_feasible`.  With it, the coarse',
        'filter is proved never to discard a code, using only the `S_0` clause',
        "(proved) and moment infeasibility (certified) -- never the paper's",
        '`q <= beta_r` at the affine rank, which does not follow from what is',
        'proved here.  See `results/coarse-filter-audit.md`.',
        '-/',
        '',
        'namespace MainTheory.Generated.CoarseRightRows',
        '',
        'open MainTheory.CoarseFilterSound',
        'open MainTheory.Generated.FiniteCoarseDirectory',
        'open MainTheory.Generated.FinitePairMappingBase',
        '',
        '/-- **A right-rejected row carries one of the 422 certified pairs.** -/',
        'theorem rejectRight_mem (i : PairId)',
        '    (h : isRejectRight (directory.decisionAt i) = true) :',
        '    directory.inputAt i ∈',
        '      MainTheory.Generated.ExtraMoment.rejectRightPairs := by',
        '  have hlt := i.isLt',
        '  rcases (show %s from by omega) with %s'
        % (' ∨ '.join('(%d ≤ i.1 ∧ i.1 < %d)' % (b, b + l)
                      for b, l in bounds),
           ' | '.join(['hc'] * n)),
    ]
    for idx, (b, l) in enumerate(bounds):
        lines += [
            '  · have hb : (⟨%d + (i.1 - %d), by omega⟩ : PairId) = i := by'
            % (b, b),
            '      apply Fin.ext',
            '      simp only []',
            '      omega',
            '    have := Chunk%02d.covered (i.1 - %d) (by omega)' % (idx, b),
            '    rw [hb] at this',
            '    exact this h',
        ]
    lines += ['', 'end MainTheory.Generated.CoarseRightRows', '']
    return NL.join(lines)


def main():
    bounds = []
    base = 0
    while base < ROWS:
        bounds.append((base, min(CHUNK, ROWS - base)))
        base += CHUNK
    only = None
    if '--chunk' in sys.argv:
        only = int(sys.argv[sys.argv.index('--chunk') + 1])
    if not os.path.isdir(OUT):
        os.makedirs(OUT)
    for i, (b, l) in enumerate(bounds):
        if only is not None and i != only:
            continue
        io.open(os.path.join(OUT, 'Chunk%02d.lean' % i), 'w',
                encoding='utf-8', newline=NL).write(chunk(i, b, l))
    if only is None:
        io.open(TOP, 'w', encoding='utf-8', newline=NL).write(top(bounds))
    print('%d chunks covering %d rows' % (len(bounds), ROWS))
    return 0


if __name__ == '__main__':
    sys.exit(main())
