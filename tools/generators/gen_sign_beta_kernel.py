"""Emit ordinary-kernel certificates for an untrusted sign-prefix search DAG.

The proposal, graph canonicalizer and SymPy computations are not trusted.
Every branch is checked by SignDagCertificate, determinants are propagated by
GramSchurCertificate, and terminal matrices supply checked integral inverses.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import re
from pathlib import Path
import sympy as sp

ROOT = Path(__file__).resolve().parents[2]
PENDING = {}


def matrix(rows):
    return '!![' + ';\n    '.join(', '.join(map(str, row)) for row in rows) + ']'


def vector(values):
    return '![' + ', '.join(map(str, values)) + ']'


def entry(mask, j):
    return 1 - 2 * ((mask >> j) & 1)


def node_name(k, i):
    return f'N{k:02d}_{i:04d}'


def write_module(base, relative, imports, body):
    module = base + '.' + relative
    if relative.startswith('Proof.'):
        # Pure kernel evaluation avoids duplicating the same closed reduction
        # in the elaborator. This never invokes a native evaluation axiom.
        body = body.replace('by decide', 'by decide +kernel')
    text = '\nnamespace ' + module + '\n\n'
    text += 'open Matrix\nopen MainTheory.SignMatrixCertificate MainTheory.SignPrefixCertificate\n'
    text += 'open MainTheory.GramSchurCertificate MainTheory.SignDagCertificate\n\n'
    text += re.sub(r'\bprefix\b', 'rowsMatrix', body) + '\nend ' + module + '\n'
    PENDING[module] = (imports, text)
    return module


def flush_modules(base, group_size, proposal, proof_group_size=1, quadratic_prune=False,
                  quadratic_chunks=False):
    mapping = {}
    grouped = {}
    for module in PENDING:
        kind, node = module[len(base)+1:].split('.')
        depth, index = map(int, node[1:].split('_'))
        size = proof_group_size if kind == 'Proof' else group_size
        target = f'{base}.{kind}.G{depth:02d}_{index//size:04d}'
        mapping[module] = target
        grouped.setdefault(target, []).append(module)
    inventory = []
    for module, nodes in grouped.items():
        imports = list(dict.fromkeys(mapping.get(dep, dep) for node in nodes for dep in PENDING[node][0]))
        text = '-- Generated by tools/generators/gen_sign_beta_kernel.py.\n'
        text += '\n'.join('import ' + name for name in imports)
        text += '\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n'
        text += ''.join(PENDING[node][1] for node in nodes)
        path = ROOT / (module.replace('.', '/') + '.lean')
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding='utf-8') != text:
            path.write_text(text, encoding='utf-8', newline='\n')
        inventory.append(dict(module=module, sha256=hashlib.sha256(text.encode()).hexdigest(),imports=imports,nodes=nodes))
    manifest = dict(schema=1, proposal_sha256=hashlib.sha256(proposal.read_bytes()).hexdigest(),
                    group_size=group_size,proof_group_size=proof_group_size,modules=inventory)
    if quadratic_prune:
        manifest['quadratic_prune'] = True
    if quadratic_chunks:
        manifest['quadratic_chunks'] = True
    destination = ROOT / base.replace('.', '/') / 'manifest.json'
    destination.write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    return mapping


def chunk_certificate(base, k, n, node, chunk, threshold, bound):
    """Check uniform pruned cubes and retain transport checks on mixed cubes."""
    assert chunk > 0 and chunk & (chunk-1) == 0
    free = chunk.bit_length()-1
    chunks = (1 << n)//chunk
    edges = node['edges']
    assert [e['mask'] for e in edges] == list(range(1 << n))
    uniform = [all(e.get('pruned') for e in edges[b*chunk:(b+1)*chunk])
               for b in range(chunks)]
    target_ids = sorted({e['target'] for e in edges if not e.get('pruned')})
    target_map = {t: j for j, t in enumerate(target_ids)}
    L = len(target_ids)
    targets = [base+'.Proof.'+node_name(k+1,t) for t in target_ids]
    imports = targets + ['MainTheory.SignQuadraticChunkPrune']
    P = sp.Matrix([[entry(row,j) for j in range(n)] for row in node['rows']])
    image = sp.Matrix(node['_adj'])*P
    quadratic = P.T*image
    body = f'def imageMatrix : Matrix (Fin {k}) (Fin {n}) ℤ :=\n  {matrix(image.tolist())}\n\n'
    body += f'def quadraticMatrix : Matrix (Fin {n}) (Fin {n}) ℤ :=\n  {matrix(quadratic.tolist())}\n\n'
    body += 'theorem checked_pullback : quadraticMatrix = prefix.transpose * gramAdj * prefix := by\n'
    body += '  rw [Matrix.mul_assoc, show gramAdj * prefix = imageMatrix by decide]\n  decide\n\n'
    target_data = [base+'.Data.'+node_name(k+1,t)+'.prefix' for t in target_ids]
    body += f'def targets : Fin {L} → Matrix (Fin {k+1}) (Fin {n}) ℤ :=\n'
    body += '  fun t => (#['+',\n    '.join(target_data)+']).getD t.val 0\n\n'
    body += f'theorem targets_good : ∀ t, PrefixGood {threshold} {bound} (by decide : {k+1} ≤ {n}) (targets t) := by\n'
    body += '  intro t\n  fin_cases t\n'
    body += ''.join(f'  · exact {t}.certificate\n' for t in targets)
    values = []
    adj = node['_adj']
    for edge in edges:
        if uniform[edge['mask']//chunk]:
            # This value is never used as an edge certificate. The entire cube
            # is proved directly from the checked restricted quadratic minimum.
            values.append('.inl ⟨0, 0⟩')
        elif edge.get('pruned'):
            cross = [n-2*(r^edge['mask']).bit_count() for r in node['rows']]
            prod = [sum(adj[i][j]*cross[j] for j in range(k)) for i in range(k)]
            assert n*node['det']-sum(x*y for x,y in zip(cross,prod)) == edge['det']
            values.append('.inl ⟨'+vector(cross)+', '+vector(prod)+'⟩')
        else:
            w = edge['transport']
            vals = [vector(w['row_perm']),vector(w['column_perm']),
                    vector([1-2*x for x in w['row_sign']]),
                    vector([1-2*x for x in w['column_sign']])]
            values.append(f'.inr ({target_map[edge["target"]]}, ⟨'+', '.join(vals)+'⟩)')
    body += f'\ndef choices : Fin {1<<n} → Edge {k} {n} {L} :=\n'
    body += '  fun mask => (#['+',\n    '.join(values)+']).getD mask.val (.inl ⟨0, 0⟩)\n\n'
    for b in range(chunks):
        mask = f'(@finProdFinEquiv {chunks} {chunk} (({b} : Fin {chunks}), j))'
        body += f'theorem child_chunk_{b:03d} : ∀ j : Fin {chunk},\n'
        body += f'    PrefixGood {threshold} {bound} (by decide : {k+1} ≤ {n})\n'
        body += f'      (Fin.snoc prefix (MainTheory.SignRowEnumeration.row (N := {n}) {mask})) := by\n'
        if uniform[b]:
            fixed = f'(MainTheory.SignQuadraticChunkPrune.fixedHighBits (N := {n}) {free} ({b*chunk} : Fin {1<<n}))'
            body += f'  have hf : ∀ j : Fin {chunk}, MainTheory.SignQuadraticMinimum.Matches\n'
            body += f'      {fixed} (MainTheory.SignRowEnumeration.row (N := {n}) {mask}) := by decide\n'
            body += '  intro j\n  apply MainTheory.SignQuadraticChunkPrune.prefixGood_snoc_of_restricted_minimum\n'
            body += f'    (by decide : {k+1} ≤ {n}) prefix gramAdj {node["det"]} (by decide) det_eq gram_inverse\n'
            body += f'    (by decide) quadraticMatrix checked_pullback {fixed}\n'
            body += f'    (by decide) _ (MainTheory.SignRowEnumeration.row_isSign _) (hf j)\n\n'
        else:
            body += f'  have he : ∀ j : Fin {chunk}, EdgeValid {threshold} prefix gramAdj {node["det"]} targets\n'
            body += f'      {mask} (choices {mask}) := by decide\n'
            body += '  intro j\n  exact MainTheory.SignQuadraticChunkPrune.prefixGood_snoc_of_edge\n'
            body += f'    (by decide : {k+1} ≤ {n}) prefix gramAdj {node["det"]} (by decide) det_eq gram_inverse\n'
            body += f'    (by decide) targets targets_good _ _ (he j)\n\n'
    body += f'theorem certificate : PrefixGood {threshold} {bound} (by decide : {k} ≤ {n}) prefix := by\n'
    body += f'  apply MainTheory.SignQuadraticChunkPrune.prefixGood_of_row_certificates (by decide : {k+1} ≤ {n}) prefix\n'
    body += f'  apply forall_chunks (c := {chunk}) (d := {chunks})\n  intro b\n  fin_cases b\n'
    body += ''.join(f'  · exact child_chunk_{b:03d}\n' for b in range(chunks))
    return imports, body


def generate(proposal, chunk, group_size, quadratic_prune=False, quadratic_chunks=False):
    quadratic_prune = quadratic_prune or quadratic_chunks
    raw = gzip.decompress(proposal.read_bytes()) if proposal.suffix == '.gz' else proposal.read_bytes()
    data = json.loads(raw)
    n, bound = data['sign_order'], data['bound']
    assert chunk > 0 and (1 << n) % chunk == 0
    threshold = (1 << (n-1)) * (bound+1)
    levels = data['levels']
    assert len(levels) == n and len(levels[0]) == 1 and levels[0][0]['rows'] == [0]
    base = f'MainTheory.Generated.SignBeta{n-1}'
    lookup = [{tuple(node['rows']): i for i, node in enumerate(level)} for level in levels]
    modules = []
    for k, level in enumerate(levels, 1):
        for i, node in enumerate(level):
            name = node_name(k, i)
            rows = node['rows']
            assert len(rows) == k
            P = sp.Matrix([[entry(r, j) for j in range(n)] for r in rows])
            G = P * P.T
            a = int(G.det())
            assert a == node['det'] and a > 0
            J = G.adjugate()
            assert G*J == a*sp.eye(k)
            node['_adj'] = [[int(x) for x in row] for row in J.tolist()]
            imports = ['MainTheory.SignDagCertificate']
            body = f'def prefix : Matrix (Fin {k}) (Fin {n}) ℤ :=\n  {matrix(P.tolist())}\n\n'
            body += f'def gramAdj : Matrix (Fin {k}) (Fin {k}) ℤ :=\n  {matrix(J.tolist())}\n\n'
            body += f'theorem gram_inverse : gram prefix * gramAdj = ({a} : ℤ) • 1 := by decide\n\n'
            body += f'theorem det_eq : (gram prefix).det = {a} := by\n'
            if k == 1:
                body += '  rw [Matrix.det_fin_one]\n  decide\n'
            else:
                parent_i = lookup[k-2][tuple(rows[:-1])]
                parent = base + '.Data.' + node_name(k-1, parent_i)
                imports.append(parent)
                parent_a = levels[k-2][parent_i]['det']
                mask = rows[-1]
                body += f'  have h := det_gram_snoc {parent}.prefix\n'
                body += f'    (MainTheory.SignRowEnumeration.row ({mask} : Fin {1<<n}))\n'
                body += f'    (MainTheory.SignRowEnumeration.row_isSign _) {parent}.gramAdj {parent_a}\n'
                body += f'    (by decide) {parent}.det_eq {parent}.gram_inverse\n'
                body += f'  rw [show Fin.snoc {parent}.prefix\n'
                body += f'    (MainTheory.SignRowEnumeration.row ({mask} : Fin {1<<n})) = prefix by decide] at h\n'
                body += f'  exact h.trans (by decide)\n'
            modules.append(write_module(base, 'Data.'+name, imports, body))
    for k in range(n, 0, -1):
        for i, node in enumerate(levels[k-1]):
            name = node_name(k, i)
            own = base + '.Data.' + name
            imports = [own, 'MainTheory.SignDagFastCertificate']
            body = f'open {own}\nopen MainTheory.SignDagFastCertificate\n\n'
            if k == n:
                P = sp.Matrix([[entry(r, j) for j in range(n)] for r in node['rows']])
                q = node['leaf']['denominator']
                J = 2*q*P.inv()
                assert 0 < q <= bound and all(x.q == 1 for x in J)
                J = [[int(x) for x in row] for row in J.tolist()]
                body += f'def cleared : Matrix (Fin {n}) (Fin {n}) ℤ :=\n  {matrix(J)}\n\n'
                body += f'theorem certificate : PrefixGood {threshold} {bound} (by decide : {k} ≤ {n}) prefix := by\n'
                body += f'  apply prefixGood_leaf\n  exact good_of_cleared_inverse (q := {q}) (J := cleared) (by decide) (by decide) (by decide)\n'
            elif quadratic_prune and all(edge.get('pruned') for edge in node['edges']):
                imports.append('MainTheory.SignQuadraticPrune')
                P = sp.Matrix([[entry(row, j) for j in range(n)] for row in node['rows']])
                image = sp.Matrix(node['_adj']) * P
                quadratic = P.T * image
                body += f'def imageMatrix : Matrix (Fin {k}) (Fin {n}) ℤ :=\n  {matrix(image.tolist())}\n\n'
                body += f'def quadraticMatrix : Matrix (Fin {n}) (Fin {n}) ℤ :=\n  {matrix(quadratic.tolist())}\n\n'
                body += 'theorem checked_pullback : quadraticMatrix = prefix.transpose * gramAdj * prefix := by\n'
                body += '  rw [Matrix.mul_assoc, show gramAdj * prefix = imageMatrix by decide]\n  decide\n\n'
                body += f'theorem certificate : PrefixGood {threshold} {bound} (by decide : {k} ≤ {n}) prefix := by\n'
                body += '  apply MainTheory.SignQuadraticPrune.prefixGood_of_quadratic_minimum\n'
                body += f'    (by decide : {k+1} ≤ {n}) prefix gramAdj {node["det"]} (by decide) det_eq gram_inverse\n'
                body += '    (by decide) quadraticMatrix checked_pullback\n  decide\n'
            elif quadratic_chunks:
                chunk_imports, chunk_body = chunk_certificate(base, k, n, node, chunk, threshold, bound)
                imports += chunk_imports
                body += chunk_body
            else:
                edges = node['edges']
                assert [e['mask'] for e in edges] == list(range(1 << n))
                target_ids = sorted({e['target'] for e in edges if not e.get('pruned')})
                target_map = {t: j for j, t in enumerate(target_ids)}
                L = len(target_ids)
                targets = [base + '.Proof.' + node_name(k+1,t) for t in target_ids]
                imports += targets
                target_data = [base + '.Data.' + node_name(k+1,t) + '.prefix' for t in target_ids]
                body += f'def targets : Fin {L} → Matrix (Fin {k+1}) (Fin {n}) ℤ :=\n'
                body += ('  fun t => (#[' + ',\n    '.join(target_data) + ']).getD t.val 0\n\n') if L else '  fun _ => 0\n\n'
                body += f'def choices : Fin {1<<n} → Edge {k} {n} {L} :=\n'
                adj = node['_adj']
                values = []
                for edge in edges:
                    if edge.get('pruned'):
                        cross = [n-2*(r ^ edge['mask']).bit_count() for r in node['rows']]
                        prod = [sum(adj[i][j]*cross[j] for j in range(k)) for i in range(k)]
                        assert n*node['det']-sum(x*y for x,y in zip(cross,prod)) == edge['det']
                        values.append('.inl ⟨' + vector(cross) + ', ' + vector(prod) + '⟩')
                    else:
                        w = edge['transport']
                        vals = [vector(w['row_perm']), vector(w['column_perm']),
                                vector([1-2*x for x in w['row_sign']]),
                                vector([1-2*x for x in w['column_sign']])]
                        values.append(f'.inr ({target_map[edge["target"]]}, ⟨' + ', '.join(vals) + '⟩)')
                body += '  fun mask => (#[' + ',\n    '.join(values) + ']).getD mask.val (.inl ⟨0, 0⟩)\n\n'
                chunks = (1 << n) // chunk
                for b in range(chunks):
                    body += f'theorem edge_chunk_{b:03d} : ∀ j : Fin {chunk},\n'
                    body += f'    MainTheory.SignDagFastCertificate.EdgeValid {threshold} prefix gramAdj {node["det"]} targets\n'
                    body += f'      (@finProdFinEquiv {chunks} {chunk} (({b} : Fin {chunks}), j))\n'
                    body += f'      (choices (@finProdFinEquiv {chunks} {chunk} (({b} : Fin {chunks}), j))) := by decide\n\n'
                body += f'theorem certificate : PrefixGood {threshold} {bound} (by decide : {k} ≤ {n}) prefix := by\n'
                body += f'  apply MainTheory.SignDagFastCertificate.prefixGood_node (by decide : {k+1} ≤ {n}) prefix gramAdj {node["det"]}\n'
                body += f'    (by decide) det_eq gram_inverse (by decide) targets (choices := choices)\n'
                body += '  · intro t\n    fin_cases t\n' if L else '  · intro t\n    exact Fin.elim0 t\n'
                body += ''.join(f'    · exact {t}.certificate\n' for t in targets)
                body += f'  · apply forall_chunks (c := {chunk}) (d := {chunks})\n'
                body += '    intro b\n    fin_cases b\n'
                body += ''.join(f'    · exact edge_chunk_{b:03d}\n' for b in range(chunks))
            modules.append(write_module(base, 'Proof.'+name, imports, body))
    mapping = flush_modules(base, group_size, proposal, quadratic_prune=quadratic_prune,
                            quadratic_chunks=quadratic_chunks)
    print(f'Generated {len(set(mapping.values()))} grouped modules ({len(modules)} node components) for binary size {n-1}; final root {mapping[base+".Proof.N01_0000"]}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--proposal', type=Path, required=True)
    parser.add_argument('--chunk', type=int, default=8)
    parser.add_argument('--group-size', type=int, default=16)
    parser.add_argument('--quadratic-prune', action='store_true',
                        help='use a checked quadratic minimum for nodes whose every child is pruned')
    parser.add_argument('--quadratic-chunks', action='store_true',
                        help='also check every uniformly pruned power-of-two row chunk by a restricted minimum')
    args = parser.parse_args()
    generate(args.proposal, args.chunk, args.group_size, args.quadratic_prune, args.quadratic_chunks)
