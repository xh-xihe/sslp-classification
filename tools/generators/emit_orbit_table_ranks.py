"""Emit integer-kernel certificates for all 66 actual active moment-matrix ranks."""
import argparse
from functools import reduce
from math import lcm
from pathlib import Path

import sympy as sp

from inspect_orbit_table_semantics import ROOT, feature, inspect


def vector(xs):
    return "![" + ", ".join(map(str, xs)) + "]"


def matrix(M):
    return "![" + ",\n  ".join(vector(list(M.row(i))) for i in range(M.rows)) + "]"


def integer_scale(M):
    d = reduce(lcm, (int(v.q) for v in M), 1)
    return d, d * M


def emit(row):
    columns = row["active_columns"]
    A = sp.Matrix([[int(b == 0) for b, k in columns], [int(b == 1) for b, k in columns]] +
                  [[(-1 if b else 1) * feature(k)[j] for b, k in columns] for j in range(21)])
    selected_rows = list(A.T.rref()[1])
    B = A[selected_rows, :]
    selected_columns = list(B.rref()[1])
    square_inverse = B[:, selected_columns].inv()
    E = A[:, selected_columns] * square_inverse
    s, RZ = integer_scale(square_inverse)
    d, EZ = integer_scale(E)
    assert B[:, selected_columns] * RZ == s * sp.eye(B.rows)
    assert EZ * B == d * A
    oid, n, r = row["id"], A.cols, B.rows
    column_literal = vector(f"({'true' if b else 'false'}, {k})" for b, k in columns)
    actual_rows = "\n".join(
        f"private theorem actual_row_{i} (j : Fin {n}) :\n"
        f"    MainTheory.FiniteMomentMatrix.matrixZ columns {i} j = matrixZ {i} j := by\n"
        "  fin_cases j <;> decide\n" for i in range(23))
    lower_rows = "\n".join(
        f"private theorem lower_row_{i} (j : Fin {r}) :\n"
        f"    (matrixZ.submatrix selectedRows selectedColumns * rightInverseZ) {i} j =\n"
        f"      (if ({i} : Fin {r}) = j then ({s} : \u2124) else 0) := by\n"
        "  fin_cases j <;> decide\n" for i in range(r))
    upper_row_proofs = []
    for i in range(23):
        header = (f"private theorem upper_row_{i} (j : Fin {n}) :\n"
                  f"    (rowExpansionZ * matrixZ.submatrix selectedRows id) {i} j = {d} * matrixZ {i} j := by\n")
        if i in selected_rows:
            k = selected_rows.index(i)
            proof = (f"  have he : \u2200 k : Fin {r}, rowExpansionZ {i} k =\n"
                     f"      (if k = {k} then ({d} : \u2124) else 0) := by decide\n"
                     f"  have hr : selectedRows {k} = {i} := by decide\n"
                     "  simp only [Matrix.mul_apply, Matrix.submatrix_apply]\n"
                     "  simp_rw [he]\n"
                     "  simp [hr]\n")
        else:
            proof = "  fin_cases j <;> decide\n"
        upper_row_proofs.append(header + proof)
    upper_rows = "\n".join(upper_row_proofs)
    actual_cases = "\n".join(f"  \u00b7 exact actual_row_{i} j" for i in range(23))
    lower_cases = "\n".join(f"  \u00b7 simpa [Matrix.one_apply] using lower_row_{i} j" for i in range(r))
    upper_cases = "\n".join(f"  \u00b7 simpa using upper_row_{i} j" for i in range(23))
    if r == 23:
        upper_rows = ""
        upper_proof = """  have he : rowExpansionZ = (1 : Matrix (Fin 23) (Fin 23) ℤ) := by decide
  have hr : selectedRows = id := by decide
  rw [he, hr]
  simp"""
    else:
        upper_proof = "  ext i j\n  fin_cases i\n" + upper_cases
    text = f"""-- Generated by tools/generators/emit_orbit_table_ranks.py.
import MainTheory.FiniteMomentMatrix

namespace MainTheory.Generated.OrbitTableRank{oid:02d}

open scoped Matrix

set_option maxRecDepth 20000
set_option maxHeartbeats 4000000

def columns : Fin {n} → MainTheory.FiniteMomentMatrix.LabeledWord := {column_literal}

def matrixZ : Matrix (Fin 23) (Fin {n}) ℤ := {matrix(A)}

def selectedRows : Fin {r} → Fin 23 := {vector(selected_rows)}

def selectedColumns : Fin {r} → Fin {n} := {vector(selected_columns)}

private def rightInverseZ : Matrix (Fin {r}) (Fin {r}) ℤ := {matrix(RZ)}

private def rowExpansionZ : Matrix (Fin 23) (Fin {r}) ℤ := {matrix(EZ)}

{actual_rows}

theorem matrixZ_actual : MainTheory.FiniteMomentMatrix.matrixZ columns = matrixZ := by
  ext i j
  fin_cases i
{actual_cases}

theorem columns_injective : Function.Injective columns := by
  let encode : MainTheory.FiniteMomentMatrix.LabeledWord → ℕ :=
    fun c => (if c.1 then 64 else 0) + c.2.val
  have hm : StrictMono (fun i => encode (columns i)) := by
    apply Fin.strictMono_iff_lt_succ.2
    intro i
    fin_cases i <;> decide
  intro i j hij
  exact hm.injective (congrArg encode hij)

{lower_rows}

theorem right_inverse_valid :
    matrixZ.submatrix selectedRows selectedColumns * rightInverseZ = {s} • (1 : Matrix (Fin {r}) (Fin {r}) ℤ) := by
  ext i j
  fin_cases i
{lower_cases}

{upper_rows}

theorem row_expansion_valid :
    rowExpansionZ * matrixZ.submatrix selectedRows id = {d} • matrixZ := by
{upper_proof}

/-- Rank of the actual normalization-plus-degree-two matrix on all active columns. -/
theorem active_moment_rank : (MainTheory.FiniteMomentMatrix.matrix columns).rank = {r} := by
  rw [MainTheory.FiniteMomentMatrix.matrix, matrixZ_actual]
  exact MainTheory.IntegerMatrixRankCertificate.rank_eq_of_integer_minor_and_expansion
    matrixZ selectedRows selectedColumns rightInverseZ rowExpansionZ {s} {d} (by norm_num) (by norm_num)
      right_inverse_valid row_expansion_valid

end MainTheory.Generated.OrbitTableRank{oid:02d}
"""
    destination = ROOT / "MainTheory/Generated" / f"OrbitTableRank{oid:02d}.lean"
    destination.write_text(text, encoding="utf-8")
    return destination


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--orbit", type=int, action="append")
    args = parser.parse_args()
    rows = inspect()
    for row in rows:
        if args.orbit and row["id"] not in args.orbit:
            continue
        print(emit(row).relative_to(ROOT))
