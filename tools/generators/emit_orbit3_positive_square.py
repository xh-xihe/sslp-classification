#!/usr/bin/env python3
"""Identify the orbit-3 positive row with its explicit 36-term cubic square.

This proves positivity for a positive semidefinite reduced moment matrix.
Constructing that matrix from arbitrary encoders remains a separate theorem.
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def vector(values):
    return '![' + ', '.join(map(str, values)) + ']'


def generate(source, output):
    spec = importlib.util.spec_from_file_location('sextic', ROOT/'tools/certificates/orbit3_exact_sextic_certificate.py')
    v = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(v)
    raw = source.read_bytes()
    data = json.loads(raw)
    triples, lookup, entries, _, _ = v.coordinate_tables()
    terms = data['cubic_polynomial']
    if len(terms) != 36:
        raise ValueError('Expected all 36 cubic terms')
    coordinates = [[entries[lookup[tuple(t)]][lookup[tuple(u)]] for u,_ in terms] for t,_ in terms]
    if any(j < 0 for row in coordinates for j in row):
        raise ValueError('Square crosses a forbidden moment entry')
    square = [0] * 269
    for i, (_, a) in enumerate(terms):
        for k, (_, b) in enumerate(terms):
            square[coordinates[i][k]] += a * b
    text = f'''-- Generated by tools/generators/emit_orbit3_positive_square.py.
-- Input SHA-256: {hashlib.sha256(raw).hexdigest()}
import SixQubit.Generated.Orbit3SexticIdentity

/-! The positive row equals the quadratic form of the 36-term cubic coefficient
vector. Its PSD hypothesis still requires realization by actual encoder moments. -/
namespace SixQubit.Generated.Orbit3PositiveSquare

open scoped Matrix

set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

def cubicTriples : Fin 36 → Fin 64 × Fin 64 × Fin 64 :=
  ![{', '.join(f'({t[0]}, {t[1]}, {t[2]})' for t,_ in terms)}]

def coefficientInt : Fin 36 → ℤ := {vector([a for _,a in terms])}
def coefficient (i : Fin 36) : ℚ := coefficientInt i
def squareInt : Fin 269 → ℤ := {vector(square)}
def coordinate : Fin 36 → Fin 36 → Fin 269 :=
  ![{', '.join(vector(row) for row in coordinates)}]

theorem square_coefficientsInt : ∀ j : Fin 269,
    squareInt j =
      ∑ i : Fin 36, ∑ k : Fin 36,
        if coordinate i k = j then coefficientInt i * coefficientInt k else 0 := by
  decide +kernel

theorem squareInt_eq : ∀ j, (squareInt j : ℚ) = Orbit3SexticIdentity.square j := by
  decide +kernel

theorem square_coefficients (j : Fin 269) :
    Orbit3SexticIdentity.square j =
      ∑ i : Fin 36, ∑ k : Fin 36,
        if coordinate i k = j then coefficient i * coefficient k else 0 := by
  rw [← squareInt_eq]
  unfold coefficient
  exact_mod_cast square_coefficientsInt j

noncomputable def momentMatrix (y : Fin 269 → ℝ) : Matrix (Fin 36) (Fin 36) ℝ :=
  fun i k => y (coordinate i k)

theorem square_quadratic_form (y : Fin 269 → ℝ) :
    Orbit3SexticIdentity.evaluate Orbit3SexticIdentity.square y =
      (fun i => (coefficient i : ℝ)) ⬝ᵥ
        (momentMatrix y *ᵥ (fun k => (coefficient k : ℝ))) := by
  have hc (j : Fin 269) : (Orbit3SexticIdentity.square j : ℝ) =
      ∑ i : Fin 36, ∑ k : Fin 36,
        if coordinate i k = j then (coefficient i : ℝ) * (coefficient k : ℝ) else 0 := by
    have h := congrArg (fun q : ℚ => (q : ℝ)) (square_coefficients j)
    simpa only [Rat.cast_sum, apply_ite, Rat.cast_mul, Rat.cast_zero] using h
  unfold Orbit3SexticIdentity.evaluate
  simp_rw [hc]
  simp only [Finset.sum_mul]
  rw [Finset.sum_comm]
  apply Finset.sum_congr rfl
  intro i _
  rw [Finset.sum_comm]
  simp only [ite_mul, zero_mul]
  simp only [Finset.sum_ite_eq, Finset.mem_univ, if_true]
  simp [dotProduct, Matrix.mulVec, momentMatrix, Finset.mul_sum, mul_comm, mul_assoc]

theorem square_nonneg_of_psd (y : Fin 269 → ℝ) (hy : (momentMatrix y).PosSemidef) :
    0 ≤ Orbit3SexticIdentity.evaluate Orbit3SexticIdentity.square y := by
  rw [square_quadratic_form]
  simpa using hy.dotProduct_mulVec_nonneg (fun i => (coefficient i : ℝ))

theorem target_zero_of_psd (y : Fin 269 → ℝ)
    (hy : (momentMatrix y).PosSemidef)
    (hz : ∀ i, Orbit3SexticIdentity.evaluate (Orbit3SexticIdentity.rows i) y = 0)
    (ht : 0 ≤ Orbit3SexticIdentity.evaluate Orbit3SexticIdentity.target y) :
    Orbit3SexticIdentity.evaluate Orbit3SexticIdentity.target y = 0 :=
  Orbit3SexticIdentity.target_zero_of_constraints y hz ht (square_nonneg_of_psd y hy)

end SixQubit.Generated.Orbit3PositiveSquare
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')
    print(f'Generated {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT/'results/orbit3-kernel/certificate.json')
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3PositiveSquare.lean')
    args = parser.parse_args()
    generate(args.input, args.output)
