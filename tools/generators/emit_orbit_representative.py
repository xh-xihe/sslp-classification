#!/usr/bin/env python3
"""Emit MainTheory/OrbitRepresentative.lean.

Each order-four and order-eight no-go theorem of the supplement names its
orbit by a triple `(q, m, a)`.  The Lean no-gos are indexed by the orbit
*number* instead, and the orbit key stores only `(q, m, mask0, mask1)`, so the
angle vector `a` never appears in them.  The two halves needed to connect them
already exist per orbit:

  SixQubit.OrbitN.S0_eq_fiber / S1_eq_fiber
      the paper support pair is the residue fibre pair of OrbitN.av
  OrderFourNoCompletion.paperN_equivalent_keyKK
      the paper support pair is carried onto directory key KK by a stored,
      kernel-checked cube action

This file writes out the composition for each of the ten orbits.  The table
below is the only input; every angle vector is copied from `SixQubit/OrbitN.lean`
and every residue from the `not_completion_of_WImage_empty` call in
`MainTheory/OrderFourNoCompletion.lean`, so a mismatch is a Lean error rather
than a silent wrong claim.

Usage:  python tools/generators/emit_orbit_representative.py
"""
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'MainTheory', 'OrbitRepresentative.lean')

AND = '∧'
ARR = '→'
FORALL = '∀'
NAT = 'ℕ'
DOT = '·'
ANGL = '⟨'
ANGR = '⟩'

# paper orbit, key index, q, m, residue, angle vector,
# paper fibre pair, equivalence theorem, keyAt theorem, SixQubit namespace,
# name of the second-fibre theorem
TABLE = [
    (25, 24, 4, 4, 1, [0, 1, 1, 1, 1, 1], 'paper25Fibers',
     'paper25_equivalent_key24', 'keyAt24_eq', 'Orbit25', 'S1_eq_fiber'),
    (26, 25, 4, 4, 1, [0, 1, 1, 2, 2, 3], 'paper26Fibers',
     'paper26_equivalent_key25', 'keyAt25_eq', 'Orbit26', 'S1_eq_fiber'),
    (27, 30, 4, 4, 1, [1, 1, 1, 1, 1, 1], 'paper27Fibers',
     'paper27_equivalent_key30', 'keyAt30_eq', 'Orbit27', 'S1_eq_fiber'),
    (28, 28, 4, 4, 1, [1, 1, 1, 1, 1, 2], 'paper28Fibers',
     'paper28_equivalent_key28', 'keyAt28_eq', 'Orbit28', 'S1_eq_fiber'),
    (29, 31, 4, 4, 1, [1, 1, 1, 1, 2, 2], 'paper29Fibers',
     'paper29_equivalent_key31', 'keyAt31_eq', 'Orbit29', 'S1_eq_fiber'),
    (30, 29, 4, 4, 1, [1, 1, 1, 1, 2, 3], 'paper30Fibers',
     'paper30_equivalent_key29', 'keyAt29_eq', 'Orbit30', 'S1_eq_fiber'),
    (31, 26, 4, 4, 1, [1, 1, 1, 2, 2, 2], 'paper31Fibers',
     'paper31_equivalent_key26', 'keyAt26_eq', 'Orbit31', 'S1_eq_fiber'),
    (32, 27, 4, 4, 1, [1, 1, 2, 2, 2, 3], 'paper32Fibers',
     'paper32_equivalent_key27', 'keyAt27_eq', 'Orbit32', 'S1_eq_fiber'),
    (62, 61, 8, 4, 2, [1, 1, 1, 5, 5, 5], 'paper62Fibers',
     'paper62_equivalent_key61', 'keyAt61_eq', 'Orbit62', 'S1_eq_fiber'),
    (63, 62, 8, 4, 2, [1, 1, 2, 4, 5, 5], 'paper63Fibers',
     'paper63_equivalent_key62', 'keyAt62_eq', 'Orbit63', 'S1_residue'),
]

HEADER = [
    'import MainTheory.OrderFourNoCompletion',
    '',
    '/-!',
    '# Orbit representatives: the `(q, m, a)` triples the no-go theorems name',
    '',
    'Each order-four and order-eight no-go theorem of the supplement is stated',
    'as "no exact code can arise from the projective moment orbit represented by',
    '`(q, m, a) = (...)`".  The Lean no-gos are indexed by the orbit *number*',
    'instead -- `q4o26nogo` reads "`paperOrbitId k = 26` implies `NoCompletion',
    '(keyAt k).fibers`" -- and nothing connected that number to the displayed',
    'angle vector.  The orbit key stores only `(q, m, mask0, mask1)`; the angle',
    'vector never appears in it.',
    '',
    'The two halves were both present and never met.',
    '`SixQubit.OrbitN.S0_eq_fiber` and `S1_eq_fiber` identify each paper support',
    "pair with the two residue fibres of that orbit's angle vector, and",
    '`OrderFourNoCompletion.paperN_equivalent_keyKK` carries the paper support',
    'pair onto the directory key by a stored, kernel-checked cube action.',
    "Composing them gives exactly the manuscript's display: the key has the",
    'stated `q` and `m`, and its fibre pair is cube-equivalent to the residue',
    'fibre pair of the stated angle vector.',
    '',
    'The second fibre sits at residue `q / m`: `1` for the eight order-four',
    'orbits, and `2` for orbits 62 and 63 where `(q, m) = (8, 4)`.',
    '',
    'This file is generated by `tools/generators/emit_orbit_representative.py`.',
    '-/',
    '',
    'namespace MainTheory.OrbitRepresentative',
    '',
    'open MainTheory.Generated.FiniteOrbitBase',
    'open MainTheory.OrderFourNoCompletion',
    '',
    "/-- The residue fibre pair of an angle vector: the manuscript's orbit",
    'representative, with the two fibres at residues `0` and `q / m`. -/',
    'def angleFiberPair {q : ' + NAT + '} (av : Fin 6 ' + ARR + ' ZMod q) (r : ZMod q) :',
    '    MainTheory.CubeAction.FiberPair 6',
    '  | false => Finset.univ.filter fun x => SS.weight av x = 0',
    '  | true => Finset.univ.filter fun x => SS.weight av x = r',
    '',
]


def emit():
    out = list(HEADER)
    for (orb, kidx, q, m, r, av, pf, equiv, keyeq, ns, s1) in TABLE:
        avs = '![' + ', '.join(str(x) for x in av) + ']'
        typed = '(%s : Fin 6 %s ZMod %d)' % (avs, ARR, q)
        out += [
            '/-- The paper support pair of orbit %d is the residue fibre pair of its' % orb,
            'angle vector. -/',
            'theorem angleFiberPair_orbit%d :' % orb,
            '    angleFiberPair %s %d = %s := by' % (typed, r, pf),
            '  funext c',
            '  cases c',
            '  %s exact SixQubit.%s.S0_eq_fiber' % (DOT, ns),
            '  %s exact SixQubit.%s.%s' % (DOT, ns, s1),
            '',
            '/-- **Orbit %d is represented by `(q, m, a) = (%d, %d, (%s))`.** -/'
            % (orb, q, m, ', '.join(str(x) for x in av)),
            'theorem orbit%d_representative (k : Fin 66) (hk : paperOrbitId k = %d) :'
            % (orb, orb),
            '    (keyAt k).q = %d %s (keyAt k).m = %d %s' % (q, AND, m, AND),
            '      MainTheory.CubeAction.FiberEquivalent',
            '        (angleFiberPair %s %d) (keyAt k).fibers := by' % (typed, r),
            '  have hidx : %s j : Fin 66, paperOrbitId j = %d %s j = %d := by decide'
            % (FORALL, orb, ARR, kidx),
            '  obtain rfl : k = %d := hidx k hk' % kidx,
            '  rw [%s, angleFiberPair_orbit%d]' % (keyeq, orb),
            '  exact %srfl, rfl, %s.2.2%s' % (ANGL, equiv, ANGR),
            '',
        ]
    out.append('end MainTheory.OrbitRepresentative')
    io.open(OUT, 'w', encoding='utf-8', newline='').write('\n'.join(out) + '\n')
    print('wrote %s (%d lines, %d orbits)' % (OUT, len(out), len(TABLE)))


if __name__ == '__main__':
    emit()
