#!/usr/bin/env python3
"""Generate fully kernel-checked beta-four and beta-five upper certificates.

The generator is deliberately *not* trusted for either matrix entries or
coverage:

* every arithmetic theorem first proves that an explicit ``Int`` matrix is
  the Lean row-code decoder's matrix;
* it then checks ``CircuitReducedAtRow`` with ordinary kernel ``decide``;
* the shallow-circuit theorem transports that result to semantic
  ``ReducedAtRow``;
* a generated, proof-only interval tree covers every monotone row-code tuple;
* ``BinaryBetaSmallSemantic`` proves that sorting the prefix rows covers every
  binary matrix.

There is no ``native_decide``, axiom, ``sorry``, external solver, or global
heartbeat override.  Arithmetic leaves contain at most ``--batch-size``
closed prefixes.  Batches of 8 and 16 passed the available representative
resource probes, but those probes do not cover every cofactor pattern and are
not a universal memory guarantee.  Callers should select 8 on a lower-memory
machine and compile representative first/middle/last leaves before a full
serial build.

This script only emits source.  Build the generated modules serially with the
repository's resource-safe wrapper.
"""

from __future__ import annotations

import argparse
from itertools import combinations_with_replacement
from pathlib import Path


DEFAULT_BATCH_SIZE = 16


def write_if_changed(path: Path, text: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def module_path(root: Path, module: str) -> Path:
    prefix = "MainTheory.Generated."
    if not module.startswith(prefix):
        raise ValueError(module)
    return root / (module[len(prefix) :].replace(".", "/") + ".lean")


def bits(code: int, width: int) -> list[int]:
    return [(code >> j) & 1 for j in range(width)]


def explicit_prefix_matrix(codes: tuple[int, ...], size: int) -> str:
    rows = [bits(code, size) for code in codes]
    rows.append([0] * size)
    body = ";\n       ".join(", ".join(map(str, row)) for row in rows)
    return f"!![{body}]"


def bitvec(code: int, width: int) -> str:
    return f"BitVec.ofNat {width} {code}"


def prefix_vector(codes: tuple[int, ...], size: int) -> str:
    return "![" + ", ".join(bitvec(code, size) for code in codes) + "]"


def cert_name(codes: tuple[int, ...]) -> str:
    return "cert_" + "_".join(f"{code:02d}" for code in codes)


def leaf_module(size: int, shard: int) -> str:
    return f"MainTheory.Generated.BinaryBetaSmall.Size{size}.Leaf.Shard{shard:04d}"


def node_module(size: int, prefix: tuple[int, ...]) -> str:
    depth = len(prefix)
    suffix = "Root" if not prefix else "P" + "_".join(f"{x:02d}" for x in prefix)
    return f"MainTheory.Generated.BinaryBetaSmall.Size{size}.Node.K{depth}.{suffix}"


def render_certificate(codes: tuple[int, ...], size: int, bound: int) -> str:
    vec = prefix_vector(codes, size)
    matrix = explicit_prefix_matrix(codes, size)
    return f"""theorem {cert_name(codes)} :
    ReducedAtRow (prefixRowsMatrix {vec}) (Fin.last {size - 1}) {bound} := by
  rw [show prefixRowsMatrix {vec} =
      ({matrix} : Matrix (Fin {size}) (Fin {size}) ℤ) by decide]
  apply CircuitReducedAtRow.toReducedAtRow (fuel := 2)
  decide
"""


def emit_leaf_modules(
    root: Path,
    size: int,
    bound: int,
    tuples: list[tuple[int, ...]],
    batch_size: int,
) -> dict[tuple[int, ...], str]:
    owner: dict[tuple[int, ...], str] = {}
    for start in range(0, len(tuples), batch_size):
        batch = tuples[start : start + batch_size]
        shard = start // batch_size
        module = leaf_module(size, shard)
        namespace = module
        theorems = "\n".join(render_certificate(t, size, bound) for t in batch)
        text = f"""-- Generated by gen_binary_beta_small_kernel.py.
-- At most {batch_size} closed ordinary-kernel arithmetic certificates.
import MainTheory.BinaryBetaSmallSemantic

namespace {namespace}

open MainTheory.BinaryDetLastRow
open MainTheory.BinaryDetSmallCircuit
open MainTheory.BinaryBetaSmallSemantic

{theorems}
end {namespace}
"""
        write_if_changed(module_path(root, module), text)
        for t in batch:
            owner[t] = module
    return owner


def variable_names(prefix_len: int, total: int) -> list[str]:
    return [f"x{k}" for k in range(prefix_len, total)]


def result_vector(prefix: tuple[int, ...], total: int, size: int) -> str:
    terms = [bitvec(code, size) for code in prefix]
    terms.extend(variable_names(len(prefix), total))
    return "![" + ", ".join(terms) + "]"


def adjacent_hypotheses(prefix: tuple[int, ...], total: int) -> list[tuple[str, str]]:
    k = len(prefix)
    result: list[tuple[str, str]] = []
    if k > 0 and k < total:
        result.append((f"h{k-1}{k}", f"{prefix[-1]} ≤ x{k}.toNat"))
    # Once a prefix is fixed, `x0 .. x(k-1)` no longer exist as variables.
    # The first comparison is the constant/variable one above; the remaining
    # variable/variable comparisons therefore start at `xk ≤ x(k+1)`.
    start = k + 1 if k > 0 else 1
    for j in range(start, total):
        result.append((f"h{j-1}{j}", f"x{j-1}.toNat ≤ x{j}.toNat"))
    return result


def child_call(
    child_prefix: tuple[int, ...],
    total: int,
    owner: dict[tuple[int, ...], str],
) -> str:
    if len(child_prefix) == total:
        module = owner[child_prefix]
        return f"{module}.{cert_name(child_prefix)}"
    module = node_module(total + 1, child_prefix)
    args = variable_names(len(child_prefix), total)
    hyps = [name for name, _ in adjacent_hypotheses(child_prefix, total)]
    rendered = " ".join(args + hyps)
    return f"{module}.cover {rendered}".rstrip()


def emit_node(
    root: Path,
    size: int,
    bound: int,
    prefix: tuple[int, ...],
    owner: dict[tuple[int, ...], str],
) -> None:
    total = size - 1
    base = 1 << size
    k = len(prefix)
    if k >= total:
        return
    lo = prefix[-1] if prefix else 0
    children = [prefix + (value,) for value in range(lo, base)]
    imports = sorted(
        {
            owner[child] if len(child) == total else node_module(size, child)
            for child in children
        }
    )
    variables = variable_names(k, total)
    hyps = adjacent_hypotheses(prefix, total)
    arg_line = " ".join(f"({x} : BitVec {size})" for x in variables)
    hyp_lines = "\n".join(f"    ({name} : {prop})" for name, prop in hyps)
    if hyp_lines:
        hyp_lines = "\n" + hyp_lines
    vector = result_vector(prefix, total, size)
    current = variables[0]
    branches: list[str] = []
    for value, child in zip(range(lo, base), children):
        eq_name = f"hcode{value:02d}"
        call = child_call(child, total, owner)
        branches.append(
            f"""  · have {eq_name} : {current} = {bitvec(value, size)} := by
      apply BitVec.eq_of_toNat_eq
      simp [hvalue]
    subst {current}
    exact {call}"""
        )
    import_text = "\n".join(f"import {m}" for m in imports)
    theorem = f"""theorem cover {arg_line}{hyp_lines} :
    ReducedAtRow (prefixRowsMatrix {vector}) (Fin.last {size - 1}) {bound} := by
  have hlt : {current}.toNat < {base} := {current}.isLt
  interval_cases hvalue : {current}.toNat
{chr(10).join(branches)}
"""
    module = node_module(size, prefix)
    text = f"""-- Generated proof-only interval-tree node.
{import_text}

namespace {module}

open MainTheory.BinaryDetLastRow
open MainTheory.BinaryBetaSmallSemantic

{theorem}
end {module}
"""
    write_if_changed(module_path(root, module), text)


def emit_nodes(
    root: Path,
    size: int,
    bound: int,
    tuples: list[tuple[int, ...]],
    owner: dict[tuple[int, ...], str],
) -> None:
    total = size - 1
    prefixes: set[tuple[int, ...]] = {()}
    for values in tuples:
        for k in range(1, total):
            prefixes.add(values[:k])
    for prefix in sorted(prefixes, key=lambda p: (-len(p), p)):
        emit_node(root, size, bound, prefix, owner)


def emit_final(root: Path, size: int, bound: int) -> str:
    total = size - 1
    root_node = node_module(size, ())
    module = f"MainTheory.Generated.BinaryBetaSmall.Size{size}.Certificate"
    adjacent: list[str] = []
    for j in range(1, total):
        adjacent.append(
            f"  have h{j-1}{j} := "
            f"hf (show ({j-1} : Fin {total}) ≤ {j} by decide)"
        )
    # Parenthesize each function application.  Without these parentheses the
    # generated `cover f 0 f 1 ...` is parsed as a left-associated application
    # of `cover` to `f`, then to `0`, rather than as `cover (f 0) (f 1) ...`.
    args = " ".join(f"(f {j})" for j in range(total))
    hyps = " ".join(f"h{j-1}{j}" for j in range(1, total))
    call = f"{root_node}.cover {args} {hyps}".rstrip()
    text = f"""-- Generated semantic endpoint for size {size}.
import {root_node}
import MainTheory.BinaryBetaSmallLower

namespace {module}

open MainTheory.BinaryBeta
open MainTheory.BinaryBetaSmallSemantic

theorem monotonePrefix : MonotonePrefixCertificate {total} {bound} := by
  intro f hf
  have hvec : f = ![{', '.join(f'f {j}' for j in range(total))}] := by
    funext i
    fin_cases i <;> rfl
  rw [hvec]
{chr(10).join(adjacent)}
  exact {call}

theorem upper : BetaBound {size} {bound} := by
  simpa using betaBound_of_monotonePrefixCertificate monotonePrefix

theorem betaExact : BetaExact {size} {bound} :=
  ⟨upper, MainTheory.BinaryBetaSmallLower.{'Four.betaFourAttained' if size == 4 else 'Five.betaFiveAttained'}⟩

end {module}
"""
    write_if_changed(module_path(root, module), text)
    return module


def emit_size(root: Path, size: int, bound: int, batch_size: int) -> str:
    total = size - 1
    base = 1 << size
    tuples = list(combinations_with_replacement(range(base), total))
    expected = 816 if size == 4 else 52360
    if len(tuples) != expected:
        raise RuntimeError(f"size {size}: got {len(tuples)}, expected {expected}")
    owner = emit_leaf_modules(root, size, bound, tuples, batch_size)
    emit_nodes(root, size, bound, tuples, owner)
    return emit_final(root, size, bound)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-root", type=Path, default=Path("MainTheory/Generated")
    )
    parser.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE)
    parser.add_argument(
        "--size", choices=("4", "5", "all"), required=True,
        help="emit one size or both (required to prevent accidental bulk output)",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if not 1 <= args.batch_size <= 16:
        raise SystemExit("--batch-size must lie in 1..16 (resource-safety cap)")
    modules: list[str] = []
    if args.size in ("4", "all"):
        modules.append(emit_size(args.output_root, 4, 3, args.batch_size))
    if args.size in ("5", "all"):
        modules.append(emit_size(args.output_root, 5, 5, args.batch_size))
    print("emitted: " + ", ".join(modules))


if __name__ == "__main__":
    main()
