#!/usr/bin/env python3
"""Tie every orbit-3 scalar row to the physical category Fourier coefficients."""
from __future__ import annotations

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(output):
    tails = [(j, k) for k in range(6) for j in range(6-k)]
    errors = [(a, j, k) for a in (0, 1) for j, k in tails]
    columns = [c for c in errors if c[2] % 2 == 0]
    keys = [(0, 0)]
    for e, (a, j, k) in enumerate(errors):
        if k % 2 == 0:
            keys.append((1, e))
        if a+j+k <= 2:
            keys.append((2, e))
        if k % 2 and (a+j+k) % 2:
            keys.append((3, e))
    size = lambda j, k: math.factorial(5)//(
        math.factorial(j)*math.factorial(k)*math.factorial(5-j-k))*2**k
    positions = ['some ' + str(columns.index(c)) if c in columns else 'none' for c in errors]
    vec = lambda xs: '![' + ', '.join(map(str, xs)) + ']'
    text = f'''-- Generated by tools/generators/emit_orbit3_category_rows.py.
import SixQubit.Generated.Orbit3Scalar
import SixQubit.Generated.Orbit3CategoryFourier

/-! Exact metadata and physical Fourier formulas for every scalar dual row.
The column-to-encoder masses are supplied by the semantic bridge. -/
namespace SixQubit.Generated.Orbit3CategoryRows

open Orbit3CategoryFourier
set_option maxRecDepth 200000
set_option maxHeartbeats 8000000

def errorTail (e : Fin 42) : Fin 21 := ⟨e.val % 21, Nat.mod_lt _ (by decide)⟩
def errorSpectator (e : Fin 42) : Fin 2 := ⟨e.val / 21, by omega⟩
def errorCategory (e : Fin 42) : ℕ × ℕ × ℕ :=
  ((errorSpectator e).val, categories (errorTail e))

def tailSize : Fin 21 → ℕ := {vec(size(j,k) for j,k in tails)}
def errorSize (e : Fin 42) : ℕ := 3 ^ (errorSpectator e).val * tailSize (errorTail e)

def columnTail : Fin 24 → Fin 21 := {vec(tails.index((j,k)) for a,j,k in columns)}
def columnSpectator : Fin 24 → Fin 2 := {vec(a for a,j,k in columns)}
def columnCode : Fin 24 → Fin 42 := {vec(errors.index(c) for c in columns)}
def columnPosition : Fin 42 → Option (Fin 24) := {vec(positions)}
def complement : Fin 42 → Fin 42 := {vec(errors.index((a,5-j-k,k)) for a,j,k in errors)}

def fourier (e : Fin 42) (c : Fin 24) : ℚ :=
  (if errorSpectator e = 0 then 1 else if columnSpectator c = 0 then 3 else -1) *
    (coefficients (columnTail c) (errorTail e) : ℚ) / (32 * errorSize e)

def spin (e : Fin 42) (c : Fin 24) : ℚ :=
  fourier e c * (-1) ^ ((Orbit3Scalar.categories c).1 +
    (Orbit3Scalar.categories c).2.1 + (Orbit3Scalar.categories c).2.2)

def equalityKind : Fin 43 → Fin 4 := {vec(k for k,e in keys)}
def equalityError : Fin 43 → Fin 42 := {vec(e for k,e in keys)}

def selector (e : Fin 42) (c : Fin 24) : ℚ := if columnCode c = e then 1 else 0

def equalityFormula (i : Fin 43) (c : Fin 24) : ℚ :=
  let e := equalityError i
  if equalityKind i = 0 then selector 0 c
  else if equalityKind i = 1 then
    fourier e c - (selector e c + selector (complement e) c) / errorSize e
  else if equalityKind i = 2 then fourier e c - selector e c / errorSize e
  else spin e c

def positiveError (i : Fin 84) : Fin 42 := ⟨i.val / 2, by omega⟩

theorem positive_formula : ∀ i c,
    Orbit3Scalar.positive i c =
      if i.val % 2 = 0 then fourier (positiveError i) c else spin (positiveError i) c := by
  decide +kernel

theorem equality_formula : ∀ i c,
    Orbit3Scalar.equalities i c = equalityFormula i c := by decide +kernel

theorem rhs_formula : ∀ i, Orbit3Scalar.rhs i =
    if equalityKind i = 0 then 1 else 0 := by decide +kernel

theorem size_positive : ∀ e, 0 < errorSize e := by decide +kernel

theorem column_category : ∀ c,
    errorCategory (columnCode c) = Orbit3Scalar.categories c ∧
      errorTail (columnCode c) = columnTail c ∧
      errorSpectator (columnCode c) = columnSpectator c := by decide +kernel

theorem columnPosition_correct : ∀ c, columnPosition (columnCode c) = some c := by decide +kernel

theorem columnCode_injective : Function.Injective columnCode := by
  intro c d h
  have hs := congrArg columnPosition h
  rw [columnPosition_correct, columnPosition_correct] at hs
  exact Option.some.inj hs

theorem errorCategory_code : ∀ e,
    21 * (errorCategory e).1 + categoryRank (errorCategory e).2 = e.val := by decide +kernel

theorem errorCategory_injective : Function.Injective errorCategory := by
  intro e f h
  apply Fin.ext
  rw [← errorCategory_code e, ← errorCategory_code f, h]

theorem absent_column_odd : ∀ e, (∀ c, columnCode c ≠ e) →
    (errorCategory e).2.2 % 2 = 1 := by decide +kernel

theorem even_columns : ∀ c, (errorCategory (columnCode c)).2.2 % 2 = 0 := by decide +kernel

theorem complement_category : ∀ e,
    errorCategory (complement e) =
      ((errorCategory e).1, 5 - (errorCategory e).2.1 - (errorCategory e).2.2,
        (errorCategory e).2.2) := by decide +kernel

theorem complement_involution : ∀ e, complement (complement e) = e := by decide +kernel

theorem complement_size : ∀ e, errorSize (complement e) = errorSize e := by decide +kernel

theorem identity_category : errorCategory 0 = (0, 0, 0) := rfl

theorem equality_conditions : ∀ i,
    (equalityKind i = 0 → equalityError i = 0) ∧
    (equalityKind i = 1 → (errorCategory (equalityError i)).2.2 % 2 = 0) ∧
    (equalityKind i = 2 → (errorCategory (equalityError i)).1 +
      (errorCategory (equalityError i)).2.1 + (errorCategory (equalityError i)).2.2 ≤ 2) ∧
    (equalityKind i = 3 → (errorCategory (equalityError i)).2.2 % 2 = 1 ∧
      ((errorCategory (equalityError i)).1 + (errorCategory (equalityError i)).2.1 +
        (errorCategory (equalityError i)).2.2) % 2 = 1) := by decide +kernel

end SixQubit.Generated.Orbit3CategoryRows
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf8', newline='\n')
    print(f'Generated {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path,
        default=ROOT/'SixQubit/Generated/Orbit3CategoryRows.lean')
    generate(parser.parse_args().output)
