#!/usr/bin/env python3
"""Expose the five spin multipliers of the orbit-3 certificate."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(source: Path, output: Path):
    raw = source.read_bytes()
    terms = json.loads(raw)['terms']
    if len(terms) != 211 or sum(t['kind'] == 'spin' for t in terms) != 5:
        raise ValueError('Expected exactly five spin terms in the complete certificate')
    triples = [term.get('triple', [0, 0, 0]) for term in terms]
    if any(len(t) != 3 or any(not isinstance(r, int) or not 0 <= r < 64 for r in t) for t in triples):
        raise ValueError('Invalid cubic triple')
    values = ', '.join(f'({a}, {b}, {c})' for a, b, c in triples)
    text = f'''-- Generated by tools/generators/emit_orbit3_spin_constraints.py.
-- Input SHA-256: {hashlib.sha256(raw).hexdigest()}
import MainTheory.Orbit3PhaseBlocks
import SixQubit.Generated.Orbit3PauliConstraints

namespace SixQubit.Generated.Orbit3SpinConstraints

open MainTheory.Orbit3PhaseBlocks
set_option maxHeartbeats 8000000

def triples : Fin 211 → Fin 64 × Fin 64 × Fin 64 := ![{values}]

def physical (i : Fin 211) : SS.BitString 6 × SS.BitString 6 × SS.BitString 6 :=
  (SixQubit.Realize.nbit (triples i).1.val,
    SixQubit.Realize.nbit (triples i).2.1.val, SixQubit.Realize.nbit (triples i).2.2.val)

theorem xor_zero : ∀ i : Fin 211, Orbit3PauliConstraints.kind i = 1 →
    ∀ j : Fin 6, SS.bxor (physical i).1 (physical i).2.1 j = (physical i).2.2 j := by
  decide +kernel

theorem full_support : ∀ i : Fin 211, Orbit3PauliConstraints.kind i = 1 →
    ∀ j : Fin 6, support (physical i).1 (physical i).2.1 j = true := by
  decide +kernel

theorem logical_charge : ∀ i : Fin 211, Orbit3PauliConstraints.kind i = 1 →
    charge (physical i).1 (physical i).2.1 = -1 := by
  decide +kernel

end SixQubit.Generated.Orbit3SpinConstraints
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT/'results/orbit3-kernel/certificate.json')
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3SpinConstraints.lean')
    args = parser.parse_args()
    generate(args.input, args.output)


if __name__ == '__main__':
    main()
