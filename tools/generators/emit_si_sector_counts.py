"""Generate ordinary-kernel witnesses for the current SI sector tables.

Serialized ids are untrusted witnesses. Lean checks their stage membership,
absence of repetitions, completeness using already proved total cardinalities,
and every sector count against the actual record/fibre-pair payload. No copied
Python sector count is trusted as a semantic assertion.
"""
from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SECTORS = [(2, 2), (3, 3), (4, 2), (4, 4), (5, 5), (6, 2), (6, 3),
           (6, 6), (7, 7), (8, 2), (8, 4), (8, 8), (9, 3), (9, 9)]
HEADER = '-- Generated by tools/generators/emit_si_sector_counts.py.\n'


def write(path: Path, lines: list[str]) -> None:
    text = HEADER + '\n'.join(lines) + '\n'
    if path.exists() and path.read_text(encoding='utf8') == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf8', newline='\n')


def literal(values: list[int]) -> str:
    return '[\n' + ',\n'.join('  ' + ', '.join(map(str, values[i:i+24]))
                              for i in range(0, len(values), 24)) + '\n]'


def emit_witnesses(data: dict, out: Path) -> dict:
    stages = {
        'coarse': data['coarse_pair_ids'],
        'feasible': [r['pair'] for r in data['rank_certificates']],
        'compatible': data['compatible_pair_ids'],
    }
    predicates = {
        'coarse': 'MainTheory.StageRecordCounts.coarseP',
        'feasible': 'MainTheory.StageRecordCounts.feasibleP',
        'compatible': 'MainTheory.OrbitRecordMultiplicity.compatible',
    }
    totals = {'coarse': (510, 508), 'feasible': (292, 291), 'compatible': (216, 215)}
    source_ids = {
        'coarse': 'FinitePairData.coarsePairIds.toList',
        'feasible': 'FiniteMomentData.feasiblePairIds',
        'compatible': 'FinitePairData.compatiblePairIds.toList',
    }
    count_roots = {
        'coarse': 'MainTheory.StageRecordCounts.coarse_record_count',
        'feasible': 'MainTheory.StageRecordCounts.feasible_record_count',
        'compatible': 'MainTheory.ActiveRankRecordCount.compatible_record_count',
    }
    lines = [
        'import MainTheory.SupplementarySectorCountBase', '',
        'namespace MainTheory.Generated.SupplementarySectorWitnesses', '',
        'open MainTheory.Generated', 'open MainTheory.SupplementarySectorCountBase', '',
        'set_option maxRecDepth 200000', 'set_option maxHeartbeats 400000000', '',
    ]
    expected = {}
    for name, pair_ids in stages.items():
        if len(pair_ids) != len(set(pair_ids)):
            raise ValueError('Repeated pair id in '+name)
        selected = set(pair_ids)
        records = [i for i, pair in enumerate(data['record_pair_ids']) if pair in selected]
        nr, np = totals[name]
        if (len(records), len(pair_ids)) != (nr, np):
            raise ValueError('Unexpected witness size in '+name)
        if any(not 0 <= i < 11422 for i in pair_ids):
            raise ValueError('Pair id out of range')
        predicate = predicates[name]
        lines += [
            f'def {name}Records : List RecordId := {literal(records)}', '',
            f'theorem {name}Records_nodup : {name}Records.Nodup := by decide',
            f'theorem {name}Records_valid : {name}Records.all {predicate} = true := by decide',
            f'theorem {name}Records_length : {name}Records.length = {nr} := by decide', '',
            f'theorem {name}Records_complete : selectedRecords {predicate} = {name}Records.toFinset := by',
            f'  apply selectedRecords_eq_list _ _ {name}Records_nodup {name}Records_valid',
            f'  simpa only [{name}Records_length] using {count_roots[name]}', '',
            f'def {name}Pairs : List PairId := {literal(pair_ids)}', '',
            f'theorem {name}Pairs_nodup : {name}Pairs.Nodup := by decide',
            f'theorem {name}Pairs_source : {name}Pairs.map Fin.val = {source_ids[name]} := by decide',
            f'theorem {name}Pairs_length : {name}Pairs.length = {np} := by decide', '',
        ]
        record_headers = [tuple(data['pair_table'][data['record_pair_ids'][r]][:2]) for r in records]
        pair_headers = [tuple(data['pair_table'][i][:2]) for i in pair_ids]
        for q, m in SECTORS:
            rc, pc = record_headers.count((q, m)), pair_headers.count((q, m))
            expected.setdefault((q, m), {})[name] = (rc, pc)
            suffix = f'q{q:02}m{m:02}'
            lines += [
                f'theorem {name}Records_{suffix} : recordCount {predicate} {q} {m} = {rc} := by',
                f'  rw [recordCount_eq_list _ _ {name}Records_nodup {name}Records_complete]',
                '  decide', '',
                f'theorem {name}Pairs_{suffix} : pairCount {name}Pairs {q} {m} = {pc} := by',
                f'  rw [pairCount_eq_list _ {name}Pairs_nodup]', '  decide', '',
            ]
    lines += ['end MainTheory.Generated.SupplementarySectorWitnesses']
    write(out/'SupplementarySectorWitnesses.lean', lines)
    return expected


def emit_headers(data: dict, out: Path) -> None:
    pairs = data['pair_table']
    blocks = []
    offset = 0
    for key, group in itertools.groupby(pairs, lambda p: tuple(p[:2])):
        size = len(list(group))
        blocks.append((key, offset, offset+size))
        offset += size
    if [key for key, _, _ in blocks] != SECTORS or offset != 11422:
        raise ValueError('Unexpected pair-table sector layout')
    lines = [
        'import MainTheory.SupplementarySectorCountBase', '',
        'namespace MainTheory.Generated.SupplementarySectorHeaders', '',
        'open MainTheory.Generated', 'open MainTheory.SupplementarySectorCountBase', '',
        'set_option maxRecDepth 20000', 'set_option maxHeartbeats 400000000', '',
        'def header (i : ℕ) : ℕ × ℕ :=',
    ]
    for (q, m), _, stop in blocks[:-1]:
        lines.append(f'  if i < {stop} then ({q}, {m}) else')
    lines += ['  (9, 9)', '']
    shards = []
    for start in range(0, 11422, 64):
        size = min(64, 11422-start)
        name = f'header_{start:05}'
        shards.append((start, size, name))
        lines += [
            f'private theorem {name} : ∀ i : Fin {size},',
            f'    let p := FinitePairRecordBase.pairAtId ⟨{start} + i.val, by omega⟩',
            f'    (p.q, p.m) = header ({start} + i.val) := by decide', '',
        ]
    lines += ['theorem header_spec (i : PairId) :',
              '    let p := FinitePairRecordBase.pairAtId i',
              '    (p.q, p.m) = header i.val := by', '  have hi := i.isLt']

    def cases(items, indent):
        if len(items) == 1:
            start, size, name = items[0]
            return [f'{indent}have h := {name} ⟨i.val - {start}, by omega⟩',
                    f'{indent}have he : {start} + (i.val - {start}) = i.val := by omega',
                    f'{indent}simpa only [he] using h']
        middle = len(items)//2
        threshold = items[middle][0]
        return [f'{indent}by_cases h{threshold} : i.val < {threshold}'] + \
            [f'{indent}·'] + cases(items[:middle], indent+'  ') + \
            [f'{indent}·'] + cases(items[middle:], indent+'  ')
    lines += cases(shards, '  ')
    lines += ['', 'theorem pairSector_iff (q m : ℕ) (i : PairId) :',
              '    pairSector q m i = true ↔ header i.val = (q, m) := by',
              '  rw [← header_spec i]', '  simp [pairSector]', '']
    for (q, m), start, stop in blocks:
        suffix = f'q{q:02}m{m:02}'
        lines += [
            f'theorem sector_{suffix} (i : PairId) :',
            f'    pairSector {q} {m} i = true ↔ {start} ≤ i.val ∧ i.val < {stop} := by',
            '  rw [pairSector_iff]', '  unfold header', '  have hi := i.isLt',
        ]
        def route_cases(remaining, indent):
            (rq, rm), _, end = remaining[0]
            eq = f'(({rq}, {rm}) : ℕ × ℕ) = ({q}, {m})'
            truth = 'True' if (rq, rm) == (q, m) else 'False'
            finish = [f'{indent}rw [show ({eq} ↔ {truth}) from by decide]',
                      f'{indent}constructor']
            if truth == 'True':
                finish += [f'{indent}· intro _; constructor <;> omega',
                           f'{indent}· intro _; trivial']
            else:
                finish += [f'{indent}· intro h; exact False.elim h',
                           f'{indent}· intro h; omega']
            if len(remaining) == 1:
                return finish
            return [f'{indent}by_cases h{end} : i.val < {end}',
                    f'{indent}· rw [if_pos h{end}]'] + \
                [line.replace(indent, indent+'  ', 1) for line in finish] + \
                [f'{indent}· rw [if_neg h{end}]'] + route_cases(remaining[1:], indent+'  ')
        lines += route_cases(blocks, '  ')
        lines += ['',
            f'theorem count_{suffix} : allPairCount {q} {m} = {stop-start} := by',
            f'  exact allPairCount_eq_interval {q} {m} {start} {stop} (by omega) sector_{suffix}', '',
        ]
    lines += ['end MainTheory.Generated.SupplementarySectorHeaders']
    cut = lines.index('theorem pairSector_iff (q m : ℕ) (i : PairId) :')
    write(out/'SupplementarySectorHeaderCertificate.lean',
          lines[:cut]+['end MainTheory.Generated.SupplementarySectorHeaders'])
    write(out/'SupplementarySectorHeaders.lean', [
        'import MainTheory.Generated.SupplementarySectorHeaderCertificate', '',
        'namespace MainTheory.Generated.SupplementarySectorHeaders', '',
        'open MainTheory.Generated', 'open MainTheory.SupplementarySectorCountBase', '',
    ]+lines[cut:])


def emit_tables(data: dict, expected: dict, out: Path) -> None:
    raw = {2: 7, 3: 28, 4: 84, 5: 210, 6: 462, 7: 924, 8: 1716, 9: 3003}
    primitive = {2: 6, 3: 27, 4: 77, 5: 209, 6: 428, 7: 923, 8: 1632, 9: 2975}
    nonempty = dict(zip(SECTORS, [6, 26, 74, 75, 200, 416, 408, 412,
                                879, 1556, 1544, 1560, 2815, 2797]))
    word = {2: 'two', 3: 'three', 4: 'four', 5: 'five', 6: 'six',
            7: 'seven', 8: 'eight', 9: 'nine'}
    # Every directory key q/m field is read from the actual generated keyAt.
    lines = [
        'import MainTheory.Generated.SupplementarySectorWitnesses',
        'import MainTheory.Generated.SupplementarySectorHeaders',
        'import MainTheory.Generated.FiniteOrbitCertificate', '',
        'namespace MainTheory.SupplementarySectorCounts', '',
        'open MainTheory.Generated', 'open MainTheory.OuterEnumeration',
        'open MainTheory.SupplementarySectorCountBase',
        'open MainTheory.Generated.SupplementarySectorWitnesses',
        'open MainTheory.Generated.SupplementarySectorHeaders', '',
        'set_option maxRecDepth 20000', 'set_option maxHeartbeats 4000000', '',
        'def sectors : List (ℕ × ℕ) := ['+', '.join(f'({q}, {m})' for q, m in SECTORS)+']', '',
        'def orbitCount (q m : ℕ) : ℕ :=',
        '  ((List.ofFn FiniteOrbitBase.keyAt).filter fun k => k.q == q && k.m == m).length', '',
        'def angleRow (q m : ℕ) : List ℕ :=',
        '  [q, m, q / m, (weakAngles6 q).length, (primitiveAngles6 q).length,',
        '    nonemptyFiberPairCount q m, recordCount MainTheory.StageRecordCounts.coarseP q m,',
        '    recordCount MainTheory.StageRecordCounts.feasibleP q m,',
        '    recordCount MainTheory.OrbitRecordMultiplicity.compatible q m]', '',
        'def pairRow (q m : ℕ) : List ℕ :=',
        '  [q, m, allPairCount q m, pairCount coarsePairs q m, pairCount feasiblePairs q m,',
        '    pairCount compatiblePairs q m, orbitCount q m]', '',
    ]
    orbit_counts = dict(zip(SECTORS, [4, 5, 15, 8, 8, 6, 6, 4, 5, 0, 2, 2, 0, 1]))
    angle_rows, pair_rows = [], []
    for q, m in SECTORS:
        suf = f'q{q:02}m{m:02}'
        ar = [q, m, q//m, raw[q], primitive[q], nonempty[(q, m)]]
        ar += [expected[(q, m)][s][0] for s in ['coarse', 'feasible', 'compatible']]
        pr = [q, m, sum(tuple(p[:2]) == (q, m) for p in data['pair_table'])]
        pr += [expected[(q, m)][s][1] for s in ['coarse', 'feasible', 'compatible']]
        pr += [orbit_counts[(q, m)]]
        angle_rows.append(ar)
        pair_rows.append(pr)
        primitive_root = 'primitive_'+word[q]+('_exact' if q >= 6 else '')
        lines += [
            f'theorem orbits_{suf} : orbitCount {q} {m} = {orbit_counts[(q,m)]} := by decide', '',
            f'theorem angle_{suf} : angleRow {q} {m} = '+str(ar)+' := by',
            f'  simp only [angleRow, sorted_{word[q]}_list_agrees, {primitive_root},',
            f'    nonempty_pair_{q}_{m}, coarseRecords_{suf}, feasibleRecords_{suf}, compatibleRecords_{suf}]',
            '  decide', '',
            f'theorem pairs_{suf} : pairRow {q} {m} = '+str(pr)+' := by',
            f'  simp only [pairRow, count_{suf}, coarsePairs_{suf}, feasiblePairs_{suf},',
            f'    compatiblePairs_{suf}, orbits_{suf}]', '',
        ]
    lines += [
        'def angleTable : List (List ℕ) := sectors.map fun s => angleRow s.1 s.2',
        'def pairTable : List (List ℕ) := sectors.map fun s => pairRow s.1 s.2', '',
        'theorem angle_table : angleTable = '+str(angle_rows)+' := by',
        '  simp only [angleTable, sectors, List.map_cons, List.map_nil, '+
        ', '.join(f'angle_q{q:02}m{m:02}' for q, m in SECTORS)+']', '',
        'theorem pair_table : pairTable = '+str(pair_rows)+' := by',
        '  simp only [pairTable, sectors, List.map_cons, List.map_nil, '+
        ', '.join(f'pairs_q{q:02}m{m:02}' for q, m in SECTORS)+']', '',
        'def angleTotals : List ℕ := List.ofFn fun i : Fin 6 =>',
        '  (angleTable.map fun row => row[i.val + 3]!).sum',
        'def pairTotals : List ℕ := List.ofFn fun i : Fin 5 =>',
        '  (pairTable.map fun row => row[i.val + 2]!).sum', '',
        'theorem angle_totals : angleTotals = [13877, 13449, 12768, 510, 292, 216] := by',
        '  unfold angleTotals', '  rw [angle_table]', '  decide', '',
        'theorem pair_totals : pairTotals = [11422, 508, 291, 215, 66] := by',
        '  unfold pairTotals', '  rw [pair_table]', '  decide', '',
        'end MainTheory.SupplementarySectorCounts',
    ]
    write(out.parent/'SupplementarySectorCounts.lean', lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT/'results/main-pipeline-certificates.json')
    parser.add_argument('--out', type=Path, default=ROOT/'MainTheory/Generated')
    args = parser.parse_args()
    data = json.loads(args.input.read_text(encoding='utf8'))
    expected = emit_witnesses(data, args.out)
    emit_headers(data, args.out)
    emit_tables(data, expected, args.out)
    for sector, counts in expected.items():
        print(sector, counts)


if __name__ == '__main__':
    main()
