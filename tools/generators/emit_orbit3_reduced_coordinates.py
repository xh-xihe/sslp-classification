#!/usr/bin/env python3
"""Generate finite coverage and physical permutation witnesses for 269 coordinates.

The tables are candidate data only. Separate kernel proofs check block tags,
entry coverage, and the concrete permutation/transposition witness of every
present entry. No moment invariance or positivity is assumed by this emitter.
"""
from __future__ import annotations

import argparse
import importlib.util
from itertools import permutations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PREFIX = 'SixQubit.Generated.Orbit3Coordinates'


def tree(values):
    if len(values) == 1:
        return f'(.leaf {values[0]})'
    split = len(values) // 2
    return f'(.node {split} {tree(values[:split])} {tree(values[split:])})'


def sparse(values):
    if not values:
        return '.empty'
    split = len(values) // 2
    key, value = values[split]
    return f'(.node {key} {value} {sparse(values[:split])} {sparse(values[split+1:])})'


def generate(directory: Path, aggregate: Path):
    spec = importlib.util.spec_from_file_location('sextic_coordinates',
        ROOT/'tools/certificates/orbit3_exact_sextic_certificate.py')
    v = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(v)
    triples, lookup, entries, _, groups = v.coordinate_tables()
    keys = list(groups)
    tags = [keys.index((t[0] | t[1] | t[2], sum((-1)**((a&62).bit_count()) for a in t))) for t in triples]
    transforms = []
    for perm in permutations(range(1, 6)):
        f = [0]+list(perm)
        bitmap = [sum(((a >> j)&1) << f[j] for j in range(6)) for a in range(64)]
        transforms.append([lookup[tuple(sorted(bitmap[a] for a in t))] for t in triples])
    representatives = [None]*269
    rows = []
    for i in range(715):
        row = []
        for j, coordinate in enumerate(entries[i]):
            if coordinate < 0:
                continue
            g = min(range(120), key=lambda p: min(transforms[p][i],transforms[p][j])*715+
                max(transforms[p][i],transforms[p][j]))
            a,b = transforms[g][i],transforms[g][j]
            rep = (min(a,b),max(a,b))
            if representatives[coordinate] not in (None,rep):
                raise ValueError('Inconsistent coordinate representative')
            representatives[coordinate] = rep
            row.append((j,f'({coordinate}, {g}, {str(a>b).lower()})'))
        rows.append(sparse(row))
    if len(keys)!=116 or any(r is None for r in representatives):
        raise ValueError('Incomplete coordinate metadata')
    directory.mkdir(parents=True,exist_ok=True)
    data = f'''-- Generated by tools/generators/emit_orbit3_reduced_coordinates.py.
import SixQubit.Generated.Orbit3CubicTriples
import SixQubit.Generated.Orbit3PermutationMetadata
import MainTheory.Orbit3PhaseBlocks
import MainTheory.SparseFiniteTable

namespace {PREFIX}.Data

open MainTheory.Orbit3PhaseBlocks
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

abbrev Entry := Fin 269 × Fin 120 × Bool

def blockKeyTable : MainTheory.BalancedFiniteTable.Tree (ℕ × ℤ) :=
  {tree([f'({a}, {b})' for a,b in keys])}
def blockKey (b : Fin 116) : ℕ × ℤ := MainTheory.BalancedFiniteTable.lookup blockKeyTable b.val
def blockTagTable : MainTheory.BalancedFiniteTable.Tree (Fin 116) := {tree(tags)}
def blockTag (i : Fin 715) : Fin 116 := MainTheory.BalancedFiniteTable.lookup blockTagTable i.val
def representativeTable : MainTheory.BalancedFiniteTable.Tree (Fin 715 × Fin 715) :=
  {tree([f'({a}, {b})' for a,b in representatives])}
def representative (c : Fin 269) : Fin 715 × Fin 715 :=
  MainTheory.BalancedFiniteTable.lookup representativeTable c.val
def rowTable : MainTheory.BalancedFiniteTable.Tree (MainTheory.SparseFiniteTable.Tree Entry) :=
  {tree(rows)}
def entry (i j : Fin 715) : Option Entry :=
  MainTheory.SparseFiniteTable.lookup (MainTheory.BalancedFiniteTable.lookup rowTable i.val) j.val

def physicalBlockLabel (i : Fin 715) : ℕ × ℤ :=
  (SixQubit.Realize.num (support (Orbit3CubicTriples.physical i).1 (Orbit3CubicTriples.physical i).2.1),
    charge (Orbit3CubicTriples.physical i).1 (Orbit3CubicTriples.physical i).2.1)

theorem block_tags_correct : ∀ i : Fin 715, physicalBlockLabel i = blockKey (blockTag i) := by
  decide +kernel

theorem block_keys_injective : ∀ a b : Fin 116, blockKey a = blockKey b → a = b := by
  decide +kernel

theorem representative_block : ∀ c : Fin 269,
    blockTag (representative c).1 = blockTag (representative c).2 := by
  decide +kernel

def permuted (g : Fin 120) (i : Fin 715) : Fin 715 :=
  Orbit3CubicTriples.pairIndex (Orbit3PermutationMetadata.bitmap g (Orbit3CubicTriples.triples i).1)
    (Orbit3PermutationMetadata.bitmap g (Orbit3CubicTriples.triples i).2.1)

def coverageValid (i j : Fin 715) : Bool :=
  decide ((entry i j).isSome = decide (blockTag i = blockTag j))

def witnessValid (i j : Fin 715) : Bool :=
  match entry i j with
  | none => true
  | some e => decide (if e.2.2 then
      (permuted e.2.1 i, permuted e.2.1 j) = (representative e.1).swap else
      (permuted e.2.1 i, permuted e.2.1 j) = representative e.1)

end {PREFIX}.Data
'''
    (directory/'Data.lean').write_text(data,encoding='utf-8',newline='\n')
    for b in range(16):
        lower,upper = b*45,min((b+1)*45,715)
        proof=f'''-- Generated by tools/generators/emit_orbit3_reduced_coordinates.py.
import {PREFIX}.Data

namespace {PREFIX}.Proof{b:02d}
open {PREFIX}.Data
set_option maxHeartbeats 160000000
set_option maxRecDepth 200000

theorem coverage : ∀ i : Fin 715, {lower} ≤ i.val ∧ i.val < {upper} →
    ∀ j : Fin 715, coverageValid i j = true := by
  decide +kernel

theorem witnesses : ∀ i : Fin 715, {lower} ≤ i.val ∧ i.val < {upper} →
    ∀ j : Fin 715, witnessValid i j = true := by
  decide +kernel

end {PREFIX}.Proof{b:02d}
'''
        (directory/f'Proof{b:02d}.lean').write_text(proof,encoding='utf-8',newline='\n')
    imports='\n'.join(f'import {PREFIX}.Proof{b:02d}' for b in range(16))
    coverage='\n'.join(f'  · exact {PREFIX}.Proof{b:02d}.coverage i (by omega) j' for b in range(16))
    witnesses='\n'.join(f'  · exact {PREFIX}.Proof{b:02d}.witnesses i (by omega) j' for b in range(16))
    total=f'''-- Generated by tools/generators/emit_orbit3_reduced_coordinates.py.
{imports}

namespace SixQubit.Generated.Orbit3ReducedCoordinates
open {PREFIX}.Data

theorem coverage_valid (i j : Fin 715) : coverageValid i j = true := by
  have hlt : i.val / 45 < 16 := by have hi := i.isLt; omega
  interval_cases h : i.val / 45
{coverage}

theorem witness_valid (i j : Fin 715) : witnessValid i j = true := by
  have hlt : i.val / 45 < 16 := by have hi := i.isLt; omega
  interval_cases h : i.val / 45
{witnesses}

theorem entry_witness (i j : Fin 715) (e : Entry) (he : entry i j = some e) :
    if e.2.2 then (permuted e.2.1 i, permuted e.2.1 j) = (representative e.1).swap else
      (permuted e.2.1 i, permuted e.2.1 j) = representative e.1 := by
  have h := witness_valid i j
  simp only [witnessValid, he] at h
  exact of_decide_eq_true h

theorem entry_coverage (i j : Fin 715) :
    (entry i j).isSome = decide (blockTag i = blockTag j) :=
  of_decide_eq_true (coverage_valid i j)

end SixQubit.Generated.Orbit3ReducedCoordinates
'''
    aggregate.parent.mkdir(parents=True,exist_ok=True)
    aggregate.write_text(total,encoding='utf-8',newline='\n')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory',type=Path,default=ROOT/'SixQubit/Generated/Orbit3Coordinates')
    parser.add_argument('--aggregate',type=Path,default=ROOT/'SixQubit/Generated/Orbit3ReducedCoordinates.lean')
    args=parser.parse_args()
    generate(args.directory,args.aggregate)


if __name__=='__main__':
    main()
