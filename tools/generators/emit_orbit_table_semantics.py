"""Connect generated actual matrix ranks to the certified full-fibre LPs."""
import argparse

from inspect_orbit_table_semantics import ROOT, inspect


def emit(row):
    oid, rid = row["id"], row["rank_row_index"]
    namespace = f"MainTheory.Generated.FiniteRankDataShard{rid:02d}"
    rank = f"MainTheory.Generated.OrbitTableRank{oid:02d}"
    source = f"""-- Generated by tools/generators/emit_orbit_table_semantics.py.
import MainTheory.FiniteMomentLPDimension
import {namespace}
import {rank}

namespace MainTheory.Generated.OrbitTableSemantics{oid:02d}

open MainTheory.FiniteMomentLP

set_option maxRecDepth 20000
set_option maxHeartbeats 2000000

theorem active_columns_exact : ∀ c,
    InActive {namespace}.face0 c ↔ ∃ i, {rank}.columns i = c := by
  unfold InActive
  intro c
  rcases c with ⟨b, x⟩
  cases b <;> fin_cases x <;> decide

/-- The actual common active affine rank in the manuscript row. -/
theorem active_affine_rank :
    min (MainTheory.AffineRankCertificate.maskAffineRank {namespace}.face0.active0)
      (MainTheory.AffineRankCertificate.maskAffineRank {namespace}.face0.active1) = {row['r_star']} := by
  rw [MainTheory.AffineRankCertificate.affineRank_eq_of_valid {namespace}.rank0_0_valid,
      MainTheory.AffineRankCertificate.affineRank_eq_of_valid {namespace}.rank1_0_valid]
  norm_num [{namespace}.rank0_0, {namespace}.rank1_0]

/-- The affine-hull dimension of all real nonnegative moment solutions on the
original full fibres, including every forced-zero coordinate. -/
theorem lp_affine_dimension :
    Module.finrank ℝ (affineSpan ℝ (polytope {namespace}.pair0)).direction = {row['lp_dimension']} := by
  have h := affine_dimension_eq_of_face {namespace}.pair0 {namespace}.face0
    {namespace}.face0_valid {rank}.columns {rank}.columns_injective active_columns_exact
  simpa only [{rank}.active_moment_rank] using h

end MainTheory.Generated.OrbitTableSemantics{oid:02d}
"""
    for old, new in [("face0", f"face{rid}"), ("pair0", f"pair{rid}"),
                     ("rank0_0", f"rank0_{rid}"), ("rank1_0", f"rank1_{rid}")]:
        source = source.replace(namespace + "." + old, namespace + "." + new)
    path = ROOT / "MainTheory/Generated" / f"OrbitTableSemantics{oid:02d}.lean"
    path.write_text(source, encoding="utf-8")
    return path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--orbit", action="append", type=int)
    args = parser.parse_args()
    for row in inspect():
        if not args.orbit or row["id"] in args.orbit:
            print(emit(row).relative_to(ROOT))
