"""Bind every manuscript row to its full fibres and three semantic statistics.

This generator proposes closed data. All data equalities and the semantic
consequences are checked by Lean; generation does not certify the output.
"""
import json

from inspect_orbit_table_semantics import ROOT, inspect


def vector(values):
    return "![" + ", ".join(map(str, values)) + "]"


def write(name, source):
    path = ROOT / "MainTheory/Generated" / (name + ".lean")
    if not path.exists() or path.read_text(encoding="utf-8") != source:
        path.write_text(source, encoding="utf-8")


def emit(rows):
    orbit = json.loads((ROOT / "results/finite-orbit-certificates.json").read_text())
    inputs = {p: i for i, p in enumerate(orbit["input_pair_ids"])}
    shard = lambda r: f"MainTheory.Generated.FiniteRankDataShard{r['rank_row_index']:02d}"
    data = "-- Generated by tools/generators/emit_orbit_table_numeric.py.\n"
    data += "import MainTheory.OuterEnumeration\nimport MainTheory.Generated.OrbitTableRecords\n"
    data += "".join(f"import {s}\n" for s in sorted(set(map(shard, rows))))
    data += "\nnamespace MainTheory.Generated.OrbitTableNumericData\n\n"
    data += "open MainTheory.FinitePipeline\n\nset_option maxRecDepth 40000\nset_option maxHeartbeats 8000000\n\n"
    for name, field in [("paperQ", "q"), ("paperM", "m"), ("paperN0", "n0"),
                        ("paperN1", "n1"), ("paperRank", "r_star"),
                        ("paperDimension", "lp_dimension"), ("paperMultiplicity", "multiplicity")]:
        data += f"def {name} : Fin 66 → ℕ := {vector(r[field] for r in rows)}\n\n"
    data += f"def paperAngle : Fin 66 → Fin 6 → ℕ := {vector(vector(r['a']) for r in rows)}\n\n"
    data += f"def paperInput : Fin 66 → Fin 215 := {vector(inputs[r['pair_id']] for r in rows)}\n\n"
    data += f"def paperPair : Fin 66 → FiberPair := {vector(shard(r) + '.pair' + str(r['rank_row_index']) for r in rows)}\n\n"
    data += f"def paperFace : Fin 66 → FaceData := {vector(shard(r) + '.face' + str(r['rank_row_index']) for r in rows)}\n\n"
    data += """/-- Full residue fibres, row labels, cardinalities, and the certified orbit key. -/
def RowFacts (i : Fin 66) : Prop :=
  (paperPair i).q = paperQ i ∧
  (paperPair i).m = paperM i ∧
  paperPair i = FiniteOrbitBase.inputAt (paperInput i) ∧
  (OrbitCertificate.witnessAt (paperInput i)).key = OrbitTableRecords.paperKey i ∧
  (∀ x : Fin 64, InMask (paperPair i).mask0 x ↔
    MainTheory.OuterEnumeration.subsetSum (paperAngle i) x.val % paperQ i = 0) ∧
  (∀ x : Fin 64, InMask (paperPair i).mask1 x ↔
    MainTheory.OuterEnumeration.subsetSum (paperAngle i) x.val % paperQ i = paperQ i / paperM i) ∧
  (Finset.univ.filter (InMask (paperPair i).mask0)).card = paperN0 i ∧
  (Finset.univ.filter (InMask (paperPair i).mask1)).card = paperN1 i ∧
  OrbitTableRecords.paperMultiplicity i = paperMultiplicity i

instance (i : Fin 66) : Decidable (RowFacts i) := by unfold RowFacts; infer_instance

"""
    for i in range(66):
        data += f"private theorem row_{i} : RowFacts {i} := by decide\n\n"
    data += "theorem all_rows (i : Fin 66) : RowFacts i := by\n  fin_cases i\n"
    data += "".join(f"  · exact row_{i}\n" for i in range(66))
    data += "\ntheorem all_faces_valid (i : Fin 66) : (paperFace i).Valid (paperPair i) := by\n  fin_cases i\n"
    data += "".join(f"  · exact {shard(r)}.face{r['rank_row_index']}_valid\n" for r in rows)
    data += "\nend MainTheory.Generated.OrbitTableNumericData\n"
    write("OrbitTableNumericData", data)

    active = "-- Generated by tools/generators/emit_orbit_table_numeric.py.\n"
    active += "import MainTheory.Generated.OrbitTableNumericData\nimport MainTheory.FiniteMomentSupportRank\n\n"
    active += "namespace MainTheory.Generated.OrbitTableActiveRanks\n\n"
    active += "open OrbitTableNumericData MainTheory.FiniteMomentSupportRank\n\n"
    active += "theorem all_real_active_ranks (i : Fin 66) (b : Bool) :\n"
    active += "    faceRank (paperFace i) b = paperRank i := by\n  fin_cases i\n"
    for row in rows:
        rid, rank = row['rank_row_index'], row['r_star']
        active += "  · cases b\n"
        for b in (0, 1):
            cert = f"{shard(row)}.rank{b}_{rid}_valid"
            active += "    · change MainTheory.ActiveFace.affineRank\n"
            active += f"        (MainTheory.MomentModelBridge.RankCast.realMaskPointSet {shard(row)}.face{rid}.active{b}) = {rank}\n"
            active += f"      rw [MainTheory.MomentModelBridge.RankCast.affineRank_real_eq_rational_of_valid {cert},\n"
            active += f"        MainTheory.AffineRankCertificate.affineRank_eq_of_valid {cert}]\n      rfl\n"
    active += """
/-- Both actual real support ranks attain r_star simultaneously, and neither
can exceed it anywhere in the full nonnegative moment polytope. -/
theorem all_maximum_support_ranks (i : Fin 66) :
    (∀ p ∈ MainTheory.FiniteMomentLP.polytope (paperPair i), ∀ b,
      supportRank p b ≤ paperRank i) ∧
    ∃ p ∈ MainTheory.FiniteMomentLP.polytope (paperPair i), ∀ b,
      supportRank p b = paperRank i := by
  constructor
  · intro p hp b
    have he := supportRank_le (paperPair i) (paperFace i) (all_faces_valid i) p hp b
    simpa only [all_real_active_ranks] using he
  · obtain ⟨p, hp, he⟩ := exists_attains_both (paperPair i) (paperFace i) (all_faces_valid i)
    exact ⟨p, hp, fun b => (he b).trans (all_real_active_ranks i b)⟩

theorem all_rank_thresholds (i : Fin 66) (r : ℕ) :
    (∃ p ∈ MainTheory.FiniteMomentLP.polytope (paperPair i),
      r ≤ min (supportRank p false) (supportRank p true)) ↔ r ≤ paperRank i := by
  simpa only [all_real_active_ranks, min_self] using
    rank_threshold_iff (paperPair i) (paperFace i) (all_faces_valid i) r

end MainTheory.Generated.OrbitTableActiveRanks
"""
    write("OrbitTableActiveRanks", active)

    source = "-- Generated by tools/generators/emit_orbit_table_numeric.py.\n"
    source += "import MainTheory.Generated.OrbitTableActiveRanks\nimport MainTheory.OrbitTablePaperKey\n"
    source += "".join(f"import MainTheory.Generated.OrbitTableSemantics{i:02d}\n" for i in range(1, 67))
    source += "\nnamespace MainTheory.Generated.OrbitTableNumeric\n\nopen OrbitTableNumericData\n\n"
    source += "set_option maxRecDepth 40000\nset_option maxHeartbeats 8000000\n\n"
    source += """/-- All 66 active affine ranks refer to the certified maximal active faces. -/
theorem all_active_affine_ranks (i : Fin 66) :
    min (MainTheory.AffineRankCertificate.maskAffineRank (paperFace i).active0)
      (MainTheory.AffineRankCertificate.maskAffineRank (paperFace i).active1) = paperRank i := by
  fin_cases i
"""
    source += "".join(f"  · exact OrbitTableSemantics{i:02d}.active_affine_rank\n" for i in range(1, 67))
    source += """
/-- All 66 dimensions are affine-hull dimensions of the entire real LP. -/
theorem all_lp_dimensions (i : Fin 66) :
    Module.finrank ℝ (affineSpan ℝ (MainTheory.FiniteMomentLP.polytope (paperPair i))).direction =
      paperDimension i := by
  fin_cases i
"""
    source += "".join(f"  · exact OrbitTableSemantics{i:02d}.lp_affine_dimension\n" for i in range(1, 67))
    source += """
theorem all_multiplicities (i : Fin 66) :
    MainTheory.OrbitRecordMultiplicity.multiplicity (OrbitTableRecords.paperKey i) =
      paperMultiplicity i :=
  (OrbitTableMultiplicities.all_multiplicities i).trans (all_rows i).2.2.2.2.2.2.2.2

/-- The row's actual full fibres represent the key whose multiplicity is counted. -/
theorem all_labeled_equivalences (i : Fin 66) :
    MainTheory.DistanceSignature.LabeledEquivalent (paperQ i) (paperM i)
      (MainTheory.FiniteOrbitPipeline.fibersOfPair (paperPair i))
      (FiniteOrbitBase.keyAt (OrbitTableRecords.paperKey i)).q
      (FiniteOrbitBase.keyAt (OrbitTableRecords.paperKey i)).m
      (FiniteOrbitBase.keyAt (OrbitTableRecords.paperKey i)).fibers := by
  have h := (OrbitCertificate.witnessAt (paperInput i)).labeledEquivalent_of_validFor
    (OrbitCertificate.witness_valid (paperInput i))
  rw [OrbitCertificate.witness_input, ← (all_rows i).2.2.1,
    (all_rows i).2.2.2.1, (all_rows i).1, (all_rows i).2.1] at h
  exact h

theorem all_statistics (i : Fin 66) :
    min (MainTheory.AffineRankCertificate.maskAffineRank (paperFace i).active0)
      (MainTheory.AffineRankCertificate.maskAffineRank (paperFace i).active1) = paperRank i ∧
    Module.finrank ℝ (affineSpan ℝ (MainTheory.FiniteMomentLP.polytope (paperPair i))).direction =
      paperDimension i ∧
    MainTheory.OrbitRecordMultiplicity.multiplicity (OrbitTableRecords.paperKey i) =
      paperMultiplicity i :=
  ⟨all_active_affine_ranks i, all_lp_dimensions i, all_multiplicities i⟩

/-- The three numeric columns, with r_star characterized by attainability in
the full real LP rather than only by a rational-mask certificate. -/
theorem all_real_statistics (i : Fin 66) (r : ℕ) :
    ((∃ p ∈ MainTheory.FiniteMomentLP.polytope (paperPair i),
      r ≤ min (MainTheory.FiniteMomentSupportRank.supportRank p false)
        (MainTheory.FiniteMomentSupportRank.supportRank p true)) ↔ r ≤ paperRank i) ∧
    Module.finrank ℝ (affineSpan ℝ (MainTheory.FiniteMomentLP.polytope (paperPair i))).direction =
      paperDimension i ∧
    MainTheory.OrbitRecordMultiplicity.multiplicity (OrbitTableRecords.paperKey i) =
      paperMultiplicity i :=
  ⟨OrbitTableActiveRanks.all_rank_thresholds i r, all_lp_dimensions i, all_multiplicities i⟩

end MainTheory.Generated.OrbitTableNumeric
"""
    write("OrbitTableNumeric", source)


if __name__ == "__main__":
    emit(inspect())
