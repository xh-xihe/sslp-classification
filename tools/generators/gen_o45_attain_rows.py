"""Generate the finite symbolic KL rows for Orbit45AttainRows.lean.

The generated Lean file checks every incidence, flip and Walsh sign with
`by decide`; its polynomial conclusions are proved by the kernel `nlinarith`
tactic from the seven displayed `Params` identities.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "SixQubit" / "Orbit45AttainRows.lean"

S0N = [0, 55, 36, 19, 20, 35, 58, 13, 14, 57]
S1N = [8, 63, 44, 27, 28, 43, 50, 5, 6, 49]
S0 = [f"x{i}" for i in range(10)]
S1 = [f"y{i}" for i in range(10)]

DIAG_E = {
    0: "Orbit45A2.e00", 3: "Orbit45A2.e03", 20: "Orbit45A2.e20",
    36: "Orbit45A2.e36", 48: "Orbit45A2.e48",
}
CROSS_E = {
    5: "Orbit45Phase.flip5", 6: "Orbit45Phase.flip6",
    8: "flip8", 17: "Orbit45Phase.flip17", 18: "Orbit45Phase.flip18",
    33: "Orbit45Phase.flip33", 34: "Orbit45Phase.flip34",
}


def allowed_z(e):
    return [z for z in range(64) if (e | z).bit_count() <= 2]


assert len(S0N) == len(set(S0N)) == 10
assert len(S1N) == len(set(S1N)) == 10
assert sum(len(allowed_z(e)) for e in DIAG_E) == 38
assert sum(len(allowed_z(e)) for e in CROSS_E) == 36


def filt(nums, other, e):
    return [i for i, n in enumerate(nums) if (n ^ e) in other]


def ins(n):
    if n == 0:
        return []
    return ["Finset.sum_insert (by decide)"] * (n - 1) + ["Finset.sum_singleton"]


def comma_lines(items, indent="    "):
    return ",\n".join(indent + x for x in items)


def header():
    return r'''import Mathlib

import SixQubit.Orbit45Attain

/-!
# Orbit 45: generated exact symbolic KL table for the direct family

This file is generated by `tools/generators/gen_o45_attain_rows.py`.
Every support incidence, xor target, Walsh sign, and low-weight case list is
independently checked by the Lean kernel.  The generator is not proof evidence.
-/

namespace SixQubit.Orbit45Attain

open scoped BigOperators ComplexConjugate
open SixQubit.Realize
open SixQubit.Orbit45Support
open SixQubit.Orbit45Phase

noncomputable section

set_option maxRecDepth 20000
set_option maxHeartbeats 2000000
-- Many rows vanish before the parameter identities are needed.
set_option linter.unusedVariables false

macro "o45_finish_row" hp:term : tactic => `(tactic| (
  simp only [SixQubit.signMul_false, SixQubit.signMul_true,
    cword_x0, cword_x1, cword_x2, cword_x3, cword_x4,
    cword_x5, cword_x6, cword_x7, cword_x8, cword_x9,
    dword_y0, dword_y1, dword_y2, dword_y3, dword_y4,
    dword_y5, dword_y6, dword_y7, dword_y8, dword_y9,
    star_neg, star_mul', star_phase, Complex.star_def, Complex.conj_ofReal]
  apply Complex.ext <;>
    simp only [Complex.add_re, Complex.add_im, Complex.neg_re, Complex.neg_im,
      Complex.mul_re, Complex.mul_im, phase_re, phase_im,
      Complex.ofReal_re, Complex.ofReal_im]
  all_goals norm_num
  all_goals ring_nf
  all_goals nlinarith [Params.amp_sum $hp, Params.q_sq $hp,
    Params.unit1 $hp, Params.unit2 $hp, Params.unit3 $hp,
    Params.triangle_re $hp, Params.triangle_im $hp]))

'''


PARAMS = "(a1 a2 a3 q u1 v1 u2 v2 u3 v3 : ℝ)\n    (hp : Params a1 a2 a3 q u1 v1 u2 v2 u3 v3)"
C = "(cword a1 a2 a3 q u1 v1 u2 v2 u3 v3)"
D = "(dword a1 a2 a3 q u1 v1 u2 v2 u3 v3)"


def diag_row(e, z):
    en = DIAG_E[e]
    bi = filt(S0N, set(S0N), e)
    ti = filt(S1N, set(S1N), e)
    bnames = [S0[i] for i in bi]
    tnames = [S1[i] for i in ti]
    rewrites = [
        f"show S0.filter (fun x => SS.bxor x {en} ∈ S0) =\n"
        f"      ({{{','.join(bnames)}}} : Finset (SS.BitString 6)) from by decide",
        f"show S1.filter (fun x => SS.bxor x {en} ∈ S1) =\n"
        f"      ({{{','.join(tnames)}}} : Finset (SS.BitString 6)) from by decide",
    ] + ins(len(bi)) + ins(len(ti))
    for i in bi:
        j = S0N.index(S0N[i] ^ e)
        rewrites.append(f"show SS.bxor {S0[i]} {en} = {S0[j]} from by decide")
    for i in ti:
        j = S1N.index(S1N[i] ^ e)
        rewrites.append(f"show SS.bxor {S1[i]} {en} = {S1[j]} from by decide")
    signs = []
    for i in bi:
        val = "true" if ((z & S0N[i]).bit_count() & 1) else "false"
        signs.append(f"show SS.bdot (nbit {z}) {S0[i]} = {val} from by decide")
    for i in ti:
        val = "true" if ((z & S1N[i]).bit_count() & 1) else "false"
        signs.append(f"show SS.bdot (nbit {z}) {S1[i]} = {val} from by decide")
    return f'''private theorem diag_{e}_{z}
    {PARAMS} :
    SixQubit.diagOn S0 {C} {en} (nbit {z}) =
      SixQubit.diagOn S1 {D} {en} (nbit {z}) := by
  unfold SixQubit.diagOn
  rw [\n{comma_lines(rewrites)}]
  simp only [\n{comma_lines(signs)}]
  o45_finish_row hp

'''


def off_row(e, z, reverse=False):
    en = CROSS_E[e]
    if reverse:
        srcn, dstn, src, dst = S0N, set(S1N), S0, S1
        sfun, tfun = C, D
        sset, tset = "S0", "S1"
        name = f"rev_{e}_{z}"
    else:
        srcn, dstn, src, dst = S1N, set(S0N), S1, S0
        sfun, tfun = D, C
        sset, tset = "S1", "S0"
        name = f"off_{e}_{z}"
    ii = filt(srcn, dstn, e)
    names = [src[i] for i in ii]
    rewrites = [
        f"show {sset}.filter (fun x => SS.bxor x {en} ∈ {tset}) =\n"
        f"      ({{{','.join(names)}}} : Finset (SS.BitString 6)) from by decide",
    ] + ins(len(ii))
    dstnums = S1N if reverse else S0N
    for i in ii:
        j = dstnums.index(srcn[i] ^ e)
        rewrites.append(f"show SS.bxor {src[i]} {en} = {dst[j]} from by decide")
    signs = []
    for i in ii:
        val = "true" if ((z & srcn[i]).bit_count() & 1) else "false"
        signs.append(f"show SS.bdot (nbit {z}) {src[i]} = {val} from by decide")
    return f'''private theorem {name}
    {PARAMS} :
    SixQubit.offSumOn {tset} {sset} {tfun} {sfun} {en} (nbit {z}) = 0 := by
  unfold SixQubit.offSumOn
  rw [\n{comma_lines(rewrites)}]
  simp only [\n{comma_lines(signs)}]
  o45_finish_row hp

'''


def finset_def(name, zs):
    return f"private def {name} : Finset (SS.BitString 6) := " \
           f"{{{','.join(f'nbit {z}' for z in zs)}}}\n"


def mem_thm(name, en):
    return f'''private theorem {name}_mem :
    ∀ z : SS.BitString 6,
      (⟨{en},z⟩ : SS.PauliString 6).wt ≤ 2 → z ∈ {name} := by decide

'''


def case_block(kind, e, zs):
    zname = f"{kind}Z{e}"
    prefix = "diag" if kind == "diag" else ("off" if kind == "off" else "rev")
    lines = [f"    have hz := {zname}_mem z hw",
             f"    simp only [{zname}, Finset.mem_insert, Finset.mem_singleton] at hz",
             "    rcases hz with " + " | ".join(["rfl"] * len(zs))]
    for z in zs:
        lines.append(f"    · exact {prefix}_{e}_{z} a1 a2 a3 q u1 v1 u2 v2 u3 v3 hp")
    return "\n".join(lines)


def footer():
    parts = []
    for e, en in DIAG_E.items():
        name = f"diagZ{e}"
        parts += [finset_def(name, allowed_z(e)), mem_thm(name, en)]
    parts.append(r'''private theorem diag_top_empty_of_not_live :
    ∀ e : SS.BitString 6, SS.hammingWt e ≤ 2 → e ∉ Orbit45A2.liveX →
      S1.filter (fun s => SS.bxor s e ∈ S1) = ∅ := by decide

theorem direct_diag_rows
    (a1 a2 a3 q u1 v1 u2 v2 u3 v3 : ℝ)
    (hp : Params a1 a2 a3 q u1 v1 u2 v2 u3 v3) :
    ∀ e z, (⟨e,z⟩ : SS.PauliString 6).wt ≤ 2 →
      SixQubit.diagOn S0 (cword a1 a2 a3 q u1 v1 u2 v2 u3 v3) e z =
      SixQubit.diagOn S1 (dword a1 a2 a3 q u1 v1 u2 v2 u3 v3) e z := by
  intro e z hw
  have hew : SS.hammingWt e ≤ 2 :=
    (Orbit45A2.hammingWt_x_le_wt (⟨e,z⟩ : SS.PauliString 6)).trans hw
  by_cases he : e ∈ Orbit45A2.liveX
  · simp only [Orbit45A2.liveX, Finset.mem_insert, Finset.mem_singleton] at he
    rcases he with rfl | rfl | rfl | rfl | rfl
''')
    for e in DIAG_E:
        parts.append(case_block("diag", e, allowed_z(e)) + "\n")
    parts.append(r'''  · unfold SixQubit.diagOn
    rw [Orbit45A2.incidence_empty_of_not_live e hew he,
      diag_top_empty_of_not_live e hew he]
    simp

private def crossLive : Finset (SS.BitString 6) :=
  {Orbit45Phase.flip5,Orbit45Phase.flip6,flip8,Orbit45Phase.flip17,
    Orbit45Phase.flip18,Orbit45Phase.flip33,Orbit45Phase.flip34}

private theorem off_empty_of_not_live :
    ∀ e : SS.BitString 6, SS.hammingWt e ≤ 2 → e ∉ crossLive →
      S1.filter (fun s => SS.bxor s e ∈ S0) = ∅ := by decide

private theorem rev_empty_of_not_live :
    ∀ e : SS.BitString 6, SS.hammingWt e ≤ 2 → e ∉ crossLive →
      S0.filter (fun s => SS.bxor s e ∈ S1) = ∅ := by decide

''')
    for kind in ("off", "rev"):
        for e, en in CROSS_E.items():
            name = f"{kind}Z{e}"
            parts += [finset_def(name, allowed_z(e)), mem_thm(name, en)]
        thm = "direct_off_rows" if kind == "off" else "direct_rev_rows"
        src0, src1, f0, f1 = (("S0", "S1", C, D) if kind == "off"
                              else ("S1", "S0", D, C))
        parts.append(f'''theorem {thm}
    (a1 a2 a3 q u1 v1 u2 v2 u3 v3 : ℝ)
    (hp : Params a1 a2 a3 q u1 v1 u2 v2 u3 v3) :
    ∀ e z, (⟨e,z⟩ : SS.PauliString 6).wt ≤ 2 →
      SixQubit.offSumOn {src0} {src1} {f0} {f1} e z = 0 := by
  intro e z hw
  have hew : SS.hammingWt e ≤ 2 :=
    (Orbit45A2.hammingWt_x_le_wt (⟨e,z⟩ : SS.PauliString 6)).trans hw
  by_cases he : e ∈ crossLive
  · simp only [crossLive, Finset.mem_insert, Finset.mem_singleton] at he
    rcases he with rfl | rfl | rfl | rfl | rfl | rfl | rfl
''')
        for e in CROSS_E:
            parts.append(case_block(kind, e, allowed_z(e)) + "\n")
        empty = "off_empty_of_not_live" if kind == "off" else "rev_empty_of_not_live"
        parts.append(f'''  · unfold SixQubit.offSumOn
    rw [{empty} e hew he]
    simp

''')
    parts.append(r'''theorem direct_is_code
    (a1 a2 a3 q u1 v1 u2 v2 u3 v3 : ℝ)
    (hp : Params a1 a2 a3 q u1 v1 u2 v2 u3 v3) :
    SS.HasDistance (code a1 a2 a3 q u1 v1 u2 v2 u3 v3) 3 := by
  apply hasDistance_of_support_rows
    (cword a1 a2 a3 q u1 v1 u2 v2 u3 v3)
    (dword a1 a2 a3 q u1 v1 u2 v2 u3 v3)
    (cword_support _ _ _ _ _ _ _ _ _ _)
    (dword_support _ _ _ _ _ _ _ _ _ _)
    (direct_diag_rows _ _ _ _ _ _ _ _ _ _ hp)
    (direct_off_rows _ _ _ _ _ _ _ _ _ _ hp)
    (direct_rev_rows _ _ _ _ _ _ _ _ _ _ hp)

end

end SixQubit.Orbit45Attain
''')
    return "".join(parts)


def main():
    text = header()
    for e in DIAG_E:
        for z in allowed_z(e):
            text += diag_row(e, z)
    for reverse in (False, True):
        for e in CROSS_E:
            for z in allowed_z(e):
                text += off_row(e, z, reverse)
    text += footer()
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
