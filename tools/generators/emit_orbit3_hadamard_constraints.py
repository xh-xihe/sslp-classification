#!/usr/bin/env python3
"""Bind all three Hadamard metadata rows to actual physical Ward identities.

This does not certify their reduced-coordinate coefficient representation.
Both the finite label transformations and the physical averaging equality
are proved by Lean; Python only supplies the explicit candidate labels.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def vector(values):
    return '![' + ', '.join(map(str, values)) + ']'


def generate(source: Path, output: Path):
    raw = source.read_bytes()
    terms = json.loads(raw)['terms']
    if len(terms) != 211 or sum(t['kind'] == 'H' for t in terms) != 3:
        raise ValueError('Expected the complete 211-row certificate and three H rows')
    labels, signs = [], []
    for term in terms:
        original = term.get('paulis', [0, 0, 0])
        if len(original) != 3 or any(not isinstance(r, int) or not 0 <= r < 4096 for r in original):
            raise ValueError('Invalid Pauli triple')
        labels.append([(r & ~65) | ((r & 1) << 6) | ((r & 64) >> 6) for r in original])
        signs.append((-1) ** sum(bool(r & 1) and bool(r & 64) for r in original))
    text = f'''-- Generated by tools/generators/emit_orbit3_hadamard_constraints.py.
-- Input SHA-256: {hashlib.sha256(raw).hexdigest()}
import MainTheory.Orbit3HadamardBridge
import SixQubit.Generated.Orbit3PauliConstraints

namespace SixQubit.Generated.Orbit3HadamardConstraints

open MainTheory.Orbit3HadamardBridge MainTheory.Orbit3CliffordAverage
open MainTheory.Orbit3PauliZeros SixQubit.Generated.SpectatorClifford
open scoped BigOperators

set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

def labels : Fin 211 → Fin 3 → Fin 4096 :=
  {vector([vector(row) for row in labels])}

def sign : Fin 211 → ℤ := {vector(signs)}

theorem transformed_labels : ∀ i : Fin 211, Orbit3PauliConstraints.kind i = 2 →
    ∀ k : Fin 3, label (hPauli (decode (Orbit3PauliConstraints.labels i k))) = labels i k := by
  decide +kernel

theorem transformed_paulis (i : Fin 211) (hi : Orbit3PauliConstraints.kind i = 2) (k : Fin 3) :
    hPauli (decode (Orbit3PauliConstraints.labels i k)) = decode (labels i k) := by
  rw [← decode_label (hPauli (decode (Orbit3PauliConstraints.labels i k))), transformed_labels i hi k]

theorem product_sign : ∀ i : Fin 211, Orbit3PauliConstraints.kind i = 2 →
    productSign (fun k => decode (Orbit3PauliConstraints.labels i k)) = sign i := by
  decide +kernel

theorem all_H_Ward_rows (i : Fin 211) (hi : Orbit3PauliConstraints.kind i = 2)
    (w : SS.State 6 ℂ) :
    (∑ g : Fin 24,
      (product (fun k => decode (Orbit3PauliConstraints.labels i k)) (act (clifford g) w) -
        (sign i : ℝ) * product (fun k => decode (labels i k)) (act (clifford g) w))) = 0 := by
  have h := actual_H_Ward (fun k => decode (Orbit3PauliConstraints.labels i k)) w
  simp_rw [transformed_paulis i hi, product_sign i hi] at h
  exact h

end SixQubit.Generated.Orbit3HadamardConstraints
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT/'results/orbit3-kernel/certificate.json')
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3HadamardConstraints.lean')
    args = parser.parse_args()
    generate(args.input, args.output)


if __name__ == '__main__':
    main()
