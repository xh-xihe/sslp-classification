"""Emit the lightweight, ordinary-kernel certificate for the 215 -> 66 step.

This program deliberately does *not* run the LP, active-face, rank, or outer
enumeration computations.  It reads the already existing exact certificate
bundle and normalizes only its small orbit directory.

The historical bundle stored orbit keys as ``(m, mask0, mask1)`` and stored a
Python ``itertools.permutations`` index.  The paper, however, retains both
``q`` and ``m`` and numbers representatives after sorting by
``(q,m,mask0,mask1)``.  Normalization therefore:

* recovers the unique ``q`` of every old key from its witnessed input rows;
* sorts the four-field keys and remaps every witness key id;
* expands the permutation index to its semantic six-entry permutation;
* independently rechecks all 215 bit-mask actions;
* emits one Lean module per action witness and one per signature computation.

The JSON remains untrusted.  Generated Lean modules use only ``by decide``
and ordinary proof terms; no native evaluator is used in the proof chain.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict, dataclass
from itertools import permutations
from pathlib import Path
from typing import Any


HEADER = """-- This file is generated by tools/generators/emit_finite_orbits_lean.py.
-- Do not edit it by hand.  The JSON input is untrusted; Lean rechecks every
-- action witness and every separating signature with ordinary kernel reduction.
"""

PERMUTATIONS = tuple(permutations(range(6)))

# The normalized key directory is sorted by ``(q,m,mask0,mask1)``.  That order
# is not the numbering used by the paper.  These are the actual paper orbit
# ids of keys 0,...,65.  In particular the eight order-five keys 32,...,39
# have paper ids 34,39,36,40,38,33,35,37.  The generated Lean identification
# bridge independently checks the paper representatives against the concrete
# input pairs and the stored cube-action witnesses; this table is only the
# public manifest lookup.  At present only its order-five slice is tied to
# literal paper supports by a Lean theorem; the other entries remain metadata
# until their corresponding paper-identification bridges are added.
PAPER_ORBIT_IDS_BY_KEY = (
    1, 2, 3, 4, 5, 6, 7, 9, 8, 11, 15, 23, 10, 16, 14, 24, 22, 13, 12, 20,
    18, 17, 21, 19, 25, 26, 31, 32, 28, 30, 27, 29, 34, 39, 36, 40, 38, 33,
    35, 37, 43, 41, 42, 46, 44, 45, 48, 47, 50, 49, 52, 51, 54, 53, 55, 56,
    59, 57, 61, 58, 60, 62, 63, 64, 65, 66,
)


@dataclass(frozen=True, order=True)
class Key:
    q: int
    m: int
    mask0: int
    mask1: int


@dataclass(frozen=True)
class Witness:
    input_index: int
    pair_id: int
    orbit_id: int
    q: int
    m: int
    permutation: tuple[int, ...]
    shift: int
    swap: bool


@dataclass(frozen=True)
class Signature:
    q: int
    m: int
    internal0: tuple[int, ...]
    internal1: tuple[int, ...]
    cross: tuple[int, ...]


@dataclass(frozen=True)
class Normalized:
    inputs: tuple[tuple[int, int, int, int], ...]
    pair_ids: tuple[int, ...]
    keys: tuple[Key, ...]
    witnesses: tuple[Witness, ...]
    signatures: tuple[Signature, ...]
    representatives: tuple[int, ...]


def write_if_changed(path: Path, text: str) -> None:
    text = text.rstrip() + "\n"
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8", newline="\n")


def mask_points(mask: int) -> list[int]:
    return [x for x in range(64) if (mask >> x) & 1]


def permute_word(x: int, permutation: tuple[int, ...]) -> int:
    """Output coordinate j receives input coordinate permutation[j]."""
    return sum(((x >> permutation[j]) & 1) << j for j in range(6))


def transform_mask(mask: int, permutation: tuple[int, ...], shift: int) -> int:
    answer = 0
    for x in mask_points(mask):
        answer |= 1 << (permute_word(x, permutation) ^ shift)
    return answer


def unordered_internal(mask: int) -> tuple[int, ...]:
    points = mask_points(mask)
    counts = [0] * 7
    for i, x in enumerate(points):
        for y in points[i + 1 :]:
            counts[(x ^ y).bit_count()] += 1
    return tuple(counts)


def ordered_internal(mask: int) -> tuple[int, ...]:
    """The convention used by MainTheory.DistanceSignature.internalHistogram."""
    unordered = unordered_internal(mask)
    return (len(mask_points(mask)),) + tuple(2 * unordered[d] for d in range(1, 7))


def cross_histogram(mask0: int, mask1: int) -> tuple[int, ...]:
    counts = [0] * 7
    for x in mask_points(mask0):
        for y in mask_points(mask1):
            counts[(x ^ y).bit_count()] += 1
    return tuple(counts)


def signature(key: Key) -> Signature:
    internal = sorted((ordered_internal(key.mask0), ordered_internal(key.mask1)))
    return Signature(
        key.q,
        key.m,
        internal[0],
        internal[1],
        cross_histogram(key.mask0, key.mask1),
    )


def signature_code(sig: Signature) -> int:
    """Mixed-radix code using q, m and cross bins (injective on this table)."""
    code = sig.q * 16 + sig.m
    for value in sig.cross:
        if not (0 <= value < 1024):
            raise ValueError("cross-histogram entry does not fit the declared radix")
        code = code * 1024 + value
    return code


def normalize(data: dict[str, Any]) -> Normalized:
    pair_table = [tuple(map(int, row)) for row in data["pair_table"]]
    compatible = tuple(map(int, data["compatible_pair_ids"]))
    raw_keys = [tuple(map(int, row)) for row in data["orbit_keys"]]
    raw_witnesses = data["cube_witnesses"]

    if len(compatible) != 215 or len(raw_witnesses) != 215:
        raise ValueError("the orbit layer must contain exactly 215 compatible rows")
    if len(set(compatible)) != len(compatible):
        raise ValueError("compatible pair ids are not unique")
    if [int(w["pair"]) for w in raw_witnesses] != list(compatible):
        raise ValueError("cube witnesses are not in compatible-pair order")
    if len(raw_keys) != 66:
        raise ValueError("the orbit layer must contain exactly 66 keys")

    key_q: dict[int, int] = {}
    for raw in raw_witnesses:
        pair_id = int(raw["pair"])
        old_id = int(raw["orbit"])
        if not (0 <= pair_id < len(pair_table)):
            raise ValueError(f"out-of-range pair id {pair_id}")
        if not (0 <= old_id < len(raw_keys)):
            raise ValueError(f"out-of-range orbit id {old_id}")
        q, m, _, _ = pair_table[pair_id]
        old_m = raw_keys[old_id][1 if len(raw_keys[old_id]) == 4 else 0]
        if m != old_m:
            raise ValueError(f"logical-order mismatch at old orbit {old_id}")
        previous = key_q.setdefault(old_id, q)
        if previous != q:
            raise ValueError(
                f"legacy orbit {old_id} mixes lift orders {previous} and {q}"
            )

    if set(key_q) != set(range(len(raw_keys))):
        missing = sorted(set(range(len(raw_keys))) - set(key_q))
        raise ValueError(f"ghost orbit keys without an input witness: {missing}")

    augmented: list[Key] = []
    for old_id, raw_key in enumerate(raw_keys):
        if len(raw_key) == 3:
            m, mask0, mask1 = raw_key
            augmented.append(Key(key_q[old_id], m, mask0, mask1))
        elif len(raw_key) == 4:
            q, m, mask0, mask1 = raw_key
            if q != key_q[old_id]:
                raise ValueError(f"lift-order mismatch at orbit {old_id}")
            augmented.append(Key(q, m, mask0, mask1))
        else:
            raise ValueError("orbit keys must have three (legacy) or four fields")

    if len(set(augmented)) != 66:
        raise ValueError("adding q does not produce 66 distinct labelled keys")
    keys = tuple(sorted(augmented))
    new_id = {key: index for index, key in enumerate(keys)}

    witnesses: list[Witness] = []
    for input_index, raw in enumerate(raw_witnesses):
        pair_id = int(raw["pair"])
        old_id = int(raw["orbit"])
        q, m, source0, source1 = pair_table[pair_id]
        key = augmented[old_id]

        if "permutation" in raw:
            permutation = tuple(map(int, raw["permutation"]))
        else:
            perm_index = int(raw["perm"])
            if not (0 <= perm_index < len(PERMUTATIONS)):
                raise ValueError(f"out-of-range permutation index {perm_index}")
            permutation = PERMUTATIONS[perm_index]
        if sorted(permutation) != list(range(6)):
            raise ValueError(f"malformed semantic permutation {permutation}")

        shift = int(raw["shift"])
        swap = bool(raw["swap"])
        if not (0 <= shift < 64):
            raise ValueError(f"out-of-range shift {shift}")

        target0 = transform_mask(source0, permutation, shift)
        target1 = transform_mask(source1, permutation, shift)
        if swap:
            target0, target1 = target1, target0
        if (q, m, target0, target1) != (
            key.q,
            key.m,
            key.mask0,
            key.mask1,
        ):
            raise ValueError(f"incorrect cube witness for compatible row {input_index}")

        witnesses.append(
            Witness(
                input_index,
                pair_id,
                new_id[key],
                q,
                m,
                permutation,
                shift,
                swap,
            )
        )

    if {w.orbit_id for w in witnesses} != set(range(66)):
        raise ValueError("normalized orbit keys are not all witnessed")

    signatures = tuple(signature(key) for key in keys)
    if len(set(signatures)) != len(signatures):
        raise ValueError("distance signatures do not separate all 66 keys")
    if len({signature_code(sig) for sig in signatures}) != len(signatures):
        raise ValueError("q/m/cross signature codes do not separate all 66 keys")

    representatives = tuple(
        next(i for i, witness in enumerate(witnesses) if witness.orbit_id == key_id)
        for key_id in range(66)
    )
    inputs = tuple(pair_table[pair_id] for pair_id in compatible)
    return Normalized(inputs, compatible, keys, tuple(witnesses), signatures, representatives)


def vector(names: list[str], indent: str = "  ") -> str:
    # Lean 4.27's `![...]` parser rejects a comma after the final element.
    return "![\n" + ",\n".join(f"{indent}{name}" for name in names) + "\n]"


def balanced_fin_vector(
    name: str, type_name: str, names: list[str], leaf_size: int = 15
) -> list[str]:
    """Emit a shallow `Fin n -> alpha` directory built from named entries.

    A single 215-entry `![...]` is semantically fine, but reducing a high
    index walks a deeply nested term.  Small literal leaves joined by a
    balanced `Fin.append` tree keep ordinary kernel reduction shallow.  The
    final definition retains exactly the same public name and function type.
    """
    if not names:
        raise ValueError("a balanced Fin vector must be nonempty")
    if leaf_size <= 0:
        raise ValueError("leaf_size must be positive")

    lines: list[str] = []
    nodes: list[tuple[str, int]] = []
    for leaf_index, start in enumerate(range(0, len(names), leaf_size)):
        chunk = names[start : start + leaf_size]
        leaf_name = f"{name}Leaf{leaf_index:02d}"
        lines.extend(
            [
                f"def {leaf_name} : Fin {len(chunk)} → {type_name} :=",
                vector(chunk),
                "",
            ]
        )
        nodes.append((leaf_name, len(chunk)))

    level = 0
    while len(nodes) > 1:
        next_nodes: list[tuple[str, int]] = []
        for pair_index in range(0, len(nodes), 2):
            if pair_index + 1 == len(nodes):
                next_nodes.append(nodes[pair_index])
                continue
            left_name, left_size = nodes[pair_index]
            right_name, right_size = nodes[pair_index + 1]
            node_name = f"{name}Node{level:02d}_{pair_index // 2:02d}"
            node_size = left_size + right_size
            lines.extend(
                [
                    f"def {node_name} : Fin {node_size} → {type_name} :=",
                    f"  Fin.append {left_name} {right_name}",
                    "",
                ]
            )
            next_nodes.append((node_name, node_size))
        nodes = next_nodes
        level += 1

    root_name, root_size = nodes[0]
    if root_size != len(names):
        raise AssertionError("balanced vector size drift")
    lines.extend(
        [
            f"def {name} : Fin {len(names)} → {type_name} :=",
            f"  {root_name}",
            "",
        ]
    )
    return lines


def nat_list(values: tuple[int, ...] | list[int], width: int = 20) -> str:
    chunks = []
    values = list(values)
    for start in range(0, len(values), width):
        chunks.append("  " + ", ".join(map(str, values[start : start + width])))
    return "[\n" + ",\n".join(chunks) + "\n]"


def histogram(values: tuple[int, ...]) -> str:
    if len(values) != 7:
        raise ValueError("a six-cube histogram must have seven bins")
    return "![" + ", ".join(map(str, values)) + "]"


def emit_base(cert: Normalized, out_dir: Path) -> None:
    if len(PAPER_ORBIT_IDS_BY_KEY) != len(cert.keys):
        raise ValueError("paper-orbit lookup does not cover every normalized key")
    if sorted(PAPER_ORBIT_IDS_BY_KEY) != list(range(1, len(cert.keys) + 1)):
        raise ValueError("paper-orbit lookup is not a permutation of 1,...,66")

    lines = [
        HEADER,
        "import MainTheory.FiniteOrbitPipeline",
        "",
        "namespace MainTheory.Generated.FiniteOrbitBase",
        "",
        "/-! The 215 explicit pairs below are the pair-table payloads at the exact",
        "compatible ids.  `FiniteOrbitRankBridge` links their identifiers to the",
        "rank audit without making every small shard import that heavy aggregate.",
        "A separate pair-payload provenance theorem is still",
        "required upstream to identify arbitrary metadata ids with table payloads. -/",
        "",
    ]
    for index, (q, m, mask0, mask1) in enumerate(cert.inputs):
        lines.append(
            f"def input{index:03d} : MainTheory.FinitePipeline.FiberPair := "
            f"⟨{q}, {m}, {mask0}, {mask1}⟩"
        )
    lines.append("")
    lines.extend(
        balanced_fin_vector(
            "inputAt",
            "MainTheory.FinitePipeline.FiberPair",
            [f"input{i:03d}" for i in range(215)],
        )
    )
    lines.extend(
        [
            "def inputPairIds : List ℕ := " + nat_list(cert.pair_ids),
            "",
        ]
    )

    for index, key in enumerate(cert.keys):
        lines.append(
            f"def key{index:02d} : MainTheory.FiniteOrbitPipeline.OrbitKey := "
            f"⟨{key.q}, {key.m}, {key.mask0}, {key.mask1}⟩"
        )
    lines.extend(
        [
            "",
            "def keyAt : Fin 66 → MainTheory.FiniteOrbitPipeline.OrbitKey :=",
            vector([f"key{i:02d}" for i in range(66)]),
            "",
        ]
    )

    for index, sig in enumerate(cert.signatures):
        lines.extend(
            [
                f"def expectedSignature{index:02d} : MainTheory.DistanceSignature.Signature 6 where",
                f"  liftOrder := {sig.q}",
                f"  logicalOrder := {sig.m}",
                "  internal :=",
                f"    {{{histogram(sig.internal0)}, {histogram(sig.internal1)}}}",
                f"  cross := {histogram(sig.cross)}",
                "",
            ]
        )
    lines.extend(
        [
            "def expectedSignatureAt : Fin 66 → MainTheory.DistanceSignature.Signature 6 :=",
            vector([f"expectedSignature{i:02d}" for i in range(66)]),
            "",
            "/-- A cheap scalar projection of a signature.  The radix bounds are",
            "checked by the generator, and the 66 concrete values are rechecked in",
            "small Lean shards.  This avoids deciding equality of function fields. -/",
            "def signatureCode (s : MainTheory.DistanceSignature.Signature 6) : ℕ :=",
            "  ((((((((s.liftOrder * 16 + s.logicalOrder) * 1024 + s.cross 0)",
            "    * 1024 + s.cross 1) * 1024 + s.cross 2) * 1024 + s.cross 3)",
            "    * 1024 + s.cross 4) * 1024 + s.cross 5) * 1024 + s.cross 6)",
            "",
            "/-- Finite inverse on the 66 concrete scalar codes. -/",
            "def codeTag (code : ℕ) : Fin 66 :=",
        ]
    )
    for index in range(65):
        prefix = "  if" if index == 0 else "  else if"
        lines.append(
            f"{prefix} code = {signature_code(cert.signatures[index])} then {index}"
        )
    lines.extend(
        [
            "  else 65",
            "",
            "def representativeAt : Fin 66 → Fin 215 :=",
            vector([str(i) for i in cert.representatives]),
            "",
            "/-- Manifest paper-orbit lookup for each q/m-aware generated key.",
            "Generated key order is lexicographic `(q,m,mask0,mask1)`, not paper",
            "order.  This data definition alone is not an identification proof;",
            "`OrderFivePaperIdentification` supplies the current kernel bridge. -/",
            "def paperOrbitId : Fin 66 → ℕ :=",
            vector([str(i) for i in PAPER_ORBIT_IDS_BY_KEY]),
            "",
            "end MainTheory.Generated.FiniteOrbitBase",
        ]
    )
    write_if_changed(out_dir / "FiniteOrbitBase.lean", "\n".join(lines))


def emit_rank_bridge(out_dir: Path) -> None:
    """Keep the heavy rank aggregate out of every small action/signature shard."""
    lines = [
        HEADER,
        "import MainTheory.Generated.FiniteOrbitBase",
        "import MainTheory.Generated.FiniteRankData",
        "",
        "namespace MainTheory.Generated.FiniteOrbitRankBridge",
        "",
        # `decide` on the 215-entry array equality needs more than the default
        # recursion depth, as in the sibling generated modules.
        "set_option maxRecDepth 1000000",
        "",
        "theorem inputPairIds_eq_rankCompatible :",
        "    MainTheory.Generated.FiniteOrbitBase.inputPairIds.toArray =",
        "      MainTheory.Generated.FiniteRankData.rankCompatiblePairIds := by",
        "  rw [MainTheory.Generated.FiniteRankData.rankCompatiblePairIds_eq_manifest]",
        "  decide",
        "",
        "end MainTheory.Generated.FiniteOrbitRankBridge",
    ]
    write_if_changed(out_dir / "FiniteOrbitRankBridge.lean", "\n".join(lines))


def emit_witness_shard(cert: Normalized, out_dir: Path, index: int) -> None:
    witness = cert.witnesses[index]
    permutation_text = "[" + ", ".join(map(str, witness.permutation)) + "]"
    swap_text = str(witness.swap).lower()
    lines = [
        HEADER,
        "import MainTheory.Generated.FiniteOrbitBase",
        "",
        f"namespace MainTheory.Generated.FiniteOrbitWitnessShard{index:03d}",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 8000000",
        "",
        f"def witness : MainTheory.FiniteOrbitPipeline.OrbitWitness 215 66 where",
        f"  input := {witness.input_index}",
        f"  key := {witness.orbit_id}",
        f"  q := {witness.q}",
        f"  m := {witness.m}",
        f"  permutation := {permutation_text}",
        f"  shift := {witness.shift}",
        f"  swap := {swap_text}",
        "",
        "theorem witness_validFor :",
        f"    witness.ValidFor MainTheory.Generated.FiniteOrbitBase.input{index:03d}",
        f"      MainTheory.Generated.FiniteOrbitBase.key{witness.orbit_id:02d} := by",
        "  unfold MainTheory.FiniteOrbitPipeline.OrbitWitness.ValidFor",
        f"  dsimp only [witness, MainTheory.Generated.FiniteOrbitBase.input{index:03d},",
        f"    MainTheory.Generated.FiniteOrbitBase.key{witness.orbit_id:02d}]",
        "  refine ⟨rfl, rfl, rfl, rfl, ?_⟩",
        "  let hp : MainTheory.FiniteOrbitPipeline.PermutationValid "
        f"{permutation_text} := by",
        "    refine ⟨rfl, by decide, ?_⟩",
        "    intro i",
        "    fin_cases i <;> decide",
        "  refine ⟨hp, by decide, ?_⟩",
        "  decide",
        "",
        f"end MainTheory.Generated.FiniteOrbitWitnessShard{index:03d}",
    ]
    write_if_changed(
        out_dir / f"FiniteOrbitWitnessShard{index:03d}.lean", "\n".join(lines)
    )


def emit_signature_shard(cert: Normalized, out_dir: Path, index: int) -> None:
    key = cert.keys[index]
    expected = cert.signatures[index]
    internal_false = ordered_internal(key.mask0)
    internal_true = ordered_internal(key.mask1)
    if sorted((internal_false, internal_true)) != [
        expected.internal0,
        expected.internal1,
    ]:
        raise ValueError(f"internal signature mismatch at key {index}")
    internal_same_order = (
        internal_false == expected.internal0
        and internal_true == expected.internal1
    )
    lines = [
        HEADER,
        "import MainTheory.Generated.FiniteOrbitBase",
        "",
        f"namespace MainTheory.Generated.FiniteOrbitSignatureShard{index:02d}",
        "",
        "set_option maxRecDepth 1000000",
        "set_option maxHeartbeats 8000000",
        "",
        "theorem signature_valid :",
        "    MainTheory.DistanceSignature.signature",
        f"      MainTheory.Generated.FiniteOrbitBase.key{index:02d}.q",
        f"      MainTheory.Generated.FiniteOrbitBase.key{index:02d}.m",
        f"      MainTheory.Generated.FiniteOrbitBase.key{index:02d}.fibers =",
        f"        MainTheory.Generated.FiniteOrbitBase.expectedSignature{index:02d} := by",
        "  have hFalse :",
        "      MainTheory.DistanceSignature.internalHistogram",
        f"        (MainTheory.Generated.FiniteOrbitBase.key{index:02d}.fibers false) =",
        f"          {histogram(internal_false)} := by",
        "    funext d",
        "    fin_cases d <;> decide",
        "  have hTrue :",
        "      MainTheory.DistanceSignature.internalHistogram",
        f"        (MainTheory.Generated.FiniteOrbitBase.key{index:02d}.fibers true) =",
        f"          {histogram(internal_true)} := by",
        "    funext d",
        "    fin_cases d <;> decide",
        "  have hCross :",
        "      MainTheory.DistanceSignature.crossHistogram",
        f"        (MainTheory.Generated.FiniteOrbitBase.key{index:02d}.fibers false)",
        f"        (MainTheory.Generated.FiniteOrbitBase.key{index:02d}.fibers true) =",
        f"          {histogram(expected.cross)} := by",
        "    funext d",
        "    fin_cases d <;> decide",
        "  unfold MainTheory.DistanceSignature.signature",
        "  apply MainTheory.DistanceSignature.Signature.ext",
        "  · rfl",
        "  · rfl",
        "  · unfold MainTheory.DistanceSignature.unorderedInternalHistograms",
        "    rw [hFalse, hTrue]",
        (
            "    rfl"
            if internal_same_order
            else "    exact Multiset.pair_comm _ _"
        ),
        "  · exact hCross",
        "",
        "/-- This shard also checks one branch of literal-signature separation",
        "without invoking decidable equality on the `Signature` structure. -/",
        "theorem expectedSignature_codeTag :",
        "    MainTheory.Generated.FiniteOrbitBase.codeTag",
        "      (MainTheory.Generated.FiniteOrbitBase.signatureCode",
        f"        MainTheory.Generated.FiniteOrbitBase.expectedSignature{index:02d}) =",
        f"        ({index} : Fin 66) := by",
        "  decide",
        "",
        f"end MainTheory.Generated.FiniteOrbitSignatureShard{index:02d}",
    ]
    write_if_changed(
        out_dir / f"FiniteOrbitSignatureShard{index:02d}.lean", "\n".join(lines)
    )


def emit_aggregate(cert: Normalized, out_dir: Path) -> None:
    lines = [
        HEADER,
        "import MainTheory.Generated.FiniteOrbitBase",
    ]
    lines.extend(
        f"import MainTheory.Generated.FiniteOrbitWitnessShard{i:03d}" for i in range(215)
    )
    lines.extend(
        f"import MainTheory.Generated.FiniteOrbitSignatureShard{i:02d}" for i in range(66)
    )
    lines.extend(
        [
            "",
            "namespace MainTheory.Generated.FiniteOrbitData",
            "",
            "set_option maxRecDepth 1000000",
            "",
            "def witnessAt : Fin 215 →",
            "    MainTheory.FiniteOrbitPipeline.OrbitWitness 215 66 :=",
            vector(
                [
                    f"MainTheory.Generated.FiniteOrbitWitnessShard{i:03d}.witness"
                    for i in range(215)
                ]
            ),
            "",
            "theorem witnessAt_validFor (i : Fin 215) :",
            "    (witnessAt i).ValidFor",
            "      (MainTheory.Generated.FiniteOrbitBase.inputAt (witnessAt i).input)",
            "      (MainTheory.Generated.FiniteOrbitBase.keyAt (witnessAt i).key) := by",
            "  fin_cases i",
        ]
    )
