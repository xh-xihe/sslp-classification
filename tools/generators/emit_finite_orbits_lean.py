def normalized_json(cert: Normalized) -> dict[str, Any]:
    return {
        "input_pair_ids": list(cert.pair_ids),
        "orbit_keys": [[key.q, key.m, key.mask0, key.mask1] for key in cert.keys],
        "cube_witnesses": [asdict(witness) for witness in cert.witnesses],
        "lean_signatures": [asdict(sig) for sig in cert.signatures],
        "representative_input_indices": list(cert.representatives),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("json", type=Path, help="existing main-pipeline certificate bundle")
    parser.add_argument("output_dir", type=Path, help="MainTheory/Generated directory")
    parser.add_argument(
        "--normalized-json",
        type=Path,
        help="optional small q/m-aware orbit-only bundle for inspection",
    )
    args = parser.parse_args()

    data = json.loads(args.json.read_text(encoding="utf-8"))
    cert = normalize(data)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    emit_base(cert, args.output_dir)
    emit_rank_bridge(args.output_dir)
    for index in range(215):
        emit_witness_shard(cert, args.output_dir, index)
    for index in range(66):
        emit_signature_shard(cert, args.output_dir, index)
    emit_aggregate(cert, args.output_dir)

    if args.normalized_json is not None:
        write_if_changed(
            args.normalized_json,
            json.dumps(normalized_json(cert), indent=2, sort_keys=True),
        )

    print("normalized 215 compatible pairs into 66 q/m-aware keys")
    print("emitted 215 action shards and 66 signature shards")


if __name__ == "__main__":
    main()
