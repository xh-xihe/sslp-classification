#!/usr/bin/env python3
"""Generate rational similarity witnesses for the seven SI spectral formulas.

Python constructs candidate bases. Lean checks each inverse and intertwining
identity, then derives the characteristic polynomial from 1-by-1 and 2-by-2
blocks. No numerical eigensolver or externally accepted polynomial is used.
"""
import argparse
from functools import reduce
import hashlib
import json
import math
from pathlib import Path
import sympy as sp

ROOT = Path(__file__).resolve().parents[2]
TABLE = {
    (0, 0, 24): [(424, 1), (192, 4), (24, 11), (16, 2), ((48, 192), 3)],
    (1, 0, 3): [(384, 1), (48, 2)],
    (2, 2, 3): [(52, 1), ((460, 47872), 1)],
    (3, 2, 4): [(50, 1), (46, 1), ((248, 10716), 1)],
    (2, 0, 8): [(32, 1), (24, 1), ((408, 9856), 1), ((352, 9216), 2)],
    (3, 0, 12): [(136, 1), (48, 1), ((352, 9216), 3), ((64, 720), 2)],
    (4, 2, 4): [(56, 1), (44, 1), ((380, 23936), 1)],
}


def primitive(v):
    multiplier = sp.ilcm(*(t.q for t in v))
    values = [int(t * multiplier) for t in v]
    common = reduce(math.gcd, values)
    return sp.Matrix([t // common for t in values])


def witness(A, factors):
    columns, blocks = [], []
    for factor, multiplicity in factors:
        if isinstance(factor, int):
            kernel = (A - factor * sp.eye(A.rows)).nullspace()
            if len(kernel) != multiplicity:
                raise ValueError('Wrong scalar eigenspace dimension')
            columns += [primitive(v) for v in kernel]
            blocks += [sp.Matrix([[factor]])] * multiplicity
        else:
            p, q = factor
            kernel = (A * A - p * A + q * sp.eye(A.rows)).nullspace()
            if len(kernel) != 2 * multiplicity:
                raise ValueError('Wrong quadratic primary space dimension')
            chosen = []
            for v in kernel:
                v = primitive(v)
                candidates = chosen + [v, A * v]
                if sp.Matrix.hstack(*candidates).rank() == len(candidates):
                    chosen = candidates
                    blocks.append(sp.Matrix([[0, -q], [1, p]]))
            if len(chosen) != 2 * multiplicity:
                raise ValueError('Failed to construct cyclic pairs')
            columns += chosen
    S = sp.Matrix.hstack(*columns)
    B = sp.diag(*blocks)
    T = S.inv()
    assert A * S == S * B and T * S == sp.eye(A.rows)
    return S, T


def rat(t):
    return str(t.p) if t.q == 1 else f'({t.p} / {t.q})'


def literal(A):
    return '![' + ',\n  '.join('![' + ', '.join(rat(A[i, j]) for j in range(A.cols)) + ']'
                              for i in range(A.rows)) + ']'


def canonical(factors):
    components = []
    for f, mult in factors:
        components += [f'(linearBlock {f})' if isinstance(f, int) else
                       f'(quadraticBlock {f[0]} {f[1]})'] * mult
    result = components[-1]
    for component in reversed(components[:-1]):
        result = f'(join {component} {result})'
    return result


def polynomial(factors):
    parts = []
    for f, mult in factors:
        factor = f'(X - C {f})' if isinstance(f, int) else f'(X ^ 2 - C {f[0]} * X + C {f[1]})'
        parts.append(factor if mult == 1 else f'{factor} ^ {mult}')
    return ' * '.join(parts)


def balanced(values):
    if len(values) == 1:
        return f'(.leaf {values[0]})'
    middle = len(values) // 2
    return f'(.node {middle} {balanced(values[:middle])} {balanced(values[middle:])})'


def generate(source, output):
    data = json.loads(source.read_text(encoding='utf8'))
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    output.mkdir(parents=True, exist_ok=True)
    keys = list(TABLE)
    modules = []
    for index, key in enumerate(keys):
        n = key[2]
        simp_lemmas = 'canonical, join_charpoly, linearBlock_charpoly'
        if any(isinstance(f, tuple) for f, _ in TABLE[key]):
            simp_lemmas += ', quadraticBlock_charpoly'
        rewrite_quadratic = "  repeat' rw [quadraticBlock_charpoly]\n" if any(
            isinstance(f, tuple) for f, _ in TABLE[key]) else ''
        finish = '  ring\n' if sum(mult for _, mult in TABLE[key]) > 2 else ''
        name = f'SixQubit.Generated.Orbit2Spectra.Pattern{index}'
        modules.append(name)
        text = f'''-- Generated by tools/generators/emit_orbit2_spectra.py.
import MainTheory.RationalSpectralCertificate

namespace {name}
open MainTheory.RationalSpectralCertificate Polynomial
noncomputable section
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

def canonical : Matrix (Fin {n}) (Fin {n}) ℚ := {canonical(TABLE[key])}
def polynomial : Polynomial ℚ := {polynomial(TABLE[key])}

theorem canonical_charpoly : canonical.charpoly = polynomial := by
  unfold canonical polynomial
  repeat' rw [join_charpoly]
  repeat' rw [linearBlock_charpoly]
{rewrite_quadratic}{finish}

end
end {name}
'''
        (output / f'Pattern{index}.lean').write_text(text, encoding='utf8', newline='\n')
    signatures = []
    for index, block in enumerate(data['blocks']):
        character = block['character']
        signature = (sum(t != 'I' for t in character), sum(t in 'XY' for t in character), len(block['matrix']))
        pattern = keys.index(signature)
        signatures.append(pattern)
        A = sp.Matrix(block['matrix'])
        S, T = witness(A, TABLE[signature])
        n = A.rows
        name = f'SixQubit.Generated.Orbit2Spectra.Block{index:03}'
        modules.append(name)
        text = f'''-- Generated by tools/generators/emit_orbit2_spectra.py.
-- Input SHA-256: {digest}
-- Character: {character}; spectral signature: {signature}.
import SixQubit.Generated.Orbit2Gram.Block{index:03}
import SixQubit.Generated.Orbit2Spectra.Pattern{pattern}

namespace {name}
open MainTheory.RationalSpectralCertificate
noncomputable section
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

/-- Restore the four units subtracted in the positivity certificate. -/
def originalMatrix : Matrix (Fin {n}) (Fin {n}) ℚ :=
  SixQubit.Generated.Orbit2Gram.Block{index:03}.matrix + 4 • (1 : Matrix (Fin {n}) (Fin {n}) ℚ)

def basis : Matrix (Fin {n}) (Fin {n}) ℚ :=
  {literal(S)}

def inverse : Matrix (Fin {n}) (Fin {n}) ℚ :=
  {literal(T)}

theorem inverse_identity : inverse * basis = 1 := by
  ext i j
  have h : ∀ i j, (inverse * basis) i j = (1 : Matrix (Fin {n}) (Fin {n}) ℚ) i j := by decide +kernel
  exact h i j

theorem intertwining : originalMatrix * basis = basis * Pattern{pattern}.canonical := by
  ext i j
  have h : ∀ i j, (originalMatrix * basis) i j = (basis * Pattern{pattern}.canonical) i j := by decide +kernel
  exact h i j

theorem charpoly : originalMatrix.charpoly = Pattern{pattern}.polynomial :=
  (charpoly_of_similarity originalMatrix Pattern{pattern}.canonical basis inverse
    inverse_identity intertwining).trans Pattern{pattern}.canonical_charpoly

end
end {name}
'''
        (output / f'Block{index:03}.lean').write_text(text, encoding='utf8', newline='\n')
        print('Generated spectrum', index, character, flush=True)
    aggregate = '\n'.join('import ' + m for m in modules) + '''
import MainTheory.BalancedFiniteTable

namespace SixQubit.Generated.Orbit2Spectra
noncomputable section
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000
'''
    aggregate += 'def tablePolynomials : Fin 7 → Polynomial ℚ :=\n  ![' + ', '.join(
        f'Pattern{i}.polynomial' for i in range(7)) + ']\n\n'
    # Store the equality with each actual matrix polynomial. A flat fin_cases
    # term constructs 111 nested equality transports and exceeds the native
    # kernel stack. Balanced lookup retains all 111 witnesses without that
    # linear transport chain.
    aggregate += '''structure Certificate where
  pattern : Fin 7
  polynomial : Polynomial ℚ
  verified : polynomial = tablePolynomials pattern

'''
    aggregate += 'def certificates : MainTheory.BalancedFiniteTable.Tree Certificate :=\n  ' + balanced([
        f'⟨{signatures[i]}, Block{i:03}.originalMatrix.charpoly, Block{i:03}.charpoly⟩'
        for i in range(111)]) + '\n\n'
    aggregate += '''def certificate (i : Fin 111) : Certificate :=
  MainTheory.BalancedFiniteTable.lookup certificates i.val

def pattern (i : Fin 111) : Fin 7 := (certificate i).pattern

def characteristicPolynomials (i : Fin 111) : Polynomial ℚ :=
  (certificate i).polynomial

'''
    aggregate += '''theorem all_characteristic_polynomials (i : Fin 111) :
    characteristicPolynomials i = tablePolynomials (pattern i) :=
  (certificate i).verified
'''
    aggregate += '\nend\nend SixQubit.Generated.Orbit2Spectra\n'
    (output / 'All.lean').write_text(aggregate, encoding='utf8', newline='\n')
    modules.append('SixQubit.Generated.Orbit2Spectra.All')
    manifest = ['# lean_files=' + str(len(modules))]
    for module in modules:
        path = output / (module.rsplit('.', 1)[1] + '.lean')
        manifest.append(hashlib.sha256(path.read_bytes()).hexdigest() + '  ' + module)
    (output / 'generation-manifest.sha256').write_text('\n'.join(manifest) + '\n', encoding='utf8')
    (output / 'serial-build-order.txt').write_text('\n'.join(modules) + '\n', encoding='utf8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT / 'results/orbit2-kernel/gram-blocks.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'SixQubit/Generated/Orbit2Spectra')
    args = parser.parse_args()
    generate(args.input, args.output)
