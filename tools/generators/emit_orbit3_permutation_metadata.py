#!/usr/bin/env python3
"""Expose exact active-permutation witnesses and their action on 64 bit labels."""
from __future__ import annotations

import argparse
from itertools import permutations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def tree(values):
    if len(values) == 1:
        return f'(.leaf {values[0]})'
    split = len(values) // 2
    return f'(.node {split} {tree(values[:split])} {tree(values[split:])})'


def generate(output: Path):
    forward, inverse, bitmap = [], [], []
    for perm in permutations(range(1, 6)):
        f = [0] + list(perm)
        inv = [f.index(j) for j in range(6)]
        forward.append(tree(f))
        inverse.append(tree(inv))
        bitmap.append(tree([sum(((a >> j) & 1) << f[j] for j in range(6)) for a in range(64)]))
    text = f'''-- Generated by tools/generators/emit_orbit3_permutation_metadata.py.
import MainTheory.BalancedFiniteTable
import MainTheory.Orbit3PermutationAverage

namespace SixQubit.Generated.Orbit3PermutationMetadata

open MainTheory.Orbit3ActualSampling MainTheory.OrderTwoScalarBridge
open SixQubit.CodeEquiv
set_option maxHeartbeats 16000000
set_option maxRecDepth 100000

def forwardTable : MainTheory.BalancedFiniteTable.Tree
    (MainTheory.BalancedFiniteTable.Tree (Fin 6)) := {tree(forward)}
def inverseTable : MainTheory.BalancedFiniteTable.Tree
    (MainTheory.BalancedFiniteTable.Tree (Fin 6)) := {tree(inverse)}

-- Pullback of amplitudes uses the inverse of the integer bitmap permutation.
def permutation (g : Fin 120) (j : Fin 6) : Fin 6 :=
  MainTheory.BalancedFiniteTable.lookup
    (MainTheory.BalancedFiniteTable.lookup inverseTable g.val) j.val
def inverse (g : Fin 120) (j : Fin 6) : Fin 6 :=
  MainTheory.BalancedFiniteTable.lookup
    (MainTheory.BalancedFiniteTable.lookup forwardTable g.val) j.val

theorem left_inverse : ∀ g : Fin 120, ∀ j : Fin 6, inverse g (permutation g j) = j := by
  decide +kernel
theorem right_inverse : ∀ g : Fin 120, ∀ j : Fin 6, permutation g (inverse g j) = j := by
  decide +kernel
theorem mask_preserved : ∀ g : Fin 120, ∀ j : Fin 6,
    orbit3Mask (permutation g j) = orbit3Mask j := by
  decide +kernel

def actual (g : Fin 120) : ActivePermutation :=
  ⟨{{ toFun := permutation g, invFun := inverse g,
      left_inv := left_inverse g, right_inv := right_inverse g }}, mask_preserved g⟩

def bitmapTable : MainTheory.BalancedFiniteTable.Tree
    (MainTheory.BalancedFiniteTable.Tree (Fin 64)) := {tree(bitmap)}
def bitmap (g : Fin 120) (a : Fin 64) : Fin 64 :=
  MainTheory.BalancedFiniteTable.lookup
    (MainTheory.BalancedFiniteTable.lookup bitmapTable g.val) a.val

def bitLabel (s : SS.BitString 6) : Fin 64 := ⟨SixQubit.Realize.num s, SixQubit.Realize.num_lt s⟩

theorem bitmap_correct : ∀ g : Fin 120, ∀ a : Fin 64,
    bitLabel (permStr (actual g).val (SixQubit.Realize.nbit a.val)) = bitmap g a := by
  decide +kernel

theorem nbit_bitmap (g : Fin 120) (a : Fin 64) :
    SixQubit.Realize.nbit (bitmap g a).val =
      permStr (actual g).val (SixQubit.Realize.nbit a.val) := by
  rw [← bitmap_correct]
  exact SixQubit.Realize.nbit_num _

end SixQubit.Generated.Orbit3PermutationMetadata
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3PermutationMetadata.lean')
    args = parser.parse_args()
    generate(args.output)


if __name__ == '__main__':
    main()
