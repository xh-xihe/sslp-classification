#!/usr/bin/env python3
"""Render the prose review into a readable document.

The claims ledger tracks every display and every named result of the two
manuscripts.  It does not track running text, and running text is where an
unformalized claim can hide, because nothing in the pipeline forces those
sentences to be looked at.  `results/prose-review-20260908.json` is the record
of that separate review; this renders it.

The document carries no manuscript text.  The sources are an unpublished
collaborator draft and are gitignored, so assertions are identified by line
number and described in our own words, the same line the claims ledger draws.

Usage:
    python tools/prose_review_doc.py            # write the document
    python tools/prose_review_doc.py --check    # fail if it is out of date
"""
import io
import argparse
import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path
import paper_release

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECORD = os.path.join(ROOT, 'results', 'prose-review-20260908.json')
OUTPUT = os.path.join(ROOT, 'results', 'prose-review-20260908.md')

KIND_ORDER = ('gap', 'covered', 'tracked', 'nonmath')
SEVERITY_ORDER = {'high': 0, 'medium': 1, 'low': 2, None: 3}


def render(record):
    rows = record['assertions']
    per = defaultdict(Counter)
    sev = defaultdict(Counter)
    for a in rows:
        per[a['source']][a['kind']] += 1
        if a['kind'] == 'gap':
            sev[a['source']][a.get('severity') or 'unrated'] += 1
    moved = Counter((a['original_kind'], a['kind']) for a in rows if a.get('corrected'))
    found = sum(1 for a in rows if a.get('origin') == 'checker')

    out = []
    w = out.append
    w('# Prose review of the 20260908 manuscripts')
    w('')
    w('The claims ledger tracks every display and every named result. It does not')
    w('track running text. That gap matters: a sentence in a paragraph is where an')
    w('unformalized claim can sit indefinitely, because nothing in the pipeline')
    w('forces anyone to look at it. This is the separate review of those sentences.')
    w('')
    w('Generated by `tools/prose_review_doc.py` from')
    w('`results/prose-review-20260908.json`. Edit the generator, never this file.')
    w('')
    w('**No manuscript text appears here.** The sources are an unpublished')
    w('collaborator draft and are gitignored; assertions are identified by line')
    w('number and described in our own words.')
    w('')
    w('## Method')
    w('')
    w(record['method'])
    w('')
    w('Each assertion is classified as one of four kinds.')
    w('')
    w('| kind | meaning |')
    w('| --- | --- |')
    w('| `gap` | a mathematical assertion with no Lean declaration behind it |')
    w('| `covered` | not carried by any tracked display or named result, but a declaration states it |')
    w('| `tracked` | restates or previews a display or named result the ledger already holds |')
    w('| `nonmath` | motivation, attribution, roadmap: nothing to certify |')
    w('')
    w('The standard for `covered` is the ledger\'s: a declaration must carry the')
    w('*whole* assertion. Prose often quantifies more broadly than any single')
    w('theorem -- "in all cases", "the same argument applies" -- and where the Lean')
    w('has the instances but not the general statement, that is a `gap`.')
    w('')
    w('## Counts')
    w('')
    w('| source | total | gap | covered | tracked | nonmath |')
    w('| --- | ---: | ---: | ---: | ---: | ---: |')
    for source in sorted(per):
        c = per[source]
        w('| `%s` | %d | %d | %d | %d | %d |'
          % (source, sum(c.values()), c['gap'], c['covered'], c['tracked'], c['nonmath']))
    total = Counter()
    for c in per.values():
        total.update(c)
    w('| **both** | **%d** | **%d** | **%d** | **%d** | **%d** |'
      % (sum(total.values()), total['gap'], total['covered'],
         total['tracked'], total['nonmath']))
    w('')
    for source in sorted(sev):
        w('Gaps in `%s` by severity: %s.'
          % (source, ', '.join('%s %d' % (k, v) for k, v in
                               sorted(sev[source].items(),
                                      key=lambda kv: SEVERITY_ORDER.get(kv[0], 3)))))
    w('')
    w('## What the adversarial pass changed')
    w('')
    w('The second agent is the reason these numbers can be quoted. It reclassified')
    w('%d assertions and found %d the first reader had not reported at all, while'
      % (sum(moved.values()), found))
    w('leaving the rest standing.')
    w('')
    w('| from | to | count |')
    w('| --- | --- | ---: |')
    for (a, b), n in sorted(moved.items(), key=lambda kv: -kv[1]):
        if a == b:
            continue
        w('| `%s` | `%s` | %d |' % (a, b, n))
    w('')
    w('The largest single correction is `gap` to `covered`: first readers reported')
    w('a missing proof that a more determined search found. That is the failure')
    w('mode this review is most exposed to, and it is why nothing here rests on a')
    w('single pass.')
    w('')
    w('---')
    w('')
    w('# Gaps')
    w('')
    w('A gap is an assertion in running text with no Lean declaration behind it.')
    w('Most are low severity: side remarks, or standard facts the development has')
    w('no reason to formalize. They are listed in full anyway, because the point of')
    w('the exercise is that no one had looked.')
    w('')
    for level in ('high', 'medium', 'low', 'unrated'):
        block = [a for a in rows if a['kind'] == 'gap'
                 and (a.get('severity') or 'unrated') == level]
        if not block:
            continue
        block.sort(key=lambda a: (a['source'], a['line']))
        w('## %s severity (%d)' % (level.capitalize(), len(block)))
        w('')
        for a in block:
            flag = ' *(found by the adversarial checker)*' if a.get('origin') == 'checker' else ''
            w('### `%s` line %d%s' % (a['source'], a['line'], flag))
            w('')
            for d in a.get('declarations') or []:
                w('- `%s`' % d)
            if a.get('declarations'):
                w('')
            w(' '.join((a.get('reason') or '').split()))
            w('')
    w('---')
    w('')
    w('# What this review does not do')
    w('')
    w('* It does not re-check the displays or the named results. Those are the')
    w('  claims ledger\'s job, and `results/named-results-20260908.md` is their')
    w('  readable form.')
    w('* It does not decide what to do about a gap. Several are assertions that')
    w('  are probably true and provable but simply are not proved here; a few are')
    w('  places where the manuscript claims less than the development proves.')
    w('  Both need an author decision, not a Lean file.')
    w('* The `covered` and `tracked` assertions are recorded in the JSON with the')
    w('  declarations and reasoning behind each, and are not repeated here.')
    w('')
    return '\n'.join(out) + '\n'


def render_version(record, version):
    lines = [f'# Prose review of the {version} manuscripts', '',
             f"Review status: **{record['status']}**.", '', record['method'], '',
             'This is a version-bound review record, not a successful kernel run.',
             'No previous-version coverage is transferred. No manuscript text is reproduced.', '',
             f'Generated from `results/prose-review-{version}.json`.', '']
    for row in record['assertions']:
        lines += [f"## {row['source']}:{row['line']} — {row['kind']}", '', row['reason'], '']
        lines += [f'- `{d}`' for d in row.get('declarations', [])]
        lines += ['']
    lines += ['## Remaining review', '', record.get('remaining', 'Complete the source-wide prose review.'), '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--paper-version', default=paper_release.DEFAULT_VERSION, type=paper_release.version)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--require-complete', action='store_true')
    parser.add_argument('--source-dir', type=Path, help='private manuscript directory bound to the review hashes')
    args = parser.parse_args(argv)
    p = paper_release.paths(args.paper_version, ROOT)
    with io.open(p['prose'], encoding='utf-8') as handle:
        record = json.load(handle)
    if any('quote' in a for a in record['assertions']):
        sys.stderr.write('FAIL: the published record contains verbatim manuscript text.\n')
        return 1
    if args.paper_version != paper_release.DEFAULT_VERSION:
        paper_release.validate_review(record, args.paper_version, ROOT, args.require_complete, args.source_dir)
        text = render_version(record, args.paper_version)
    else:
        if args.require_complete and any(a['kind'] == 'gap' for a in record['assertions']):
            raise ValueError('historical prose review still contains gaps')
        text = render(record)
    output = p['prose_doc']
    if args.check:
        if not output.exists():
            sys.stderr.write('FAIL: %s does not exist; run the generator.\n' % output)
            return 1
        if output.read_text(encoding='utf-8') != text:
            sys.stderr.write('FAIL: %s is stale; regenerate with '
                             'python tools/prose_review_doc.py --paper-version %s\n' % (output, args.paper_version))
            return 1
        sys.stdout.write('prose-review document is current\n')
        return 0
    output.write_text(text, encoding='utf-8', newline='\n')
    sys.stdout.write('wrote %s (%d bytes)\n' % (output, len(text.encode('utf-8'))))
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError) as exc:
        sys.stderr.write('FAIL: ' + str(exc) + '\n')
        sys.exit(1)
