"""Check the exact-realization modules against the manifest.

Each `SixQubit/Orbit<N>Real.lean` decides its own Knill--Laflamme certificate,
so the kernel already establishes that the exhibited pair is an exact
`((6,2,3))` code.  What the kernel cannot establish is that the pair belongs to
the orbit the module is named for: `tools/manifest.json` is not a Lean object,
and a module could carry a perfectly valid code for the wrong angle record.
That is precisely the defect that hit four no-go modules before `gate.py`
existed, and it is what this script exists to prevent.

Five obligations per module:

  A  orbit identity.  The module's `(av, q, delta)` must be the manifest's
     record for that orbit, compared by canonical form under the group
     generated by local flips, qubit permutation, unit scaling and exchange of
     the two logical words -- not by string equality, since equivalent records
     look different.

  B  supports lie in the declared fibers.  Recomputed here from `(av, q)`
     rather than read from the module.  Lean decides the same fact; this is a
     second, independent computation of it.

  C  the two supports are disjoint and carry the declared term counts.

  D  amplitudes normalize.  The squared norms of the table entries must sum to
     the constant `N` the module feeds to `normalized_of`, and the scale must
     satisfy `sc^2 N = 1`.  Arithmetic is done in the same eight-integer ring
     the Lean uses.

  E  the module states `is_code`.

Usage:
    python tools/run.py verification/realized.py
    python tools/run.py verification/realized.py 7 45
    python tools/run.py verification/realized.py --selftest
"""
import io
import itertools
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
SQ = os.path.join(REPO, 'SixQubit')
ORBITS = [7, 8, 9, 10, 11, 16, 21, 22, 23, 45]
N = 6


class CheckError(RuntimeError):
    pass


def ascii_safe(s):
    return s.encode('ascii', 'backslashreplace').decode('ascii')


# --------------------------------------------------------------------------
# the eight-integer ring, independently of the generator
# --------------------------------------------------------------------------

ZERO = (0,) * 8


def zconj(x):
    return x[:4] + tuple(-p for p in x[4:])


def zmul(x, y):
    if x == ZERO or y == ZERO:
        return ZERO
    a0, a1, a2, a3, b0, b1, b2, b3 = x
    c0, c1, c2, c3, d0, d1, d2, d3 = y
    return (
        (a0*c0 + 2*a1*c1 + 3*a2*c2 + 6*a3*c3) - (b0*d0 + 2*b1*d1 + 3*b2*d2 + 6*b3*d3),
        (a0*c1 + a1*c0 + 3*a2*c3 + 3*a3*c2) - (b0*d1 + b1*d0 + 3*b2*d3 + 3*b3*d2),
        (a0*c2 + a2*c0 + 2*a1*c3 + 2*a3*c1) - (b0*d2 + b2*d0 + 2*b1*d3 + 2*b3*d1),
        (a0*c3 + a3*c0 + a1*c2 + a2*c1) - (b0*d3 + b3*d0 + b1*d2 + b2*d1),
        (a0*d0 + 2*a1*d1 + 3*a2*d2 + 6*a3*d3) + (b0*c0 + 2*b1*c1 + 3*b2*c2 + 6*b3*c3),
        (a0*d1 + a1*d0 + 3*a2*d3 + 3*a3*d2) + (b0*c1 + b1*c0 + 3*b2*c3 + 3*b3*c2),
        (a0*d2 + a2*d0 + 2*a1*d3 + 2*a3*d1) + (b0*c2 + b2*c0 + 2*b1*c3 + 2*b3*c1),
        (a0*d3 + a3*d0 + a1*d2 + a2*d1) + (b0*c3 + b3*c0 + b1*c2 + b2*c1))


def znorm(x):
    """|x|^2, which must come out rational for a table entry."""
    v = zmul(zconj(x), x)
    if v[1:] != (0,) * 7:
        raise CheckError('entry has irrational squared norm: %s' % (v,))
    return v[0]


# --------------------------------------------------------------------------
# the group action on orbit records
# --------------------------------------------------------------------------

def canonical(a, q, delta):
    best = None
    for flips in itertools.product((1, -1), repeat=len(a)):
        b = [(f * x) % q for f, x in zip(flips, a)]
        for u in range(1, q):
            if math.gcd(u, q) != 1:
                continue
            c = tuple(sorted((u * x) % q for x in b))
            for s in (1, -1):
                key = (c, (s * u * delta) % q)
                if best is None or key < best:
                    best = key
    return best


# --------------------------------------------------------------------------
# parsing
# --------------------------------------------------------------------------

def parse_av(src):
    m = re.search(r'def\s+av\s*:\s*Fin\s+6\s*(?:->|→)\s*ZMod\s+(\d+)\s*:=\s*!\[([^\]]*)\]', src)
    if not m:
        raise CheckError('cannot parse av')
    a = [int(x.strip()) for x in m.group(2).split(',')]
    if len(a) != N:
        raise CheckError('av has %d entries' % len(a))
    return a, int(m.group(1))


def parse_residues(src):
    out = []
    for k in (0, 1):
        m = re.search(r'theorem\s+L%d_in_fiber\b.{0,200}?SS\.weight\s+av\s+x\s*=\s*(\d+)'
                      % k, src, re.S)
        if not m:
            raise CheckError('cannot parse the residue asserted by L%d_in_fiber' % k)
        out.append(int(m.group(1)))
    return out


def parse_support(src, k):
    m = re.search(r'def\s+L%d\s*:\s*List\s*\(SS\.BitString 6\)\s*:=\s*\[(.*?)\]' % k,
                  src, re.S)
    if not m:
        raise CheckError('cannot parse L%d' % k)
    out = []
    for row in re.findall(r'bs((?:\s+(?:true|false)){6})', m.group(1)):
        out.append(tuple(1 if b == 'true' else 0 for b in row.split()))
    return out


def parse_table(src, name):
    m = re.search(r'def\s+%s\s*\(x : SS\.BitString 6\)\s*:\s*ZQ\s*:=(.*?)else ZQ\.zero'
                  % name, src, re.S)
    if not m:
        raise CheckError('cannot parse table %s' % name)
    out = {}
    for num, vals in re.findall(
            r'num x = (\d+) then z8((?:\s+(?:\(-?\d+\)|-?\d+)){8})', m.group(1)):
        v = tuple(int(t.strip('()')) for t in vals.split())
        if int(num) in out:
            raise CheckError('%s assigns mask %s twice' % (name, num))
        out[int(num)] = v
    return out


def parse_N(src):
    m = re.search(r'star sc \* sc \* \((-?\d+) : ℂ\) = 1', src)
    if not m:
        raise CheckError('cannot parse the normalization constant')
    return int(m.group(1))


def parse_sc(src):
    m = re.search(r'def\s+sc\s*:\s*ℂ\s*:=\s*\((\d+)/(\d+)\s*:\s*ℂ\)', src)
    if not m:
        raise CheckError('cannot parse the scale')
    return int(m.group(1)), int(m.group(2))


def numof(x):
    return sum(b << j for j, b in enumerate(x))


# --------------------------------------------------------------------------
# the checks
# --------------------------------------------------------------------------

def check_orbit(oid, src, manifest, report):
    a, q = parse_av(src)
    r0, r1 = parse_residues(src)
    delta = (r1 - r0) % q

    entry = manifest.get(str(oid))
    if entry is None:
        raise CheckError('manifest has no orbit %d' % oid)
    lc, mc = canonical(a, q, delta), canonical(entry['a'], entry['q'], entry['d'])
    report(oid, 'A orbit identity', lc == mc,
           'Lean a=%s q=%d delta=%d -> %s ; manifest a=%s delta=%d -> %s'
           % (a, q, delta, lc, entry['a'], entry['d'], mc))
    report(oid, 'A lift order', entry['q'] == q,
           'q = %d on both sides' % q if entry['q'] == q
           else 'manifest q=%d, Lean q=%d' % (entry['q'], q))

    L0, L1 = parse_support(src, 0), parse_support(src, 1)
    for k, (L, r) in enumerate(((L0, r0), (L1, r1))):
        wrong = [numof(x) for x in L
                 if sum(ai * xi for ai, xi in zip(a, x)) % q != r % q]
        report(oid, 'B support %d in fiber %d' % (k, r), not wrong,
               '%d words, all at residue %d' % (len(L), r) if not wrong
               else 'masks off the fiber: %s' % wrong[:6])

    inter = set(map(numof, L0)) & set(map(numof, L1))
    report(oid, 'C supports disjoint', not inter,
           'no shared word' if not inter else 'shared: %s' % sorted(inter)[:6])
    report(oid, 'C equal term counts', len(L0) == len(L1) and len(set(map(numof, L0))) == len(L0),
           '%d + %d words, no repeats' % (len(L0), len(L1)))

    t0, t1 = parse_table(src, 'c0z'), parse_table(src, 'c1z')
    Nc = parse_N(src)
    num, den = parse_sc(src)
    for k, (t, L) in enumerate(((t0, L0), (t1, L1))):
        keys = set(t) == set(map(numof, L))
        report(oid, 'D table %d matches support' % k, keys,
               '%d entries' % len(t) if keys
               else 'table keys differ from L%d' % k)
        tot = sum(znorm(v) for v in t.values())
        report(oid, 'D table %d normalizes' % k, tot == Nc,
               'sum of squared entries = %d' % tot if tot == Nc
               else 'sum is %d, module declares %d' % (tot, Nc))
    ok = num * num * Nc == den * den
    report(oid, 'D scale closes', ok,
           '(%d/%d)^2 * %d = 1' % (num, den, Nc) if ok
           else '(%d/%d)^2 * %d != 1' % (num, den, Nc))

    report(oid, 'E is_code stated',
           bool(re.search(r'^theorem is_code\s*:\s*SS\.HasDistance', src, re.M)),
           'theorem is_code : SS.HasDistance ![w0, w1] 3')


def load_manifest():
    return json.loads(io.open(os.path.join(REPO, 'tools', 'manifest.json'),
                              encoding='utf-8').read())


def load_sources(orbits):
    out = {}
    for oid in orbits:
        p = os.path.join(SQ, 'Orbit%dReal.lean' % oid)
        if not os.path.exists(p):
            raise CheckError('missing module %s' % p)
        out[oid] = io.open(p, encoding='utf-8').read()
    return out


# --------------------------------------------------------------------------
# self-test
# --------------------------------------------------------------------------

MUTATIONS = [
    ('av entry changed', 7, 'def av : Fin 6 → ZMod 3 := ![0, 1, 1, 1, 2, 2]',
     'def av : Fin 6 → ZMod 3 := ![0, 1, 1, 1, 2, 1]'),
    ('declared residue changed', 10, 'SS.weight av x = 2', 'SS.weight av x = 1'),
    ('normalization constant changed', 21, '(16 : ℂ) = 1', '(8 : ℂ) = 1'),
    ('scale changed', 11, 'def sc : ℂ := (1/4 : ℂ)', 'def sc : ℂ := (1/2 : ℂ)'),
    ('an amplitude entry corrupted', 22, 'then z8 1 0 0 0 0 0 0 0',
     'then z8 2 0 0 0 0 0 0 0'),
    ('is_code removed', 45, 'theorem is_code : SS.HasDistance',
     'theorem not_is_code : SS.HasDistance'),
]


def run_once(sources, manifest, orbits):
    fails = []

    def report(oid, label, ok, detail):
        if not ok:
            fails.append((oid, label, detail))
    for oid in orbits:
        check_orbit(oid, sources[oid], manifest, report)
    return fails


def selftest():
    base = load_sources(ORBITS)
    manifest = load_manifest()
    fails = run_once(dict(base), manifest, ORBITS)
    if fails:
        print('SELFTEST ABORTED: the unmutated tree already fails')
        for oid, label, detail in fails:
            print('   orbit %-3s %-28s %s' % (oid, label, ascii_safe(detail)))
        return 1

    print('%-40s %s' % ('mutation', 'caught?'))
    missed, inert = [], []
    for name, oid, old, new in MUTATIONS:
        cnt = base[oid].count(old)
        if cnt < 1:
            inert.append(name)
            print('   %-37s INERT (anchor absent in orbit %d)' % (name, oid))
            continue
        mutated = dict(base)
        mutated[oid] = base[oid].replace(old, new, 1)
        try:
            f = run_once(mutated, manifest, ORBITS)
            caught, why = bool(f), (f[0][1] if f else '')
        except CheckError as exc:
            caught, why = True, 'CheckError: %s' % ascii_safe(str(exc))[:36]
        if not caught:
            missed.append(name)
        print('   %-37s %-5s %s' % (name, 'yes' if caught else 'NO', why))

    print()
    print('%d mutations, %d missed, %d inert' % (len(MUTATIONS), len(missed), len(inert)))
    if missed or inert:
        for n in missed:
            print('   MISSED: %s' % n)
        for n in inert:
            print('   INERT: %s' % n)
        return 1
    print('SELFTEST PASS')
    return 0


def main(argv):
    try:
        if '--selftest' in argv:
            return selftest()
        want = [int(a) for a in argv if a.isdigit()] or ORBITS
        sources, manifest = load_sources(want), load_manifest()
        results = []

        def report(oid, label, ok, detail):
            results.append((oid, label, ok, detail))
        for oid in want:
            check_orbit(oid, sources[oid], manifest, report)
        bad = [r for r in results if not r[2]]
        for oid, label, ok, detail in results:
            if not ok:
                print('orbit %-3s %-28s FAIL  %s' % (oid, label, ascii_safe(detail)))
        by_orbit = {}
        for oid, label, ok, _ in results:
            by_orbit.setdefault(oid, [0, 0])
            by_orbit[oid][0] += 1
            by_orbit[oid][1] += 0 if ok else 1
        for oid in want:
            n, f = by_orbit[oid]
            print('orbit %-3s %2d checks, %d failed  %s' % (oid, n, f, 'ok' if not f else 'FAIL'))
        print()
        print('%d orbits, %d checks, %d failed'
              % (len(want), len(results), len(bad)))
        return 1 if bad else 0
    except CheckError as exc:
        print('FAIL: %s' % ascii_safe(str(exc)))
        return 1


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
