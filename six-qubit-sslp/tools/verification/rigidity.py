BS_DEF = re.compile(
    r'^def\s+([A-Za-z][A-Za-z0-9_]*)\s*:\s*SS\.BitString\s+6\s*:=\s*bs\s+'
    r'((?:(?:true|false)\s+){5}(?:true|false))',
    re.M)


def bitstring_symbols(sources):
    """name -> 6-tuple of 0/1, from `def nm : SS.BitString 6 := bs b0 .. b5`."""
    out = {}
    for src in sources:
        for m in BS_DEF.finditer(src):
            bits = tuple(1 if b == 'true' else 0 for b in m.group(2).split())
            if len(bits) != N:
                raise CheckError('malformed bitstring literal for %s' % m.group(1))
            prev = out.get(m.group(1))
            if prev is not None and prev != bits:
                raise CheckError('symbol %s defined twice with different values'
                                 % m.group(1))
            out[m.group(1)] = bits
    return out


def parse_av(src):
    m = re.search(r'def\s+av\s*:\s*Fin\s+6\s*(?:->|→)\s*ZMod\s+(\d+)\s*:=\s*!\[([^\]]*)\]',
                  src)
    if not m:
        raise CheckError('could not parse `av` from Orbit36Code')
    q = int(m.group(1))
    a = [int(x.strip()) for x in m.group(2).split(',')]
    if len(a) != N:
        raise CheckError('`av` has %d entries, expected %d' % (len(a), N))
    return a, q


def parse_fiber_residues(src):
    """The residues asserted by S0_eq_fiber / S1_eq_fiber."""
    out = []
    for name in ('S0_eq_fiber', 'S1_eq_fiber'):
        m = re.search(r'theorem\s+' + name + r'\b(.{0,400}?)SS\.weight\s+av\s+x\s*=\s*(\d+)',
                      src, re.S)
        if not m:
            raise CheckError('could not parse the residue asserted by %s' % name)
        out.append(int(m.group(2)))
    return out


def headline_region(src, name):
    """(start, end) of the binder list of `theorem name ... : conclusion`.

    The self-test needs this.  Anchors such as `(ho0 : offSum c d ex1 w0 = 0)`
    occur five times in the module -- in the headline, and again in the lemmas
    it is assembled from -- so a whole-file `replace(old, new, 1)` mutates a
    lemma and leaves the headline pristine, and the mutation tests nothing.
    That is the same failure that made two earlier checkers here agree with
    each other while both were wrong.
    """
    k = src.find('theorem ' + name)
    if k < 0:
        raise CheckError('headline theorem %s not found' % name)
    stack, i, pairs = [], k, {')': '(', ']': '[', '}': '{'}
    while i < len(src):
        ch = src[i]
        if ch in '([{':
            stack.append(ch)
        elif ch in ')]}':
            if not stack or stack.pop() != pairs[ch]:
                raise CheckError('unbalanced brackets in %s' % name)
        elif not stack and ch == ':' and not src.startswith(':=', i):
            return k, i
        i += 1
    raise CheckError('could not find the conclusion of %s' % name)


def mutate_headline(src, name, old, new):
    """Apply a mutation inside the headline binder list, or refuse."""
    start, end = headline_region(src, name)
    region = src[start:end]
    n = region.count(old)
    if n != 1:
        raise CheckError('anchor occurs %d times in the headline region '
                         '(need exactly 1): %s' % (n, ascii_safe(old[:60])))
    return src[:start] + region.replace(old, new, 1) + src[end:]


def headline_binders(src, name):
    """The parenthesised binders of `theorem name ... : conclusion`."""
    k = src.find('theorem ' + name)
    if k < 0:
        raise CheckError('headline theorem %s not found' % name)
    stack, i, pairs = [], k, {')': '(', ']': '[', '}': '{'}
    binders, cur = [], None
    while i < len(src):
        ch = src[i]
        if ch in '([{':
            if not stack:
                cur = ''
            elif cur is not None:
                cur += ch
            stack.append(ch)
        elif ch in ')]}':
            if not stack or stack.pop() != pairs[ch]:
                raise CheckError('unbalanced brackets in %s' % name)
            if stack:
                if cur is not None:
                    cur += ch
            elif cur is not None:
                binders.append(' '.join(cur.split()))
                cur = None
        elif not stack and ch == ':' and not src.startswith(':=', i):
            return binders
        elif cur is not None:
            cur += ch
        i += 1
    raise CheckError('could not find the conclusion of %s' % name)


# --------------------------------------------------------------------------
# the group action on orbit records
# --------------------------------------------------------------------------

def canonical(a, q, delta):
    """Lex-min image of (sorted a, delta) under flips, permutation, scaling, swap."""
    best = None
    for flips in itertools.product((1, -1), repeat=len(a)):
        b = [(f * x) % q for f, x in zip(flips, a)]
        for u in range(1, q):
            if math.gcd(u, q) != 1:
                continue
            c = tuple(sorted((u * x) % q for x in b))
            for s in (1, -1):
                key = (c, (s * u * delta) % q)
                if best is None or key < best:
                    best = key
    return best


def fiber(a, q, residue):
    out = set()
    for x in itertools.product((0, 1), repeat=len(a)):
        if sum(ai * xi for ai, xi in zip(a, x)) % q == residue % q:
            out.add(tuple(x))
    return out


