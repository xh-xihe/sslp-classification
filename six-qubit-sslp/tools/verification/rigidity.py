def canonical(a, q, delta):
    """Lex-min image of (sorted a, delta) under flips, permutation, scaling, swap."""
    best = None
    for flips in itertools.product((1, -1), repeat=len(a)):
        b = [(f * x) % q for f, x in zip(flips, a)]
        for u in range(1, q):
            if math.gcd(u, q) != 1:
                continue
            c = tuple(sorted((u * x) % q for x in b))
            for s in (1, -1):
                key = (c, (s * u * delta) % q)
                if best is None or key < best:
                    best = key
    return best


def fiber(a, q, residue):
    out = set()
    for x in itertools.product((0, 1), repeat=len(a)):
        if sum(ai * xi for ai, xi in zip(a, x)) % q == residue % q:
            out.add(tuple(x))
    return out


