def check(sources, manifest, report):
    """sources: module name -> text.  Returns list of (label, ok, detail)."""
    code = sources['Orbit36Code']
    final = sources[HEADLINE_MODULE]
    syms = bitstring_symbols([sources[m] for m in SYMBOL_MODULES] + [code])

    a, q = parse_av(code)
    r0, r1 = parse_fiber_residues(code)
    delta = (r1 - r0) % q

    # --- A  orbit identity -------------------------------------------------
    entry = manifest.get('36')
    if entry is None:
        raise CheckError('manifest has no orbit 36')
    lean_canon = canonical(a, q, delta)
    man_canon = canonical(entry['a'], entry['q'], entry['d'])
    report('A  orbit identity', lean_canon == man_canon,
           'Lean a=%s q=%d delta=%d -> %s ; manifest a=%s q=%d delta=%d -> %s'
           % (a, q, delta, lean_canon, entry['a'], entry['q'], entry['d'], man_canon))
    if entry['q'] != q:
        report('A  lift order', False,
               'manifest q=%d but Lean q=%d' % (entry['q'], q))
    else:
        report('A  lift order', True, 'q = %d on both sides' % q)

    # --- B  fibers ---------------------------------------------------------
    F0, F1 = fiber(a, q, r0), fiber(a, q, r1)
    ys = [syms['y%d' % i] for i in range(12)]
    zs = [syms['z%d' % i] for i in range(12)]
    report('B  residue-%d fiber' % r0, set(ys) == F0 and len(set(ys)) == len(F0),
           '%d literals, fiber has %d' % (len(set(ys)), len(F0)))
    report('B  residue-%d fiber' % r1, set(zs) == F1 and len(set(zs)) == len(F1),
           '%d literals, fiber has %d' % (len(set(zs)), len(F1)))
    comp_ok = all(tuple(1 - b for b in y) == z for y, z in zip(ys, zs))
    report('B  fibers complementary', comp_ok,
           'z_i = complement(y_i) for all 12' if comp_ok
           else 'some z_i is not the complement of y_i')

    # --- C  hypothesis classification -------------------------------------
    binders = headline_binders(final, HEADLINE)
    rows, other, kinds = [], [], {'support': 0, 'moment': 0, 'row': 0, 'var': 0}
    for b in binders:
        body = b.split(':', 1)[1].strip() if ':' in b else b
        m = re.match(r'^offSum\s+c\s+d\s+(\S+)\s+(\S+)\s*=\s*0$', body)
        if m:
            kinds['row'] += 1
            rows.append((m.group(1), m.group(2)))
        elif re.match(r'^(∀|forall)\s+\S+,\s*\S+\s*(?:∉|not in)\s*\S+\s*(?:->|→)\s*'
                      r'[cd]\s+\S+\s*=\s*0$', body):
            kinds['support'] += 1
        elif body.startswith('MomentSystem'):
            kinds['moment'] += 1
        elif re.match(r'^SS\.BitString\s+6\s*(?:->|→)\s*ℂ$', body):
            kinds['var'] += 1
        else:
            other.append(body[:90])
    report('C  no unclassified hypothesis', not other,
           '%d binders: %d rows, %d support, %d moment, %d variables'
           % (len(binders), kinds['row'], kinds['support'], kinds['moment'],
              kinds['var'])
           + ('' if not other else ' ; UNCLASSIFIED: ' + ' | '.join(other)))
    report('C  moment system present', kinds['moment'] == EXPECTED_MOMENT,
           '%d MomentSystem binders (expected exactly %d)'
           % (kinds['moment'], EXPECTED_MOMENT))
    report('C  both supports present', kinds['support'] == EXPECTED_SUPPORTS,
           '%d support binders (expected exactly %d)'
           % (kinds['support'], EXPECTED_SUPPORTS))
    report('C  KL row count as declared', kinds['row'] == EXPECTED_ROWS,
           '%d KL rows (expected exactly %d)' % (kinds['row'], EXPECTED_ROWS))

    # --- D  Pauli weight ---------------------------------------------------
    bad, unresolved = [], []
    for e, z in rows:
        ke, kz = e.split('.')[-1], z.split('.')[-1]
        if ke not in syms or kz not in syms:
            unresolved.append('%s %s' % (e, z))
            continue
        w = sum(1 for i in range(N) if syms[ke][i] or syms[kz][i])
        if w > 2:
            bad.append('%s %s has weight %d' % (e, z, w))
    report('D  every row resolves', not unresolved,
           'all %d rows resolved' % len(rows) if not unresolved
           else 'UNRESOLVED: ' + ', '.join(unresolved))
    report('D  every row has weight <= 2', not bad,
           '%d rows, max weight 2' % len(rows) if not bad else '; '.join(bad))

    # --- F  moment-system content -----------------------------------------
    # Derived from the fibers, not compared against momentgate.  Sharing code
    # with momentgate would make the two checkers fail together; an earlier
    # pair here did exactly that, agreeing with each other while both missed
    # the same row.
    fields, ferrs = structure_fields(sources['Orbit36'])
    for e in ferrs:
        report('F  structure parses', False, e)
    if not ferrs:
        report('F  structure parses', True, '%d fields' % len(fields))

    # The binder list fixes which probability each name denotes. Swapping two
    # entries here while leaving every row alone renumbers the whole system
    # silently; that is the defect class that hit four no-go modules.
    hdr = re.search(r'structure MomentSystem\s*\(([^)]*)\)', sources['Orbit36'])
    if hdr is None:
        report('F  binder order', False, 'cannot read the MomentSystem binder list')
    else:
        got = [b for b in hdr.group(1).split(':')[0].split() if b]
        want = (['q%d' % i for i in range(len(ys))]
                + ['r%d' % j for j in range(len(zs))])
        report('F  binder order', got == want,
               'q0..q%d then r0..r%d, in index order' % (len(ys) - 1, len(zs) - 1)
               if got == want
               else 'binders start %s..., expected %s...'
                    % (' '.join(got[:4]), ' '.join(want[:4])))

    intended = derive_moment_rows(ys, zs)
    declared, dup, malformed = {}, [], []
    nonneg = set()
    for name, body in fields:
        m = re.match(r'^0\s*(?:≤|<=)\s*([qr]\d+)$', body)
        if m:
            nonneg.add(m.group(1))
            continue
        parts = body.split('=')
        if len(parts) != 2:
            malformed.append(name)
            continue
        try:
            lhs, rhs = linear_side(parts[0]), linear_side(parts[1])
        except CheckError as exc:
            malformed.append('%s (%s)' % (name, exc))
            continue
        if (lhs, rhs) in declared:
            dup.append(name)
        declared[(lhs, rhs)] = name
    report('F  every equation parses', not malformed,
           'all %d equations parse' % len(declared) if not malformed
           else 'MALFORMED: ' + ', '.join(malformed))
    report('F  no duplicate equation', not dup,
           'no row states the same equation twice' if not dup
           else 'DUPLICATED: ' + ', '.join(dup))

    unintended = [declared[k] for k in declared if k not in intended]
    report('F  no equation beyond the KL moments', not unintended,
           '%d declared rows, all are genuine moment conditions' % len(declared)
           if not unintended
           else 'NOT A MOMENT CONDITION: ' + ', '.join(sorted(unintended)))

    every = set(intended.values())
    covered = set(intended[k] for k in declared if k in intended)
    missing = sorted(every - covered)
    # Absent rows only make the headline stronger, so they are reported, never
    # failed -- the same convention momentgate uses for the no-gos.
    report('F  declared rows are correct', True,
           '%d of %d possible moment rows declared%s'
           % (len(covered), len(every),
              '' if not missing else ' (absent: %s)' % ', '.join(missing[:6])))

    # Names carry no logical weight -- content decides -- but a row named `m1`
    # that states the condition for a different qubit set means the generator
    # emitted something other than what it thought, so it is worth surfacing.
    misnamed = ['%s states %s' % (nm, intended[k])
                for k, nm in declared.items()
                if k in intended and intended[k] != nm]
    report('F  row names match their content', not misnamed,
           'all %d rows are named for the condition they state' % len(declared)
           if not misnamed else '; '.join(sorted(misnamed)[:5]))

    allvars = set('q%d' % i for i in range(len(ys))) | set(
        'r%d' % i for i in range(len(zs)))
    report('F  nonnegativity covers every state', nonneg == allvars,
           '%d of %d states have an explicit 0 <= p field'
           % (len(nonneg), len(allvars)))

    # --- G  the headline passes probabilities in declaration order ---------
    order_ok, order_detail = headline_moment_order(final, HEADLINE, len(ys), len(zs))
    report('G  headline passes q_i = normSq (c y_i) in order', order_ok, order_detail)

    # --- E  non-vacuity ----------------------------------------------------
    vac = sources.get('Orbit36Vacuity', '')
    applies = re.search(r'rigidity_nonvacuous', vac) and re.search(
        HEADLINE_MODULE + r'\.' + HEADLINE, vac)
    report('E  non-vacuity witness applies the headline', bool(applies),
           'Orbit36Vacuity.rigidity_nonvacuous applies %s.%s'
           % (HEADLINE_MODULE, HEADLINE) if applies
           else 'no application of the headline found in Orbit36Vacuity')
    return rows


def load_sources():
    mods = set(SYMBOL_MODULES) | {'Orbit36Code', HEADLINE_MODULE, 'Orbit36Vacuity'}
    return {m: read(m) for m in mods}


def load_manifest():
    path = os.path.join(REPO, 'tools', 'manifest.json')
    return json.loads(io.open(path, encoding='utf-8').read())


