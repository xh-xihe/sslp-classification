def structure_fields(src):
    """[(name, one-line body)] of the MomentSystem structure, plus errors.

    Fields wrap onto continuation lines, and proof bodies elsewhere in the file
    carry the same two-space indentation, so the block is delimited first and
    only then split into fields.  An earlier checker here skipped wrapped
    fields silently and reported a correct module as entirely wrong.
    """
    k = src.find('structure MomentSystem')
    if k < 0:
        return [], ['no MomentSystem structure found']
    body = src[k:]
    nl = body.index(chr(10)) + 1
    m = re.search(r'^\S', body[nl:], re.M)
    block = body[nl:nl + m.start()] if m else body[nl:]

    fields, errors, cur = [], [], None
    for line in block.split(chr(10)):
        if not line.strip():
            continue
        m = re.match(r'^  (\w+)\s*:\s*(.*)$', line)
        if m:
            if cur:
                fields.append(cur)
            cur = (m.group(1), m.group(2).strip())
        elif cur is not None and line.startswith('  '):
            cur = (cur[0], (cur[1] + ' ' + line.strip()).strip())
        else:
            errors.append('unrecognized line in structure: %s'
                          % ascii_safe(line.strip()[:60]))
    if cur:
        fields.append(cur)
    return fields, errors


def linear_side(expr):
    """`q0 + q1 + q2` -> (frozenset{'q0','q1','q2'}, 0); `1` -> (frozenset(), 1).

    Anything else -- a coefficient, a repeated variable, a subtraction -- is an
    error rather than a silent approximation.  Collapsing a row to a bare index
    set is what let four modules pass with the wrong constants.
    """
    terms = [t.strip() for t in expr.strip().split('+')]
    names, const = [], 0
    for t in terms:
        if re.fullmatch(r'[qr]\d+', t):
            names.append(t)
        elif re.fullmatch(r'\d+', t):
            const += int(t)
        else:
            raise CheckError('cannot read term %r' % ascii_safe(t))
    if len(set(names)) != len(names):
        raise CheckError('a variable appears twice')
    return frozenset(names), const


def derive_moment_rows(ys, zs):
    """Every legitimate equation of the system, keyed by content.

    Normalization, plus one row per qubit subset of size 1 or 2:
    the probability mass on strings carrying all of T must agree between the
    two fibers.  Both orientations are accepted, since which side is written
    first carries no meaning.
    """
    allq = frozenset('q%d' % i for i in range(len(ys)))
    allr = frozenset('r%d' % i for i in range(len(zs)))
    out = {}

    def put(key, name):
        (lv, lc), (rv, rc) = key
        out[((lv, lc), (rv, rc))] = name
        out[((rv, rc), (lv, lc))] = name

    put(((allq, 0), (frozenset(), 1)), 'n0')
    put(((allr, 0), (frozenset(), 1)), 'n1')
    for size in (1, 2):
        for T in itertools.combinations(range(N), size):
            lv = frozenset('q%d' % i for i, y in enumerate(ys)
                           if all(y[t] for t in T))
            rv = frozenset('r%d' % j for j, z in enumerate(zs)
                           if all(z[t] for t in T))
            put(((lv, 0), (rv, 0)),
                'm' + ''.join(str(t + 1) for t in T))
    return out


def headline_moment_order(src, name, nb, nt):
    """The headline must pass normSq (c y0..y_{nb-1}) then (d z0..z_{nt-1})."""
    for b in headline_binders(src, name):
        body = b.split(':', 1)[1].strip() if ':' in b else b
        if not body.startswith('MomentSystem'):
            continue
        got = re.findall(r'normSq\s*\(\s*([cd])\s+([yz])(\d+)\s*\)', body)
        want = ([('c', 'y', str(i)) for i in range(nb)]
                + [('d', 'z', str(j)) for j in range(nt)])
        if got == want:
            return True, '%d bottom then %d top, in index order' % (nb, nt)
        for k, (g, w) in enumerate(zip(got, want)):
            if g != w:
                return False, ('position %d passes %s %s%s, expected %s %s%s'
                               % (k, g[0], g[1], g[2], w[0], w[1], w[2]))
        return False, ('%d probabilities passed, expected %d'
                       % (len(got), len(want)))
    return False, 'no MomentSystem binder found in the headline'


