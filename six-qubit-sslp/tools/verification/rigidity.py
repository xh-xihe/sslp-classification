"""Hold the orbit-36 rigidity chain to the standard the 51 no-gos are held to.

The no-go modules are guarded four ways: `gate.py` checks that a module targets
the orbit it claims, `momentgate.py` that its moment rows are transcribed
correctly, `classify.py` that no algebraic fact is smuggled in as a hypothesis,
and `admis.py` that every Pauli row has weight at most two.  Orbit 36 arrived
later and had none of them, even though its headline takes the same kind of
hypotheses and can fail the same way: a mis-transcribed row or a smuggled fact
would void it invisibly, and the Lean kernel would not notice, because the
kernel checks the proof, not the statement.

Five obligations are checked here.

  A  orbit identity.  `Orbit36Code.av` is `(1,1,1,1,2,3)` at `q = 5` with
     fibers at residues 0 and 4.  `manifest.json` records orbit 36 as
     `(1,1,1,2,2,4)` with `delta = 1`.  Those are different records and must be
     shown to be the same orbit, not assumed to be: they are compared by
     canonical form under the group generated by local flips
     (`a_j -> -a_j`, both fibers shift together so `delta` survives), qubit
     permutation, unit scaling (`a -> u a`, `delta -> u delta`), and exchange of
     the two logical states (`delta -> -delta`).

  B  fibers.  The residue-0 and residue-4 fibers are recomputed from `(av, q)`
     here and compared against the `y`/`z` literals the headline indexes.  Lean
     decides the same fact, so this is a second, independent computation of it.

  C  hypothesis classification.  Every binder of the headline must be a support
     condition, the moment system, an off-diagonal KL row, or a plain variable.
     Anything else is a candidate smuggled assumption and fails.

  D  Pauli weight.  Every KL row must resolve to a genuine weight-at-most-two
     Pauli.  A weight-three row would quietly weaken the result to a
     distance-four statement.

  E  non-vacuity.  `Orbit36Vacuity.rigidity_nonvacuous` must actually apply the
     headline, so the hypotheses are known to be satisfiable rather than merely
     unrefuted.

Usage:
    python tools/run.py verification/rigidity.py
    python tools/run.py verification/rigidity.py --selftest

Like the other checkers here, the parser is deliberately conservative and
fail-closed for the grammar this repository uses.  It is not a general Lean
parser, and it says so rather than guessing.
"""
import io
import itertools
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
SQ = os.path.join(REPO, 'SixQubit')

HEADLINE_MODULE = 'Orbit36Final'
HEADLINE = 'orbit36_rigidity'
SYMBOL_MODULES = ('Orbit36', 'Orbit36Enum')
N = 6

# The headline assumes exactly these many off-diagonal KL rows.  Dropping one
# would make the theorem stronger, not weaker, and Lean would reject the proof
# anyway; the count is pinned here for transcription fidelity, so that a silent
# change in what is assumed shows up as a checker failure rather than as a
# quietly different theorem.
EXPECTED_ROWS = 22
EXPECTED_SUPPORTS = 2
EXPECTED_MOMENT = 1


def ascii_safe(s):
    """Console-safe: this repository is developed on a GBK-codepage terminal."""
    return s.encode('ascii', 'backslashreplace').decode('ascii')


class CheckError(RuntimeError):
    pass


def read(module):
    path = os.path.join(SQ, module + '.lean')
    if not os.path.exists(path):
        raise CheckError('missing module %s' % path)
    return io.open(path, encoding='utf-8').read()


