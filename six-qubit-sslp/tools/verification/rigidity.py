def run_once(sources, manifest):
    fails = []

    def report(label, ok, detail):
        if not ok:
            fails.append((label, detail))
    check(sources, manifest, report)
    return fails


def selftest():
    base = load_sources()
    manifest = load_manifest()

    fails = run_once(dict(base), manifest)
    if fails:
        print('SELFTEST ABORTED: the unmutated tree already fails')
        for label, detail in fails:
            print('   %-40s %s' % (label, detail))
        return 1

    print('%-44s %s' % ('mutation', 'caught?'))
    missed, inert = [], []
    for name, module, old, new in MUTATIONS:
        mutated = dict(base)
        try:
            if module == HEADLINE_MODULE:
                # Must be applied inside the headline, not at the first
                # whole-file hit; see mutate_headline.
                mutated[module] = mutate_headline(base[module], HEADLINE, old, new)
            else:
                if base[module].count(old) != 1:
                    inert.append(name)
                    print('   %-41s INERT (anchor occurs %d times, need 1)'
                          % (name, base[module].count(old)))
                    continue
                mutated[module] = base[module].replace(old, new, 1)
        except CheckError as exc:
            inert.append(name)
            print('   %-41s INERT (%s)' % (name, ascii_safe(str(exc))[:44]))
            continue
        if mutated[module] == base[module]:
            inert.append(name)
            print('   %-41s INERT (mutation changed nothing)' % name)
            continue
        try:
            fails = run_once(mutated, manifest)
            caught = bool(fails)
            why = fails[0][0] if fails else ''
        except CheckError as exc:
            caught, why = True, 'CheckError: %s' % ascii_safe(str(exc))[:44]
        if not caught:
            missed.append(name)
        print('   %-41s %-5s %s' % (name, 'yes' if caught else 'NO', why))

    print()
    print('%d mutations, %d missed, %d inert' % (len(MUTATIONS), len(missed), len(inert)))
    if missed or inert:
        for n in missed:
            print('   MISSED: %s' % n)
        for n in inert:
            print('   INERT (anchor no longer present, so the mutation tested nothing): %s' % n)
        return 1
    print('SELFTEST PASS')
    return 0


def main(argv):
    try:
        if '--selftest' in argv:
            return selftest()
        sources, manifest = load_sources(), load_manifest()
        results = []

        def report(label, ok, detail):
            results.append((label, ok, detail))
        rows = check(sources, manifest, report)
        for label, ok, detail in results:
            print('%-38s %-5s %s' % (label, 'ok' if ok else 'FAIL',
                                     ascii_safe(detail)))
        bad = [r for r in results if not r[1]]
        print()
        print('%d checks, %d failed, %d KL rows verified'
              % (len(results), len(bad), len(rows)))
        return 1 if bad else 0
    except CheckError as exc:
        print('FAIL: %s' % exc)
        return 1


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
