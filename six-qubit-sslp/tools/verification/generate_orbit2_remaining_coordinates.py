path=ROOT/'MainTheory/Orbit2RemainingCoordinates.lean'
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--check',action='store_true')
if p.parse_args().check:
    if path.read_text(encoding='utf8')!=text:
        raise SystemExit('STALE '+str(path))
    print('PASS exact 492-coordinate source regeneration')
