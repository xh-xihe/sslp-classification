"""Generate exact kernel proofs for the SI's literal 23-by-20 moment matrix."""
from pathlib import Path
from itertools import combinations
import sympy as s

ROOT = Path(__file__).resolve().parents[2]
WORDS = [0,36,20,58,14,57,13,35,19,55]
TOP = [x ^ 8 for x in WORDS]
PAIRS = list(combinations(range(6),2))
features = [lambda x,j=j:(x>>j)&1 for j in range(6)] + [
    lambda x,j=j,k=k:((x>>j)&1)*((x>>k)&1) for j,k in PAIRS]
A = s.Matrix([[1]*10+[0]*10,[0]*10+[1]*10] + [
    [f(x) for x in WORDS]+[-f(x) for x in TOP] for f in features])
COLS = list(A.rref()[1])
ROWS = list(A[:,COLS].T.rref()[1])
assert len(ROWS) == 17
M = A.extract(ROWS,COLS)
L,U,swaps = M.LUdecomposition()
perm = list(range(17))
for i,j in swaps:
    perm[i],perm[j] = perm[j],perm[i]
MINOR_ROWS = [ROWS[i] for i in perm]
assert A.extract(MINOR_ROWS,COLS) == L*U and (L*U).det() == -108

def num(v):
    return str(v) if v.q == 1 else f'({v.p}/{v.q})'

def mat(B):
    return '!![' + ';\n    '.join(','.join(num(v) for v in B.row(i)) for i in range(B.rows)) + ']'

