#!/usr/bin/env python3
"""Generate the proof-source catalog and topic navigation without claiming coverage."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIBRARIES = ('SS', 'QECC', 'MainTheory', 'SixQubit', 'Orbit2')


def topic(relative):
    parts = Path(relative).parts
    library, stem = parts[0], Path(relative).stem
    if len(parts) == 1:
        return 'Library entry points'
    if library == 'SS':
        return 'Shared Pauli and KL foundations'
    if library == 'QECC':
        return 'Section III: QECC formalization'
    if library == 'Orbit2':
        return 'Orbit 2: imported proof package'
    if 'Generated' in parts:
        return 'Generated certificates'
    if 'Audit' in stem or 'AxiomCheck' in stem:
        return 'Kernel audits'
    if stem.startswith('Orbit2') and not stem.startswith(('Orbit21', 'Orbit22', 'Orbit23', 'Orbit24', 'Orbit25', 'Orbit26', 'Orbit27', 'Orbit28', 'Orbit29')):
        return 'Orbit 2: physical encoder bridges'
    if stem.startswith('Orbit3') and not stem.startswith(('Orbit30', 'Orbit31', 'Orbit32', 'Orbit33', 'Orbit34', 'Orbit35', 'Orbit36', 'Orbit37', 'Orbit38', 'Orbit39')):
        return 'Orbit 3: scalar and sextic encoder bridges'
    if stem.startswith('SevenQubit'):
        return 'Seven-qubit example'
    if stem.startswith(('Quaternion', 'SmallTransversal', 'SmallNonClifford', 'BoundedProjectiveClifford', 'CliffordProjective')):
        return 'Projective Clifford groups and minimum length'
    if library == 'SixQubit':
        return 'Six-qubit orbit proofs and constructions'
    if stem.startswith(('Orbit', 'Directory', 'Completion', 'OrderTwo', 'Enumerator', 'Realization', 'OpenOrbit', 'ProvedWE', 'WImage')):
        return 'Six-qubit classification and enumerator transport'
    if stem.startswith(('QECC', 'Paper', 'GeneralColored', 'Colored', 'PhaseSector', 'FiniteGate', 'Gate', 'Diagonal', 'D3', 'NumberDetection', 'CommonMean', 'PositiveAffine', 'ProbabilityFrame')):
        return 'General SSLP theory and paper bridges'
    if stem.startswith(('Cubic', 'FiniteCubic', 'FinitePhase', 'FiniteHaar', 'Spectator', 'ThreeCopy', 'PauliCategory', 'PhysicalPauli')):
        return 'Exact moment and symmetry infrastructure'
    return 'General algebra and code infrastructure'


def catalog(root=ROOT):
    root = Path(root)
    paths = [p for library in LIBRARIES for p in (root / library).rglob('*.lean')]
    paths += [root / (library + '.lean') for library in LIBRARIES
              if (root / (library + '.lean')).is_file()]
    rows = []
    for path in sorted(paths):
        relative = path.relative_to(root).as_posix()
        rows.append({'module': relative[:-5].replace('/', '.'), 'path': relative,
                     'sha256_lf': hashlib.sha256(path.read_bytes().replace(b'\r\n', b'\n')).hexdigest(),
                     'library': relative.split('/')[0].removesuffix('.lean'),
                     'topic': topic(relative)})
    return {'schema': 1, 'scope': 'Active Lean sources only. Compilation and manuscript coverage are recorded separately.',
            'libraries': list(LIBRARIES), 'module_count': len(rows),
            'counts_by_library': dict(sorted(Counter(row['library'] for row in rows).items())),
            'modules': rows}


def navigation(data):
    lines = ['# Proof modules by topic', '',
             'Generated by `python tools/repository_index.py`. The grouping is navigation,',
             'not a manuscript coverage decision. See [proof entry points](proof-index.md)',
             'and [current status](status.md) for statements and verification scope.', '',
             f"Active modules: **{data['module_count']}**. The complete machine-readable inventory",
             'is [results/proof-modules.json](../results/proof-modules.json).', '',
             '| Library | Modules |', '| --- | ---: |']
    lines += [f'| `{library}/` | {count} |' for library, count in data['counts_by_library'].items()]
    for title in sorted({r['topic'] for r in data['modules']}):
        rows = [r for r in data['modules'] if r['topic'] == title]
        lines += ['', f'## {title}', '']
        if title == 'Generated certificates':
            counts = Counter('/'.join(Path(r['path']).parts[:3]) if len(Path(r['path']).parts) > 3
                             else '/'.join(Path(r['path']).parts[:2]) for r in rows)
            lines += ['Generated payloads are grouped by certificate family. Consult their',
                      '`generation-manifest.sha256`, `manifest.json` and build-order files.', '',
                      '| Family | Modules |', '| --- | ---: |']
            lines += [f'| [{family}](../{family}) | {count} |' for family, count in sorted(counts.items())]
        else:
            lines += [f"- [{r['module']}](../{r['path']})" for r in rows]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = catalog()
    outputs = {'results/proof-modules.json': json.dumps(data, indent=2) + '\n',
               'docs/proof-modules.md': navigation(data)}
    for relative, content in outputs.items():
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                raise SystemExit('FAIL: regenerate ' + relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    print(f"PASS: repository index ({data['module_count']} active Lean modules)")


if __name__ == '__main__':
    main()
