#!/usr/bin/env python3
"""Emit kernel proofs of the active-letter Fourier generating polynomials."""
from __future__ import annotations
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def multiply(left, right):
    out = {}
    for (j, k), a in left.items():
        for (z, t), b in right.items():
            out[j+z, k+t] = out.get((j+z, k+t), 0) + a*b
    return out


def generate(output):
    categories = [(j, k) for k in range(6) for j in range(6-k)]
    coefficients = []
    for j, k in categories:
        p = {(0, 0): 1}
        for count, factor in [(5-j-k, {(0,0):1, (1,0):1, (0,1):2}),
                              (j, {(0,0):1, (1,0):1, (0,1):-2}),
                              (k, {(0,0):1, (1,0):-1})]:
            for _ in range(count):
                p = multiply(p, factor)
        coefficients.append([p.get(c, 0) for c in categories])
    vec = lambda row: '![' + ', '.join(map(str, row)) + ']'
    matrix = '![' + ',\n  '.join(vec(row) for row in coefficients) + ']'
    text = f'''-- Generated by tools/generators/emit_orbit3_category_fourier.py.
import MainTheory.PauliCategoryFourier

/-! All 21 physical active-letter generating polynomials, expanded by ordinary
kernel-checked ring reasoning. Their coefficients count Pauli characters. -/
namespace SixQubit.Generated.Orbit3CategoryFourier

open MainTheory.PauliCategoryFourier
open scoped BigOperators
noncomputable section
set_option maxHeartbeats 4000000

def categories : Fin 21 → ℕ × ℕ := ![{', '.join(f'({j}, {k})' for j,k in categories)}]
def coefficients : Fin 21 → Fin 21 → ℤ := {matrix}

def expanded (i : Fin 21) : Polynomial :=
  ∑ e : Fin 21, coefficients i e •
    (monomial 1 0 ^ (categories e).1 * monomial 0 1 ^ (categories e).2)

'''
    for i, (j, k) in enumerate(categories):
        assoc = lambda terms: ' + ('.join(terms) + ' + 0' + ')' * (len(terms)-1)
        concrete = assoc([f'({c} : ℤ) • (monomial 1 0 ^ {z} * monomial 0 1 ^ {t})'
                          for c, (z, t) in zip(coefficients[i], categories)])
        generic = assoc([f'({c} : R) * (X ^ {z} * Y ^ {t})'
                         for c, (z, t) in zip(coefficients[i], categories)])
        casts = ['Int.cast_neg', 'Int.cast_ofNat']
        if 0 in coefficients[i]:
            casts.append('Int.cast_zero')
        text += f'''theorem polynomial_identity_{i:02} {{R : Type*}} [CommRing R] (X Y : R) :
    (1 + X + 2 * Y) ^ {5-j-k} * (1 + X - 2 * Y) ^ {j} * (1 - X) ^ {k} =
      {generic} := by ring

theorem expanded_{i:02} : expanded {i} =
    {concrete} := by
  unfold expanded
  simp only [Fin.sum_univ_succ, Fin.sum_univ_zero]
  rfl

theorem expansion_{i:02} :
    identityFactor ^ {5-j-k} * zFactor ^ {j} * transverseFactor ^ {k} = expanded {i} := by
  rw [identityFactor_eq, zFactor_eq, transverseFactor_eq, expanded_{i:02}]
  simp_rw [zsmul_eq_mul]
  simpa only [{', '.join(casts)}] using
    polynomial_identity_{i:02} (monomial 1 0) (monomial 0 1)

'''
    text += '''theorem expansion (i : Fin 21) :
    identityFactor ^ (5 - (categories i).1 - (categories i).2) *
      zFactor ^ (categories i).1 * transverseFactor ^ (categories i).2 = expanded i := by
  fin_cases i
'''
    text += '\n'.join(f'  · exact expansion_{i:02}' for i in range(21))
    text += '''

def categoryRank (c : ℕ × ℕ) : ℕ := c.1 + c.2 * (13 - c.2) / 2

theorem categoryRank_correct : ∀ i, categoryRank (categories i) = i.val := by decide +kernel

theorem categories_injective : Function.Injective categories := by
  intro i j h
  apply Fin.ext
  rw [← categoryRank_correct i, ← categoryRank_correct j, h]

theorem expanded_coefficient (i e : Fin 21) :
    expanded i (categories e) = coefficients i e := by
  unfold expanded
  simp_rw [monomial_pow_mul]
  change (∑ j : Fin 21, coefficients i j •
    Finsupp.single (categories j) (1 : ℤ)) (categories e) = _
  simp only [Finsupp.coe_finset_sum, Finset.sum_apply, Finsupp.smul_apply,
    Finsupp.single_apply, smul_eq_mul]
  simp [categories_injective.eq_iff]

end
end SixQubit.Generated.Orbit3CategoryFourier
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf8', newline='\n')
    print(f'Generated {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path,
        default=ROOT/'SixQubit/Generated/Orbit3CategoryFourier.lean')
    generate(parser.parse_args().output)
