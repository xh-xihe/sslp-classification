#!/usr/bin/env python3
"""Expose and kernel-check the actual Pauli zero factors of all sextic KL rows.

The generated metadata is not a proof of reduced coefficient semantics. It
identifies every KL multiplier with a zero expectation of an actual encoder.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def vector(values):
    return '![' + ', '.join(map(str, values)) + ']'


def generate(source: Path, output: Path):
    raw = source.read_bytes()
    terms = json.loads(raw)['terms']
    if len(terms) != 211 or Counter(t['kind'] for t in terms) != {'kl': 203, 'spin': 5, 'H': 3}:
        raise ValueError('Expected the complete 211-row certificate')
    kinds = [dict(kl=0, spin=1, H=2)[t['kind']] for t in terms]
    labels = [t.get('paulis', [0, 0, 0]) for t in terms]
    if any(len(row) != 3 or any(not isinstance(r, int) or not 0 <= r < 4096 for r in row)
           for row in labels):
        raise ValueError('Invalid Pauli triple')
    text = f'''-- Generated by tools/generators/emit_orbit3_pauli_constraints.py.
-- Input SHA-256: {hashlib.sha256(raw).hexdigest()}
import MainTheory.Orbit3PauliZeros

namespace SixQubit.Generated.Orbit3PauliConstraints

open MainTheory.Orbit3PauliZeros MainTheory.Orbit3ScalarCategoryRealization
open SixQubit.ParityLogicalState
open scoped BigOperators

set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

def kind : Fin 211 → Fin 3 := {vector(kinds)}
def labels : Fin 211 → Fin 3 → Fin 4096 :=
  {vector([vector(row) for row in labels])}

theorem kl_zero_factor : ∀ i : Fin 211, kind i = 0 →
    ∃ k : Fin 3, Constrained (decode (labels i k)) := by
  decide +kernel

theorem constraint_count :
    (Finset.univ.filter (fun r : Fin 4096 => Constrained (decode r))).card = 429 := by
  decide +kernel

theorem target_count :
    (Finset.univ.filter (fun r : Fin 4096 =>
      MainTheory.PhysicalPauliCategories.category (decode r) = (1, 0, 2))).card = 120 := by
  decide +kernel

theorem all_kl_multiplier_products_zero (W : Encoder) (i : Fin 211) (hi : kind i = 0) :
    (∏ k : Fin 3, SS.innerC (superposition W.states)
      (SS.pauliAct (decode (labels i k)) (superposition W.states))) = 0 :=
  triple_zero W (fun k => decode (labels i k)) (kl_zero_factor i hi)

end SixQubit.Generated.Orbit3PauliConstraints
'''
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT/'results/orbit3-kernel/certificate.json')
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/Orbit3PauliConstraints.lean')
    args = parser.parse_args()
    generate(args.input, args.output)


if __name__ == '__main__':
    main()
