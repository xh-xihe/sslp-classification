#!/usr/bin/env python3
"""Exact three-copy Clifford twirl, with Gaussian arithmetic kernel checks.

Discovery uses rational arithmetic. The emitted Lean modules separately check
the literal Clifford entries, all 4096 twirl entries, and the permutation span.
No numerical rank or floating point result is used by the Lean proof.
"""
from __future__ import annotations
import argparse
from itertools import permutations
from pathlib import Path
import sympy as sp
import emit_spectator_clifford as cliff

ROOT = Path(__file__).resolve().parents[2]


def add(a, b):
    return a[0]+b[0], a[1]+b[1]


def mul(a, b):
    return a[0]*b[0]-a[1]*b[1], a[0]*b[1]+a[1]*b[0]


def gauss(a):
    return f'⟨{a[0]}, {a[1]}⟩'


def vec(xs):
    return '!['+', '.join(map(str, xs))+']'


def discover():
    reps = [cliff.canonical(cliff.IDENTITY)[0]]
    seen = set(reps)
    for m in reps:
        for generator in (cliff.H, cliff.S):
            n = cliff.canonical(cliff.mm(generator, m))[0]
            if n not in seen:
                seen.add(n)
                reps.append(n)
    assert len(reps) == 24
    matrices, denominators, weights = [], [], []
    for m in reps:
        assert all(not x[1] and not x[3] for x in m)
        d = sp.ilcm(*[x.denominator for a in m for x in (a[0], a[2])])
        assert d in (1, 2)
        matrices.append([(int(d*a[0]), int(d*a[2])) for a in m])
        denominators.append(int(d))
        weights.append(int(64 // d**6))
    copies = []
    for m in matrices:
        k = []
        for x in range(8):
            row = []
            for y in range(8):
                a = (1, 0)
                for i in range(3):
                    a = mul(a, m[2*((x >> i)&1)+((y >> i)&1)])
                row.append(a)
            k.append(row)
        copies.append(k)
    data = []
    for r in range(64):
        x, z = r % 8, r // 8
        row = []
        for c in range(64):
            a, b = c % 8, c // 8
            v = (0, 0)
            for w, k in zip(weights, copies):
                value = mul(k[x][a], (k[z][b][0], -k[z][b][1]))
                v = add(v, (w*value[0], w*value[1]))
            assert v[1] == 0
            row.append(v[0])
        data.append(row)
    perms = list(permutations(range(3)))[:5]
    def permute(p, y):
        return sum(((y >> p[i])&1) << i for i in range(3))
    basis = sp.Matrix([[int(r % 8 == permute(p, r // 8)) for p in perms]
                       for r in range(64)])
    pivots = list(basis.T.rref()[1])
    assert len(pivots) == 5
    minor = basis[pivots, :]
    coeff = minor.inv()*sp.Matrix(data)[pivots, :]
    assert basis*coeff == sp.Matrix(data)
    assert all(x.q == 1 for x in coeff)
    return matrices, denominators, weights, data, perms, [list(map(int, coeff.row(i))) for i in range(5)]


def generate(output):
    matrices, denominators, weights, data, perms, coeff = discover()
    output.mkdir(parents=True, exist_ok=True)
    code = ['''-- Generated by tools/generators/emit_spectator_cubic_twirl.py.
import MainTheory.ThreeCopyPermutationCommutant
import SixQubit.Generated.SpectatorClifford

namespace SixQubit.Generated.SpectatorCubicTwirl
noncomputable section
open MainTheory.ThreeCopyPermutationCommutant Orbit2.TensorPauli
open scoped BigOperators

def encode (x : Triple) : Fin 8 := ⟨(x 0).val+2*(x 1).val+4*(x 2).val, by
  have h0 := (x 0).isLt
  have h1 := (x 1).isLt
  have h2 := (x 2).isLt
  omega⟩

def decode (x : Fin 8) : Triple :=
  ![⟨x.val%2, by omega⟩, ⟨(x.val/2)%2, by omega⟩, ⟨x.val/4, by omega⟩]

theorem decode_encode : ∀ x, decode (encode x)=x := by decide +kernel
theorem encode_decode : ∀ x, encode (decode x)=x := by decide +kernel

def row (b a : Fin 8) : Fin 64 := ⟨a.val+8*b.val, by omega⟩
def pair (x y : Triple) : Fin 64 := row (encode y) (encode x)
def first (r : Fin 64) : Triple := decode ⟨r.val%8, by omega⟩
def second (r : Fin 64) : Triple := decode ⟨r.val/8, by omega⟩
theorem first_pair : ∀ x y, first (pair x y)=x := by decide +kernel
theorem second_pair : ∀ x y, second (pair x y)=y := by decide +kernel
theorem row_split : ∀ r : Fin 64, row ⟨r.val/8, by omega⟩ ⟨r.val%8, by omega⟩=r := by
  decide +kernel
''']
    code.append('def denominator : Fin 24 → ℕ := '+vec(denominators))
    code.append('def weight : Fin 24 → ℤ := '+vec(weights))
    code.append('def localG : Fin 24 → Matrix (Fin 2) (Fin 2) GaussianInt := '+
                vec('!!['+gauss(m[0])+', '+gauss(m[1])+'; '+gauss(m[2])+', '+gauss(m[3])+']'
                    for m in matrices))
    code.append('def data : Fin 64 → Fin 64 → ℤ := '+vec(vec(row) for row in data))
    code.append('def coefficient : Fin 5 → Fin 64 → ℤ := '+vec(vec(row) for row in coeff))
    code.append('def sigma (k : Fin 5) : Equiv.Perm (Fin 3) where\n'+
                '  toFun := '+vec(vec(p) for p in perms)+' k\n'+
                '  invFun := '+vec(vec(p.index(i) for i in range(3)) for p in perms)+' k\n'+
                '  left_inv := by revert k; decide +kernel\n'+
                '  right_inv := by revert k; decide +kernel\n')
    code.append('''def gaussianCopies (g : Fin 24) : Matrix Triple Triple GaussianInt :=
  fun x y => ∏ i : Fin 3, localG g (x i) (y i)

def numerator (r c : Fin 64) : GaussianInt := ∑ g : Fin 24,
  (weight g : GaussianInt)*gaussianCopies g (first r) (first c)*
    star (gaussianCopies g (second r) (second c))

def integerPermutation (k : Fin 5) (r : Fin 64) : ℤ :=
  if first r=permute (sigma k) (second r) then 1 else 0

theorem permutation_span : ∀ r c,
    data r c=∑ k : Fin 5, coefficient k c*integerPermutation k r := by
  decide +kernel

end
end SixQubit.Generated.SpectatorCubicTwirl
''')
    (output/'Data.lean').write_text('\n\n'.join(code)+'\n', encoding='utf8', newline='\n')
    for b in range(8):
        (output/f'Check{b:02d}.lean').write_text(f'''-- Generated by tools/generators/emit_spectator_cubic_twirl.py.
import SixQubit.Generated.SpectatorCubicTwirl.Data

namespace SixQubit.Generated.SpectatorCubicTwirl
set_option maxHeartbeats 12000000
set_option maxRecDepth 100000
theorem check{b:02d} : ∀ a : Fin 8, ∀ c : Fin 64,
    numerator (row {b} a) c=(data (row {b} a) c : GaussianInt) := by
  intro a
  fin_cases a <;> decide +kernel
end SixQubit.Generated.SpectatorCubicTwirl
''', encoding='utf8', newline='\n')
    code = [f'import SixQubit.Generated.SpectatorCubicTwirl.Check{b:02d}' for b in range(8)]
    code.append('''
namespace SixQubit.Generated.SpectatorCubicTwirl
set_option maxHeartbeats 16000000
set_option maxRecDepth 100000
theorem numerator_correct (r c : Fin 64) : numerator r c=(data r c : GaussianInt) := by
  rw [← row_split r]
  generalize (⟨r.val/8, by omega⟩ : Fin 8)=b
  generalize (⟨r.val%8, by omega⟩ : Fin 8)=a
  fin_cases b
''')
    code.extend('  · exact check'+f'{b:02d}'+' a c' for b in range(8))
    code.append('end SixQubit.Generated.SpectatorCubicTwirl\n')
    (output/'Checks.lean').write_text('\n'.join(code), encoding='utf8', newline='\n')
    print('Emitted 4096 exact twirl entries and a five-permutation span', flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'SixQubit/Generated/SpectatorCubicTwirl')
    generate(parser.parse_args().output)
