"""Emit ordinary-kernel certificates for the outer-record pair table.

This generator is intentionally independent of the numerical/LP stages in
``main_pipeline.py``.  It reads the already serialized pair ids, recomputes
only the small combinatorial outer enumeration, and emits bounded Lean
modules.  Lean subsequently checks all residue masks from their definitions;
the Python recomputation is therefore only an early consistency check.

The generated proof has three independent parts:

* 12,768 exact rows show that each surviving outer record maps to its declared
  entry of the 11,422-entry pair table;
* 11,422 inverse rows show that every table entry has an outer-record witness.
* 11,422 bounded left-inverse equations show that distinct table indices carry
  distinct exact payloads.

The first two instantiate ``PairProvenance.Table.Validity``; the third proves
that 11,422 is the cardinality of the deduplicated payload family, rather than
merely the length of an index type.  No count or literal-array equality is used
as a substitute for any semantic property.
"""

from __future__ import annotations

import argparse
import json
from itertools import combinations_with_replacement
from math import gcd
from pathlib import Path


HEADER = """-- Generated by tools/generators/emit_pair_provenance_lean.py.
-- The JSON is untrusted input: every record and residue mask is rechecked by Lean.
"""

EXACT_SHARD_SIZE = 32
PAIR_SHARD_SIZE = 64
INVERSE_SHARD_SIZE = 64
PAIR_CODE_BASE = 1 << 64


def write_generated(path: Path, lines: list[str]) -> None:
    content = "\n".join(lines)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8", newline="\n")


def wrapped(values: list[int], width: int = 24, indent: str = "  ") -> list[str]:
    return [indent + ", ".join(map(str, values[start:start + width]))
            for start in range(0, len(values), width)]


def array_literal(values: list[int], width: int = 24) -> list[str]:
    if not values:
        return ["#[]"]
    body = wrapped(values, width)
    return ["#[", *[line + ("," if i + 1 < len(body) else "")
                    for i, line in enumerate(body)], "]"]


def list_literal(values: list[int], width: int = 24) -> list[str]:
    if not values:
        return ["[]"]
    body = wrapped(values, width)
    return ["[", *[line + ("," if i + 1 < len(body) else "")
                   for i, line in enumerate(body)], "]"]


def assigned(name: str, type_text: str, literal: list[str]) -> list[str]:
    return [f"def {name} : {type_text} := {literal[0]}",
            *literal[1:]]


def logical_orders(q: int) -> list[int]:
    return [m for m in range(2, q + 1) if q % m == 0]


def primitive(q: int, angle: tuple[int, ...]) -> bool:
    value = q
    for coordinate in angle:
        value = gcd(value, coordinate)
    return value == 1


def fibre_mask(q: int, angle: tuple[int, ...], residue: int) -> int:
    mask = 0
    for word in range(64):
        total = sum(angle[j] for j in range(6) if (word >> j) & 1)
        if total % q == residue:
            mask |= 1 << word
    return mask


def outer_records() -> tuple[
        list[tuple[int, int, tuple[int, ...], int, int]],
        list[tuple[int, int, int, int, int]]]:
    """Return records and ``(q,m,a0,start,count)`` chunk metadata."""
    records: list[tuple[int, int, tuple[int, ...], int, int]] = []
    chunks: list[tuple[int, int, int, int, int]] = []
    for q in range(2, 10):
        for m in logical_orders(q):
            for a0 in range(q):
                start = len(records)
                for tail in combinations_with_replacement(range(a0, q), 5):
                    angle = (a0, *tail)
                    if not primitive(q, angle):
                        continue
                    mask0 = fibre_mask(q, angle, 0)
                    mask1 = fibre_mask(q, angle, q // m)
                    if mask1:
                        records.append((q, m, angle, mask0, mask1))
                chunks.append((q, m, a0, start, len(records) - start))
    return records, chunks


def raw_record_literal(q: int, m: int, angle: tuple[int, ...]) -> str:
    coords = " ".join(map(str, angle))
    return ("{ q := %d, m := %d, a := "
            "OuterEnumeration.angle6 %s }") % (q, m, coords)


def qualified_list(items: list[str], indent: str = "  ") -> list[str]:
    if not items:
        return ["[]"]
    return ["[", *[f"{indent}{item}" + ("," if i + 1 < len(items) else "")
                    for i, item in enumerate(items)], "]"]


def balanced_expr(items: list[str], operator: str) -> str:
    """A logarithmic-depth binary expression over a nonempty item list."""
    if not items:
        raise ValueError("balanced expression needs at least one item")
    if len(items) == 1:
        return items[0]
    middle = len(items) // 2
    left = balanced_expr(items[:middle], operator)
    right = balanced_expr(items[middle:], operator)
    return f"{operator} ({left}) ({right})"


def pair_code(pair: tuple[int, int, int, int] | list[int]) -> int:
    """An exact, kernel-recomputed routing key for one fiber pair.

    The key is used only to route a total left-inverse lookup.  Injectivity is
    ultimately proved in Lean by the pointwise left-inverse equations; it is
    not trusted from this Python encoding.
    """
    q, m, mask0, mask1 = pair
    if not (0 <= q and 0 <= m < 16):
        raise ValueError(f"pair has an out-of-range routing header: {pair}")
    if not (0 <= mask0 < PAIR_CODE_BASE and 0 <= mask1 < PAIR_CODE_BASE):
        raise ValueError(f"pair has a mask outside 64 bits: {pair}")
    return (((q * 16 + m) * PAIR_CODE_BASE + mask0) * PAIR_CODE_BASE
            + mask1)


def lookup_expr(entries: list[tuple[int, int]], argument: str = "code") -> str:
    """Balanced total lookup on sorted ``(code, pair_id)`` entries.

    Values outside the certified table are deliberately sent to an extremal
    entry.  Only the generated left-inverse equations are later used.  This
    keeps the trusted statement small and avoids pretending the lookup is a
    membership decision procedure.
    """
    if not entries:
        raise ValueError("lookup expression needs at least one entry")
    if len(entries) == 1:
        return str(entries[0][1])
    middle = len(entries) // 2
    threshold = entries[middle][0]
    left = lookup_expr(entries[:middle], argument)
    right = lookup_expr(entries[middle:], argument)
    return f"(if {argument} < {threshold} then {left} else {right})"


def routed_module_expr(children: list[tuple[str, int, int]],
                       argument: str = "code") -> str:
    """Balanced routing among sorted child key intervals."""
    if not children:
        raise ValueError("routing expression needs at least one child")
    if len(children) == 1:
        return f"{children[0][0]}.lookup {argument}"
    middle = len(children) // 2
    threshold = children[middle][1]
    left = routed_module_expr(children[:middle], argument)
    right = routed_module_expr(children[middle:], argument)
    return f"(if {argument} < {threshold} then {left} else {right})"


def right_assoc_expr(items: list[str], operator: str, empty: str) -> str:
    """A list-shaped expression ending in an explicit empty block.

    This is deliberately not balanced: it mirrors the definitional shape of
    `List.flatMap` at the tiny q/m/a₀ hierarchy (depth at most nine per
    layer), while the large 12,768-row payload remains in bounded leaves.
    """
    result = empty
    for item in reversed(items):
        result = f"{operator} ({item}) ({result})"
    return result


def emit_mapping_base(out_dir: Path) -> None:
    """Emit only generic bounded-index machinery; never a large data vector."""
    lines = [
        HEADER,
        "import MainTheory.PairProvenance",
        "",
        "namespace MainTheory.Generated.FinitePairMappingBase",
        "",
        "open MainTheory",
        "open MainTheory.FinitePipeline",
        "",
        "universe u v",
        "",
        "abbrev PairId := Fin 11422",
        "abbrev Segment (α : Type u) (n : ℕ) := Fin n → α",
        "",
        "namespace Segment",
        "",
        "/-- Concatenation is a balanced finite-function dispatcher, not a",
        "materialized large vector. -/",
        "def append {α : Type u} {m n : ℕ}",
        "    (left : Segment α m) (right : Segment α n) : Segment α (m + n) :=",
        "  Fin.append left right", "",
        "def Pointwise {α : Type u} {β : Type v} {n : ℕ}",
        "    (R : α → β → Prop) (left : Segment α n) (right : Segment β n) : Prop :=",
        "  ∀ i, R (left i) (right i)", "",
        "theorem Pointwise.append {α : Type u} {β : Type v} {m n : ℕ}",
        "    {R : α → β → Prop}",
        "    {a₀ : Segment α m} {a₁ : Segment α n}",
        "    {b₀ : Segment β m} {b₁ : Segment β n}",
        "    (h₀ : Pointwise R a₀ b₀) (h₁ : Pointwise R a₁ b₁) :",
        "    Pointwise R (append a₀ a₁) (append b₀ b₁) := by",
        "  intro i",
        "  refine Fin.addCases (fun j => ?_) (fun j => ?_) i",
        "  · change R (Fin.append a₀ a₁ (Fin.castAdd n j))",
        "      (Fin.append b₀ b₁ (Fin.castAdd n j))",
        "    rw [Fin.append_left, Fin.append_left]",
        "    exact h₀ j",
        "  · change R (Fin.append a₀ a₁ (Fin.natAdd m j))",
        "      (Fin.append b₀ b₁ (Fin.natAdd m j))",
        "    rw [Fin.append_right, Fin.append_right]",
        "    exact h₁ j", "",
        "end Segment", "",
        "end MainTheory.Generated.FinitePairMappingBase", "",
    ]
    write_generated(out_dir / "FinitePairMappingBase.lean", lines)

    # Preserve the old module name only as a tiny compatibility facade.  In
    # particular it must never again contain either 10k-element array.
    facade = [
        HEADER, "import MainTheory.Generated.FinitePairMappingBase", "",
        "namespace MainTheory.Generated.FinitePairMappingData", "",
        "open MainTheory.Generated.FinitePairMappingBase", "",
        "end MainTheory.Generated.FinitePairMappingData", "",
    ]
    write_generated(out_dir / "FinitePairMappingData.lean", facade)


def emit_pair_payload(
        data: dict, out_dir: Path
        ) -> tuple[str, list[tuple[str, int, int]]]:
    """Emit the 11,422 payloads as bounded functions, never one large Array."""
    pairs = data["pair_table"]
    leaves: list[tuple[str, int, int]] = []
    for shard, start in enumerate(range(0, len(pairs), PAIR_SHARD_SIZE)):
        stop = min(start + PAIR_SHARD_SIZE, len(pairs))
        count = stop - start
        module = f"MainTheory.Generated.PairProvenance.Payload.Shard{shard:03d}"
        leaves.append((module, start, count))
        lines = [
            HEADER, "import MainTheory.Generated.FinitePairMappingBase", "",
            f"namespace {module}", "",
            "open MainTheory.FinitePipeline",
            "open MainTheory.Generated.FinitePairMappingBase", "",
            "def pairArray : Array FiberPair := #[",
        ]
        for offset, (q, m, mask0, mask1) in enumerate(pairs[start:stop]):
            comma = "," if offset + 1 < count else ""
            lines.append(f"  ⟨{q}, {m}, {mask0}, {mask1}⟩{comma}")
        lines += [
            "]", "", f"theorem pairArray_size : pairArray.size = {count} := by decide", "",
            f"def pairs : Segment FiberPair {count} := fun i =>",
            "  pairArray[Fin.cast pairArray_size.symm i]", "",
            f"end {module}", "",
        ]
        path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)

    current = leaves
    level = 0
    while len(current) > 1:
        next_level: list[tuple[str, int, int]] = []
        for node_index, offset in enumerate(range(0, len(current), 8)):
            children = current[offset:offset + 8]
            start = children[0][1]
            count = sum(child[2] for child in children)
            module = ("MainTheory.Generated.PairProvenance.Payload."
                      f"NodeL{level:02d}N{node_index:03d}")
            lines = [HEADER]
            lines += [f"import {child[0]}" for child in children]
            expression = balanced_expr(
                [f"{child[0]}.pairs" for child in children], "Segment.append")
            lines += [
                "", f"namespace {module}", "",
                "open MainTheory.FinitePipeline",
                "open MainTheory.Generated.FinitePairMappingBase", "",
                f"def pairs : Segment FiberPair {count} :=", f"  {expression}", "",
                f"end {module}", "",
            ]
            path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
            write_generated(path, lines)
            next_level.append((module, start, count))
        current = next_level
        level += 1

    root, start, count = current[0]
    if start != 0 or count != 11422:
        raise ValueError("pair payload hierarchy does not cover all pair ids")
    module = "MainTheory.Generated.FinitePairFunctionData"
    lines = [
        HEADER, f"import {root}", "", f"namespace {module}", "",
        "open MainTheory.FinitePipeline",
        "open MainTheory.Generated.FinitePairMappingBase", "",
        f"def pairs : Segment FiberPair 11422 := {root}.pairs", "",
        "def pairAtId (i : PairId) : FiberPair := pairs i", "",
        f"end {module}", "",
    ]
    write_generated(out_dir / "FinitePairFunctionData.lean", lines)
    return module, leaves


def emit_pair_distinctness(
        data: dict, pair_module: str,
        payload_leaves: list[tuple[str, int, int]], out_dir: Path) -> str:
    """Emit a low-depth kernel certificate that all 11,422 payloads differ.

    A balanced total lookup from exact payloads back to ``PairId`` is emitted
    independently of the payload dispatcher.  Bounded leaves then prove, by
    ordinary kernel reduction, that this lookup is a left inverse of every
    payload position.  The final injectivity theorem is a generic consequence
    of that left inverse; the numeral 11,422 is never used as a substitute for
    distinctness.
    """
    pairs = [tuple(row) for row in data["pair_table"]]
    coded = sorted((pair_code(pair), pair_id)
                   for pair_id, pair in enumerate(pairs))
    if len({code for code, _pair_id in coded}) != len(coded):
        raise ValueError("pair table contains duplicate exact routing keys")

    lookup_base = "MainTheory.Generated.PairProvenance.Distinct.LookupBase"
    base_lines = [
        HEADER, "import MainTheory.Generated.FinitePairMappingBase", "",
        f"namespace {lookup_base}", "",
        "open MainTheory.FinitePipeline",
        "open MainTheory.Generated.FinitePairMappingBase", "",
        "/-- Exact routing code.  Its only trusted use is through the",
        "kernel-checked left-inverse equations emitted below. -/",
        "def pairCode (pair : FiberPair) : Nat :=",
        f"  (((pair.q * 16 + pair.m) * {PAIR_CODE_BASE} + pair.mask0) *",
        f"    {PAIR_CODE_BASE} + pair.mask1)", "",
        f"end {lookup_base}", "",
    ]
    path = out_dir.joinpath(*lookup_base.split(".")[2:]).with_suffix(".lean")
    write_generated(path, base_lines)

    lookup_leaves: list[tuple[str, int, int]] = []
    for shard, start in enumerate(range(0, len(coded), PAIR_SHARD_SIZE)):
        entries = coded[start:start + PAIR_SHARD_SIZE]
        module = ("MainTheory.Generated.PairProvenance.Distinct.Lookup."
                  f"Shard{shard:03d}")
        lookup_leaves.append((module, entries[0][0], entries[-1][0]))
        lines = [
            HEADER, f"import {lookup_base}", "", f"namespace {module}", "",
            "open MainTheory.Generated.FinitePairMappingBase", "",
            "/-- Total lookup on this sorted key interval. -/",
            "def lookup (code : Nat) : PairId :=",
            f"  {lookup_expr(entries)}", "", f"end {module}", "",
        ]
        path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)

    current_lookup = lookup_leaves
    level = 0
    while len(current_lookup) > 1:
        next_level: list[tuple[str, int, int]] = []
        for node_index, offset in enumerate(range(0, len(current_lookup), 8)):
            children = current_lookup[offset:offset + 8]
            module = ("MainTheory.Generated.PairProvenance.Distinct.Lookup."
                      f"NodeL{level:02d}N{node_index:03d}")
            lines = [HEADER]
            lines += [f"import {child[0]}" for child in children]
            lines += [
                "", f"namespace {module}", "",
                "open MainTheory.Generated.FinitePairMappingBase", "",
                "def lookup (code : Nat) : PairId :=",
                f"  {routed_module_expr(children)}", "", f"end {module}", "",
            ]
            path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
            write_generated(path, lines)
            next_level.append((module, children[0][1], children[-1][2]))
        current_lookup = next_level
        level += 1

    lookup_root = current_lookup[0][0]
    lookup_module = "MainTheory.Generated.PairProvenance.Distinct.LookupData"
    lines = [
        HEADER, f"import {lookup_root}", "", f"namespace {lookup_module}", "",
        "open MainTheory.FinitePipeline",
        "open MainTheory.Generated.FinitePairMappingBase",
        f"open {lookup_base}", "",
        f"def lookupCode (code : Nat) : PairId := {lookup_root}.lookup code", "",
        "def lookupPair (pair : FiberPair) : PairId := lookupCode (pairCode pair)", "",
        f"end {lookup_module}", "",
    ]
    path = out_dir.joinpath(*lookup_module.split(".")[2:]).with_suffix(".lean")
    write_generated(path, lines)

    distinct_base = "MainTheory.Generated.PairProvenance.Distinct.Base"
    lines = [
        HEADER, f"import {lookup_module}", "", f"namespace {distinct_base}", "",
        "open MainTheory.FinitePipeline",
        "open MainTheory.Generated.FinitePairMappingBase",
        f"open {lookup_module}", "",
        "def pairIdAt (start count : Nat) (bound : start + count <= 11422)",
        "    (i : Fin count) : PairId :=",
        "  ⟨start + i.val, by omega⟩", "",
        "/-- A contiguous payload block on which `lookupPair` is a left inverse. -/",
        "structure LeftInverseBlock (start count : Nat)",
        "    (bound : start + count <= 11422) where",
        "  pairs : Segment FiberPair count",
        "  exactAt : (i : Fin count) →",
        "    lookupPair (pairs i) = pairIdAt start count bound i", "",
        "def LeftInverseBlock.append {start leftCount rightCount : Nat}",
        "    {leftBound : start + leftCount <= 11422}",
        "    {rightBound : start + leftCount + rightCount <= 11422}",
        "    {wholeBound : start + (leftCount + rightCount) <= 11422}",
        "    (left : LeftInverseBlock start leftCount leftBound)",
        "    (right : LeftInverseBlock (start + leftCount) rightCount rightBound) :",
        "    LeftInverseBlock start (leftCount + rightCount) wholeBound where",
        "  pairs := Segment.append left.pairs right.pairs",
        "  exactAt := by",
        "    intro i",
        "    refine Fin.addCases (fun j => ?_) (fun j => ?_) i",
        "    · change lookupPair",
        "        (Fin.append left.pairs right.pairs (Fin.castAdd rightCount j)) =",
        "        pairIdAt start (leftCount + rightCount) wholeBound",
        "          (Fin.castAdd rightCount j)",
        "      rw [Fin.append_left]",
        "      simpa [pairIdAt] using left.exactAt j",
        "    · change lookupPair",
        "        (Fin.append left.pairs right.pairs (Fin.natAdd leftCount j)) =",
        "        pairIdAt start (leftCount + rightCount) wholeBound",
        "          (Fin.natAdd leftCount j)",
        "      rw [Fin.append_right]",
        "      simpa [pairIdAt, Nat.add_assoc] using right.exactAt j", "",
        f"end {distinct_base}", "",
    ]
    path = out_dir.joinpath(*distinct_base.split(".")[2:]).with_suffix(".lean")
    write_generated(path, lines)

    exact_leaves: list[tuple[str, int, int]] = []
    for shard, (payload_module, start, count) in enumerate(payload_leaves):
        module = ("MainTheory.Generated.PairProvenance.Distinct.Exact."
                  f"Shard{shard:03d}")
        exact_leaves.append((module, start, count))
        lines = [
            HEADER, f"import {distinct_base}", f"import {payload_module}", "",
            f"namespace {module}", "",
            "open MainTheory.Generated.FinitePairMappingBase",
            f"open {distinct_base}", "",
            "set_option maxRecDepth 1000000",
            "set_option maxHeartbeats 4000000", "",
            f"def block : LeftInverseBlock {start} {count} (by omega) where",
            f"  pairs := {payload_module}.pairs",
            "  exactAt := by",
            "    intro i",
            "    fin_cases i <;> decide", "", f"end {module}", "",
        ]
        path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)

    current_exact = exact_leaves
    level = 0
    while len(current_exact) > 1:
        next_level = []
        for node_index, offset in enumerate(range(0, len(current_exact), 8)):
            children = current_exact[offset:offset + 8]
            start = children[0][1]
            count = sum(child[2] for child in children)
            module = ("MainTheory.Generated.PairProvenance.Distinct.Exact."
                      f"NodeL{level:02d}N{node_index:03d}")
            lines = [HEADER]
            lines += [f"import {child[0]}" for child in children]
            lines += [
                "", f"namespace {module}", "", f"open {distinct_base}", "",
                f"def block : LeftInverseBlock {start} {count} (by omega) :=",
                "  " + balanced_expr(
                    [f"{child[0]}.block" for child in children],
                    "LeftInverseBlock.append"), "", f"end {module}", "",
            ]
            path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
            write_generated(path, lines)
            next_level.append((module, start, count))
        current_exact = next_level
        level += 1

    exact_root, start, count = current_exact[0]
    if start != 0 or count != 11422:
        raise ValueError("distinctness hierarchy does not cover every pair id")
    module = "MainTheory.Generated.FinitePairDistinctness"
    lines = [
        HEADER, f"import {exact_root}", f"import {pair_module}", "",
        f"namespace {module}", "",
        "open MainTheory.FinitePipeline",
        "open MainTheory.Generated.FinitePairMappingBase",
        f"open {distinct_base}", f"open {lookup_module}", "",
        f"def block : LeftInverseBlock 0 11422 (by omega) := {exact_root}.block", "",
        "theorem block_pairs_eq :",
        f"    block.pairs = {pair_module}.pairs := by rfl", "",
        "/-- The generated lookup is a kernel-checked left inverse at every",
        "one of the 11,422 table indices. -/",
        "theorem lookupAt (i : PairId) :",
        f"    lookupPair ({pair_module}.pairAtId i) = i := by",
        "  have h := block.exactAt i",
        "  rw [block_pairs_eq] at h",
        f"  simpa [{pair_module}.pairAtId, pairIdAt] using h", "",
        "theorem lookupPair_leftInverse :",
        f"    Function.LeftInverse lookupPair {pair_module}.pairAtId := lookupAt", "",
        "/-- No two table indices carry the same payload. -/",
        "theorem pairAtId_injective :",
        f"    Function.Injective {pair_module}.pairAtId := by",
        "  intro i j hij",
        "  have h := congrArg lookupPair hij",
        "  rw [lookupAt i, lookupAt j] at h",
        "  exact h", "",
        "/-- An explicit embedding witnesses that the payload image contains",
        "11,422 distinct values. -/",
        "def pairEmbedding : PairId ↪ FiberPair where",
        f"  toFun := {pair_module}.pairAtId",
        "  inj' := pairAtId_injective", "",
        f"end {module}", "",
    ]
    write_generated(out_dir / "FinitePairDistinctness.lean", lines)
    return module


def emit_record_base(pair_module: str, out_dir: Path) -> str:
    module = "MainTheory.Generated.FinitePairRecordBase"
    lines = [
        HEADER, f"import {pair_module}", "", f"namespace {module}", "",
        "open MainTheory",
        "open MainTheory.Generated.FinitePairMappingBase", "",
        "abbrev RecordId := Fin 12768", "",
        f"def pairAtId (i : PairId) : FinitePipeline.FiberPair := {pair_module}.pairAtId i", "",
        "def Matches (pairId : PairId) (record : OuterEnumeration.RawRecord) : Prop :=",
        "  pairAtId pairId = OuterCompleteness.recordFiberPair record", "",
        "/-- A bounded block of rows together with its exact semantic source.",
        "Blocks compose without materializing all rows in one term. -/",
        "structure RecordBlock (count : ℕ) where",
        "  ids : Segment PairId count",
        "  records : Segment OuterEnumeration.RawRecord count",
        "  exactAt : Segment.Pointwise Matches ids records",
        "  expectedRecords : List OuterEnumeration.RawRecord",
        "  records_eq_expected : List.ofFn records = expectedRecords", "",
        "def RecordBlock.empty : RecordBlock 0 where",
        "  ids := fun i => Fin.elim0 i",
        "  records := fun i => Fin.elim0 i",
        "  exactAt := by intro i; exact Fin.elim0 i",
        "  expectedRecords := []",
        "  records_eq_expected := rfl", "",
        "def RecordBlock.append {m n : ℕ}",
        "    (left : RecordBlock m) (right : RecordBlock n) : RecordBlock (m + n) where",
        "  ids := Segment.append left.ids right.ids",
        "  records := Segment.append left.records right.records",
        "  exactAt := Segment.Pointwise.append left.exactAt right.exactAt",
        "  expectedRecords := left.expectedRecords ++ right.expectedRecords",
        "  records_eq_expected := by",
        "    change List.ofFn (Fin.append left.records right.records) =",
        "      left.expectedRecords ++ right.expectedRecords",
        "    rw [List.ofFn_fin_append, left.records_eq_expected,",
        "      right.records_eq_expected]", "",
        f"end {module}", "",
    ]
    write_generated(out_dir / "FinitePairRecordBase.lean", lines)
    return module


def emit_exact_shards(data: dict, records: list[tuple[int, int, tuple[int, ...], int, int]],
                      chunks: list[tuple[int, int, int, int, int]],
                      record_base: str, out_dir: Path
                      ) -> tuple[list[tuple[str, int, int, int, int]], int]:
    pair_table = [tuple(row) for row in data["pair_table"]]
    record_ids = data["record_pair_ids"]
    chunk_modules: list[tuple[str, int, int, int, int]] = []
    shard_number = 0
    for q, m, a0, chunk_start, chunk_count in chunks:
        shard_modules: list[str] = []
        chunk_stop = chunk_start + chunk_count
        for start in range(chunk_start, chunk_stop, EXACT_SHARD_SIZE):
            stop = min(start + EXACT_SHARD_SIZE, chunk_stop)
            module = f"MainTheory.Generated.PairProvenance.Exact.Shard{shard_number:03d}"
            shard_modules.append(module)
            ids = record_ids[start:stop]
            literals = []
            for index in range(start, stop):
                rq, rm, angle, mask0, mask1 = records[index]
                pid = record_ids[index]
                if pair_table[pid] != (rq, rm, mask0, mask1):
                    raise ValueError(f"record {index} maps to an incorrect pair id {pid}")
                literals.append(raw_record_literal(rq, rm, angle))
            count = stop - start
            lines = [
                HEADER,
                f"import {record_base}",
                "",
                f"namespace {module}", "",
                "open MainTheory",
                "open MainTheory.Generated.FinitePairMappingBase",
                f"open {record_base}",
                "",
                "set_option maxRecDepth 1000000",
                "set_option maxHeartbeats 4000000",
                "",
            ]
            lines += assigned("idArray", "Array PairId", array_literal(ids))
            lines += ["", f"theorem idArray_size : idArray.size = {count} := by decide", ""]
            lines += ["def recordArray : Array OuterEnumeration.RawRecord := #["]
            lines += [f"  {literal}" + ("," if i + 1 < len(literals) else "")
                      for i, literal in enumerate(literals)]
            lines += [
                "]", "", f"theorem recordArray_size : recordArray.size = {count} := by decide", "",
                f"def ids : Segment PairId {count} := fun i =>",
                "  idArray[Fin.cast idArray_size.symm i]", "",
                f"def records : Segment OuterEnumeration.RawRecord {count} := fun i =>",
                "  recordArray[Fin.cast recordArray_size.symm i]", "",
                "theorem exactAt : Segment.Pointwise Matches ids records := by",
                "  intro i",
                "  fin_cases i <;> decide", "",
                f"end {module}", "",
            ]
            path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
            write_generated(path, lines)
            shard_number += 1

        chunk_module = f"MainTheory.Generated.PairProvenance.Chunk.Q{q:02d}M{m:02d}A{a0:02d}"
        chunk_modules.append((chunk_module, q, m, a0, chunk_count))
        # Keep the record-base import even for genuinely empty chunks (there are two
        # of them), where no exact-row shard exists to provide it transitively.
        lines = [HEADER, f"import {record_base}"]
        lines += [f"import {module}" for module in shard_modules]
        lines += [
            "", f"namespace {chunk_module}", "",
            "open MainTheory",
            "open MainTheory.Generated.FinitePairMappingBase",
            f"open {record_base}",
            "", "set_option maxRecDepth 1000000", "set_option maxHeartbeats 8000000", "",
        ]
        if shard_modules:
            ids_expr = balanced_expr([f"{name}.ids" for name in shard_modules],
                                     "Segment.append")
            records_expr = balanced_expr([f"{name}.records" for name in shard_modules],
                                         "Segment.append")
            exact_expr = balanced_expr([f"{name}.exactAt" for name in shard_modules],
                                       "Segment.Pointwise.append")
        else:
            ids_expr = "fun i => Fin.elim0 i"
            records_expr = "fun i => Fin.elim0 i"
            exact_expr = "by intro i; exact Fin.elim0 i"
        lines += [
            f"def ids : Segment PairId {chunk_count} := {ids_expr}", "",
            f"def records : Segment OuterEnumeration.RawRecord {chunk_count} :=",
            f"  {records_expr}", "",
            "theorem exactAt : Segment.Pointwise Matches ids records :=",
            f"  {exact_expr}",
        ]
        lines += [
            "", "def expectedRecords : List OuterEnumeration.RawRecord :=",
            f"  (OuterEnumeration.nonemptyAngleChunk {q} {m} {a0}).map fun a =>",
            f"    {{ q := {q}, m := {m}, a := a }}", "",
            "/-- This checks the literal records against the actual executable chunk,",
            "including order and the nonempty-fiber filter. -/",
            "theorem records_eq_expected :",
            "    List.ofFn records = expectedRecords := by decide", "",
            f"def segment : RecordBlock {chunk_count} where",
            "  ids := ids",
            "  records := records",
            "  exactAt := exactAt",
            "  expectedRecords := expectedRecords",
            "  records_eq_expected := records_eq_expected", "",
            f"end {chunk_module}", "",
        ]
        path = out_dir.joinpath(*chunk_module.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)
    return chunk_modules, shard_number


def emit_record_aggregate(
        chunk_modules: list[tuple[str, int, int, int, int]], record_base: str,
        out_dir: Path) -> str:
    """Aggregate records through the actual q/m/a₀ loop hierarchy.

    No module imports all 85 chunks.  Each (q,m) node imports at most nine
    chunks, each q node imports at most three pair nodes, and the outer root
    imports eight q nodes.  Explicit empty blocks preserve the right-associated
    `List.flatMap` shape, so the final semantic link is structural rather than
    a 12,768-row decision procedure.
    """
    by_pair: dict[tuple[int, int], list[tuple[str, int]]] = {}
    pair_order: list[tuple[int, int]] = []
    for name, q, m, _a0, count in chunk_modules:
        key = (q, m)
        if key not in by_pair:
            by_pair[key] = []
            pair_order.append(key)
        by_pair[key].append((name, count))

    pair_nodes: list[tuple[str, int, int, int]] = []
    for q, m in pair_order:
        children = by_pair[(q, m)]
        total = sum(count for _name, count in children)
        node = f"MainTheory.Generated.PairProvenance.Record.PairQ{q:02d}M{m:02d}"
        lines = [HEADER]
        lines += [f"import {name}" for name, _count in children]
        expr = right_assoc_expr(
            [f"{name}.segment" for name, _count in children],
            "RecordBlock.append", "RecordBlock.empty")
        lines += [
            "", f"namespace {node}", "",
            "open MainTheory.Generated.FinitePairMappingBase", "",
            f"open {record_base}", "",
            f"def segment : RecordBlock {total} :=", f"  {expr}", "",
            f"end {node}", "",
        ]
        path = out_dir.joinpath(*node.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)
        pair_nodes.append((node, q, m, total))

    by_q: dict[int, list[tuple[str, int]]] = {}
    q_order: list[int] = []
    for name, q, _m, count in pair_nodes:
        if q not in by_q:
            by_q[q] = []
            q_order.append(q)
        by_q[q].append((name, count))

    q_nodes: list[tuple[str, int, int]] = []
    for q in q_order:
        children = by_q[q]
        total = sum(count for _name, count in children)
        node = f"MainTheory.Generated.PairProvenance.Record.ModulusQ{q:02d}"
        lines = [HEADER]
        lines += [f"import {name}" for name, _count in children]
        expr = right_assoc_expr(
            [f"{name}.segment" for name, _count in children],
            "RecordBlock.append", "RecordBlock.empty")
        lines += [
            "", f"namespace {node}", "",
            "open MainTheory.Generated.FinitePairMappingBase", "",
            f"open {record_base}", "",
            f"def segment : RecordBlock {total} :=", f"  {expr}", "",
            f"end {node}", "",
        ]
        path = out_dir.joinpath(*node.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)
        q_nodes.append((node, q, total))

    root = "MainTheory.Generated.PairProvenance.Record.Outer"
    lines = [HEADER]
    lines += [f"import {name}" for name, _q, _count in q_nodes]
    root_expr = right_assoc_expr(
        [f"{name}.segment" for name, _q, _count in q_nodes],
        "RecordBlock.append", "RecordBlock.empty")
    lines += [
        "", f"namespace {root}", "",
        "open MainTheory",
        "open MainTheory.Generated.FinitePairMappingBase", "",
        f"open {record_base}", "",
        "def segment : RecordBlock 12768 :=", f"  {root_expr}", "",
        "/-- The hierarchy has exactly the definitional q/m/a₀ flatMap shape",
        "of the trusted outer enumeration; no literal-row count is used here. -/",
        "theorem expectedRecords_eq_outer :",
        "    segment.expectedRecords = OuterEnumeration.nonemptyFiberRecords := by",
        "  rfl", "",
        f"end {root}", "",
    ]
    path = out_dir.joinpath(*root.split(".")[2:]).with_suffix(".lean")
    write_generated(path, lines)

    module = "MainTheory.Generated.FinitePairRecordData"
    lines = [HEADER, f"import {root}"]
    lines += [
        "", f"namespace {module}", "",
        "open MainTheory",
        "open MainTheory.Generated.FinitePairMappingBase", "",
        f"open {record_base}", "",
        f"def segment : RecordBlock 12768 := {root}.segment", "",
        "def ids : Segment PairId 12768 := segment.ids", "",
        "def records : Segment OuterEnumeration.RawRecord 12768 := segment.records", "",
        "theorem exactAt : Segment.Pointwise Matches ids records := segment.exactAt", "",
        "theorem records_eq_outer :",
        "    List.ofFn records = OuterEnumeration.nonemptyFiberRecords := by",
        "  exact segment.records_eq_expected.trans",
        f"    {root}.expectedRecords_eq_outer", "",
    ]
    lines += [
        "def recordPairId (i : RecordId) : PairId := ids i", "",
        "def generatedRecord (i : RecordId) : OuterEnumeration.RawRecord := records i", "",
        "theorem exactRecordId (i : RecordId) :",
        "    pairAtId (recordPairId i) =",
        "      OuterCompleteness.recordFiberPair (generatedRecord i) := by",
        "  have h := exactAt i",
        "  simpa [Matches, recordPairId, generatedRecord] using h", "",
        "/-- Coverage of the actual outer list by the generated record blocks. -/",
        "theorem outerRecord_has_generated (i : PairProvenance.OuterRecordIndex) :",
        "    ∃ j : RecordId, generatedRecord j = PairProvenance.outerRecord i := by",
        "  have hmem : PairProvenance.outerRecord i ∈ List.ofFn records := by",
        "    rw [records_eq_outer]",
        "    exact PairProvenance.outerRecord_mem i",
        "  rcases List.mem_ofFn.mp hmem with ⟨j, hj⟩",
        "  exact ⟨j, by simpa [generatedRecord] using hj⟩", "",
        "/-- Conversely, every generated row is an actual indexed outer record. -/",
        "theorem generatedRecord_has_outer (j : RecordId) :",
        "    ∃ i : PairProvenance.OuterRecordIndex,",
        "      PairProvenance.outerRecord i = generatedRecord j := by",
        "  have hmem : generatedRecord j ∈ OuterEnumeration.nonemptyFiberRecords := by",
        "    rw [← records_eq_outer]",
        "    exact List.mem_ofFn.mpr ⟨j, rfl⟩",
        "  rcases List.mem_iff_get.mp hmem with ⟨i, hi⟩",
        "  exact ⟨i, by simpa [PairProvenance.outerRecord] using hi⟩", "",
        "/-- A contiguous block of table-entry witnesses.  Storing only",
        "`inverseVal` makes proof irrelevance and segment concatenation cheap. -/",
        "structure WitnessSegment (start count : ℕ) (bound : start + count ≤ 11422) where",
        "  witnesses : Segment RecordId count",
        "  inverseVal : ∀ i, (recordPairId (witnesses i)).val = start + i.val", "",
        "def WitnessSegment.append {start leftCount rightCount : ℕ}",
        "    {leftBound : start + leftCount ≤ 11422}",
        "    {rightBound : start + leftCount + rightCount ≤ 11422}",
        "    {wholeBound : start + (leftCount + rightCount) ≤ 11422}",
        "    (left : WitnessSegment start leftCount leftBound)",
        "    (right : WitnessSegment (start + leftCount) rightCount rightBound) :",
        "    WitnessSegment start (leftCount + rightCount) wholeBound where",
        "  witnesses := Segment.append left.witnesses right.witnesses",
        "  inverseVal := by",
        "    intro i",
        "    refine Fin.addCases (fun j => ?_) (fun j => ?_) i",
        "    · change (recordPairId",
        "        (Fin.append left.witnesses right.witnesses (Fin.castAdd rightCount j))).val =",
        "        start + j.val",
        "      rw [Fin.append_left]",
        "      exact left.inverseVal j",
        "    · change (recordPairId",
        "        (Fin.append left.witnesses right.witnesses (Fin.natAdd leftCount j))).val =",
        "        start + (leftCount + j.val)",
        "      rw [Fin.append_right]",
        "      simpa only [Nat.add_assoc] using right.inverseVal j", "",
        f"end {module}", "",
    ]
    write_generated(out_dir / "FinitePairRecordData.lean", lines)
    return module


def emit_inverse_shards(data: dict, record_module: str, record_base: str,
                        out_dir: Path) -> list[tuple[str, int, int]]:
    witnesses = data["pair_witness_records"]
    modules: list[tuple[str, int, int]] = []
    for shard, start in enumerate(range(0, len(witnesses), INVERSE_SHARD_SIZE)):
        stop = min(start + INVERSE_SHARD_SIZE, len(witnesses))
        module = f"MainTheory.Generated.PairProvenance.Inverse.Shard{shard:03d}"
        count = stop - start
        modules.append((module, start, count))
        lines = [
            HEADER, f"import {record_module}", "",
            f"namespace {module}", "",
            "open MainTheory.Generated.FinitePairMappingBase",
            f"open {record_base}",
            f"open {record_module}", "",
            "set_option maxRecDepth 1000000", "set_option maxHeartbeats 4000000", "",
        ]
        lines += assigned("witnessArray", "Array RecordId",
                          array_literal(witnesses[start:stop]))
        lines += [
            "", f"theorem witnessArray_size : witnessArray.size = {count} := by decide", "",
            f"def witnesses : Segment RecordId {count} := fun i =>",
            "  witnessArray[Fin.cast witnessArray_size.symm i]", "",
            f"def segment : WitnessSegment {start} {count} (by omega) where",
            "  witnesses := witnesses",
            "  inverseVal := by",
            "    intro i",
            "    fin_cases i <;> decide", "",
            f"end {module}", "",
        ]
        path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)
    return modules


def emit_inverse_aggregate(
        leaves: list[tuple[str, int, int]], record_module: str, record_base: str,
        out_dir: Path) -> str:
    """Build a fanout-8 hierarchy; no module imports all 179 leaves."""
    current = leaves
    level = 0
    while len(current) > 1:
        next_level: list[tuple[str, int, int]] = []
        for node_index, offset in enumerate(range(0, len(current), 8)):
            children = current[offset:offset + 8]
            start = children[0][1]
            count = sum(child[2] for child in children)
            module = ("MainTheory.Generated.PairProvenance.Inverse."
                      f"NodeL{level:02d}N{node_index:03d}")
            lines = [HEADER]
            lines += [f"import {child[0]}" for child in children]
            lines += [
                "", f"namespace {module}", "",
                f"open {record_module}", "",
                f"def segment : WitnessSegment {start} {count} (by omega) :=",
                "  " + balanced_expr([f"{child[0]}.segment" for child in children],
                                       "WitnessSegment.append"), "",
                f"end {module}", "",
            ]
            path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
            write_generated(path, lines)
            next_level.append((module, start, count))
        current = next_level
        level += 1

    root, start, count = current[0]
    if start != 0 or count != 11422:
        raise ValueError("inverse hierarchy does not cover all pair ids")
    module = "MainTheory.Generated.PairProvenance.InverseData"
    lines = [HEADER, f"import {root}"]
    lines += [
        "", f"namespace {module}", "",
        "open MainTheory.Generated.FinitePairMappingBase",
        f"open {record_base}",
        f"open {record_module}", "",
        f"def witnessSegment : WitnessSegment 0 11422 (by omega) := {root}.segment", "",
        "def pairWitnessRecord (i : PairId) : RecordId := witnessSegment.witnesses i", "",
        "theorem inverseAt (i : PairId) :",
        "    recordPairId (pairWitnessRecord i) = i := by",
        "  apply Fin.ext",
        "  simpa [pairWitnessRecord] using witnessSegment.inverseVal i", "",
        f"end {module}", "",
    ]
    path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
    write_generated(path, lines)
    return module


def emit_final(record_module: str, record_base: str, inverse_module: str,
               distinct_module: str, out_dir: Path) -> None:
    module = "MainTheory.Generated.FinitePairProvenance"
    lines = [HEADER, f"import {record_module}", f"import {inverse_module}",
             f"import {distinct_module}"]
    lines += [
        "", f"namespace {module}", "",
        "open MainTheory",
        "open MainTheory.Generated.FinitePairMappingBase",
        f"open {record_base}",
        f"open {record_module}", "",
              "noncomputable def generatedIndexForOuter",
              "    (i : PairProvenance.OuterRecordIndex) : RecordId :=",
              "  Classical.choose (outerRecord_has_generated i)", "",
              "theorem generatedIndexForOuter_spec (i : PairProvenance.OuterRecordIndex) :",
              "    generatedRecord (generatedIndexForOuter i) =",
              "      PairProvenance.outerRecord i :=",
              "  Classical.choose_spec (outerRecord_has_generated i)", "",
              "noncomputable def table : PairProvenance.Table where",
              "  pairCount := 11422",
              "  pairs := pairAtId",
              "  recordToPair := fun i => recordPairId (generatedIndexForOuter i)", "",
              "theorem exactRecord (i : PairProvenance.OuterRecordIndex) :",
              "    table.pairAt (table.recordToPair i) = PairProvenance.outerPair i := by",
              "  change pairAtId (recordPairId (generatedIndexForOuter i)) =",
              "    OuterCompleteness.recordFiberPair (PairProvenance.outerRecord i)",
              "  rw [← generatedIndexForOuter_spec i]",
              "  exact exactRecordId (generatedIndexForOuter i)", "",
              "theorem noGhostIndex (j : PairId) :",
              "    ∃ i : PairProvenance.OuterRecordIndex,",
              "      table.pairAt j = PairProvenance.outerPair i := by",
              f"  let recordId := {inverse_module}.pairWitnessRecord j",
              "  rcases generatedRecord_has_outer recordId with ⟨i, hi⟩",
              "  refine ⟨i, ?_⟩",
              "  change pairAtId j =",
              "    OuterCompleteness.recordFiberPair (PairProvenance.outerRecord i)",
              "  rw [hi]",
              f"  rw [← {inverse_module}.inverseAt j]",
              "  exact exactRecordId recordId", "",
              "/-- The generated 12,768-to-11,422 map satisfies both semantic",
              "directions required by `PairProvenance.Table.Validity`. -/",
              "noncomputable def validity : table.Validity where",
              "  exactRecord := exactRecord",
              "  noGhostIndex := noGhostIndex", "",
              "/-- The table index is a genuine deduplication index: different",
              "indices carry different exact fiber-pair payloads. -/",
              "theorem pairAt_injective : Function.Injective table.pairAt := by",
              "  intro i j hij",
              f"  exact {distinct_module}.pairAtId_injective hij", "",
              "noncomputable def deduplicated : table.Deduplicated where",
              "  pairAt_injective := pairAt_injective", "",
              "theorem exact_image : table.image = PairProvenance.outerImage :=",
              "  validity.image_eq_outerImage", "",
              "theorem every_entry_has_outer_record (j : Fin table.pairCount) :",
              "    Exists fun i : PairProvenance.OuterRecordIndex =>",
              "      table.pairAt j = PairProvenance.outerPair i :=",
              "  validity.noGhostPair j", "",
              f"end {module}", ""]
    write_generated(out_dir / "FinitePairProvenance.lean", lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default="results/main-pipeline-certificates.json")
    parser.add_argument("--out", default="MainTheory/Generated")
    args = parser.parse_args()

    with open(args.input, encoding="utf-8") as handle:
        data = json.load(handle)
    if len(data["pair_table"]) != 11422:
        raise ValueError("expected exactly 11,422 pair-table entries")
    if len(data["record_pair_ids"]) != 12768:
        raise ValueError("expected exactly 12,768 record ids")
    if len(data["pair_witness_records"]) != 11422:
        raise ValueError("expected one witness for every pair-table entry")

    records, chunks = outer_records()
    if len(records) != 12768 or len(chunks) != 85:
        raise ValueError("recomputed Lean-shaped outer enumeration has wrong size")
    for pair_id, record_index in enumerate(data["pair_witness_records"]):
        if not 0 <= record_index < len(records):
            raise ValueError(f"pair witness {pair_id} is out of range")
        if data["record_pair_ids"][record_index] != pair_id:
            raise ValueError(f"pair witness {pair_id} does not invert record_pair_ids")

    out_dir = Path(args.out)
    emit_mapping_base(out_dir)
    pair_module, payload_leaves = emit_pair_payload(data, out_dir)
    distinct_module = emit_pair_distinctness(
        data, pair_module, payload_leaves, out_dir)
    record_base = emit_record_base(pair_module, out_dir)
    chunk_modules, exact_shard_count = emit_exact_shards(
        data, records, chunks, record_base, out_dir)
    record_aggregate = emit_record_aggregate(chunk_modules, record_base, out_dir)
    inverse_modules = emit_inverse_shards(
        data, record_aggregate, record_base, out_dir)
    inverse_aggregate = emit_inverse_aggregate(
        inverse_modules, record_aggregate, record_base, out_dir)
    emit_final(record_aggregate, record_base, inverse_aggregate,
               distinct_module, out_dir)
    print(f"emitted {len(chunk_modules)} chunks, "
          f"{exact_shard_count} exact shards, "
          f"{len(inverse_modules)} inverse shards, "
          f"and {len(payload_leaves)} distinctness shards")


if __name__ == "__main__":
    main()
