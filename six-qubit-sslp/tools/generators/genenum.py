"""Emit the exact-enumerator module for the orbits with a forced stabilizer.

For a projective-order-two orbit with `q = 4`, the diagonal gate `D(a;4)` acts
logically as `diag(1,-1)`, so `D(a;4)^2` is scalar on the code.  That square is
the Z-string on the coordinates where `a` is odd, and its sign on a support word
`x` is `(-1)^{sum_{j in S} x_j} = (-1)^{A_a(x)}`, which is `+1` on both fibers
because `A_a(x)` is `0` or `2` modulo four.  So the string fixes the code, and
`SixQubit/Pin.lean` turns that into the whole enumerator:

    weight 1  ->  A = (1, 1, 0, 0, 15, 15, 0)      "E_1^A"
    weight 2  ->  A = (1, 0, 1, 0, 11, 16,  3)     "E_2^A"

Five of the ten realized orbits qualify.  Orbit 21's string has weight four, so
its image needs the manuscript's label-sensitive argument instead, and orbit 45
has `q = 6`, where the square is not a Pauli at all.  Orbits 7, 8 and 9 have
`m = q = 3`, where the cube is the identity and carries no information.

Together with `Orbit<n>Real.lean`, which exhibits a code attaining that
enumerator, this makes the exact weight-enumerator image of each of the five a
single point.

    python tools/run.py generators/genenum.py
    python tools/run.py generators/genenum.py --check
"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
import genreal as G                                          # noqa: E402

OUT = os.path.join(REPO, 'SixQubit')
NL = chr(10)

# unnormalized coefficients, keyed by the weight of the forced stabilizer
VALUES = {1: (4, 0, 0, 60, 60, 0), 2: (0, 4, 0, 44, 64, 12)}
NAMES = {1: 'E_1^A = (1, 1, 0, 0, 15, 15, 0)',
         2: 'E_2^A = (1, 0, 1, 0, 11, 16, 3)'}
BNAMES = {1: 'E_1^B = (1, 1, 0, 30, 45, 33, 18)',
          2: 'E_2^B = (1, 0, 1, 24, 35, 40, 27)'}


def forced_mask(rec):
    """The Z-mask of `D(a;q)^m`, or None when that square is not a Pauli."""
    q, m, a = rec['q'], rec['m'], rec['a']
    ang = [(m * ai) % q for ai in a]
    if q % 2 or not all(v in (0, q // 2) for v in ang):
        return None
    return tuple(1 if v == q // 2 else 0 for v in ang)


def emit(oid, rec, zm, w0, w1):
    q, a = rec['q'], rec['a']
    r0 = sum(ai * xi for ai, xi in zip(a, sorted(w0)[0])) % q
    r1 = sum(ai * xi for ai, xi in zip(a, sorted(w1)[0])) % q
    wt = sum(zm)
    a1, a2, a3, a4, a5, a6 = VALUES[wt]
    bits = ', '.join('true' if b else 'false' for b in zm)
    branch = '.1' if wt == 1 else '.2'
    return '''import Mathlib
import SS.HilbertKL
import SixQubit.Pin
import SixQubit.BEnumerator
import SixQubit.Orbit{oid}Real

/-!
# Orbit {oid}: the exact weight-enumerator image

Orbit {oid} has `q = {q}`, `m = {m}` and angle vector `a = {a}`.  The diagonal gate
acts logically as `diag(1,-1)`, so its square is scalar on any code in the
orbit; that square is the `Z`-string on the coordinates where `a` is odd, here
`{bitsdoc}`, of Pauli weight {wt}.

Its sign on a support word `x` is `(-1)^{{A_a(x)}}`, and `A_a(x)` is `0` or `2`
modulo four on the two fibers, so the sign is `+1` and the string fixes the
code.  That is a finite condition over the two supports and is decided here.

`SixQubit/Pin.lean` then squeezes: a fixing Pauli of weight {wt} forces
`Aco_{wt} >= 4`, the shadow inequality of `SixQubit/Shadow.lean` forces
`Aco_1 + Aco_2 + Aco_3 <= 4`, and the coefficients are nonnegative, so the
triple has no freedom.  The six-qubit MacWilliams normal form does the rest.

The conclusion holds for *every* code in the orbit, not only the one exhibited
in `SixQubit/Orbit{oid}Real.lean`; that module supplies a code attaining it, so
the exact image is a single point:

    {name}

Generated by `tools/generators/genenum.py`.
-/

namespace SixQubit.Orbit{oid}Enum

open SS.MacWilliams SixQubit.Pin SixQubit.Orbit{oid}Real

/-- The forced stabilizer `D(a;{q})^{m}`, as a `Z`-mask. -/
def zmask : SS.BitString 6 := ![{bits}]

/-- The mask has even overlap with every bottom word. -/
theorem zmask_L0 : ∀ s ∈ L0, SS.bdot zmask s = false := by decide

/-- The mask has even overlap with every top word. -/
theorem zmask_L1 : ∀ s ∈ L1, SS.bdot zmask s = false := by decide

/-- Its Pauli weight. -/
theorem zmask_wt :
    (⟨fun _ => false, zmask⟩ : SS.PauliString 6).wt = {wt} := by decide

/-- **The exact weight-enumerator image of orbit {oid}.**

Any exact `((6,2,3))` code supported in the two fibers of orbit {oid} has the
enumerator `{name}`, in the unnormalized form where `A_0 = 4`. -/
theorem enumerator_unique (c d : SS.State 6 ℂ)
    (hc : ∀ s, s ∉ L0 → c s = 0) (hd : ∀ s, s ∉ L1 → d s = 0)
    (hnc : SS.innerC c c = 1) (hnd : SS.innerC d d = 1)
    (hdist : SS.HasDistance ![c, d] 3) :
    Aco ![c, d] 1 = {a1} ∧ Aco ![c, d] 2 = {a2} ∧ Aco ![c, d] 3 = {a3}
      ∧ Aco ![c, d] 4 = {a4} ∧ Aco ![c, d] 5 = {a5}
      ∧ Aco ![c, d] 6 = {a6} := by
  have hnorm : ∀ k, SS.innerC ((![c, d] : Fin 2 → SS.State 6 ℂ) k)
      ((![c, d] : Fin 2 → SS.State 6 ℂ) k) = 1 := by
    intro k
    fin_cases k
    · exact hnc
    · exact hnd
  have hG : ∀ k, SS.pauliAct (⟨fun _ => false, zmask⟩ : SS.PauliString 6)
      ((![c, d] : Fin 2 → SS.State 6 ℂ) k)
        = (![c, d] : Fin 2 → SS.State 6 ℂ) k := by
    intro k
    fin_cases k
    · exact zstring_fixes c L0 hc zmask zmask_L0
    · exact zstring_fixes d L1 hd zmask zmask_L1
  exact (enumerator_of_forced ![c, d] hdist (Aco_zero _ hnorm) hnorm _ hG){branch}
    zmask_wt

/-! ## The hypothesis really is the orbit condition

`L0` and `L1` are not merely *contained* in the two fibers, they *are* the two
fibers.  Without that, `enumerator_unique` would be about codes supported in one
particular list of words rather than about every code in the orbit, and the
difference is not cosmetic: for orbits 7, 8, 9, 21 and 45 the exhibited support
is a proper subset of its fiber, which is exactly why those need a
support-reduction argument before anything else. -/

/-- The bottom support list is the whole residue-{r0} fiber. -/
theorem L0_eq_fiber :
    (Finset.univ.filter (fun x : SS.BitString 6 => SS.weight av x = {r0}))
      = L0.toFinset := by decide

/-- The top support list is the whole residue-{r1} fiber. -/
theorem L1_eq_fiber :
    (Finset.univ.filter (fun x : SS.BitString 6 => SS.weight av x = {r1}))
      = L1.toFinset := by decide

/-- **The exact image, stated over the fibers.**

The same conclusion as `enumerator_unique`, with the support hypothesis written
as membership of the orbit's fibers rather than of a list. -/
theorem enumerator_unique_fiber (c d : SS.State 6 ℂ)
    (hc : ∀ s, SS.weight av s ≠ {r0} → c s = 0)
    (hd : ∀ s, SS.weight av s ≠ {r1} → d s = 0)
    (hnc : SS.innerC c c = 1) (hnd : SS.innerC d d = 1)
    (hdist : SS.HasDistance ![c, d] 3) :
    Aco ![c, d] 1 = {a1} ∧ Aco ![c, d] 2 = {a2} ∧ Aco ![c, d] 3 = {a3}
      ∧ Aco ![c, d] 4 = {a4} ∧ Aco ![c, d] 5 = {a5}
      ∧ Aco ![c, d] 6 = {a6} := by
  refine enumerator_unique c d (fun s hs => hc s ?_) (fun s hs => hd s ?_)
    hnc hnd hdist
  · intro hw
    exact hs (List.mem_toFinset.mp (L0_eq_fiber ▸ Finset.mem_filter.mpr
      ⟨Finset.mem_univ s, hw⟩))
  · intro hw
    exact hs (List.mem_toFinset.mp (L1_eq_fiber ▸ Finset.mem_filter.mpr
      ⟨Finset.mem_univ s, hw⟩))

/-- The exhibited code of `SixQubit/Orbit{oid}Real.lean` satisfies the hypotheses,
so the image is nonempty and therefore exactly one point. -/
theorem enumerator_attained :
    Aco ![w0, w1] 1 = {a1} ∧ Aco ![w0, w1] 2 = {a2} ∧ Aco ![w0, w1] 3 = {a3}
      ∧ Aco ![w0, w1] 4 = {a4} ∧ Aco ![w0, w1] 5 = {a5}
      ∧ Aco ![w0, w1] 6 = {a6} :=
  enumerator_unique w0 w1 w0_vanishes w1_vanishes w0_normalized w1_normalized
    is_code

/-! ## The complete `A`/`B` enumerator pair -/

/-- **The exact `A`- and `B`-enumerator image over the complete orbit-{oid}
fibers.**  `IsE{wt}A` and `IsE{wt}B` use the common unnormalised convention
`Aco = 4 A`, `Bco = 4 B`; hence the second component is exactly
`{bname}` after division by four. -/
theorem enumerator_pair_unique_fiber (c d : SS.State 6 ℂ)
    (hc : ∀ s, SS.weight av s ≠ {r0} → c s = 0)
    (hd : ∀ s, SS.weight av s ≠ {r1} → d s = 0)
    (hnc : SS.innerC c c = 1) (hnd : SS.innerC d d = 1)
    (hdist : SS.HasDistance ![c, d] 3) :
    IsE{wt}A ![c, d] ∧ IsE{wt}B ![c, d] := by
  have hnorm : ∀ k, SS.innerC ((![c, d] : Fin 2 → SS.State 6 ℂ) k)
      ((![c, d] : Fin 2 → SS.State 6 ℂ) k) = 1 := by
    intro k
    fin_cases k
    · exact hnc
    · exact hnd
  have hA0 : Aco ![c, d] 0 = 4 := Aco_zero _ hnorm
  rcases enumerator_unique_fiber c d hc hd hnc hnd hdist with
    ⟨hA1, hA2, hA3, hA4, hA5, hA6⟩
  have hA : IsE{wt}A ![c, d] := ⟨hA0, hA1, hA2, hA3, hA4, hA5, hA6⟩
  exact ⟨hA, e{wt}B_of_e{wt}A _ hA⟩

/-- The exhibited orbit-{oid} code attains the complete enumerator pair. -/
theorem enumerator_pair_attained : IsE{wt}A ![w0, w1] ∧ IsE{wt}B ![w0, w1] := by
  have hnorm : ∀ k, SS.innerC ((![w0, w1] : Fin 2 → SS.State 6 ℂ) k)
      ((![w0, w1] : Fin 2 → SS.State 6 ℂ) k) = 1 := by
    intro k
    fin_cases k
    · exact w0_normalized
    · exact w1_normalized
  have hA0 : Aco ![w0, w1] 0 = 4 := Aco_zero _ hnorm
  rcases enumerator_attained with ⟨hA1, hA2, hA3, hA4, hA5, hA6⟩
  have hA : IsE{wt}A ![w0, w1] := ⟨hA0, hA1, hA2, hA3, hA4, hA5, hA6⟩
  exact ⟨hA, e{wt}B_of_e{wt}A _ hA⟩

end SixQubit.Orbit{oid}Enum
'''.format(oid=oid, q=q, m=rec['m'], a=tuple(a), bits=bits, r0=r0, r1=r1,
           bitsdoc=''.join(str(b) for b in zm), wt=wt, name=NAMES[wt],
           bname=BNAMES[wt], branch=branch,
           a1=a1, a2=a2, a3=a3, a4=a4, a5=a5, a6=a6)


def main(argv):
    check_only = '--check' in argv
    want = [int(a) for a in argv if a.isdigit()]
    real, cplx, jobs = G.load_doc()
    print('%-6s %-8s %-6s %-6s %s' % ('orbit', 'z-mask', 'wt', 'fixes', 'image'))
    written = 0
    for oid in (want or G.TARGETS):
        rec = jobs[oid]
        zm = forced_mask(rec)
        if zm is None or sum(zm) not in VALUES:
            print('%-6d %-8s %-6s %-6s %s'
                  % (oid, ''.join(map(str, zm)) if zm else 'not Pauli',
                     sum(zm) if zm else '-', '-', 'no forced stabilizer of weight 1 or 2'))
            continue
        w0 = G.build_word(real, cplx, rec['base'], 0, rec['perm'], rec['t'])
        w1 = G.build_word(real, cplx, rec['base'], 1, rec['perm'], rec['t'])
        if rec['swap']:
            w0, w1 = w1, w0
        ok = all(sum(zi * xi for zi, xi in zip(zm, x)) % 2 == 0
                 for x in list(w0) + list(w1))
        print('%-6d %-8s %-6d %-6s %s'
              % (oid, ''.join(map(str, zm)), sum(zm),
                 'yes' if ok else 'NO', NAMES[sum(zm)]))
        if not ok:
            return 1
        if not check_only:
            io.open(os.path.join(OUT, 'Orbit%dEnum.lean' % oid), 'w',
                    encoding='utf-8', newline=NL).write(emit(oid, rec, zm, w0, w1))
            written += 1
    print()
    print('modules written: %d' % written)
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
