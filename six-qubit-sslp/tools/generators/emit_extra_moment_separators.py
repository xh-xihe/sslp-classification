#!/usr/bin/env python3
"""Certify that every right-rejected coarse row admits no common moment point.

`main.tex` reduces 11,422 labelled pairs to 508 with

    min(affdim S_0, affdim S_delta) >= r_min(q)            six:eq:coarserank

Only the `S_0` clause has a proof in this development: the zero-residue fibre
contains the all-zero word, so its affine and linear ranks agree
(`MaskRankBridge.residueZeroMask_affineRank_eq_span`), and the linear-rank
denominator bound suffices.  The `S_delta` clause needs `q <= beta_r` at the
*affine* rank of the support, which does not follow -- see
`results/coarse-filter-audit.md`.

This generator removes the need for that clause to be sound, without changing
a single number the paper reports.  The generated coarse directory rejects
each discarded row by one of two witnesses; 422 rows carry the right-hand one.
For each of those this emits an exact rational separator -- the Farkas dual of
the moment LP, in the shape `FinitePipeline.SeparatorData` already expects --
proving the row admits no common moment point at all.  A genuine code supplies
its own common moment point, so a right-rejected row can never discard a code,
whatever the status of the clause that rejected it.

The 422 are the 350 rows failing only the `S_delta` clause plus 72 failing
both; all 422 are needed, because in the `.rejectRight` branch of a case
analysis the left-hand argument is not available.

Usage:  python tools/generators/emit_extra_moment_separators.py [--probe N]
"""
import io
import math
import os
import re
import sys
from fractions import Fraction as F

sys.path.insert(0, os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__)))), 'tools'))
import exact_lp                                            # noqa: E402

ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'MainTheory', 'Generated', 'ExtraMoment')
TOP = os.path.join(ROOT, 'MainTheory', 'Generated', 'ExtraMomentData.lean')
PER_SHARD = 8
NL = chr(10)


def words(mask):
    return [x for x in range(64) if (mask >> x) & 1]


def bits(x):
    return [(x >> j) & 1 for j in range(6)]


def phi(x):
    b = bits(x)
    return ([F(b[i]) for i in range(6)] +
            [F(b[i] * b[j]) for i in range(6) for j in range(i + 1, 6)])


def separator(mask0, mask1):
    """An exact integer separator, or None when the pair is moment feasible."""
    P0, P1 = words(mask0), words(mask1)
    if not P0 or not P1:
        return None
    c0 = [phi(x) for x in P0]
    c1 = [phi(y) for y in P1]
    n0, n1 = len(P0), len(P1)
    A = [[F(1)] * n0 + [F(0)] * n1, [F(0)] * n0 + [F(1)] * n1]
    b = [F(1), F(1)]
    for r in range(21):
        A.append([c0[k][r] for k in range(n0)] + [-c1[k][r] for k in range(n1)])
        b.append(F(0))
    status, _, y = exact_lp.solve(A, b)
    exact_lp.check(A, b, status, None, y)
    if status == 'feasible':
        return None
    h = y[2:]
    den = 1
    for v in h:
        den = den * v.denominator // math.gcd(den, v.denominator)
    h = [int(v * den) for v in h]
    g = 0
    for v in h:
        g = math.gcd(g, abs(v))
    if g > 1:
        h = [v // g for v in h]
    lo = max(sum(F(h[k]) * c0[i][k] for k in range(21)) for i in range(n0))
    hi = min(sum(F(h[k]) * c1[i][k] for k in range(21)) for i in range(n1))
    if not lo < hi:
        return None
    return h, lo, hi


def load_pairs():
    src = io.open(os.path.join(ROOT, 'MainTheory', 'Generated',
                               'FinitePairData.lean'), encoding='utf-8').read()
    block = src[src.index('def pairTable'):src.index('theorem pairTable_size')]
    return [tuple(int(x) for x in m)
            for m in re.findall(r'⟨(\d+), (\d+), (\d+), (\d+)⟩', block)]


def reject_right_pairs():
    """Rows the generated coarse directory certifies by its right clause.

    Read straight out of `Generated/Coarse/Input/Shard*.lean`, where each row
    writes its pair literally in a `show DecisionWitness (...)` line."""
    pat = re.compile(
        r'show DecisionWitness \(⟨(\d+), (\d+), (\d+), (\d+)⟩ : FiberPair\)'
        r'\s*\n\s*exact \.(\w+)')
    d = os.path.join(ROOT, 'MainTheory', 'Generated', 'Coarse', 'Input')
    rows = []
    for f in sorted(os.listdir(d)):
        if not (f.startswith('Shard') and f.endswith('.lean')):
            continue
        src = io.open(os.path.join(d, f), encoding='utf-8').read()
        for m in pat.finditer(src):
            q, mm, m0, m1, ctor = m.groups()
            if ctor == 'rejectRight':
                rows.append((int(q), int(mm), int(m0), int(m1)))
    return rows


def rat(v):
    if v.denominator == 1:
        return str(v.numerator)
    return '(%d : ℚ) / %d' % (v.numerator, v.denominator)


def shard(idx, rows):
    lines = [
        '-- Generated by tools/generators/emit_extra_moment_separators.py.',
        '-- Do not edit by hand; regenerate it instead.',
        '',
        'import MainTheory.Generated.FinitePairData',
        'import MainTheory.RealMomentSeparatorBridge',
        '',
        'namespace MainTheory.Generated.ExtraMoment.Shard%02d' % idx,
        '',
        'open MainTheory.FinitePipeline',
        '',
        'set_option maxRecDepth 1000000',
        'set_option maxHeartbeats 4000000',
        '',
    ]
    for (pid, q, m, m0, m1, h, lo, hi) in rows:
        lines += [
            'def pair%d : FiberPair := ⟨%d, %d, %d, %d⟩' % (pid, q, m, m0, m1),
            '',
            'def sep%d : SeparatorData :=' % pid,
            '  { h := [%s],' % ', '.join(str(v) for v in h),
            '    lower := %s, upper := %s }' % (rat(lo), rat(hi)),
            '',
            'theorem sep%d_valid : sep%d.Valid pair%d := by' % (pid, pid, pid),
            '  norm_num [SeparatorData.Valid, pair%d, sep%d, score,'
            % (pid, pid),
            '    listVector21, feature, bit, InMask]',
            '  constructor',
            '  · intro x hx',
            '    fin_cases x <;>',
            '      norm_num [Nat.testBit, Nat.shiftRight_eq_div_pow] at hx <;>',
            '      norm_num [Nat.testBit, Nat.shiftRight_eq_div_pow]',
            '  · intro x hx',
            '    fin_cases x <;>',
            '      norm_num [Nat.testBit, Nat.shiftRight_eq_div_pow] at hx <;>',
            '      norm_num [Nat.testBit, Nat.shiftRight_eq_div_pow]',
            '',
            'theorem pair%d_infeasible :' % pid,
            '    ¬ ∃ p0 p1, Feasible pair%d p0 p1 :=' % pid,
            '  not_feasible_of_separatorData sep%d_valid' % pid,
            '',
            'theorem pair%d_realInfeasible :' % pid,
            '    ¬ ∃ w : MainTheory.RealMomentSeparatorBridge.RealWeight'
            ' pair%d,' % pid,
            '      MainTheory.RealMomentSeparatorBridge.RealFeasible pair%d w :='
            % pid,
            '  MainTheory.RealMomentSeparatorBridge'
            '.not_realFeasible_of_separatorData sep%d_valid' % pid,
            '',
        ]
    ids = [r[0] for r in rows]
    lines += [
        '/-- The pairs certified in this shard. -/',
        'def pairs : List FiberPair := [%s]'
        % ', '.join('pair%d' % i for i in ids),
        '',
        'theorem pairs_infeasible (p : FiberPair) (h : p ∈ pairs) :',
        '    ¬ ∃ p0 p1, Feasible p p0 p1 := by',
        '  simp only [pairs, List.mem_cons, List.not_mem_nil, or_false] at h',
        '  rcases h with %s' % ' | '.join(['rfl'] * len(ids)),
    ]
    for i in ids:
        lines.append('  · exact pair%d_infeasible' % i)
    lines += [
        '',
        'theorem pairs_realInfeasible (p : FiberPair) (h : p ∈ pairs) :',
        '    ¬ ∃ w : MainTheory.RealMomentSeparatorBridge.RealWeight p,',
        '      MainTheory.RealMomentSeparatorBridge.RealFeasible p w := by',
        '  simp only [pairs, List.mem_cons, List.not_mem_nil, or_false] at h',
        '  rcases h with %s' % ' | '.join(['rfl'] * len(ids)),
    ]
    for i in ids:
        lines.append('  · exact pair%d_realInfeasible' % i)
    lines += ['', 'end MainTheory.Generated.ExtraMoment.Shard%02d' % idx, '']
    return NL.join(lines)


def aggregate(nshards, npairs):
    lines = [
        '-- Generated by tools/generators/emit_extra_moment_separators.py.',
        '-- Do not edit by hand; regenerate it instead.',
        '',
    ]
    lines += ['import MainTheory.Generated.ExtraMoment.Shard%02d' % i
              for i in range(nshards)]
    lines += [
        '',
        '/-!',
        '# Moment infeasibility for every right-rejected coarse row',
        '',
        'The generated coarse directory rejects each discarded row by one of',
        'two witnesses.  Rejection by the `S_0` clause is sound and proved',
        '(`MaskRankBridge`, `CoarseFilterEntry`).  Rejection by the `S_delta`',
        "clause rests on the paper's `q <= beta_r` at the *affine* rank of the",
        'support, which does not follow from the linear-rank bound this',
        'development proves -- see `results/coarse-filter-audit.md`.',
        '',
        'This file removes the need for that clause to be sound, without',
        'changing a number the paper reports.  Every one of the %d rows the'
        % npairs,
        'directory rejects by its right-hand witness is shown here to admit no',
        'common moment point at all, by an exact rational separator: the',
        'Farkas dual of the moment LP, in the shape `SeparatorData` expects.',
        'A genuine code supplies its own common moment point, so a',
        'right-rejected row can never discard a code, whatever the status of',
        'the clause that rejected it.',
        '-/',
        '',
        'namespace MainTheory.Generated.ExtraMoment',
        '',
        'open MainTheory.FinitePipeline',
        '',
        'set_option maxRecDepth 400000',
        '',
        'def shardPairs : List (List FiberPair) := [%s]'
        % ', '.join('Shard%02d.pairs' % i for i in range(nshards)),
        '',
        '/-- The pairs the coarse directory rejects by its right clause. -/',
        'def rejectRightPairs : List FiberPair := shardPairs.flatten',
        '',
        'theorem rejectRightPairs_length :',
        '    rejectRightPairs.length = %d := by decide' % npairs,
        '',
        '/-- **No right-rejected row admits a common moment point.** -/',
        'theorem rejectRightPairs_infeasible (p : FiberPair)',
        '    (h : p ∈ rejectRightPairs) : ¬ ∃ p0 p1, Feasible p p0 p1 := by',
        '  rw [rejectRightPairs, List.mem_flatten] at h',
        '  obtain ⟨l, hl, hp⟩ := h',
        '  simp only [shardPairs, List.mem_cons, List.not_mem_nil, or_false]'
        ' at hl',
        '  rcases hl with %s' % ' | '.join(['rfl'] * nshards),
    ]
    for i in range(nshards):
        lines.append('  · exact Shard%02d.pairs_infeasible p hp' % i)
    lines += [
        '',
        "/-- **And no real one either.**  A code's probabilities are real,",
        'not rational, so this is the form the code-level argument needs; a',
        'rational separator excludes the real fibre LP as well. -/',
        'theorem rejectRightPairs_realInfeasible (p : FiberPair)',
        '    (h : p ∈ rejectRightPairs) :',
        '    ¬ ∃ w : MainTheory.RealMomentSeparatorBridge.RealWeight p,',
        '      MainTheory.RealMomentSeparatorBridge.RealFeasible p w := by',
        '  rw [rejectRightPairs, List.mem_flatten] at h',
        '  obtain ⟨l, hl, hp⟩ := h',
        '  simp only [shardPairs, List.mem_cons, List.not_mem_nil, or_false]'
        ' at hl',
        '  rcases hl with %s' % ' | '.join(['rfl'] * nshards),
    ]
    for i in range(nshards):
        lines.append('  · exact Shard%02d.pairs_realInfeasible p hp' % i)
    lines += ['', 'end MainTheory.Generated.ExtraMoment', '']
    return NL.join(lines)


def main():
    pairs = load_pairs()
    index = {p: i for i, p in enumerate(pairs)}
    rr = reject_right_pairs()
    todo = [(index[p], p[0], p[1], p[2], p[3]) for p in rr]
    print('rows rejected by the directory right clause: %d' % len(todo))
    if '--probe' in sys.argv:
        todo = todo[:int(sys.argv[sys.argv.index('--probe') + 1])]
    rows = []
    for (pid, q, m, m0, m1) in todo:
        s = separator(m0, m1)
        if s is None:
            print('  NO SEPARATOR (moment feasible): id=%d q=%d m=%d'
                  % (pid, q, m))
            continue
        h, lo, hi = s
        rows.append((pid, q, m, m0, m1, h, lo, hi))
    print('separators found: %d / %d' % (len(rows), len(todo)))
    if not os.path.isdir(OUT):
        os.makedirs(OUT)
    shards = [rows[i:i + PER_SHARD] for i in range(0, len(rows), PER_SHARD)]
    for i, block in enumerate(shards):
        io.open(os.path.join(OUT, 'Shard%02d.lean' % i), 'w',
                encoding='utf-8', newline=NL).write(shard(i, block))
    io.open(TOP, 'w', encoding='utf-8',
            newline=NL).write(aggregate(len(shards), len(rows)))
    print('wrote %d shards and %s'
          % (len(shards), os.path.relpath(TOP, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
