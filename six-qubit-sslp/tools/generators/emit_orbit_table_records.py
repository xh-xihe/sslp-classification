"""Emit the complete 216 surviving record witnesses and their certified orbit keys."""
import json

from inspect_orbit_table_semantics import ROOT, inspect


def vector(xs):
    return "![" + ", ".join(map(str, xs)) + "]"


def emit():
    pipeline = json.loads((ROOT / "results/main-pipeline-certificates.json").read_text())
    orbit = json.loads((ROOT / "results/finite-orbit-certificates.json").read_text())
    input_of_pair = {p: i for i, p in enumerate(orbit["input_pair_ids"])}
    key_of_input = {w["input_index"]: w["orbit_id"] for w in orbit["cube_witnesses"]}
    records = [(i, p, input_of_pair[p], key_of_input[input_of_pair[p]])
               for i, p in enumerate(pipeline["record_pair_ids"]) if p in input_of_pair]
    assert len(records) == 216
    table = inspect()
    facts = "\n".join(
        f"private theorem fact_{i} : Facts {i} := by decide\n" for i in range(216))
    cases = "\n".join(f"  · exact fact_{i}" for i in range(216))
    source = f"""-- Generated by tools/generators/emit_orbit_table_records.py.
import MainTheory.Generated.FinitePairRecordData
import MainTheory.Generated.FinitePairData
import MainTheory.Generated.OrbitCertificate.WitnessTable

namespace MainTheory.Generated.OrbitTableRecords

set_option maxRecDepth 20000
set_option maxHeartbeats 4000000

def record : Fin 216 → Fin 12768 := {vector(t[0] for t in records)}

def pairId : Fin 216 → Fin 11422 := {vector(t[1] for t in records)}

def input : Fin 216 → Fin 215 := {vector(t[2] for t in records)}

def key : Fin 216 → Fin 66 := {vector(t[3] for t in records)}

def paperKey : Fin 66 → Fin 66 := {vector(row['certified_orbit_index'] for row in table)}

def paperMultiplicity : Fin 66 → ℕ := {vector(row['multiplicity'] for row in table)}

def Facts (i : Fin 216) : Prop :=
  MainTheory.Generated.FinitePairRecordData.recordPairId (record i) = pairId i ∧
  MainTheory.Generated.FinitePairRecordBase.pairAtId (pairId i) =
    MainTheory.Generated.FiniteOrbitBase.inputAt (input i) ∧
  MainTheory.Generated.FinitePairData.compatiblePairIds.toList.contains (pairId i).val = true ∧
  (MainTheory.Generated.OrbitCertificate.witnessAt (input i)).key = key i

instance (i : Fin 216) : Decidable (Facts i) := by unfold Facts; infer_instance

{facts}

theorem facts (i : Fin 216) : Facts i := by
  fin_cases i
{cases}

theorem record_strictMono : StrictMono record := by
  apply Fin.strictMono_iff_lt_succ.2
  intro i
  fin_cases i <;> decide

theorem record_injective : Function.Injective record := record_strictMono.injective

end MainTheory.Generated.OrbitTableRecords
"""
    destination = ROOT / "MainTheory/Generated/OrbitTableRecords.lean"
    destination.write_text(source, encoding="utf-8")
    print(destination.relative_to(ROOT))


if __name__ == "__main__":
    emit()
