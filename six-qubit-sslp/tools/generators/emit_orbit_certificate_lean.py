#!/usr/bin/env python3
"""Emit the final assembly of the six-qubit orbit directory.

Everything this file needs already existed and was already kernel-checked:
`MainTheory/Generated/FiniteOrbitBase.lean` holds the 215 coarse inputs, the
66 orbit keys, their 66 expected distance signatures, the scalar signature
codes and the representative map; `FiniteOrbitWitnessShard000..214` each prove
one `OrbitWitness.ValidFor`.  What was missing was the assembly: nothing built
a `FiniteOrbitPipeline.FiniteCertificate 215 66` out of them, so
`Directory.Valid.hasExactlyClasses` -- the statement that there are exactly 66
labelled orbit classes -- had no instance and `orbit_coverage` had no users.

Emitted, in dependency order:

  Generated/OrbitCertificate/SignatureShardNN.lean   6 keys each, 11 shards
  Generated/OrbitCertificate/Signatures.lean         the 66-way assembly
  Generated/OrbitCertificate/WitnessTable.lean       witnessAt + validity
  Generated/FiniteOrbitCertificate.lean              the certificate

The signature shards are the only expensive part: each key costs roughly
fifteen seconds of ordinary kernel reduction (the fibres are `Finset`s of
`Fin 6 -> Bool`, and the histograms filter their squares), which is why they
are split six to a file rather than proved in one `decide`.

Usage:  python tools/generators/emit_orbit_certificate_lean.py [--only N]
"""
import io
import os
import sys

ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'MainTheory', 'Generated', 'OrbitCertificate')
KEYS = 66
INPUTS = 215
KEYS_PER_SHARD = 6
LEAF = 15
BASE = 'MainTheory.Generated.FiniteOrbitBase'
HEADER = ['-- Generated by tools/generators/emit_orbit_certificate_lean.py.',
          '-- Do not edit by hand; regenerate it instead.', '']


def write(path, text):
    io.open(path, 'w', encoding='utf-8', newline='\n').write(text)
    print('wrote', os.path.relpath(path, ROOT))


def signature_shard(shard, keys):
    lines = list(HEADER) + [
        'import %s' % BASE,
        '',
        '/-! One orbit key per theorem: an ordinary kernel computation of its',
        'internal and cross distance histograms, checked against the literal',
        'stored beside the key. -/',
        '',
        'namespace MainTheory.Generated.OrbitCertificate.SignatureShard%02d'
        % shard,
        '',
        'open MainTheory.DistanceSignature',
        'open %s' % BASE,
        '',
        'set_option maxRecDepth 1000000',
        'set_option maxHeartbeats 4000000',
        '',
    ]
    for k in keys:
        lines += [
            'theorem sig%02d :' % k,
            '    signature key%02d.q key%02d.m key%02d.fibers =' % (k, k, k),
            '      expectedSignature%02d := by' % k,
            '  refine Signature.ext rfl rfl ?_ ?_',
            '  · decide',
            '  · funext d; fin_cases d <;> decide',
            '',
        ]
    lines += ['end MainTheory.Generated.OrbitCertificate.SignatureShard%02d'
              % shard, '']
    return '\n'.join(lines)


def signatures_module(shard_of):
    lines = list(HEADER)
    lines += ['import MainTheory.Generated.OrbitCertificate.SignatureShard%02d'
              % s for s in sorted(set(shard_of.values()))]
    lines += [
        '',
        'namespace MainTheory.Generated.OrbitCertificate',
        '',
        'open MainTheory.DistanceSignature',
        'open %s' % BASE,
        '',
        '/-- **The 66 declared signatures are the actual ones.**',
        '',
        'This is the only certificate field that is a genuine computation',
        'rather than a lookup: it says the literal invariants stored beside',
        'each key really are that key\'s internal and cross distance',
        'histograms. -/',
        'theorem signature_exact (k : Fin %d) :' % KEYS,
        '    signature (keyAt k).q (keyAt k).m (keyAt k).fibers =',
        '      expectedSignatureAt k := by',
        '  fin_cases k',
    ]
    for k in range(KEYS):
        lines.append('  · exact SignatureShard%02d.sig%02d'
                     % (shard_of[k], k))
    lines += [
        '',
        '/-- The scalar signature code is a left inverse on those 66',
        'signatures. -/',
        'theorem codeTag_signatureCode (k : Fin %d) :' % KEYS,
        '    codeTag (signatureCode (expectedSignatureAt k)) = k := by',
        '  revert k; decide',
        '',
        '/-- Hence the 66 signatures are pairwise distinct, which is what',
        'rules out two declared keys being cube equivalent. -/',
        'theorem expectedSignatureAt_injective :',
        '    Function.Injective expectedSignatureAt := by',
        '  intro k l h',
        '  have hk := codeTag_signatureCode k',
        '  have hl := codeTag_signatureCode l',
        '  rw [h] at hk',
        '  exact hk.symm.trans hl',
        '',
        'end MainTheory.Generated.OrbitCertificate',
        '',
    ]
    return '\n'.join(lines)


def witness_table_module():
    """Mirror the balanced `Fin.append` tree that `FiniteOrbitBase.inputAt`
    uses, so that lookup at a literal index stays a shallow reduction."""
    lines = list(HEADER)
    lines += ['import MainTheory.Generated.FiniteOrbitWitnessShard%03d' % i
              for i in range(INPUTS)]
    lines += [
        '',
        '/-! The 215 separately checked witnesses, collected into one',
        'function and shown to sit at their own indices. -/',
        '',
        'namespace MainTheory.Generated.OrbitCertificate',
        '',
        'open MainTheory.FiniteOrbitPipeline',
        'open %s' % BASE,
        '',
        'set_option maxRecDepth 1000000',
        'set_option maxHeartbeats 4000000',
        '',
        'abbrev W := OrbitWitness %d %d' % (INPUTS, KEYS),
        '',
    ]
    starts = list(range(0, INPUTS, LEAF))
    for li, s in enumerate(starts):
        n = min(LEAF, INPUTS - s)
        lines.append('def witnessLeaf%02d : Fin %d → W :=' % (li, n))
        lines.append('![')
        lines.append(',\n'.join(
            '  MainTheory.Generated.FiniteOrbitWitnessShard%03d.witness' % i
            for i in range(s, s + n)))
        lines.append(']')
        lines.append('')
    names = ['witnessLeaf%02d' % i for i in range(len(starts))]
    sizes = [min(LEAF, INPUTS - s) for s in starts]
    node = 0
    while len(names) > 1:
        nxt, nxtsizes = [], []
        for i in range(0, len(names) - 1, 2):
            total = sizes[i] + sizes[i + 1]
            nm = 'witnessNode%02d' % node
            node += 1
            lines.append('def %s : Fin %d → W :=' % (nm, total))
            lines.append('  Fin.append %s %s' % (names[i], names[i + 1]))
            lines.append('')
            nxt.append(nm)
            nxtsizes.append(total)
        if len(names) % 2 == 1:
            nxt.append(names[-1])
            nxtsizes.append(sizes[-1])
        names, sizes = nxt, nxtsizes
    lines += [
        'def witnessAt : Fin %d → W := %s' % (INPUTS, names[0]),
        '',
        '/-- Each stored witness sits at its own index. -/',
        'theorem witness_input (i : Fin %d) : (witnessAt i).input = i := by'
        % INPUTS,
        '  revert i; decide',
        '',
        '/-- **Every one of the 215 rank-compatible pairs is carried onto its',
        'declared orbit key** by a witness the kernel has checked. -/',
        'theorem witness_valid (i : Fin %d) :' % INPUTS,
        '    (witnessAt i).ValidFor (inputAt (witnessAt i).input)',
        '      (keyAt (witnessAt i).key) := by',
        '  fin_cases i',
    ]
    for i in range(INPUTS):
        lines.append('  · exact MainTheory.Generated.FiniteOrbitWitness'
                     'Shard%03d.witness_validFor' % i)
    lines += [
        '',
        '/-- Every key is the target of the witness at its representative',
        'index, so no key is a directory-only ghost. -/',
        'theorem representative_key (k : Fin %d) :' % KEYS,
        '    (witnessAt (representativeAt k)).key = k := by',
        '  revert k; decide',
        '',
        'end MainTheory.Generated.OrbitCertificate',
        '',
    ]
    return '\n'.join(lines)


CERTIFICATE = '''-- Generated by tools/generators/emit_orbit_certificate_lean.py.
-- Do not edit by hand; regenerate it instead.

import MainTheory.Generated.OrbitCertificate.Signatures
import MainTheory.Generated.OrbitCertificate.WitnessTable

/-!
# The 215-to-66 orbit directory, assembled

Every ingredient below already existed and was already kernel-checked:
`FiniteOrbitBase` holds the 215 rank-compatible fibre pairs, the 66 orbit
keys, their expected distance signatures and the representative map, and
`FiniteOrbitWitnessShard000..214` each prove one `OrbitWitness.ValidFor`.
What was missing was this assembly, and with it every conclusion that depends
on it: `Directory.Valid` had no instance, so `orbit_coverage`,
`no_ghost_key` and `hasExactlyClasses` had no users and the last step of the
reduction `13,877 -> ... -> 66` was a pile of parts rather than a theorem.

`FiniteCertificate` bundles the five obligations -- one valid witness per
input, each at its own index, a representative for every key, and the declared
signatures being both exact and injective -- and `directory_valid` turns them
into the four conditions of `Directory.Valid`.
-/

namespace MainTheory.Generated.FiniteOrbitCertificate

open MainTheory.FiniteOrbitPipeline
open MainTheory.Generated.FiniteOrbitBase
open MainTheory.Generated.OrbitCertificate

/-- The generated 215-input, 66-key certificate. -/
def certificate : FiniteCertificate 215 66 where
  inputAt := inputAt
  keyAt := keyAt
  witnessAt := witnessAt
  witness_valid := witness_valid
  witness_input := witness_input
  representative := representativeAt
  representative_key := representative_key
  signatures := expectedSignatureAt
  signature_exact := signature_exact
  signatures_injective := expectedSignatureAt_injective

/-- The orbit directory itself. -/
def directory : Directory := certificate.directory

theorem directory_valid : directory.Valid := certificate.directory_valid

@[simp] theorem directory_keyCount : directory.keyCount = 66 := rfl
@[simp] theorem directory_inputCount : directory.inputCount = 215 := rfl

/-- **Coverage.**  Every rank-compatible fibre pair is labelled equivalent to
one of the 66 declared orbit keys. -/
theorem orbit_coverage (i : Fin 215) :
    ∃ k : Fin 66,
      MainTheory.DistanceSignature.LabeledEquivalent
        (inputAt i).q (inputAt i).m (fibersOfPair (inputAt i))
        (keyAt k).q (keyAt k).m (keyAt k).fibers :=
  directory_valid.orbit_coverage i trivial

/-- **No ghost keys.**  Every declared key is realized by an actual input. -/
theorem no_ghost_key (k : Fin 66) :
    ∃ i : Fin 215,
      MainTheory.DistanceSignature.LabeledEquivalent
        (inputAt i).q (inputAt i).m (fibersOfPair (inputAt i))
        (keyAt k).q (keyAt k).m (keyAt k).fibers := by
  obtain ⟨i, _, h⟩ := directory_valid.no_ghost_key k
  exact ⟨i, h⟩

/-- **Exactly 66 classes.**  The classification map is onto the 66 keys, and
two inputs receive the same key precisely when they are labelled
equivalent. -/
theorem hasExactlyClasses : HasExactlyClasses directory 66 :=
  directory_valid.hasExactlyClasses

end MainTheory.Generated.FiniteOrbitCertificate
'''


def main():
    if not os.path.isdir(OUT):
        os.makedirs(OUT)
    shard_of = {}
    shards = []
    for start in range(0, KEYS, KEYS_PER_SHARD):
        keys = list(range(start, min(start + KEYS_PER_SHARD, KEYS)))
        s = start // KEYS_PER_SHARD
        shards.append((s, keys))
        for k in keys:
            shard_of[k] = s
    only = None
    if '--only' in sys.argv:
        only = int(sys.argv[sys.argv.index('--only') + 1])
    for s, keys in shards:
        if only is None or s == only:
            write(os.path.join(OUT, 'SignatureShard%02d.lean' % s),
                  signature_shard(s, keys))
    if only is not None:
        return 0
    write(os.path.join(OUT, 'Signatures.lean'), signatures_module(shard_of))
    write(os.path.join(OUT, 'WitnessTable.lean'), witness_table_module())
    write(os.path.join(ROOT, 'MainTheory', 'Generated',
                       'FiniteOrbitCertificate.lean'), CERTIFICATE)
    return 0


if __name__ == '__main__':
    sys.exit(main())
