#!/usr/bin/env python3
"""Bind the spectral table to the physical quartic's checked block family."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(output):
    blocks = json.loads((ROOT / 'results/orbit2-kernel/gram-blocks.json').read_text(encoding='utf8'))['blocks']
    text = '''-- Generated by tools/generators/emit_orbit2_physical_spectra.py.
import Orbit2.Global
import MainTheory.Orbit2SpectralTable

namespace SixQubit.Generated.Orbit2PhysicalSpectra
open scoped BigOperators
noncomputable section
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000
'''
    for index, block in enumerate(blocks):
        n = len(block['matrix'])
        text += f'''
theorem matrix{index:03} : Orbit2.Block{index:03}.M = Orbit2Spectra.Block{index:03}.originalMatrix := by
  ext i j
  have h : ∀ i j : Fin {n}, Orbit2.Block{index:03}.M i j = Orbit2Spectra.Block{index:03}.originalMatrix i j := by
    decide +kernel
  exact h i j
'''
    text += '''
theorem physical_dimensions : ∀ i : Fin 111, (Orbit2.checkedBlocks i).n =
    MainTheory.Orbit2SpectralTable.sizes (Orbit2Spectra.pattern i) := by decide +kernel

def blockIndex (group : Fin 3) (entry : Fin 37) : Fin 111 :=
  ⟨37 * group.val + entry.val, by omega⟩
'''
    for group in range(3):
        text += f'''
theorem characteristic_group{group} (entry : Fin 37) :
    (Orbit2.checkedBlocks (blockIndex {group} entry)).M.charpoly =
      Orbit2Spectra.tablePolynomials (Orbit2Spectra.pattern (blockIndex {group} entry)) := by
  fin_cases entry
'''
        text += ''.join(f'  · exact (congrArg Matrix.charpoly matrix{i:03}).trans Orbit2Spectra.Block{i:03}.charpoly\n'
                        for i in range(37 * group, 37 * (group + 1)))
    text += '''
theorem physical_characteristic_polynomials (i : Fin 111) :
    (Orbit2.checkedBlocks i).M.charpoly = Orbit2Spectra.tablePolynomials (Orbit2Spectra.pattern i) := by
  have h (group : Fin 3) (entry : Fin 37) :
      (Orbit2.checkedBlocks (blockIndex group entry)).M.charpoly =
        Orbit2Spectra.tablePolynomials (Orbit2Spectra.pattern (blockIndex group entry)) := by
    fin_cases group
    · exact characteristic_group0 entry
    · exact characteristic_group1 entry
    · exact characteristic_group2 entry
  let group : Fin 3 := ⟨i.val / 37, by omega⟩
  let entry : Fin 37 := ⟨i.val % 37, Nat.mod_lt _ (by norm_num)⟩
  have hi : blockIndex group entry = i := by
    apply Fin.ext
    dsimp [blockIndex, group, entry]
    omega
  rw [← hi]
  exact h group entry
'''
    text += '\nend\nend SixQubit.Generated.Orbit2PhysicalSpectra\n'
    output.write_text(text, encoding='utf8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'SixQubit/Generated/Orbit2PhysicalSpectra.lean')
    args = parser.parse_args()
    generate(args.output)
