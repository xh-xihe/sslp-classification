#!/usr/bin/env python3
"""Exhaustive traces for the 120 physical weight-three target Paulis."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
from emit_orbit3_collected_rows import tree

ROOT = Path(__file__).resolve().parents[2]


def balanced(values):
    if len(values) == 1:
        return f'(.leaf {values[0]})'
    m = len(values) // 2
    return f'(.node {m} {balanced(values[:m])} {balanced(values[m:])})'


def generate(output, data_output, aggregate_output):
    spec = importlib.util.spec_from_file_location('target_verifier', ROOT / 'tools/certificates/orbit3_exact_sextic_certificate.py')
    v = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(v)
    _, _, entries, pairs, _ = v.coordinate_tables()
    labels = [r for r in range(4096) if v.category(r) == (1, 0, 2)]
    assert len(labels) == 120
    final_rows = []
    output.mkdir(parents=True, exist_ok=True)
    for index, label in enumerate(labels):
        x, z = label & 63, label >> 6
        phase = (x & z).bit_count() % 2
        prefix = [0] * 512
        states = [prefix.copy()]
        for a in range(64):
            for b in range(64):
                coord = entries[pairs[a][b]][pairs[a ^ x][b ^ x]]
                if coord >= 0:
                    parity = ((a & z).bit_count() + (b & z).bit_count() + phase) % 2
                    prefix[coord] += -1 if parity else 1
            states.append(prefix.copy())
        final_rows.append(prefix)
        namespace = f'SixQubit.Generated.Orbit3TargetTraces.Trace{index:03}'
        text = f'''-- Generated by tools/generators/emit_orbit3_target_traces.py.
-- Exhaustive target Pauli label: {label} = x + 64*z.
import MainTheory.DyadicCoefficientTree
import MainTheory.BalancedFiniteTable

namespace {namespace}
'''
        for i, state in enumerate(states):
            text += f'\ndef state{i:02} : MainTheory.DyadicCoefficientTree.Tree 9 :=\n  {tree(state)}\n'
        text += '\ndef stateTable : MainTheory.BalancedFiniteTable.Tree (MainTheory.DyadicCoefficientTree.Tree 9) :=\n  '
        text += balanced([f'state{i:02}' for i in range(65)])
        text += '\n\ndef states (n : ℕ) : MainTheory.DyadicCoefficientTree.Tree 9 :=\n  MainTheory.BalancedFiniteTable.lookup stateTable n\n'
        text += f'\nend {namespace}\n'
        (output / f'Trace{index:03}.lean').write_text(text, encoding='utf8', newline='\n')
        proof = f'''-- Generated by tools/generators/emit_orbit3_target_traces.py.
import {namespace}
import SixQubit.Generated.Orbit3TargetData
import MainTheory.Orbit3CoefficientTrace

namespace {namespace}.Checks
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000
'''
        for a in range(64):
            proof += f'''
theorem step{a:02} : MainTheory.DyadicCoefficientTree.accumulate state{a:02}
    (MainTheory.Orbit3CoefficientTrace.rowTerms (Orbit3TargetData.triple {index}) {a}) = state{a+1:02} := by
  decide +kernel
'''
        proof += f'''
theorem steps : ∀ a : Fin 64, MainTheory.DyadicCoefficientTree.accumulate (states a.val)
    (MainTheory.Orbit3CoefficientTrace.rowTerms (Orbit3TargetData.triple {index}) a) = states (a.val + 1) := by
  intro a
  fin_cases a
'''
        proof += ''.join(f'  · exact step{a:02}\n' for a in range(64))
        proof += f'''
theorem initial : states 0 = MainTheory.DyadicCoefficientTree.zero 9 := by decide +kernel
theorem final : states 64 = Orbit3TargetData.finalRow {index} := by decide +kernel

theorem evaluation (y : Fin 269 → ℝ) :
    MainTheory.DyadicCoefficientTree.evaluate (Orbit3TargetData.finalRow {index})
      (MainTheory.Orbit3CoefficientCollection.padded y) =
        MainTheory.Orbit3PauliMomentInterpretation.rawEvaluation (Orbit3TargetData.triple {index}) y := by
  rw [← final]
  exact MainTheory.Orbit3CoefficientTrace.pauli_trace_evaluation _ states initial steps y

end {namespace}.Checks
'''
        (output / f'Trace{index:03}Checks.lean').write_text(proof, encoding='utf8', newline='\n')
    target = json.loads((ROOT / 'results/orbit3-kernel/reduced-coefficients.json').read_text(encoding='utf8'))['target']
    assert [sum(row[j] for row in final_rows) for j in range(269)] == target
    text = '''-- Generated by tools/generators/emit_orbit3_target_traces.py.
import MainTheory.DyadicCoefficientTree
import MainTheory.BalancedFiniteTable
import MainTheory.PhysicalPauliCategories
import MainTheory.Orbit3Target
import MainTheory.Orbit3PauliCubicExpansion
import SixQubit.Generated.Orbit3SexticIdentity
import SixQubit.Realize

namespace SixQubit.Generated.Orbit3TargetData
open scoped BigOperators
set_option maxHeartbeats 32000000
set_option maxRecDepth 200000
'''
    text += '\ndef labels : Fin 120 → ℕ := ![' + ', '.join(map(str, labels)) + ']\n'
    text += '''
def pauli (i : Fin 120) : SS.PauliString 6 :=
  ⟨SixQubit.Realize.nbit (labels i % 64), SixQubit.Realize.nbit (labels i / 64)⟩
def triple (i : Fin 120) : Fin 3 → SS.PauliString 6 :=
  ![pauli i, pauli i, ⟨fun _ => false, fun _ => false⟩]

theorem injective : Function.Injective pauli := by decide +kernel
theorem coverage : Finset.univ.image pauli = Finset.univ.filter
    (fun P : SS.PauliString 6 => MainTheory.PhysicalPauliCategories.category P = MainTheory.Orbit3Target.targetCategory) := by
  have hm : ∀ i : Fin 120, MainTheory.PhysicalPauliCategories.category (pauli i) =
      MainTheory.Orbit3Target.targetCategory := by decide +kernel
  have hc : ∀ a b : Fin 64,
      MainTheory.PhysicalPauliCategories.category
        (⟨SixQubit.Realize.nbit a.val, SixQubit.Realize.nbit b.val⟩ : SS.PauliString 6) =
          MainTheory.Orbit3Target.targetCategory →
      ∃ i : Fin 120, labels i % 64 = a.val ∧ labels i / 64 = b.val := by decide +kernel
  ext P
  simp only [Finset.mem_image, Finset.mem_univ, true_and, Finset.mem_filter]
  constructor
  · rintro ⟨i, rfl⟩
    exact hm i
  · intro hP
    let a : Fin 64 := ⟨SixQubit.Realize.num P.x, SixQubit.Realize.num_lt P.x⟩
    let b : Fin 64 := ⟨SixQubit.Realize.num P.z, SixQubit.Realize.num_lt P.z⟩
    have he : (⟨SixQubit.Realize.nbit a.val, SixQubit.Realize.nbit b.val⟩ : SS.PauliString 6) = P := by
      cases P
      simp only [a, b, SixQubit.Realize.nbit_num]
    obtain ⟨i, hi, hj⟩ := hc a b (he.symm ▸ hP)
    refine ⟨i, ?_⟩
    unfold pauli
    rw [hi, hj]
    exact he
theorem xor_x : ∀ i, SS.bxor (triple i 0).x (triple i 1).x = (triple i 2).x := by decide +kernel
theorem xor_z : ∀ i, SS.bxor (triple i 0).z (triple i 1).z = (triple i 2).z := by decide +kernel
theorem even_y : ∀ i, MainTheory.Orbit3PauliCubicExpansion.totalY (triple i) % 2 = 0 := by decide +kernel
'''
    for i, row in enumerate(final_rows):
        text += f'\ndef row{i:03} : MainTheory.DyadicCoefficientTree.Tree 9 :=\n  {tree(row)}\n'
    text += '\ndef rowTable : MainTheory.BalancedFiniteTable.Tree (MainTheory.DyadicCoefficientTree.Tree 9) :=\n  '
    text += balanced([f'row{i:03}' for i in range(120)])
    text += '''

def finalRow (i : Fin 120) : MainTheory.DyadicCoefficientTree.Tree 9 :=
  MainTheory.BalancedFiniteTable.lookup rowTable i.val

theorem target_coefficients : ∀ j : Fin 269,
    (∑ i : Fin 120, (MainTheory.DyadicCoefficientTree.lookup (finalRow i) j.val : ℚ)) =
      Orbit3SexticIdentity.target j := by decide +kernel

end SixQubit.Generated.Orbit3TargetData
'''
    data_output.write_text(text, encoding='utf8', newline='\n')
    aggregate = '-- Generated by tools/generators/emit_orbit3_target_traces.py.\n'
    aggregate += ''.join(f'import SixQubit.Generated.Orbit3TargetTraces.Trace{i:03}Checks\n' for i in range(120))
    aggregate += '''
namespace SixQubit.Generated.Orbit3CollectedTarget
theorem all_evaluations (i : Fin 120) (y : Fin 269 → ℝ) :
    MainTheory.DyadicCoefficientTree.evaluate (Orbit3TargetData.finalRow i)
      (MainTheory.Orbit3CoefficientCollection.padded y) =
        MainTheory.Orbit3PauliMomentInterpretation.rawEvaluation (Orbit3TargetData.triple i) y := by
  fin_cases i
'''
    aggregate += ''.join(f'  · exact Orbit3TargetTraces.Trace{i:03}.Checks.evaluation y\n' for i in range(120))
    aggregate += '\nend SixQubit.Generated.Orbit3CollectedTarget\n'
    aggregate_output.write_text(aggregate, encoding='utf8', newline='\n')
    modules = sorted(output.glob('*.lean'))
    (output / 'generation-manifest.sha256').write_text('# lean_files=' + str(len(modules)) + '\n' + ''.join(
        hashlib.sha256(p.read_bytes()).hexdigest() + '  SixQubit.Generated.Orbit3TargetTraces.' + p.stem + '\n' for p in modules), encoding='utf8')
    (output / 'serial-build-order.txt').write_text(''.join('SixQubit.Generated.Orbit3TargetTraces.' + p.stem + '\n' for p in modules), encoding='utf8')
    print('Generated 120 complete target traces and coefficient binding.', flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'SixQubit/Generated/Orbit3TargetTraces')
    parser.add_argument('--data-output', type=Path, default=ROOT / 'SixQubit/Generated/Orbit3TargetData.lean')
    parser.add_argument('--aggregate-output', type=Path, default=ROOT / 'SixQubit/Generated/Orbit3CollectedTarget.lean')
    args = parser.parse_args()
    generate(args.output, args.data_output, args.aggregate_output)
