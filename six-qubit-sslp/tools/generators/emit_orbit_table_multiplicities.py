"""Emit kernel-checked multiplicities of the 66 manuscript-labelled orbits."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

proofs = "\n".join(
    f"private theorem count_{i} : assignedCount (OrbitTableRecords.paperKey {i}) =\n"
    f"    OrbitTableRecords.paperMultiplicity {i} := by decide\n"
    for i in range(66)
)
cases = "\n".join(f"  · exact count_{i}" for i in range(66))
text = f"""-- Generated by tools/generators/emit_orbit_table_multiplicities.py.
import MainTheory.OrbitRecordMultiplicity

namespace MainTheory.Generated.OrbitTableMultiplicities

open MainTheory.OrbitRecordMultiplicity

set_option maxRecDepth 20000
set_option maxHeartbeats 2000000

{proofs}

theorem assignedCount_eq_paperMultiplicity (i : Fin 66) :
    assignedCount (OrbitTableRecords.paperKey i) = OrbitTableRecords.paperMultiplicity i := by
  fin_cases i
{cases}

/-- The manuscript multiplicities count actual surviving records modulo labelled cube equivalence. -/
theorem all_multiplicities (i : Fin 66) :
    multiplicity (OrbitTableRecords.paperKey i) = OrbitTableRecords.paperMultiplicity i := by
  rw [multiplicity_eq_assignedCount, assignedCount_eq_paperMultiplicity]

end MainTheory.Generated.OrbitTableMultiplicities
"""
destination = ROOT / "MainTheory/Generated/OrbitTableMultiplicities.lean"
destination.write_text(text, encoding="utf-8")
print(destination.relative_to(ROOT))
