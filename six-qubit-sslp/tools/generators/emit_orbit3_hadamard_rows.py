"""Candidate cumulative Hadamard differences; every transition is kernel checked."""
from pathlib import Path
import argparse
import importlib.util
from emit_orbit3_row_trace import inputs
from emit_orbit3_collected_rows import tree

ROOT=Path(__file__).resolve().parents[2]

def table(v):
    if len(v)==1: return f'(.leaf {v[0]})'
    mid=len(v)//2
    return f'(.node {mid} {table(v[:mid])} {table(v[mid:])})'

def generate_aggregate(output):
    rows = list(range(208, 211))
    text = ''.join(f'import SixQubit.Generated.Orbit3CollectedRows.TraceH{i}Certified\n' for i in rows)
    text += '''
namespace SixQubit.Generated.Orbit3CollectedHadamardRows

theorem hadamard_indices : ∀ i : Fin 211, Orbit3PauliConstraints.kind i = 2 →
    i = 208 ∨ i = 209 ∨ i = 210 := by decide +kernel

theorem all_hadamard_primitive_rows_zero
    (W : MainTheory.Orbit3ScalarCategoryRealization.Encoder)
    (i : Fin 211) (hi : Orbit3PauliConstraints.kind i = 2) :
    Orbit3SexticIdentity.evaluate (Orbit3SexticIdentity.rows i)
      (MainTheory.Orbit3CoordinateRealization.coordinates W) = 0 := by
  rcases hadamard_indices i hi with h | h | h
'''
    text += ''.join(f'  · subst i; exact Orbit3CollectedRows.TraceH{i}.Certified.primitive_row_zero W\n' for i in rows)
    text += '\nend SixQubit.Generated.Orbit3CollectedHadamardRows\n'
    output.write_text(text, encoding='utf8', newline='\n')


def generate(out):
    spec=importlib.util.spec_from_file_location('hadamard_trace',ROOT/'tools/certificates/orbit3_exact_sextic_certificate.py')
    v=importlib.util.module_from_spec(spec); spec.loader.exec_module(v)
    terms, rows, (_,_,entries,pairs,_)=inputs()
    out.mkdir(parents=True,exist_ok=True)
    for i in range(208,211):
        term=terms[i]
        assert term['kind']=='H'
        transformed,hsign=v.hadamard(term['paulis'])
        triples=[(term['paulis'],1),(transformed,-hsign)]
        prefix=[0]*512; states=[prefix.copy()]
        for a in range(64):
            for labels,weight in triples:
                xs=[r&63 for r in labels]; zs=[r>>6 for r in labels]
                phase=sum((x&z).bit_count() for x,z in zip(xs,zs))%4
                assert phase%2==0 and labels[0]^labels[1]^labels[2]==0
                for b in range(64):
                    coord=entries[pairs[a][b]][pairs[a^xs[0]][b^xs[1]]]
                    if coord>=0:
                        parity=sum((t&z).bit_count() for t,z in zip((a,b,a^b),zs))%2
                        prefix[coord]+=weight*(1 if (parity+phase//2)%2==0 else -1)
            states.append(prefix.copy())
        assert prefix[:269]==[c*term['row_divisor'] for c in rows[i]]
        ns=f'SixQubit.Generated.Orbit3CollectedRows.TraceH{i}'
        header='-- Generated by tools/generators/emit_orbit3_hadamard_rows.py.\n'
        text=header+'import MainTheory.DyadicCoefficientTree\nimport MainTheory.BalancedFiniteTable\n\n'+f'namespace {ns}\n\n'
        for a,state in enumerate(states):
            text+=f'def state{a:02d} : MainTheory.DyadicCoefficientTree.Tree 9 :=\n  {tree(state)}\n\n'
        text+='def stateTable : MainTheory.BalancedFiniteTable.Tree (MainTheory.DyadicCoefficientTree.Tree 9) :=\n  '+table([f'state{a:02d}' for a in range(65)])+'\n\n'
        text+='def states (n : ℕ) : MainTheory.DyadicCoefficientTree.Tree 9 :=\n  MainTheory.BalancedFiniteTable.lookup stateTable n\n\n'+f'end {ns}\n'
        (out/f'TraceH{i}.lean').write_text(text,encoding='utf-8',newline='\n')
        proof=header+f'import {ns}\nimport MainTheory.Orbit3CollectedHadamardRow\n\nnamespace {ns}.Checks\n\nset_option maxHeartbeats 16000000\nset_option maxRecDepth 200000\n\n'
        for a in range(64):
            proof+=f'theorem step{a:02d} : MainTheory.DyadicCoefficientTree.accumulate state{a:02d}\n    (MainTheory.Orbit3CollectedHadamardRow.hRowTerms {i} {a}) = state{a+1:02d} := by decide +kernel\n\n'
        proof+=f'theorem steps : ∀ a : Fin 64, MainTheory.DyadicCoefficientTree.accumulate (states a.val)\n    (MainTheory.Orbit3CollectedHadamardRow.hRowTerms {i} a) = states (a.val + 1) := by\n  intro a\n  fin_cases a\n'
        for a in range(64): proof+=f'  · exact step{a:02d}\n'
        proof+='\ntheorem initial : states 0 = MainTheory.DyadicCoefficientTree.zero 9 := by decide +kernel\n\n'
        proof+=f'theorem final : states 64 = SixQubit.Generated.Orbit3CollectedRows.Data.row{i} := by decide +kernel\n\nend {ns}.Checks\n'
        (out/f'TraceH{i}Checks.lean').write_text(proof,encoding='utf-8',newline='\n')
        certified=header+f'''import {ns}Checks

namespace {ns}.Certified
open MainTheory.DyadicCoefficientTree SixQubit.Generated
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

theorem primitive_coefficients : ∀ j : Fin 269,
    (lookup Orbit3CollectedRows.Data.row{i} j.val : ℚ) =
      (Orbit3RowMetadata.rowDivisor {i} : ℚ) * Orbit3SexticIdentity.rows {i} j := by decide +kernel

theorem primitive_row_zero (W : MainTheory.Orbit3ScalarCategoryRealization.Encoder) :
    Orbit3SexticIdentity.evaluate (Orbit3SexticIdentity.rows {i})
      (MainTheory.Orbit3CoordinateRealization.coordinates W) = 0 :=
  MainTheory.Orbit3CollectedHadamardRow.primitive_row_zero W {i} (by decide +kernel)
    states Checks.initial Checks.steps Checks.final primitive_coefficients

end {ns}.Certified
'''
        (out/f'TraceH{i}Certified.lean').write_text(certified,encoding='utf-8',newline='\n')
    print('Generated three Hadamard coefficient traces; candidates require kernel checks.')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output-dir',type=Path,default=ROOT/'SixQubit/Generated/Orbit3CollectedRows')
    generate(p.parse_args().output_dir)
