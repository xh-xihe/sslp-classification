def pair_literal(pair: list[int]) -> str:
    q, m, mask0, mask1 = pair
    return f"(⟨{q}, {m}, {mask0}, {mask1}⟩ : FiberPair)"


def emit_input_data(data: dict, plan: dict, base_module: str,
                    lower_modules: list[str], upper_modules: list[str],
                    out_dir: Path) -> str:
    pairs = data["pair_table"]
    leaves: list[tuple[str, int, int]] = []
    for shard, start in enumerate(range(0, len(pairs), INPUT_ROWS_PER_SHARD)):
        stop = min(start + INPUT_ROWS_PER_SHARD, len(pairs))
        count = stop - start
        module = f"MainTheory.Generated.Coarse.Input.Shard{shard:03d}"
        leaves.append((module, start, count))
        needed: set[str] = set()
        for row in plan["rows"][start:stop]:
            if row["keep"]:
                needed.add(lower_modules[row["lower0"]])
                needed.add(lower_modules[row["lower1"]])
            else:
                needed.add(upper_modules[row["upper"]])
        lines = [HEADER, f"import {base_module}"]
        lines += [f"import {name}" for name in sorted(needed)]
        lines += [
            "", f"namespace {module}", "",
            "open MainTheory.FinitePipeline",
            "open MainTheory.CoarseFilter",
            "open MainTheory.Generated.FinitePairMappingBase",
            f"open {base_module}", "",
            "set_option maxRecDepth 1000000",
            "set_option maxHeartbeats 4000000", "",
            f"def inputAt : Segment FiberPair {count} := ![",
        ]
        for local, pair in enumerate(pairs[start:stop]):
            comma = "," if local + 1 < count else ""
            lines.append(f"  {pair_literal(pair)}{comma}")
        lines += ["]", ""]

        lines += [
            f"def decisionAt (i : Fin {count}) : DecisionWitness (inputAt i) := by",
            "  fin_cases i",
        ]
        for local, (pair, row) in enumerate(zip(pairs[start:stop], plan["rows"][start:stop])):
            lines += [
                f"  · change DecisionWitness {pair_literal(pair)}",
            ]
            if row["keep"]:
                lower0 = row["lower0"]
                lower1 = row["lower1"]
                module0 = lower_modules[lower0]
                module1 = lower_modules[lower1]
                data0 = f"{module0}.data{lower0:04d}"
                data1 = f"{module1}.data{lower1:04d}"
                lines += [
                    "    exact .keep",
                    f"      {{ data0 := {data0}",
                    f"        data1 := {data1}",
                    f"        lower0 := {module0}.valid{lower0:04d}",
                    f"        lower1 := {module1}.valid{lower1:04d}",
                    f"        threshold0 := by norm_num [rMin, {data0}]",
                    f"        threshold1 := by norm_num [rMin, {data1}] }}",
                ]
            else:
                upper = row["upper"]
                upper_module = upper_modules[upper]
                upper_data = f"{upper_module}.data{upper:04d}"
                constructor = ".rejectLeft" if row["upper_side"] == 0 else ".rejectRight"
                lines += [
                    f"    exact {constructor}",
                    f"      {{ data := {upper_data}",
                    f"        upper := {upper_module}.valid{upper:04d}",
                    f"        below := by norm_num [rMin, {upper_data}] }}",
                ]
        lines += ["", f"def outputOfInput : Segment (Option OutputId) {count} := !["]
        for local, output in enumerate(plan["output_of_input"][start:stop]):
            value = "none" if output is None else f"some {output}"
            comma = "," if local + 1 < count else ""
            lines.append(f"  {value}{comma}")
        lines += [
            "]", "", f"def block : InputBlock {start} {count} (by omega) where",
            "  inputAt := inputAt",
            "  decisionAt := decisionAt",
            "  outputOfInput := outputOfInput",
            "  pairExact := by",
            "    intro i",
            "    fin_cases i <;> decide",
            "  lookup_defined_exact := by",
            "    intro i",
            "    fin_cases i <;> decide", "",
            f"end {module}", "",
        ]
        path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)

    nodes: list[tuple[str, int, int]] = []
    for node_index, offset in enumerate(range(0, len(leaves), 32)):
        children = leaves[offset:offset + 32]
        start = children[0][1]
        count = sum(child[2] for child in children)
        module = f"MainTheory.Generated.Coarse.Input.Node{node_index:02d}"
        lines = [HEADER]
        lines += [f"import {child[0]}" for child in children]
        expression = balanced_expr(
            [f"{child[0]}.block" for child in children], "InputBlock.append")
        lines += [
            "", f"namespace {module}", "", f"open {base_module}", "",
            f"def block : InputBlock {start} {count} (by omega) :=",
            f"  {expression}", "", f"end {module}", "",
        ]
        path = out_dir.joinpath(*module.split(".")[2:]).with_suffix(".lean")
        write_generated(path, lines)
        nodes.append((module, start, count))

    root_module = "MainTheory.Generated.Coarse.InputData"
    lines = [HEADER]
    lines += [f"import {node[0]}" for node in nodes]
    expression = balanced_expr(
        [f"{node[0]}.block" for node in nodes], "InputBlock.append")
    lines += [
        "", f"namespace {root_module}", "",
        "open MainTheory.FinitePipeline",
        "open MainTheory.CoarseFilter",
        "open MainTheory.Generated.FinitePairMappingBase",
        f"open {base_module}", "",
        "def block : InputBlock 0 11422 (by omega) :=", f"  {expression}", "",
        "def inputAt : PairId → FiberPair := block.inputAt", "",
        "def decisionAt (i : PairId) : DecisionWitness (inputAt i) := block.decisionAt i", "",
        "def outputOfInput : PairId → Option OutputId := block.outputOfInput", "",
        "theorem inputAt_eq_pairAtId (i : PairId) :",
        "    inputAt i = MainTheory.Generated.FinitePairFunctionData.pairAtId i := by",
        "  simpa [inputAt, inputId] using block.pairExact i", "",
        "theorem lookup_defined_exact (i : PairId) :",
        "    (outputOfInput i).isSome = (decisionAt i).kept :=",
        "  block.lookup_defined_exact i", "",
        f"end {root_module}", "",
    ]
    write_generated(out_dir / "Coarse" / "InputData.lean", lines)
    return root_module


