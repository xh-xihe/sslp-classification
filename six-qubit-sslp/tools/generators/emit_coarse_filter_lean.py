        "    {leftBound : start + leftCount ≤ 11422}",
        "    {rightBound : start + leftCount + rightCount ≤ 11422}",
        "    {wholeBound : start + (leftCount + rightCount) ≤ 11422}",
        "    (left : InputBlock start leftCount leftBound)",
