#!/usr/bin/env python3
"""Generate kernel-checked rational LDL certificates for all orbit-2 blocks.

The JSON supplies mathematical matrix data, never an accepted proof result.
Each output module checks the factorization, inverse and positive diagonal in
Lean. This component proves block positivity; connecting the matrix to the
quartic expression and to actual encoders is a separate required component.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def ldlt(matrix):
    n = len(matrix)
    lower = [[Fraction(i == j) for j in range(n)] for i in range(n)]
    diagonal = []
    for k in range(n):
        pivot = Fraction(matrix[k][k]) - sum(lower[k][j] ** 2 * diagonal[j] for j in range(k))
        if pivot <= 0:
            raise ValueError(f"Nonpositive pivot {k}: {pivot}")
        diagonal.append(pivot)
        for i in range(k + 1, n):
            lower[i][k] = (Fraction(matrix[i][k]) - sum(
                lower[i][j] * lower[k][j] * diagonal[j] for j in range(k))) / pivot
    inverse = [[Fraction(i == j) for j in range(n)] for i in range(n)]
    for i in range(n):
        for j in range(i):
            inverse[i][j] = -sum(lower[i][k] * inverse[k][j] for k in range(j, i))
    return lower, diagonal, inverse


def rat(value):
    value = Fraction(value)
    if value.denominator == 1:
        return str(value.numerator)
    return f"({value.numerator}/{value.denominator})"


def vector(values):
    return "![" + ", ".join(map(rat, values)) + "]"


def matrix_literal(rows):
    return "![" + ",\n  ".join(vector(row) for row in rows) + "]"


def generate(source: Path, output: Path):
    raw = source.read_bytes()
    data = json.loads(raw)
    blocks = data["blocks"]
    if len(blocks) != 111:
        raise ValueError("Expected all 111 blocks")
    output.mkdir(parents=True, exist_ok=True)
    imports = []
    certificates = []
    for index, block in enumerate(blocks):
        n = len(block["matrix"])
        shifted = [[value - 4 * int(i == j) for j, value in enumerate(row)]
                   for i, row in enumerate(block["matrix"])]
        lower, diagonal, inverse = ldlt(shifted)
        module = f"SixQubit.Generated.Orbit2Gram.Block{index:03}"
        imports.append(f"import {module}")
        certificates.append(f"⟨{n}, {module}.matrix, {module}.certificate⟩")
        text = f'''-- Generated by tools/generators/emit_orbit2_gram.py.
-- Input SHA-256: {hashlib.sha256(raw).hexdigest()}
-- Character: {block['character']}; monomial indices: {block['monomial_indices']}.
import MainTheory.RationalGramCertificate

namespace {module}

set_option maxHeartbeats 8000000
set_option maxRecDepth 200000

def matrix : Matrix (Fin {n}) (Fin {n}) ℚ :=
  {matrix_literal(shifted)}

def lower : Matrix (Fin {n}) (Fin {n}) ℚ :=
  {matrix_literal(lower)}

def inverse : Matrix (Fin {n}) (Fin {n}) ℚ :=
  {matrix_literal(inverse)}

def diagonal : Fin {n} → ℚ := {vector(diagonal)}

theorem entries : ∀ i j, matrix i j = ∑ k, lower i k * diagonal k * lower j k := by
  decide +kernel

theorem inverse_identity : inverse * lower = 1 := by
  ext i j
  have h : ∀ i j, (inverse * lower) i j = (1 : Matrix (Fin {n}) (Fin {n}) ℚ) i j := by
    decide +kernel
  exact h i j

theorem diagonal_positive : ∀ i, 0 < diagonal i := by decide +kernel

def certificate : MainTheory.RationalGramCertificate.Certificate matrix where
  factor := lower
  inverse := inverse
  diagonal := diagonal
  factorization := MainTheory.RationalGramCertificate.factorization_of_entries _ _ _ entries
  inverse_identity := inverse_identity
  diagonal_positive := diagonal_positive

open scoped ComplexOrder in
theorem shifted_posDef :
    (MainTheory.RationalGramCertificate.complexMatrix matrix).PosDef := certificate.posDef

end {module}
'''
        (output / f"Block{index:03}.lean").write_text(text, encoding="utf-8", newline="\n")
    aggregate = "\n".join(imports) + '''

/-! All 111 block certificates; full encoder rigidity is not claimed here. -/
namespace SixQubit.Generated.Orbit2Gram

def certificates : Fin 111 →
    Σ n, Σ A : Matrix (Fin n) (Fin n) ℚ,
      MainTheory.RationalGramCertificate.Certificate A :=
  ![''' + ",\n    ".join(certificates) + ''']

open scoped ComplexOrder in
theorem all_blocks_posDef (i : Fin 111) :
    (MainTheory.RationalGramCertificate.complexMatrix (certificates i).2.1).PosDef :=
  (certificates i).2.2.posDef

end SixQubit.Generated.Orbit2Gram
'''
    (output / "All.lean").write_text(aggregate, encoding="utf-8", newline="\n")
    modules = [f"SixQubit.Generated.Orbit2Gram.Block{i:03}" for i in range(111)]
    modules.append("SixQubit.Generated.Orbit2Gram.All")
    manifest = [f"# lean_files={len(modules)}"]
    for module in modules:
        path = output / (module.rsplit('.', 1)[1] + '.lean')
        manifest.append(hashlib.sha256(path.read_bytes()).hexdigest() + '  ' + module)
    (output / 'generation-manifest.sha256').write_text('\n'.join(manifest) + '\n', encoding='utf-8')
    (output / 'serial-build-order.txt').write_text('\n'.join(modules) + '\n', encoding='utf-8')
    print(f"Generated {len(blocks)} exact rational block certificates at {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path,
                        default=ROOT / "results/orbit2-kernel/gram-blocks.json")
    parser.add_argument("--output", type=Path, default=ROOT / "SixQubit/Generated/Orbit2Gram")
    args = parser.parse_args()
    generate(args.input, args.output)
