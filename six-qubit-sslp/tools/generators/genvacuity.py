"""Emit SixQubit/Vacuity.lean: witnesses showing no wrapper is vacuously true.

A theorem whose hypotheses cannot all hold is true and says nothing. Each
`no_code` compiles and has a clean axiom footprint, but that alone does not rule
out the possibility that its support and normalization hypotheses are already
contradictory, in which case `SS.HasDistance` would be doing no work.

The first version of this module used a uniform amplitude, which normalizes only
when the fiber size is a perfect square, so it covered one orbit. A point mass
`c = indicator {y0}` works for EVERY orbit regardless of fiber size: it is
supported on `S0` because `y0` is, and `innerC c c = 1` because exactly one term
survives. So all fifty-one are covered by the same three-line proof.

The point mass is of course not a code - that is exactly the point. It shows the
non-distance hypotheses are jointly satisfiable, hence what each wrapper asserts
is that such a pair cannot ALSO have distance three.
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
SQ = os.path.join(REPO, 'SixQubit')
NL = chr(10)

orbits = []
for f in sorted(os.listdir(SQ)):
    if not f.startswith('CodeOrbit') and f != 'CodeOrder9.lean':
        continue
    src = io.open(os.path.join(SQ, f), encoding='utf-8').read()
    ns = re.search(r'namespace (\S+)', src).group(1)
    base = ns.split('.')[-1]
    orbits.append((f[:-5], ns, base))
orbits.sort(key=lambda t: 66 if t[2] == 'Order9' else int(re.sub(r'[^0-9]', '', t[2])))
print('wrappers found: %d' % len(orbits))

L = []
W = L.append
W('import Mathlib')
W('')
W('import SS.FullKL')
W('import SS.HilbertKL')
for m, _, _ in orbits:
    W('import SixQubit.%s' % m)
W('')
W('/-!')
W('# No wrapper is vacuously true')
W('')
W('Each `no_code` theorem assumes support, normalization and')
W('`SS.HasDistance ![c, d] 3`, and concludes `False`. A theorem whose hypotheses')
W('cannot all hold is true and says nothing, so before reading any of them as a')
W('no-go one must know that the hypotheses OTHER than `HasDistance` are jointly')
W('satisfiable. Otherwise `HasDistance` would be carrying no weight.')
W('')
W('For every one of the fifty-one orbits this module exhibits such a pair: the')
W('point masses `c = indicator {y0}` on the bottom fiber and `d = indicator {z}`')
W('on the top. They are supported correctly and normalized, and they are')
W('emphatically not codes -- which is the point. What each wrapper therefore')
W('says is that no such pair can additionally have distance three.')
W('')
W('Generated by `tools/generators/genvacuity.py`; no `sorry`, no `native_decide`.')
W('-/')
W('')
W('namespace SixQubit.Vacuity')
W('')
W('open scoped BigOperators')
W('')
W('noncomputable section')
W('')
W('/-- The point mass at a single bit string. -/')
W('def pt (s : SS.BitString 6) : SS.BitString 6 -> ℂ := fun t => if t = s then 1 else 0')
W('')
W('theorem pt_support (s : SS.BitString 6) (S : Finset (SS.BitString 6)) (hs : s ∈ S) :')
W('    ∀ t, t ∉ S → pt s t = 0 := by')
W('  intro t ht')
W('  have : t ≠ s := by rintro rfl; exact ht hs')
W('  simp [pt, this]')
W('')
W('theorem pt_norm (s : SS.BitString 6) : SS.innerC (pt s) (pt s) = 1 := by')
W('  unfold SS.innerC pt')
W('  rw [Finset.sum_eq_single s]')
W('  · simp')
W('  · intro b _ hb; simp [hb]')
W('  · intro h; exact absurd (Finset.mem_univ s) h')
W('')
for m, ns, base in orbits:
    ofile = 'Order9.lean' if base == 'Order9' else base + '.lean'
    osrc = io.open(os.path.join(SQ, ofile), encoding='utf-8').read()
    top = (ns + '.z0') if re.search(r'^def z0 ', osrc, re.M) else ('SS.complement ' + ns + '.y0')
    W('/-- The non-distance hypotheses of `%s.no_code` are jointly' % ns)
    W('satisfiable, so that theorem is not vacuously true. -/')
    W('theorem live_%s :' % base)
    W('    (∀ x, x ∉ %s.S0 → pt %s.y0 x = 0) ∧' % (ns, ns))
    W('    (∀ y, y ∉ %s.S1 → pt (%s) y = 0) ∧' % (ns, top))
    W('    SS.innerC (pt %s.y0) (pt %s.y0) = 1 ∧' % (ns, ns))
    W('    SS.innerC (pt (%s)) (pt (%s)) = 1 :=' % (top, top))
    W('  ⟨pt_support _ _ (by decide), pt_support _ _ (by decide),')
    W('   pt_norm _, pt_norm _⟩')
    W('')
W('end')
W('')
W('end SixQubit.Vacuity')

io.open(os.path.join(SQ, 'Vacuity.lean'), 'w', encoding='utf-8').write(NL.join(L) + NL)
print('wrote SixQubit/Vacuity.lean : %d lines, %d orbits covered'
      % (len(L), len(orbits)))
