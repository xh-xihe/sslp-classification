"""Emit kernel obligations binding the five supplied rows to actual spin terms."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[2]


def generate_aggregate(output):
    rows = list(range(203, 208))
    text = ''.join(f'import SixQubit.Generated.Orbit3CollectedRows.Spin{i}\n' for i in rows)
    text += '''
namespace SixQubit.Generated.Orbit3CollectedSpinRows

theorem spin_indices : ∀ i : Fin 211, Orbit3PauliConstraints.kind i = 1 →
    i = 203 ∨ i = 204 ∨ i = 205 ∨ i = 206 ∨ i = 207 := by decide +kernel

theorem all_spin_primitive_rows_zero
    (W : MainTheory.Orbit3ScalarCategoryRealization.Encoder)
    (i : Fin 211) (hi : Orbit3PauliConstraints.kind i = 1) :
    Orbit3SexticIdentity.evaluate (Orbit3SexticIdentity.rows i)
      (MainTheory.Orbit3CoordinateRealization.coordinates W) = 0 := by
  rcases spin_indices i hi with h | h | h | h | h
'''
    text += ''.join(f'  · subst i; exact Orbit3CollectedRows.Spin{i}.primitive_row_zero W\n' for i in rows)
    text += '\nend SixQubit.Generated.Orbit3CollectedSpinRows\n'
    output.write_text(text, encoding='utf8', newline='\n')

def generate(out):
    out.mkdir(parents=True, exist_ok=True)
    for i in range(203, 208):
        text = f'''-- Generated by tools/generators/emit_orbit3_spin_rows.py.
import MainTheory.Orbit3CollectedSpinRow

namespace SixQubit.Generated.Orbit3CollectedRows.Spin{i:03d}
open MainTheory.DyadicCoefficientTree MainTheory.Orbit3RowCoordinateExpressions
open SixQubit.Generated
set_option maxHeartbeats 16000000
set_option maxRecDepth 200000

theorem collected_coefficients :
    MainTheory.Orbit3SpinMomentInterpretation.coefficients (spinIndex {i}) =
      Orbit3CollectedRows.Data.row{i:03d} := by decide +kernel

theorem primitive_coefficients : ∀ j : Fin 269,
    (lookup Orbit3CollectedRows.Data.row{i:03d} j.val : ℚ) =
      (Orbit3RowMetadata.rowDivisor {i} : ℚ) * Orbit3SexticIdentity.rows {i} j := by
  decide +kernel

theorem primitive_row_zero (W : MainTheory.Orbit3ScalarCategoryRealization.Encoder) :
    Orbit3SexticIdentity.evaluate (Orbit3SexticIdentity.rows {i})
      (MainTheory.Orbit3CoordinateRealization.coordinates W) = 0 :=
  MainTheory.Orbit3CollectedSpinRow.primitive_row_zero W {i}
    collected_coefficients primitive_coefficients

end SixQubit.Generated.Orbit3CollectedRows.Spin{i:03d}
'''
        (out / f'Spin{i:03d}.lean').write_text(text, encoding='utf-8', newline='\n')

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output-dir', type=Path, default=ROOT/'SixQubit/Generated/Orbit3CollectedRows')
    generate(p.parse_args().output_dir)
