"""Emit `MainTheory/Generated/RankSymmetry.lean`.

`lem:six-active-rank-reduction` compares `q` against `beta (min rank0 rank1)`,
so entering that filter from a code needs a lower bound on *both* active
affine ranks.  A code's pivot bounds the left one
(`CodeActiveFace.rank_le_activeMaskRank`); the right one comes from the
paper's own unlabeled Lemma "Maximum support rank from the active face",
whose content is that the two active affine ranks coincide.

That equality is a property of the 291 certified rank rows, and it holds:
every row has `rank0.rank = rank1.rank` (the distribution is 6:198, 5:51,
4:42 on both sides).  Each row's two rank fields are literal numerals, so each
instance is `rfl`; this file collects the 291 of them and the `forall` form
the filter entry consumes.

The shard sources are read only to learn how many shards there are and what
they are called.  No rank value is copied here, so a regenerated shard cannot
silently disagree with a stale table in this file.
"""

import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
GEN = os.path.join(ROOT, 'MainTheory', 'Generated')
OUT = os.path.join(GEN, 'RankSymmetry.lean')

NS = 'MainTheory.Generated.FiniteRankDataShard'


def shard_indices():
    """The shard order used by `FiniteRankData.certifiedRows`, read from that
    file rather than guessed, so this generator cannot drift from the pipeline
    generator that produced the append."""
    src = io.open(os.path.join(GEN, 'FiniteRankData.lean'),
                  encoding='utf-8').read()
    body = src.split('def certifiedRows : List CertifiedRankRow :=', 1)[1]
    body = body.split(chr(10) + chr(10), 1)[0]
    order = re.findall(r'FiniteRankDataShard(\d+)\.rows', body)
    have = set(re.findall(r'^FiniteRankDataShard(\d+)\.lean$', n)[0]
               for n in os.listdir(GEN)
               if re.match(r'^FiniteRankDataShard\d+\.lean$', n))
    missing = have.difference(order)
    if missing:
        raise SystemExit('shards not in certifiedRows: %s' % sorted(missing))
    return order


def row_name(i):
    """Each shard holds one certified row, named by its *global* index rather
    than by the shard's, so the name is read from the shard's own `rows`."""
    src = io.open(os.path.join(GEN, 'FiniteRankDataShard%s.lean' % i),
                  encoding='utf-8').read()
    m = re.search(r'def rows : List CertifiedRankRow := \[(\w+)\]', src)
    if not m:
        raise SystemExit('shard %s has no single-row `rows`' % i)
    return m.group(1)


HEADER = """-- Generated by tools/generators/emit_rank_symmetry_lean.py.
-- Do not edit it by hand; regenerate it from the rank shards.

import MainTheory.Generated.FiniteRankData

/-!
# The two active affine ranks agree on every certified row

This is the finite content of the paper's unlabeled Lemma "Maximum support
rank from the active face": `r_* = affdim U_0 = affdim U_1`.  The abstract
statement is `MomentPolytope.exists_maximum_support_rank`, over the real
polytope; what the rank filter actually compares are the two *rational*
affine ranks stored by the certificates, and those agree row by row.

Each row stores both ranks as numerals, so every instance is `rfl`.  The
`forall` form at the end is what the code-side entry into
`lem:six-active-rank-reduction` consumes: a code's pivot bounds the left
active rank, and this transports the bound to the right one, which is the
half `min` would otherwise leave unproved.
-/

namespace MainTheory.Generated.RankSymmetry

open MainTheory.FiniteRankPipeline

"""


def main():
    idx = shard_indices()
    if not idx:
        raise SystemExit('no FiniteRankDataShard*.lean found in %s' % GEN)

    parts = [HEADER]

    for i in idx:
        row = row_name(i)
        parts.append(
            'theorem shard%s :\n'
            '    %s%s.%s.row.rank0.rank =\n'
            '      %s%s.%s.row.rank1.rank := rfl\n\n'
            % (i, NS, i, row, NS, i, row))

    unfold = ',\n    '.join('%s%s.rows' % (NS, i) for i in idx)
    rewrites = ',\n    '.join('shard%s' % i for i in idx)

    parts.append(
        'set_option maxRecDepth 40000 in\n'
        'set_option maxHeartbeats 4000000 in\n'
        '/-- The two rank columns of the certified rows are the same list. -/\n'
        'theorem ranks_map_eq :\n'
        '    MainTheory.Generated.FiniteRankData.certifiedRows.map\n'
        '        (fun cert => cert.row.rank0.rank)\n'
        '      = MainTheory.Generated.FiniteRankData.certifiedRows.map\n'
        '          (fun cert => cert.row.rank1.rank) := by\n'
        '  simp only [MainTheory.Generated.FiniteRankData.certifiedRows,\n'
        '    List.map_append, List.map_cons, List.map_nil,\n'
        '    %s]\n'
        '  rw [%s]\n\n' % (unfold, rewrites))

    parts.append(
        'set_option maxHeartbeats 4000000 in\n'
        '/-- **Both active affine ranks agree, on every one of the certified\n'
        'rank rows.**\n\n'
        'This is the row-level form the code-side rank-filter entry uses. -/\n'
        'theorem ranks_equal :\n'
        '    ∀ cert ∈ MainTheory.Generated.FiniteRankData.certifiedRows,\n'
        '      cert.row.rank0.rank = cert.row.rank1.rank :=\n'
        '  List.map_eq_map_iff.1 ranks_map_eq\n\n')

    parts.append('end MainTheory.Generated.RankSymmetry\n')

    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(''.join(parts))
    print('wrote %s with %d shard lemmas' % (OUT, len(idx)))


if __name__ == '__main__':
    main()
